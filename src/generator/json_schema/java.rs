#[derive(Debug, Clone, Default)]
struct ArrayConstraints {
    min_items: Option<u64>,
    max_items: Option<u64>,
    unique_items: bool,
    contains: Option<Box<Schema>>,
    min_contains: Option<u64>,
    max_contains: Option<u64>,
}

impl ArrayConstraints {
    fn from_schema(schema: &Schema) -> Self {
        Self {
            min_items: schema.min_items,
            max_items: schema.max_items,
            unique_items: schema.unique_items == Some(true),
            contains: schema.contains.clone(),
            min_contains: schema.min_contains,
            max_contains: schema.max_contains,
        }
    }

    fn is_empty(&self) -> bool {
        self.min_items.is_none()
            && self.max_items.is_none()
            && !self.unique_items
            && self.contains.is_none()
    }
}

/// A pinned string `format` lowered for Java: the canonical name (for the
/// reason), the pinned regex with the per-target `$`→`\z` rewrite already
/// applied, and the optional total-length guard. See
/// `specs/json-schema/features/format.md`.
#[derive(Debug, Clone)]
struct JavaFormat {
    name: &'static str,
    pattern: String,
    max_code_points: Option<usize>,
}

#[derive(Debug, Clone, Default)]
struct StringLengthConstraints {
    min_length: Option<u64>,
    max_length: Option<u64>,
    /// The loader-normalized `pattern` with the per-target `$`→`\z` rewrite
    /// already applied (Java's strict end-of-input anchor). See
    /// `specs/json-schema/features/pattern.md`.
    pattern: Option<String>,
    /// A pinned `format` check (regex + optional length guard) on the same node.
    format: Option<JavaFormat>,
}

impl StringLengthConstraints {
    fn from_schema(schema: &Schema) -> Self {
        Self {
            min_length: schema.min_length,
            max_length: schema.max_length,
            pattern: schema
                .pattern
                .as_deref()
                .map(|pattern| crate::json_schema::pattern::rewrite_end_anchor(pattern, r"\z")),
            format: schema
                .format
                .as_deref()
                .and_then(crate::json_schema::format::check_for)
                .map(|check| JavaFormat {
                    name: check.name,
                    pattern: crate::json_schema::pattern::rewrite_end_anchor(&check.pattern, r"\z"),
                    max_code_points: check.max_code_points,
                }),
        }
    }

    /// True when there is no length bound, pattern, or format.
    fn is_empty(&self) -> bool {
        self.min_length.is_none()
            && self.max_length.is_none()
            && self.pattern.is_none()
            && self.format.is_none()
    }

    /// True when there is a length bound (needing the `codePointCount` local).
    fn has_length(&self) -> bool {
        self.min_length.is_some() || self.max_length.is_some()
    }
}

