/// Runtime `TemporalSupport.java`: the pinned narrowed regexes, the Gregorian
/// calendar predicate, and the parse/serialize adapters for the materialized
/// temporal formats. The serializer is generator-owned (RFC 3339, original
/// offset preserved, +00:00/-00:00 -> Z, trailing fractional zeros trimmed;
