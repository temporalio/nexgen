/// Renders a numeric literal for an `integer` (`long`) or `number` (`double`)
/// position.
///
/// A **fractional** bound over an integer position keeps its `double` spelling —
/// `>= 1.5` rejects `1` and accepts `2`, which is what the bound means, where
/// the truncated `>= 1L` would accept `1`. Java widens the `long` operand for
/// the comparison, so the emitted predicate stays a single expression. An
/// integral spelling of an integer literal (`1.0` for `const: 1.0`) still
/// renders as `1L`, never `0L`.
fn java_bound_literal(number: &serde_json::Number, is_integer: bool) -> String {
    if is_integer
        && let Some(value) = number.as_f64()
        && value.fract() == 0.0
    {
        return format!("{}L", value as i64);
    }
    // Number-field bounds render as a `double` literal.
    let text = number.to_string();
    if text.contains('.') || text.contains('e') || text.contains('E') {
        text
    } else {
        format!("{text}.0")
    }
}

/// Renders an authored JSON Schema count for use in Java source. Counts above
/// `Integer.MAX_VALUE` need the `L` suffix even when compared with an `int`-
/// valued collection size; the loader permits the full portable 2^53-1 range.
fn java_count_literal(count: u64) -> String {
    if count > i32::MAX as u64 {
        format!("{count}L")
    } else {
        count.to_string()
    }
}

/// Emits the numeric-constraint predicates over `value_expr` (a validated
/// `long`/`double` in scope) into the collecting deserializer, appending
/// `Violation`s. `is_integer` selects `long`/`double` divisibility.
fn render_java_numeric_checks(
    output: &mut String,
    value_expr: &str,
    json: &str,
    constraints: &NumericConstraints,
    is_integer: bool,
    indent: &str,
) {
    let mut emit = |condition: String, reason: &str| {
        output.push_str(&format!(
            "{indent}if ({condition}) {{\n{indent}    violations.add(new Violation({json}, \"{reason}, got \" + {value_expr}));\n{indent}}}\n"
        ));
    };
    if let Some(min) = &constraints.minimum {
        let bound = java_bound_literal(min, is_integer);
        emit(
            format!("{value_expr} < {bound}"),
            &format!("must be >= {}", trim_java_bound(&bound)),
        );
    }
    if let Some(max) = &constraints.maximum {
        let bound = java_bound_literal(max, is_integer);
        emit(
            format!("{value_expr} > {bound}"),
            &format!("must be <= {}", trim_java_bound(&bound)),
        );
    }
    if let Some(min) = &constraints.exclusive_minimum {
        let bound = java_bound_literal(min, is_integer);
        emit(
            format!("{value_expr} <= {bound}"),
            &format!("must be > {}", trim_java_bound(&bound)),
        );
    }
    if let Some(max) = &constraints.exclusive_maximum {
        let bound = java_bound_literal(max, is_integer);
        emit(
            format!("{value_expr} >= {bound}"),
            &format!("must be < {}", trim_java_bound(&bound)),
        );
    }
    if let Some(divisor) = &constraints.multiple_of {
        let bound = java_bound_literal(divisor, is_integer);
        emit(
            format!("{value_expr} % {bound} != 0"),
            &format!("must be a multiple of {}", trim_java_bound(&bound)),
        );
    }
}

/// True when an in-memory value contains a JSON Schema `number` position whose
/// Java `double` can carry NaN or infinity. References validate in their own
/// generated serializer; union branches validate through their dispatcher.
fn java_type_needs_finite_check(ty: &JavaType) -> bool {
    match ty {
        JavaType::Double => true,
        JavaType::List(element) => java_type_needs_finite_check(element),
        _ => false,
    }
}

/// True when an in-memory `integer` position is reachable through `ty`. A Java
/// `long` spans ±(2^63−1) while the shared wire contract caps integers at
/// ±(2^53−1), so serialize has to hold the value to the same cap the parser
/// (`SpecNumbers.specLong`) enforces — otherwise the emitter writes a number its
/// own reader rejects.
fn java_type_needs_integer_cap_check(ty: &JavaType) -> bool {
    match ty {
        JavaType::Long => true,
        JavaType::List(element) => java_type_needs_integer_cap_check(element),
        _ => false,
    }
}

/// Emits the serialize-side ±(2^53−1) integer cap for every `integer` reachable
/// through `ty`, recursively extending array paths like number validation.
fn render_java_integer_cap_checks(
    output: &mut String,
    ty: &JavaType,
    value_expr: &str,
    path_expr: &str,
    indent: &str,
    depth: usize,
) {
    match ty {
        JavaType::Long => {
            output.push_str(&format!(
                "{indent}if ({value_expr} < -SpecNumbers.INTEGER_CAP || {value_expr} > SpecNumbers.INTEGER_CAP) {{\n{indent}    violations.add(new Violation({path_expr}, \"exceeds \\u00b1(2^53-1) integer cap\"));\n{indent}}}\n"
            ));
        }
        JavaType::List(element) if java_type_needs_integer_cap_check(element) => {
            let index = format!("integerCapIndex{depth}");
            let value = format!("integerCapValue{depth}");
            let element_path = format!("{path_expr} + \"[\" + {index} + \"]\"");
            output.push_str(&format!(
                "{indent}for (int {index} = 0; {index} < {value_expr}.size(); {index}++) {{\n"
            ));
            output.push_str(&format!(
                "{indent}    {} {value} = {value_expr}.get({index});\n",
                element.boxed_name()
            ));
            output.push_str(&format!("{indent}    if ({value} != null) {{\n"));
            render_java_integer_cap_checks(
                output,
                element,
                &value,
                &element_path,
                &format!("{indent}        "),
                depth + 1,
            );
            output.push_str(&format!("{indent}    }}\n{indent}}}\n"));
        }
        _ => {}
    }
}

/// True when an in-memory materialized temporal can hold a value the wire
/// grammar cannot spell. **Every** kind can: a `LocalDate`/`OffsetDateTime`
/// carries Gregorian year zero and five-digit years, an `OffsetDateTime`/
/// `OffsetTime` carries a sub-minute UTC offset the wire form truncates, and a
/// `Duration` is signed, nanosecond-resolution and unbounded while the pinned
/// `PTnHnMnS` grammar is none of those. See
/// `specs/json-schema/features/format.md` and Python's `_check_date_time` /
/// `_check_time` / `_check_duration`.
fn java_type_needs_temporal_check(ty: &JavaType) -> bool {
    match ty {
        JavaType::Temporal(_) => true,
        JavaType::List(element) => java_type_needs_temporal_check(element),
        _ => false,
    }
}

/// The `TemporalSupport` static method asserting a value is writable as this
/// kind's wire form (the serialize-side counterpart of `parse*`).
fn java_temporal_check_fn(kind: crate::json_schema::format::TemporalKind) -> &'static str {
    match kind {
        crate::json_schema::format::TemporalKind::DateTime => "checkDateTime",
        crate::json_schema::format::TemporalKind::Date => "checkDate",
        crate::json_schema::format::TemporalKind::Time => "checkTime",
        crate::json_schema::format::TemporalKind::Duration => "checkDuration",
    }
}

fn schema_has_recursive_value_checks(schema: &Schema) -> bool {
    schema.const_value.is_some()
        || schema.enum_values.is_some()
        || !NumericConstraints::from_schema(schema).is_empty()
        || !StringLengthConstraints::from_schema(schema).is_empty()
        || !ArrayConstraints::from_schema(schema).is_empty()
        || element_shape(schema).is_some()
}

fn render_java_recursive_value_checks(
    output: &mut String,
    value_expr: &str,
    path_expr: &str,
    schema: &Schema,
    ty: &JavaType,
    indent: &str,
    depth: usize,
) {
    match ty {
        JavaType::String => {
            render_java_inline_string_checks(output, value_expr, path_expr, schema, indent);
        }
        JavaType::Long | JavaType::Double => {
            render_java_numeric_checks(
                output,
                value_expr,
                path_expr,
                &NumericConstraints::from_schema(schema),
                matches!(ty, JavaType::Long),
                indent,
            );
            render_java_closed_scalar_checks(output, value_expr, path_expr, schema, ty, indent);
        }
        JavaType::Boolean => {
            render_java_closed_scalar_checks(output, value_expr, path_expr, schema, ty, indent);
        }
        JavaType::Temporal(kind) => {
            let wire = format!("nestedWire{depth}");
            let expression = java_temporal_format_fn(*kind)
                .map(|format_fn| format!("TemporalSupport.{format_fn}({value_expr})"))
                .unwrap_or_else(|| value_expr.to_string());
            output.push_str(&format!("{indent}String {wire} = {expression};\n"));
            render_java_inline_string_checks(output, &wire, path_expr, schema, indent);
        }
        JavaType::Bytes(encoding) => {
            let wire = format!("nestedWire{depth}");
            output.push_str(&format!(
                "{indent}String {wire} = Base64Support.{}({value_expr});\n",
                java_content_encoding_format_fn(*encoding)
            ));
            render_java_inline_string_checks(output, &wire, path_expr, schema, indent);
        }
        JavaType::List(element_ty) => {
            let constraints = ArrayConstraints::from_schema(schema);
            if let Some(item_schema) = element_shape(schema) {
                let item_nullable = schema.items.as_deref().is_some_and(allows_null);
                let index = format!("validationIndex{depth}");
                let item = format!("validationValue{depth}");
                let item_path = format!("{path_expr} + \"[\" + {index} + \"]\"");
                output.push_str(&format!(
                    "{indent}for (int {index} = 0; {index} < {value_expr}.size(); {index}++) {{\n{indent}    {} {item} = {value_expr}.get({index});\n{indent}    if ({item} == null) {{\n",
                    element_ty.boxed_name()
                ));
                if item_nullable {
                    output.push_str(&format!("{indent}        continue;\n"));
                } else {
                    output.push_str(&format!(
                        "{indent}        violations.add(new Violation({item_path}, \"explicit null not allowed\"));\n"
                    ));
                }
                output.push_str(&format!("{indent}    }} else {{\n"));
                render_java_recursive_value_checks(
                    output,
                    &item,
                    &item_path,
                    item_schema,
                    element_ty,
                    &format!("{indent}        "),
                    depth + 1,
                );
                output.push_str(&format!("{indent}    }}\n{indent}}}\n"));
            }
            if !constraints.is_empty() {
                render_java_array_checks(
                    output,
                    value_expr,
                    path_expr,
                    element_ty,
                    &constraints,
                    None,
                    indent,
                );
            }
        }
        JavaType::Ref { .. } | JavaType::Union { .. } | JavaType::ClosedValue { .. } => {}
    }
}

/// Emits the serialize-side finiteness predicate for every `number` reachable
/// through `ty`. Arrays recurse elementwise and extend the violation path at
/// each level, so nested failures surface as `field[1][2]`.
fn render_java_finite_checks(
    output: &mut String,
    ty: &JavaType,
    value_expr: &str,
    path_expr: &str,
    indent: &str,
    depth: usize,
) {
    match ty {
        JavaType::Double => {
            output.push_str(&format!(
                "{indent}if (!Double.isFinite({value_expr})) {{\n{indent}    violations.add(new Violation({path_expr}, \"must be a finite number, got \" + {value_expr}));\n{indent}}}\n"
            ));
        }
        JavaType::List(element) if java_type_needs_finite_check(element) => {
            let index = format!("finiteIndex{depth}");
            let value = format!("finiteValue{depth}");
            let element_path = format!("{path_expr} + \"[\" + {index} + \"]\"");
            output.push_str(&format!(
                "{indent}for (int {index} = 0; {index} < {value_expr}.size(); {index}++) {{\n"
            ));
            output.push_str(&format!(
                "{indent}    {} {value} = {value_expr}.get({index});\n",
                element.boxed_name()
            ));
            output.push_str(&format!("{indent}    if ({value} != null) {{\n"));
            render_java_finite_checks(
                output,
                element,
                &value,
                &element_path,
                &format!("{indent}        "),
                depth + 1,
            );
            output.push_str(&format!("{indent}    }}\n{indent}}}\n"));
        }
        _ => {}
    }
}

/// Emits the serialize-side representability predicate for every materialized
