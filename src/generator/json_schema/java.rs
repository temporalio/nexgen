/// Resolution context for a single input module (file). Carries the package
/// root and the module path so `$ref` values can be resolved to a Java
/// `(package, class)` pair.
pub(in crate::generator) struct JavaContext<'a> {
    pub(in crate::generator) base_package: &'a str,
    pub(in crate::generator) module: &'a ModulePath,
    /// Maps a planned model's `full_name` (the canonical string that appears in
    /// planned `$ref` values) to its `(package, class)` pair.
    pub(in crate::generator) registry: &'a BTreeMap<String, (String, String)>,
    /// The `full_name` of every definition that is a `oneOf` union, so a `$ref`
    /// at one can be told apart from a `$ref` at a POJO.
    pub(in crate::generator) union_defs: &'a BTreeSet<String>,
}

impl JavaContext<'_> {
    pub(in crate::generator) fn package_for_module(
        base_package: &str,
        module: &[String],
    ) -> String {
        if module.is_empty() {
            base_package.to_string()
        } else {
            format!("{base_package}.{}", module.join("."))
        }
    }

    fn current_package(&self) -> String {
        Self::package_for_module(self.base_package, &self.module.0)
    }

    /// True when a `$ref` points at a named `oneOf` union definition.
    fn ref_is_union(&self, reference: &str) -> bool {
        self.union_defs
            .contains(reference.strip_prefix("#/$defs/").unwrap_or(reference))
    }

    /// Resolve a `$ref` string to the target (package, class) pair.
    fn resolve_ref(&self, reference: &str) -> (String, String) {
        // Planned `$ref` values take the form `#/$defs/<full_name>`, where
        // `<full_name>` is the registry key.
        let key = reference.strip_prefix("#/$defs/").unwrap_or(reference);
        if let Some(resolved) = self.registry.get(key) {
            return resolved.clone();
        }
        if let Some(resolved) = self.registry.get(reference) {
            return resolved.clone();
        }
        let (path_part, fragment) = match reference.split_once('#') {
            Some((path, fragment)) => (path, Some(fragment)),
            None => (reference, None),
        };

        let target_module: Vec<String> = if path_part.is_empty() {
            self.module.0.clone()
        } else {
            // Cross-file reference: resolve relative to the current file's
            // directory (the module path without its file-stem leaf).
            let mut segments = self.module.0.clone();
            segments.pop();
            for segment in path_part.split('/') {
                match segment {
                    "" | "." => {}
                    ".." => {
                        segments.pop();
                    }
                    other => {
                        segments.push(crate::parser::strip_json_schema_extension(other).to_string())
                    }
                }
            }
            segments
        };

        let class = match fragment {
            Some(fragment) if !fragment.is_empty() => {
                let name = fragment
                    .strip_prefix("/$defs/")
                    .unwrap_or_else(|| fragment.trim_start_matches('/'));
                name.to_upper_camel_case()
            }
            _ => target_module
                .last()
                .map(|segment| segment.to_upper_camel_case())
                .unwrap_or_default(),
        };
        (
            Self::package_for_module(self.base_package, &target_module),
            class,
        )
    }
}

#[derive(Debug, Clone)]
enum JavaType {
    Long,
    Double,
    Boolean,
    String,
    Ref {
        package: String,
        class: String,
        /// True when the target definition is a `oneOf` union — a sealed
        /// interface Jackson cannot instantiate, so a value in this position
        /// decodes through the interface's static `fromNode` dispatcher rather
        /// than `readTreeAsValue`.
        union: bool,
    },
    List(Box<JavaType>),
    /// A `oneOf` sum type — a sealed-by-convention interface. `class` is the
    /// (possibly nested) interface name.
    Union {
        class: String,
    },
    /// A materialized temporal `format` (native `java.time` construct, or a
    /// validated+canonicalized `String` for `time` — no single `java.time` type
    /// holds both offset-bearing and offset-less time). See `format.md`.
    Temporal(crate::json_schema::format::TemporalKind),
    /// A materialized `contentEncoding` (native `byte[]`; the wire is a JSON
    /// string carrying the encoded form). See `contentEncoding.md`.
    Bytes(crate::json_schema::content_encoding::Encoding),
    /// A closed value-set (`const`/`enum`) rendered as a nested value class:
    /// a private constructor, one known constant per member, and Jackson
    /// `@JsonCreator`/`@JsonValue` over the underlying scalar `wire` type. The
    /// class is the boxed type of the owning field; it can only ever hold a
    /// known constant, so it is a compile-time closed contract (P13.1). See
    /// `specs/json-schema/features/{const,enum}.md`.
    ClosedValue {
        /// The nested value-class name (`Kind`, `Status`), derived from the
        /// owning member and scoped inside the enclosing POJO.
        class: String,
        /// The underlying scalar the value class wraps (String/Long/Double/
        /// Boolean); the wire form and the `getValue()`/`@JsonCreator` type.
        wire: Box<JavaType>,
    },
}

impl JavaType {
    fn boxed_name(&self) -> String {
        match self {
            JavaType::Long => "Long".to_string(),
            JavaType::Double => "Double".to_string(),
            JavaType::Boolean => "Boolean".to_string(),
            JavaType::String => "String".to_string(),
            JavaType::Ref { class, .. } => class.clone(),
            JavaType::List(inner) => format!("List<{}>", inner.boxed_name()),
            JavaType::Union { class } => class.clone(),
            JavaType::Temporal(kind) => java_temporal_type(*kind).to_string(),
            JavaType::Bytes(_) => "byte[]".to_string(),
            // The value class is the field's boxed type; it is always a
            // reference (never a stored primitive), even when required.
            JavaType::ClosedValue { class, .. } => class.clone(),
        }
    }

    fn primitive_name(&self) -> Option<&'static str> {
        match self {
            JavaType::Long => Some("long"),
            JavaType::Double => Some("double"),
            JavaType::Boolean => Some("boolean"),
            _ => None,
        }
    }

    /// Writes a nullable TYPE_USE annotation on this carrier. Collections
    /// deliberately do not recurse here: collection presence and element
    /// nullability are independent schema axes.
    fn nullable_declaration(&self, declaration: String) -> String {
        match self {
            JavaType::Bytes(_) => "byte @Nullable []".to_string(),
            _ => format!("@Nullable {declaration}"),
        }
    }

    fn collect_refs(&self, refs: &mut BTreeSet<(String, String)>) {
        match self {
            JavaType::Ref { package, class, .. } => {
                refs.insert((package.clone(), class.clone()));
            }
            JavaType::List(inner) => inner.collect_refs(refs),
            // A closed value class is nested in the same file — no import.
            _ => {}
        }
    }
}

/// The Java type a materialized temporal `format` maps to. `date-time` uses the
/// idiomatic `OffsetDateTime`; the shared materialized offset domain is exactly
/// the range its `ZoneOffset` can carry. `time` stays a `String` because no
/// single `java.time` type holds both offset-bearing and offset-less time-of-day
/// values.
fn java_temporal_type(kind: crate::json_schema::format::TemporalKind) -> &'static str {
    match kind {
        crate::json_schema::format::TemporalKind::DateTime => "OffsetDateTime",
        crate::json_schema::format::TemporalKind::Date => "LocalDate",
        crate::json_schema::format::TemporalKind::Time => "String",
        crate::json_schema::format::TemporalKind::Duration => "Duration",
    }
}

#[derive(Debug, Clone, Copy, Default)]
