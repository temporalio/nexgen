/// Emits the compiled-once statics a `contains` matcher needs at `scope`.
/// Returns true when anything was written.
fn render_contains_pattern_statics(
    output: &mut String,
    constraints: &ArrayConstraints,
    scope: &str,
    indent: &str,
) -> bool {
    let Some(matcher) = constraints.contains.as_deref() else {
        return false;
    };
    let mut wrote = false;
    if let Some(pattern) = &matcher.pattern {
        let pattern = crate::json_schema::pattern::rewrite_end_anchor(pattern, r"\z");
        output.push_str(&format!(
            "{indent}private static final java.util.regex.Pattern {} = java.util.regex.Pattern.compile({});\n",
            java_contains_pattern_field_name(scope),
            java_string_literal(&pattern),
        ));
        wrote = true;
    }
    if let Some(check) = matcher
        .format
        .as_deref()
        .and_then(crate::json_schema::format::check_for)
    {
        let pattern = crate::json_schema::pattern::rewrite_end_anchor(&check.pattern, r"\z");
        output.push_str(&format!(
            "{indent}private static final java.util.regex.Pattern {} = java.util.regex.Pattern.compile({});\n",
            java_contains_format_field_name(scope),
            java_string_literal(&pattern),
        ));
        wrote = true;
    }
    wrote
}

/// Emits the object member-count predicates (`minProperties`/`maxProperties`)
/// over `size_expr` (the number of distinct wire member keys, one number over
/// the whole object) into the collecting deserializer. See
/// `specs/json-schema/features/minProperties.md`.
fn render_java_property_count_checks(
    output: &mut String,
    size_expr: &str,
    schema: &Schema,
    indent: &str,
) {
    if let Some(min) = schema.min_properties {
        let min_literal = java_count_literal(min as u64);
        output.push_str(&format!(
            "{indent}if ({size_expr} < {min_literal}) {{\n{indent}    violations.add(new Violation(\"\", \"must have at least {min} properties, got \" + {size_expr}));\n{indent}}}\n"
        ));
    }
    if let Some(max) = schema.max_properties {
        let max_literal = java_count_literal(max as u64);
        output.push_str(&format!(
            "{indent}if ({size_expr} > {max_literal}) {{\n{indent}    violations.add(new Violation(\"\", \"must have at most {max} properties, got \" + {size_expr}));\n{indent}}}\n"
        ));
    }
}

/// Emits the `propertyNames` key-shape predicate over the keys of `node_expr`,
/// applying the (string-length) key subschema to each key. `codePointCount`
/// counts Unicode code points — spec-correct. See
/// `specs/json-schema/features/propertyNames.md`.
fn render_java_property_name_checks(
    output: &mut String,
    node_expr: &str,
    subschema: &Schema,
    indent: &str,
) {
    let constraints = StringLengthConstraints::from_schema(subschema);
    if constraints.is_empty() && subschema.const_value.is_none() && subschema.enum_values.is_none()
    {
        return;
    }
    output.push_str(&format!(
        "{indent}Iterator<String> propertyNameKeys = {node_expr}.fieldNames();\n{indent}while (propertyNameKeys.hasNext()) {{\n"
    ));
    output.push_str(&format!(
        "{indent}    String pnKey = propertyNameKeys.next();\n"
    ));
    if constraints.has_length() {
        output.push_str(&format!(
            "{indent}    int pnLength = pnKey.codePointCount(0, pnKey.length());\n"
        ));
        if let Some(min) = constraints.min_length {
            let min_literal = java_count_literal(min);
            output.push_str(&format!(
                "{indent}    if (pnLength < {min_literal}) {{\n{indent}        violations.add(new Violation(Violation.memberPath(pnKey), \"invalid property name \\\"\" + pnKey + \"\\\": must have length >= {min}, got \" + pnLength));\n{indent}    }}\n"
            ));
        }
        if let Some(max) = constraints.max_length {
            let max_literal = java_count_literal(max);
            output.push_str(&format!(
                "{indent}    if (pnLength > {max_literal}) {{\n{indent}        violations.add(new Violation(Violation.memberPath(pnKey), \"invalid property name \\\"\" + pnKey + \"\\\": must have length <= {max}, got \" + pnLength));\n{indent}    }}\n"
            ));
        }
    }
    let mut non_length = constraints.clone();
    non_length.min_length = None;
    non_length.max_length = None;
    render_java_string_checks(
        output,
        "pnKey",
        "Violation.memberPath(pnKey)",
        PROPERTY_NAME_POSITION,
        &non_length,
        &format!("{indent}    "),
    );
    render_java_closed_string_checks(
        output,
        "pnKey",
        "Violation.memberPath(pnKey)",
        subschema,
        &format!("{indent}    "),
    );
    output.push_str(&format!("{indent}}}\n"));
}

/// Emits the `dependentRequired` cross-field presence predicate over
/// `node_expr` (the parsed wire tree): for each present trigger key, each
/// dependent key must also be present. See
/// `specs/json-schema/features/dependentRequired.md`.
fn render_java_dependent_required(
    output: &mut String,
    node_expr: &str,
    schema: &Schema,
    indent: &str,
) {
    let Some(dependent_required) = &schema.dependent_required else {
        return;
    };
    for (trigger, deps) in dependent_required {
        output.push_str(&format!(
            "{indent}if ({node_expr}.has({})) {{\n",
            java_string_literal(trigger)
        ));
        for dep in deps {
            let reason = format!(
                "property {} is required when {} is present",
                quote_for_message(dep),
                quote_for_message(trigger)
            );
            output.push_str(&format!(
                "{indent}    if (!{node_expr}.has({})) {{\n{indent}        violations.add(new Violation({}, {}));\n{indent}    }}\n",
                java_string_literal(dep),
                java_violation_path_literal(dep),
                java_string_literal(&reason)
            ));
        }
        output.push_str(&format!("{indent}}}\n"));
    }
}

/// Renders a Java literal for a scalar matcher value in the element's boxed
/// type.
fn java_scalar_literal(value: &Value, element_ty: &JavaType) -> String {
    match value {
        Value::String(text) => java_string_literal(text),
        Value::Bool(boolean) => boolean.to_string(),
        Value::Number(number) => java_bound_literal(number, matches!(element_ty, JavaType::Long)),
        _ => "null".to_string(),
    }
}

/// A single `element == literal` / `literal.equals(element)` match term, boxed
/// per the element type (strings compare by value, scalars unbox).
fn java_equals_term(value: &Value, elem: &str, element_ty: &JavaType) -> String {
    let literal = java_scalar_literal(value, element_ty);
    match element_ty {
        JavaType::String => format!("{literal}.equals({elem})"),
        _ => format!("{elem} == {literal}"),
    }
}

/// Builds the boolean Java match expression for a scalar `contains` matcher over
/// `elem` (a boxed element). A type-only matcher matches every element, so an
/// empty condition set renders as the literal `true`.
fn java_matcher_condition(
    matcher: &Schema,
    elem: &str,
    element_ty: &JavaType,
    scope: Option<&str>,
) -> String {
    let is_integer = matches!(element_ty, JavaType::Long);
    let mut parts: Vec<String> = Vec::new();
    if let Some(value) = &matcher.const_value {
        parts.push(java_equals_term(value, elem, element_ty));
    }
    if let Some(values) = &matcher.enum_values {
        let alternatives = values
            .iter()
            .map(|value| java_equals_term(value, elem, element_ty))
            .collect::<Vec<_>>()
            .join(" || ");
        if !alternatives.is_empty() {
            parts.push(format!("({alternatives})"));
        }
    }
    if let Some(min) = &matcher.minimum {
        parts.push(format!("{elem} >= {}", java_bound_literal(min, is_integer)));
    }
    if let Some(max) = &matcher.maximum {
        parts.push(format!("{elem} <= {}", java_bound_literal(max, is_integer)));
    }
    if let Some(min) = &matcher.exclusive_minimum {
        parts.push(format!("{elem} > {}", java_bound_literal(min, is_integer)));
    }
    if let Some(max) = &matcher.exclusive_maximum {
        parts.push(format!("{elem} < {}", java_bound_literal(max, is_integer)));
    }
    if let Some(divisor) = &matcher.multiple_of {
        parts.push(format!(
            "{elem} % {} == 0",
            java_bound_literal(divisor, is_integer)
        ));
    }
    if let Some(min) = matcher.min_length {
        let min_literal = java_count_literal(min);
        parts.push(format!(
            "{elem}.codePointCount(0, {elem}.length()) >= {min_literal}"
        ));
    }
    if let Some(max) = matcher.max_length {
        let max_literal = java_count_literal(max);
        parts.push(format!(
            "{elem}.codePointCount(0, {elem}.length()) <= {max_literal}"
        ));
    }
    if let Some(pattern) = &matcher.pattern {
        let pattern = crate::json_schema::pattern::rewrite_end_anchor(pattern, r"\z");
        // Compile-once: the matcher runs inside a per-element loop, so an
        // inline `Pattern.compile` would recompile per element on every
        // (de)serialize ([[pattern]] §"Why compile-once"). A scoped position
        // hangs the compiled pattern on a static class member instead.
        parts.push(match scope {
            Some(scope) => format!(
                "{}.matcher({elem}).find()",
                java_contains_pattern_field_name(scope)
            ),
            None => format!(
                "java.util.regex.Pattern.compile({}).matcher({elem}).find()",
                java_string_literal(&pattern)
            ),
        });
    }
    if let Some(format) = matcher
        .format
        .as_deref()
        .and_then(crate::json_schema::format::check_for)
    {
        let pattern = crate::json_schema::pattern::rewrite_end_anchor(&format.pattern, r"\z");
        if let Some(max) = format.max_code_points {
            parts.push(format!(
                "{elem}.codePointCount(0, {elem}.length()) <= {max}"
            ));
        }
        parts.push(match scope {
            Some(scope) => format!(
                "{}.matcher({elem}).find()",
                java_contains_format_field_name(scope)
            ),
            None => format!(
                "java.util.regex.Pattern.compile({}).matcher({elem}).find()",
                java_string_literal(&pattern)
            ),
        });
    }
    if parts.is_empty() {
        "true".to_string()
    } else {
        parts.join(" && ")
    }
}

fn matcher_kind<'a>(matcher: &'a Schema, fallback: &'a JavaType) -> &'a str {
    matcher
        .ty
        .as_ref()
        .and_then(Value::as_str)
        .unwrap_or(match fallback {
            JavaType::String => "string",
            JavaType::Boolean => "boolean",
            JavaType::Long => "integer",
            JavaType::Double => "number",
            _ => "unsupported",
        })
}

fn java_typed_matcher_guard(matcher: &Schema, elem: &str, element_ty: &JavaType) -> String {
    match (matcher_kind(matcher, element_ty), element_ty) {
        ("string", JavaType::String) | ("boolean", JavaType::Boolean) => "true".to_string(),
        ("integer", JavaType::Long) | ("number", JavaType::Long) => "true".to_string(),
        ("number", JavaType::Double) => format!("Double.isFinite({elem})"),
        ("integer", JavaType::Double) => format!(
            "Double.isFinite({elem}) && {elem} == Math.rint({elem}) && {elem} >= -(double) SpecNumbers.INTEGER_CAP && {elem} <= (double) SpecNumbers.INTEGER_CAP"
        ),
        _ => "false".to_string(),
    }
}

/// True when an in-memory element needs a derived `uniqueItems` equality key:
/// a materialized value (temporal / `contentEncoding`) whose Java type compares
/// by reference or by an offset-sensitive natural equality, or a `number` whose
/// `-0.0` must fold onto `0.0`.
fn java_needs_unique_key_mapping(ty: &JavaType) -> bool {
    match ty {
        JavaType::Double | JavaType::Temporal(_) | JavaType::Bytes(_) => true,
        JavaType::List(inner) => java_needs_unique_key_mapping(inner),
        _ => false,
    }
}

/// The serialize-side `uniqueItems` equality key for one in-memory element.
///
/// Per decision D10 a materialized value compares on its **canonical wire
/// string** — the same side the deserialize path compares (`SpecNumbers.valueKey`
/// over the wire node) — never on the native value and never by reference.
/// `byte[]` has no value equality at all, and `OffsetDateTime` compares
/// offset-sensitively while the wire string is what the contract is written
/// over. A `number` folds `-0.0` onto `0.0` so serialize agrees with
/// deserialize (P1). Everything else already has value equality.
fn java_unique_key_expr(ty: &JavaType, elem: &str, depth: usize) -> String {
    match ty {
        JavaType::Double => format!("SpecNumbers.numberKey({elem})"),
        JavaType::Temporal(kind) => match java_temporal_format_fn(*kind) {
            Some(format_fn) => {
                format!("({elem} == null ? null : TemporalSupport.{format_fn}({elem}))")
            }
            None => elem.to_string(),
        },
        JavaType::Bytes(encoding) => format!(
            "({elem} == null ? null : Base64Support.{}({elem}))",
            java_content_encoding_format_fn(*encoding)
        ),
        JavaType::List(inner) if java_needs_unique_key_mapping(inner) => {
            let param = format!("uniqueKeyElement{depth}");
            format!(
                "({elem} == null ? null : {elem}.stream().map({param} -> ({})).collect(java.util.stream.Collectors.toList()))",
                java_unique_key_expr(inner, &param, depth + 1)
            )
        }
        _ => elem.to_string(),
    }
}

/// Emits the array-constraint predicates over `items` (a built `List<T>` in
/// scope) into the collecting deserializer, appending `Violation`s.
fn render_java_array_checks(
    output: &mut String,
    list: &str,
    json: &str,
    element_ty: &JavaType,
    constraints: &ArrayConstraints,
    scope: Option<&str>,
    indent: &str,
) {
    if let Some(min) = constraints.min_items {
        let min_literal = java_count_literal(min);
        output.push_str(&format!(
            "{indent}if ({list}.size() < {min_literal}) {{\n{indent}    violations.add(new Violation({json}, \"must have at least {min} items, got \" + {list}.size()));\n{indent}}}\n"
        ));
    }
    if let Some(max) = constraints.max_items {
        let max_literal = java_count_literal(max);
        output.push_str(&format!(
            "{indent}if ({list}.size() > {max_literal}) {{\n{indent}    violations.add(new Violation({json}, \"must have at most {max} items, got \" + {list}.size()));\n{indent}}}\n"
        ));
    }
    if constraints.unique_items {
        output.push_str(&format!(
            "{indent}java.util.Map<Object, Integer> seen = new java.util.HashMap<>();\n"
        ));
        output.push_str(&format!(
            "{indent}for (int index = 0; index < {list}.size(); index++) {{\n"
        ));
        output.push_str(&format!(
            "{indent}    Object element = {};\n",
            java_unique_key_expr(element_ty, &format!("{list}.get(index)"), 0)
        ));
        output.push_str(&format!(
            "{indent}    Integer priorIndex = seen.get(element);\n"
        ));
        output.push_str(&format!("{indent}    if (priorIndex != null) {{\n"));
        output.push_str(&format!(
            "{indent}        violations.add(new Violation({json}, \"duplicate items: element at index \" + index + \" equals index \" + priorIndex));\n"
        ));
        output.push_str(&format!("{indent}    }} else {{\n"));
        output.push_str(&format!("{indent}        seen.put(element, index);\n"));
        output.push_str(&format!("{indent}    }}\n"));
        output.push_str(&format!("{indent}}}\n"));
    }
    if let Some(matcher) = &constraints.contains {
        let boxed = element_ty.boxed_name();
        let (matcher_value, matcher_ty) =
            if matches!(element_ty, JavaType::Temporal(_) | JavaType::Bytes(_)) {
                (
                    java_unique_key_expr(element_ty, "element", 0),
                    JavaType::String,
                )
            } else {
                ("element".to_string(), element_ty.clone())
            };
        let condition = java_matcher_condition(matcher, &matcher_value, &matcher_ty, scope);
        let guard = java_typed_matcher_guard(matcher, &matcher_value, &matcher_ty);
        let effective_min = constraints.min_contains.unwrap_or(1);
        let effective_min_literal = java_count_literal(effective_min);
        output.push_str(&format!("{indent}int matchCount = 0;\n"));
        output.push_str(&format!("{indent}for ({boxed} element : {list}) {{\n"));
        output.push_str(&format!(
            "{indent}    if (element != null && ({guard}) && ({condition})) {{\n"
        ));
        output.push_str(&format!("{indent}        matchCount++;\n"));
        output.push_str(&format!("{indent}    }}\n"));
        output.push_str(&format!("{indent}}}\n"));
        if effective_min > 0 {
            output.push_str(&format!(
                "{indent}if (matchCount < {effective_min_literal}) {{\n"
            ));
            if constraints.min_contains.is_some() {
                output.push_str(&format!(
                    "{indent}    violations.add(new Violation({json}, \"too few matching items: at least {effective_min}, got \" + matchCount));\n"
                ));
            } else {
                output.push_str(&format!(
                    "{indent}    violations.add(new Violation({json}, \"no element matches the required schema\"));\n"
                ));
            }
            output.push_str(&format!("{indent}}}\n"));
        }
        if let Some(max) = constraints.max_contains {
            let max_literal = java_count_literal(max);
            output.push_str(&format!("{indent}if (matchCount > {max_literal}) {{\n"));
            output.push_str(&format!(
                "{indent}    violations.add(new Violation({json}, \"too many matching items: at most {max}, got \" + matchCount));\n"
            ));
            output.push_str(&format!("{indent}}}\n"));
        }
    }
}

/// Emits deserialize-side sibling array checks over the original Jackson
/// array node. Element conversion may omit failed values from the typed list;
/// `minItems`, `maxItems`, `uniqueItems`, and `contains` must not observe that
/// shortened implementation detail.
fn render_java_raw_array_checks(
    output: &mut String,
    node: &str,
    json: &str,
    element_ty: &JavaType,
    constraints: &ArrayConstraints,
    scope: Option<&str>,
    indent: &str,
) {
    if let Some(min) = constraints.min_items {
        let min_literal = java_count_literal(min);
        output.push_str(&format!(
            "{indent}if ({node}.size() < {min_literal}) {{\n{indent}    violations.add(new Violation({json}, \"must have at least {min} items, got \" + {node}.size()));\n{indent}}}\n"
        ));
    }
    if let Some(max) = constraints.max_items {
        let max_literal = java_count_literal(max);
        output.push_str(&format!(
            "{indent}if ({node}.size() > {max_literal}) {{\n{indent}    violations.add(new Violation({json}, \"must have at most {max} items, got \" + {node}.size()));\n{indent}}}\n"
        ));
    }
    if constraints.unique_items {
        output.push_str(&format!(
            "{indent}java.util.Map<Object, Integer> rawSeen = new java.util.HashMap<>();\n{indent}for (int rawIndex = 0; rawIndex < {node}.size(); rawIndex++) {{\n{indent}    Object rawKey = SpecNumbers.valueKey({node}.get(rawIndex));\n{indent}    Integer priorIndex = rawSeen.get(rawKey);\n{indent}    if (priorIndex != null) {{\n{indent}        violations.add(new Violation({json}, \"duplicate items: element at index \" + rawIndex + \" equals index \" + priorIndex));\n{indent}    }} else {{\n{indent}        rawSeen.put(rawKey, rawIndex);\n{indent}    }}\n{indent}}}\n"
        ));
    }
    if let Some(matcher) = &constraints.contains {
        let kind = matcher_kind(matcher, element_ty);
        let (guard, value, evaluation_ty) = match kind {
            "string" => (
                "rawElement.isTextual()".to_string(),
                "rawElement.textValue()",
                JavaType::String,
            ),
            "boolean" => (
                "rawElement.isBoolean()".to_string(),
                "rawElement.booleanValue()",
                JavaType::Boolean,
            ),
            "integer" => (
                "SpecNumbers.isSpecLong(rawElement)".to_string(),
                "rawElement.doubleValue()",
                JavaType::Double,
            ),
            "number" => (
                "rawElement.isNumber() && Double.isFinite(rawElement.doubleValue())".to_string(),
                "rawElement.doubleValue()",
                JavaType::Double,
            ),
            _ => ("false".to_string(), "rawElement", element_ty.clone()),
        };
        let condition = java_matcher_condition(matcher, value, &evaluation_ty, scope);
        let effective_min = constraints.min_contains.unwrap_or(1);
        let effective_min_literal = java_count_literal(effective_min);
        output.push_str(&format!(
            "{indent}int rawMatchCount = 0;\n{indent}for (JsonNode rawElement : {node}) {{\n{indent}    if ({guard} && ({condition})) {{\n{indent}        rawMatchCount++;\n{indent}    }}\n{indent}}}\n"
        ));
        if effective_min > 0 {
            output.push_str(&format!(
                "{indent}if (rawMatchCount < {effective_min_literal}) {{\n"
            ));
            if constraints.min_contains.is_some() {
                output.push_str(&format!(
                    "{indent}    violations.add(new Violation({json}, \"too few matching items: at least {effective_min}, got \" + rawMatchCount));\n"
                ));
            } else {
                output.push_str(&format!(
                    "{indent}    violations.add(new Violation({json}, \"no element matches the required schema\"));\n"
                ));
            }
            output.push_str(&format!("{indent}}}\n"));
        }
        if let Some(max) = constraints.max_contains {
            let max_literal = java_count_literal(max);
            output.push_str(&format!(
                "{indent}if (rawMatchCount > {max_literal}) {{\n{indent}    violations.add(new Violation({json}, \"too many matching items: at most {max}, got \" + rawMatchCount));\n{indent}}}\n"
            ));
        }
    }
}

/// Strips the Java literal suffix/`.0` for human-readable reason messages so
/// they match the other targets (`10`, not `10L`).
fn trim_java_bound(literal: &str) -> String {
    literal
        .strip_suffix('L')
        .map(str::to_string)
        .unwrap_or_else(|| {
            literal
                .strip_suffix(".0")
                .map(str::to_string)
                .unwrap_or_else(|| literal.to_string())
        })
}

