fn operation_has_flattened_convenience(
    _operation: &PlannedOperation,
    model: &PlannedModel,
    _api_plan: &PlannedSpec,
) -> bool {
    model.public_fields().next().is_some() && model_function_fields_flattenable(model)
}

fn model_function_fields_flattenable(model: &PlannedModel) -> bool {
    let mut has_function_fields = false;
    for (_, field) in model.public_fields() {
        if let Some(function) = &field.function {
            has_function_fields = true;
            if function.name_extractor.is_none() || function.call_extractor.is_none() {
                return false;
            }
        }
    }
    !has_function_fields || model_has_extractable_function_fields(model)
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum FlattenedFunctionMode {
    String,
    Expression,
}

struct FlattenedOverload {
    function_modes: Vec<(String, FlattenedFunctionMode)>,
}

impl FlattenedOverload {
    fn function_mode(&self, field_name: &str) -> FlattenedFunctionMode {
        self.function_modes
            .iter()
            .find_map(|(candidate, mode)| (candidate == field_name).then_some(*mode))
            .unwrap_or(FlattenedFunctionMode::String)
    }

    fn has_expression_functions(&self) -> bool {
        self.function_modes
            .iter()
            .any(|(_, mode)| matches!(mode, FlattenedFunctionMode::Expression))
    }
}

fn flattened_overloads(model: &PlannedModel) -> Vec<FlattenedOverload> {
    let function_fields = model
        .public_fields()
        .filter(|(_, field)| field.function.is_some())
        .collect::<Vec<_>>();
    if function_fields.is_empty() {
        return vec![FlattenedOverload {
            function_modes: Vec::new(),
        }];
    }
    (0..(1usize << function_fields.len()))
        .map(|mask| FlattenedOverload {
            function_modes: function_fields
                .iter()
                .enumerate()
                .map(|(index, (field_name, _))| {
                    let mode = if mask & (1usize << index) == 0 {
                        FlattenedFunctionMode::String
                    } else {
                        FlattenedFunctionMode::Expression
                    };
                    ((*field_name).to_string(), mode)
                })
                .collect(),
        })
        .collect()
}

