fn flattened_method_parameter_docs(
    model: &PlannedModel,
    api_plan: &PlannedSpec,
    overload: &FlattenedOverload,
) -> Vec<(String, String)> {
    let mut params = Vec::new();
    for (field_name, field) in model.public_fields() {
        if field.function.is_none() {
            continue;
        }
        if let Some(nested_model) = flattened_nested_model(field, api_plan) {
            for (_, nested_field) in nested_model.public_fields() {
                if nested_field.function.is_none() {
                    continue;
                }
                push_field_parameter_doc(&mut params, nested_field);
            }
            continue;
        }
        push_field_parameter_doc(&mut params, field);
        if matches!(
            overload.function_mode(field_name),
            FlattenedFunctionMode::String
        ) {
            push_function_args_parameter_docs(&mut params, model, field);
        }
    }
    if model_has_options_fields(model, api_plan) {
        params.push((
            "options".to_string(),
            dotnet_doc(model.doc())
                .map(str::to_string)
                .unwrap_or_else(|| "Options for the operation.".to_string()),
        ));
    }
    params
}

fn push_field_parameter_doc(
    params: &mut Vec<(String, String)>,
    field: &RecordFieldSpec<PlannedFamily>,
) {
    params.push((
        csharp_parameter_name(&field.name),
        field
            .doc
            .as_ref()
            .and_then(dotnet_doc)
            .map(str::to_string)
            .unwrap_or_else(|| fallback_parameter_doc(field)),
    ));
}

fn fallback_parameter_doc(field: &RecordFieldSpec<PlannedFamily>) -> String {
    format!("The {} value.", csharp_parameter_name(&field.name))
}

fn push_function_args_parameter_docs(
    params: &mut Vec<(String, String)>,
    model: &PlannedModel,
    function_field: &RecordFieldSpec<PlannedFamily>,
) {
    let Some(function) = &function_field.function else {
        return;
    };
    for arg_field_name in &function.arg_fields {
        let Some(arg_field) = model.fields.get(arg_field_name) else {
            continue;
        };
        push_field_parameter_doc(params, arg_field);
    }
}

