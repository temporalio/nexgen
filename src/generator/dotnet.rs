const GENERATED_HEADER: &str = concat!(
    "// <auto-generated />\n// Generated by nexgen v",
    env!("CARGO_PKG_VERSION"),
    ". DO NOT EDIT!"
);
const GENERATED_CODE_ATTRIBUTE: &str = "[GeneratedCode(\"nexgen\", null)]";
