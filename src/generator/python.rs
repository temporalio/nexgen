fn render_request_only_operation_function(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) {
    let function_name = request_operation_function_name(service, operation);
    let render_request_doc = operation.unpacked_input.is_none();
    if operation.deprecated {
        output.push_str(
            "@typing_extensions.deprecated(\"This operation is deprecated.\", category=None)\n",
        );
    }
    output.push_str("async def ");
    output.push_str(&function_name);
    output.push_str("(\n");
    render_endpoint_parameter(output, service);
    if let Some(input) = &operation.input {
        output.push_str("    request: ");
        output.push_str(&input.annotation);
        output.push_str(",\n");
    }
    if operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result
    {
        output.push_str(") -> ");
        output.push_str(&function_unpacked_implementation_return_annotation(
            service, operation,
        ));
        output.push_str(":\n");
    } else {
        output.push_str(") -> ");
        output.push_str(&temporalio_workflow_type_ref(
            service,
            "NexusOperationHandle",
        ));
        output.push_str("[\n");
        output.push_str("    ");
        output.push_str(&temporalio_workflow_type_annotation(
            service,
            &operation.output_annotation,
        ));
        output.push_str(",\n");
        output.push_str("]:\n");
        if render_request_doc {
            render_operation_docstring(output, operation, &[], None);
        }
        render_temporalio_workflow_runtime_imports(
            output,
            service,
            &temporalio_workflow_operation_runtime_names(service, operation),
            "    ",
        );
        render_inline_nexus_client(output, service, "    ");
        if operation.generic_model_types {
            output.push_str("    return typing.cast(\n");
            output.push_str("        ");
            output.push_str(&temporalio_workflow_type_ref(
                service,
                "NexusOperationHandle",
            ));
            output.push_str("[\n");
            output.push_str("            ");
            output.push_str(&temporalio_workflow_type_annotation(
                service,
                &operation.output_annotation,
            ));
            output.push_str(",\n");
            output.push_str("        ],\n");
            output.push_str("        await nexus_client.start_operation(\n");
        } else {
            output.push_str("    return await nexus_client.start_operation(\n");
        }
        output.push_str("        operation=");
        if operation.generic_model_types {
            output.push_str("    ");
        }
        output.push_str(&python_string_literal(operation.wire_name));
        output.push_str(",\n");
        output.push_str("        ");
        if operation.generic_model_types {
            output.push_str("    ");
        }
        output.push_str("input=");
        output.push_str(operation_input_wire_expr(operation));
        output.push_str(",\n");
        if !operation.output_none {
            output.push_str("        ");
            if operation.generic_model_types {
                output.push_str("    ");
            }
            output.push_str("output_type=");
            output.push_str(&operation.output_type_expr);
            output.push_str(",\n");
        }
        if operation.generic_model_types {
            output.push_str("        ),\n");
            output.push_str("    )\n");
        } else {
            output.push_str("    )\n");
        }
        return;
    }

    if render_request_doc {
        render_operation_docstring(output, operation, &[], None);
    }

    render_temporalio_workflow_runtime_imports(
        output,
        service,
        &temporalio_workflow_operation_runtime_names(service, operation),
        "    ",
    );

    if operation.output_direct_result {
        render_inline_nexus_client(output, service, "    ");
        output.push_str("    handle = await nexus_client.start_operation(\n");
        output.push_str("        operation=");
        output.push_str(&python_string_literal(operation.wire_name));
        output.push_str(",\n");
        output.push_str("        ");
        output.push_str("input=");
        output.push_str(operation_input_wire_expr(operation));
        output.push_str(",\n");
        output.push_str("        output_type=");
        output.push_str(&operation.output_type_expr);
        output.push_str(",\n");
        output.push_str("    )\n");
        if service.endpoint.is_none()
            && operation.output_module_path.as_deref() == Some("._resources")
        {
            output.push_str("    resource = await handle\n");
            output.push_str("    setattr(resource, \"_endpoint\", endpoint)\n");
            output.push_str("    return resource\n");
        } else {
            output.push_str("    return await handle\n");
        }
        return;
    }

    render_inline_nexus_client(output, service, "    ");
    output.push_str("    handle = await nexus_client.start_operation(\n");
    output.push_str("        operation=");
    output.push_str(&python_string_literal(operation.wire_name));
    output.push_str(",\n");
    output.push_str("        input=");
    output.push_str(operation_input_wire_expr(operation));
    output.push_str(",\n");
    if !operation.output_none {
        output.push_str("        output_type=");
        output.push_str(&operation.output_type_expr);
        output.push_str(",\n");
    }
    output.push_str("    )\n");
    if let Some(transform_expr) = &operation.output_transform_expr {
        output.push_str("    result = await handle\n");
        output.push_str("    return ");
        output.push_str(&temporalio_workflow_value_expr(service, transform_expr));
        output.push('\n');
    } else if let Some(resource_return) = &operation.output_resource_return {
        output.push_str("    result = await handle\n");
        if service.endpoint.is_none() {
            output.push_str("    resource = ");
        } else {
            output.push_str("    return ");
        }
        output.push_str(&resource_return.resource_type_name);
        output.push_str("(\n");
        for binding in &resource_return.bindings {
            output.push_str("        ");
            output.push_str(&python_field_name(&binding.field_name));
            output.push('=');
            output.push_str(&resource_return_binding_expr_python(binding));
            output.push_str(",\n");
        }
        output.push_str("    )\n");
        if service.endpoint.is_none() {
            output.push_str("    setattr(resource, \"_endpoint\", endpoint)\n");
            output.push_str("    return resource\n");
        }
    }
}

fn render_unpacked_operation_docstring(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
    primary_function: Option<&RenderedFunctionField>,
) {
    let mut args = Vec::<(String, String)>::new();
    for field in &unpacked_input.parameters {
        if let Some(function) = primary_function
            && field.attr_name == function.callable_field_name
        {
            if let Some(doc) = &field.doc {
                args.push((field.attr_name.clone(), doc.clone()));
            }
            if let Some(parameters) = python_function_fixed_positional_args(function) {
                for parameter in parameters {
                    args.push((
                        parameter.name.clone(),
                        format!("Argument for {}.", function.callable_field_name),
                    ));
                }
            } else {
                args.push((
                    "positional_args".to_string(),
                    format!(
                        "Positional arguments for {}. Cannot be set if args is set.",
                        function.callable_field_name
                    ),
                ));
            }
            continue;
        }

        if let Some(function) = unpacked_input
            .functions
            .iter()
            .find(|function| function.args_field_name == field.attr_name)
        {
            let generated_doc = if function.primary {
                match &function.args {
                    RenderedFunctionArgs::Varargs { .. } => format!(
                        "List-form arguments for {}. Cannot be set if positional_args are set. \
                        For typed {} callables, list contents are not statically typechecked; \
                        pass {} arguments positionally for precise typechecking.",
                        function.callable_field_name,
                        function.callable_field_name,
                        function.callable_field_name
                    ),
                    _ => format!(
                        "List-form arguments for {}. Cannot be set if positional_args are set.",
                        function.callable_field_name
                    ),
                }
            } else {
                match &function.args {
                    RenderedFunctionArgs::Varargs { .. } => format!(
                        "Argument value, or list of argument values, for {}. For typed \
                        single-argument signals, scalar signal_args values are statically \
                        typechecked. List-form signal_args values are not precisely typechecked. \
                        To pass a single signal argument that is itself a list, wrap it in \
                        another list; otherwise the list is interpreted as multiple signal \
                        arguments.",
                        function.callable_field_name
                    ),
                    _ => format!(
                        "Argument value, or list of argument values, for {}. To pass a single \
                        argument that is itself a list, wrap it in another list; otherwise the \
                        list is interpreted as multiple arguments.",
                        function.callable_field_name
                    ),
                }
            };
            args.push((field.attr_name.clone(), generated_doc));
            continue;
        }

        if let Some(doc) = &field.doc
            && !python_field_doc_rendered_as_function_arg(unpacked_input, &field.attr_name)
        {
            args.push((field.attr_name.clone(), doc.clone()));
        }
    }

    render_operation_docstring(output, operation, &args, operation.return_doc.as_deref());
}

fn python_field_doc_rendered_as_function_arg(
    unpacked_input: &RenderedUnpackedInput,
    field_name: &str,
) -> bool {
    unpacked_input.functions.iter().any(|function| {
        python_function_fixed_positional_args(function).is_some_and(|parameters| {
            parameters
                .iter()
                .any(|parameter| parameter.name == field_name)
        })
    })
}

fn render_operation_docstring(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    args: &[(String, String)],
    returns: Option<&str>,
) {
    render_python_docstring(
        output,
        "    ",
        operation.doc.as_deref(),
        args,
        returns,
        operation.experimental,
    );
}

pub(in crate::generator) fn render_python_docstring(
    output: &mut String,
    indent: &str,
    summary: Option<&str>,
    args: &[(String, String)],
    returns: Option<&str>,
    experimental: bool,
) {
    let mut lines = Vec::<String>::new();
    let docstring_width = PYTHON_FORMAT_LINE_LENGTH.saturating_sub(indent.chars().count());
    let has_summary = summary.is_some_and(|summary| !summary.trim().is_empty());
    if let Some(summary) = summary.map(str::trim).filter(|summary| !summary.is_empty()) {
        for line in summary.lines() {
            push_wrapped_python_docstring_line(&mut lines, "", "", line.trim(), docstring_width);
        }
    }
    if experimental {
        if !lines.is_empty() {
            lines.push(String::new());
        }
        lines.push(".. warning::".to_string());
        push_wrapped_python_docstring_line(
            &mut lines,
            "    ",
            "    ",
            EXPERIMENTAL_WARNING,
            docstring_width,
        );
    }
    if !args.is_empty() {
        if !lines.is_empty() {
            lines.push(String::new());
        }
        lines.push("Args:".to_string());
        for (name, doc) in args {
            let mut doc_lines = doc.trim().lines();
            let first_prefix = format!("    {name}: ");
            let continuation_prefix = "        ";
            let first = doc_lines.next().unwrap_or_default().trim();
            push_wrapped_python_docstring_line(
                &mut lines,
                &first_prefix,
                continuation_prefix,
                first,
                docstring_width,
            );
            for line in doc_lines {
                push_wrapped_python_docstring_line(
                    &mut lines,
                    continuation_prefix,
                    continuation_prefix,
                    line.trim(),
                    docstring_width,
                );
            }
        }
    }
    if let Some(returns) = returns.map(str::trim).filter(|returns| !returns.is_empty()) {
        if !lines.is_empty() {
            lines.push(String::new());
        }
        lines.push("Returns:".to_string());
        let mut return_lines = returns.lines();
        if let Some(first) = return_lines.next() {
            push_wrapped_python_docstring_line(
                &mut lines,
                "    ",
                "    ",
                first.trim(),
                docstring_width,
            );
        }
        for line in return_lines {
            push_wrapped_python_docstring_line(
                &mut lines,
                "    ",
                "    ",
                line.trim(),
                docstring_width,
            );
        }
    }
    if lines.is_empty() {
        return;
    }

    output.push_str(indent);
    output.push_str("\"\"\"");
    if !has_summary {
        output.push('\n');
        for line in &lines {
            if !line.is_empty() {
                output.push_str(indent);
                output.push_str(&python_docstring_literal_text(line));
            }
            output.push('\n');
        }
        output.push_str(indent);
        output.push_str("\"\"\"\n");
        return;
    }
    if lines.len() == 1 {
        output.push_str(&python_docstring_literal_text(&lines[0]));
        output.push_str("\"\"\"\n");
        return;
    }

    output.push_str(&python_docstring_literal_text(&lines[0]));
    output.push('\n');
    for line in lines.iter().skip(1) {
        if !line.is_empty() {
            output.push_str(indent);
            output.push_str(&python_docstring_literal_text(line));
        }
        output.push('\n');
    }
    output.push_str(indent);
    output.push_str("\"\"\"\n");
}

fn push_wrapped_python_docstring_line(
    lines: &mut Vec<String>,
    first_prefix: &str,
    continuation_prefix: &str,
    text: &str,
    max_width: usize,
) {
    if text.is_empty() {
        lines.push(first_prefix.trim_end().to_string());
        return;
    }

    let mut prefix = first_prefix;
    let mut current = String::new();
    for word in text.split_whitespace() {
        let prefix_width = prefix.chars().count();
        let current_width = current.chars().count();
        let word_width = word.chars().count();
        let separator_width = usize::from(!current.is_empty());
        if current_width > 0
            && prefix_width + current_width + separator_width + word_width > max_width
        {
            lines.push(format!("{prefix}{current}"));
            prefix = continuation_prefix;
            current.clear();
        }
        if !current.is_empty() {
            current.push(' ');
        }
        current.push_str(word);
    }

    lines.push(format!("{prefix}{current}"));
}

fn python_docstring_literal_text(value: &str) -> String {
    value
        .replace('\\', "\\\\")
        .replace("\"\"\"", "\\\"\\\"\\\"")
}

fn render_unpacked_operation_function(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
) {
    if !unpacked_input.functions.is_empty() {
        render_function_unpacked_implementation(output, service, operation, unpacked_input);
        return;
    }

    if operation.deprecated {
        output.push_str(
            "@typing_extensions.deprecated(\"This operation is deprecated.\", category=None)\n",
        );
    }
    output.push_str("async def ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    render_endpoint_parameter(output, service);
    output.push_str("    *,\n");
    for field in &unpacked_input.parameters {
        output.push_str("    ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        output.push_str(&python_parameter_annotation(
            &field.annotation,
            &field.default_kind,
        ));
        if let Some(default_expr) = python_parameter_default_expr(&field.default_kind) {
            render_python_default_expr(output, &default_expr, "    ");
        }
        output.push_str(",\n");
    }
    if operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result
    {
        output.push_str(") -> ");
        output.push_str(&function_unpacked_implementation_return_annotation(
            service, operation,
        ));
        output.push_str(":\n");
    } else {
        output.push_str(") -> ");
        output.push_str(&temporalio_workflow_type_ref(
            service,
            "NexusOperationHandle",
        ));
        output.push_str("[\n");
        output.push_str("    ");
        output.push_str(&function_unpacked_implementation_return_annotation(
            service, operation,
        ));
        output.push_str(",\n");
        output.push_str("]:\n");
    }
    render_unpacked_operation_docstring(output, operation, unpacked_input, None);
    for flattened_message in &unpacked_input.flattened_messages {
        render_flattened_message_setup(output, flattened_message);
    }
    output.push_str("    request = ");
    output.push_str(&unpacked_input.model_name);
    output.push_str("(\n");
    for field in &unpacked_input.request_fields {
        output.push_str("        ");
        output.push_str(&field.attr_name);
        output.push('=');
        output.push_str(&unpacked_request_field_value_expr(field));
        output.push_str(",\n");
    }
    output.push_str("    )\n");
    output.push_str("    return await ");
    output.push_str(&request_operation_function_name(service, operation));
    output.push('(');
    output.push_str(endpoint_forward_args(service));
    output.push_str(")\n");
}

fn function_unpacked_implementation_return_annotation(
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) -> String {
    let output_annotation = erase_python_type_parameters_with_replacement(
        &operation.overload_output_annotation,
        &operation.output_type_parameters,
        "typing.Any",
    );
    temporalio_workflow_type_annotation(service, &output_annotation)
}

fn operation_public_return_annotation(
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) -> String {
    let output_annotation = function_unpacked_implementation_return_annotation(service, operation);
    if operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result
    {
        output_annotation
    } else {
        format!(
            "{}[{output_annotation}]",
            temporalio_workflow_type_ref(service, "NexusOperationHandle")
        )
    }
}

fn render_function_unpacked_implementation(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
) {
    if operation.deprecated {
        output.push_str(
            "@typing_extensions.deprecated(\"This operation is deprecated.\", category=None)\n",
        );
    }
    output.push_str("async def ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    render_endpoint_parameter(output, service);

    let primary_function = primary_function(&unpacked_input.functions);
    if let Some(function) = primary_function {
        output.push_str("    ");
        output.push_str(&function.callable_field_name);
        output.push_str(": ");
        output.push_str(&function.callable_annotation);
        output.push_str(",\n");
        if let Some(parameters) = python_function_fixed_positional_args(function) {
            for parameter in parameters {
                output.push_str("    ");
                output.push_str(&parameter.name);
                output.push_str(": ");
                output.push_str(&parameter.annotation);
                output.push_str(",\n");
            }
        } else {
            output.push_str("    *positional_args: ");
            output.push_str(&python_function_positional_args_annotation(function));
            output.push_str(",\n");
        }
    }

    let has_keyword_only_parameters = unpacked_input
        .parameters
        .iter()
        .any(|field| rendered_function_implementation_renders_field(field, primary_function));
    if primary_function.is_none()
        || (primary_function
            .and_then(python_function_fixed_positional_args)
            .is_some()
            && has_keyword_only_parameters)
    {
        output.push_str("    *,\n");
    }

    for field in &unpacked_input.parameters {
        if !rendered_function_implementation_renders_field(field, primary_function) {
            continue;
        }
        output.push_str("    ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        if let Some(function) = unpacked_input
            .functions
            .iter()
            .find(|function| function.callable_field_name == field.attr_name)
        {
            output.push_str(&function.callable_annotation);
        } else if unpacked_input
            .functions
            .iter()
            .any(|function| function.args_field_name == field.attr_name)
        {
            let function = unpacked_input
                .functions
                .iter()
                .find(|function| function.args_field_name == field.attr_name)
                .expect("function args field should have a function");
            let primary_args = primary_function
                .is_some_and(|function| function.args_field_name == field.attr_name);
            output.push_str(&python_function_args_parameter_annotation(
                function,
                primary_args,
            ));
        } else {
            output.push_str(&python_parameter_annotation(
                &field.annotation,
                &field.default_kind,
            ));
        }
        if let Some(default_expr) = python_parameter_default_expr(&field.default_kind) {
            render_python_default_expr(output, &default_expr, "    ");
        }
        output.push_str(",\n");
    }

    if operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result
    {
        output.push_str(") -> ");
        output.push_str(&function_unpacked_implementation_return_annotation(
            service, operation,
        ));
        output.push_str(":\n");
    } else {
        output.push_str(") -> ");
        output.push_str(&temporalio_workflow_type_ref(
            service,
            "NexusOperationHandle",
        ));
        output.push_str("[\n");
        output.push_str("    ");
        output.push_str(&function_unpacked_implementation_return_annotation(
            service, operation,
        ));
        output.push_str(",\n");
        output.push_str("]:\n");
    }
    render_unpacked_operation_docstring(output, operation, unpacked_input, primary_function);

    for function in &unpacked_input.functions {
        if function.primary && matches!(function.args, RenderedFunctionArgs::Typed { .. }) {
            continue;
        }
        let normalized_args_name = format!("normalized_{}", function.args_field_name);
        if function.primary {
            output.push_str("    if positional_args and ");
            output.push_str(&function.args_field_name);
            output.push_str(" is not None:\n");
            output.push_str(
                "        raise TypeError(\"cannot specify both positional arguments and ",
            );
            output.push_str(&function.args_field_name);
            output.push_str("\")\n");
            output.push_str("    ");
            output.push_str(&normalized_args_name);
            output.push_str(": ");
            output.push_str(&python_function_normalized_args_annotation(function));
            output.push_str(" | None = (\n");
            output.push_str("        list(positional_args)\n");
            output.push_str("        if positional_args\n");
            output.push_str("        else ");
            output.push_str(&function.args_field_name);
            output.push('\n');
            output.push_str("    )\n");
        } else {
            output.push_str("    ");
            output.push_str(&normalized_args_name);
            output.push_str(": ");
            output.push_str(&python_function_normalized_args_annotation(function));
            output.push_str(" | None\n");
            output.push_str("    if ");
            output.push_str(&function.args_field_name);
            output.push_str(" is None:\n");
            output.push_str("        ");
            output.push_str(&normalized_args_name);
            output.push_str(" = None\n");
            output.push_str("    elif isinstance(");
            output.push_str(&function.args_field_name);
            output.push_str(", list):\n");
            output.push_str("        ");
            output.push_str(&normalized_args_name);
            match &function.args {
                RenderedFunctionArgs::Varargs { .. } => {
                    output.push_str(" = typing.cast(list[typing.Any], ");
                    output.push_str(&function.args_field_name);
                    output.push_str(")\n");
                }
                _ => {
                    output.push_str(" = ");
                    output.push_str(&function.args_field_name);
                    output.push('\n');
                }
            }
            output.push_str("    else:\n");
            output.push_str("        ");
            output.push_str(&normalized_args_name);
            output.push_str(" = [");
            output.push_str(&function.args_field_name);
            output.push_str("]\n");
        }
    }
    for flattened_message in &unpacked_input.flattened_messages {
        render_flattened_message_setup(output, flattened_message);
    }

    output.push_str("    request = ");
    output.push_str(&unpacked_input.model_name);
    output.push_str("(\n");
    for field in &unpacked_input.request_fields {
        let value_expr = unpacked_input
            .functions
            .iter()
            .find(|function| function.args_field_name == field.value_expr)
            .map(|function| format!("normalized_{}", function.args_field_name))
            .unwrap_or_else(|| unpacked_request_field_value_expr(field));
        output.push_str("        ");
        output.push_str(&field.attr_name);
        output.push('=');
        output.push_str(&value_expr);
        output.push_str(",\n");
    }
    output.push_str("    )\n");
    output.push_str("    return await ");
    output.push_str(&request_operation_function_name(service, operation));
    output.push('(');
    output.push_str(endpoint_forward_args(service));
    output.push_str(")\n");
}

fn rendered_function_implementation_renders_field(
    field: &RenderedUnpackedInputField,
    primary_function: Option<&RenderedFunctionField>,
) -> bool {
    if primary_function.is_some_and(|function| function.callable_field_name == field.attr_name) {
        return false;
    }
    if primary_function
        .and_then(python_function_fixed_positional_args)
        .is_some_and(|parameters| {
            parameters
                .iter()
                .any(|parameter| parameter.name == field.attr_name)
        })
    {
        return false;
    }
    true
}

fn render_flattened_message_setup(
    output: &mut String,
    flattened_message: &RenderedFlattenedMessage,
) {
    let always_construct = flattened_message.required
        || flattened_message
            .fields
            .iter()
            .any(|field| field.default_kind == PythonFieldDefaultKind::Required);

    output.push_str("    ");
    output.push_str(&flattened_message.local_name);
    output.push_str(" = ");
    if always_construct {
        output.push_str(&flattened_message.model_name);
        output.push_str("(\n");
        for field in &flattened_message.fields {
            output.push_str("        ");
            output.push_str(&field.attr_name);
            output.push('=');
            output.push_str(&field.value_expr);
            output.push_str(",\n");
        }
        output.push_str("    )\n");
        return;
    }

    output.push_str("(\n");
    output.push_str("        None\n");
    output.push_str("        if ");
    for (index, field) in flattened_message.fields.iter().enumerate() {
        if index > 0 {
            output.push_str(" and ");
        }
        output.push_str(&field.value_expr);
        output.push_str(" is None");
    }
    output.push_str("\n");
    output.push_str("        else ");
    output.push_str(&flattened_message.model_name);
    output.push_str("(\n");
    for field in &flattened_message.fields {
        output.push_str("            ");
        output.push_str(&field.attr_name);
        output.push('=');
        output.push_str(&field.value_expr);
        output.push_str(",\n");
    }
    output.push_str("        )\n");
    output.push_str("    )\n");
}

