pub(in crate::generator) const GENERATED_HEADER: &str = concat!(
    "# Generated by nexgen v",
    env!("CARGO_PKG_VERSION"),
    ". DO NOT EDIT!"
);
const PYTHON_FORMAT_LINE_LENGTH: usize = 88;
