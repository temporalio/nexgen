fn function_type_parameters(
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) -> Vec<PythonTypeParameter> {
    let mut parameters = BTreeSet::new();
    for function in functions {
        for case in function_overload_cases(function, output_type_parameters) {
            parameters.extend(case.type_parameters);
        }
    }
    parameters.into_iter().collect()
}

fn render_function_type_parameter_definitions(
    output: &mut String,
    functions: &[RenderedFunctionField],
    output_type_parameters: &BTreeSet<String>,
) {
    let parameters = function_type_parameters(functions, output_type_parameters);
    if parameters.is_empty() {
        return;
    }

    for parameter in parameters {
        match parameter {
            PythonTypeParameter::TypeVar(name) => {
                output.push_str(&name);
                output.push_str(" = typing.TypeVar(");
                output.push_str(&python_string_literal(&name));
                output.push_str(")\n");
            }
            PythonTypeParameter::TypeVarTuple(name) => {
                output.push_str(&name);
                output.push_str(" = typing_extensions.TypeVarTuple(");
                output.push_str(&python_string_literal(&name));
                output.push_str(")\n");
            }
        }
    }
}

fn render_package_init(
    services: &[RenderedService<'_>],
    model_names: &[String],
    _resource_names: &[String],
    resource_operation_owners: &BTreeMap<String, String>,
    support_names: &[String],
    _api_plan: &PlannedSpec,
    _model_hoists: Option<&PythonModelHoists>,
    root_package_imports: &RootPackageImports,
) -> String {
    let operation_function_names = services
        .iter()
        .filter(|service| service.endpoint.is_some())
        .flat_map(|service| {
            service
                .operations
                .iter()
                .map(|operation| operation.attr_name.clone())
        })
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect::<Vec<_>>();
    let service_object_names = services
        .iter()
        .filter(|service| service.endpoint.is_none())
        .map(endpoint_service_object_name)
        .collect::<Vec<_>>();
    let operation_registry_body = render_operation_registry_body(services);
    let operation_registry_support_names =
        used_python_symbol_imports(&operation_registry_body, support_names);
    let mut output = String::new();
    render_generated_file_header(&mut output);
    output.push('\n');
    render_root_package_imports(&mut output, root_package_imports);
    if !model_names.is_empty() {
        render_named_python_import(&mut output, ".models", model_names);
    }
    if services
        .iter()
        .any(|service| !service.operations.is_empty())
    {
        output.push_str("import collections.abc\n");
        output.push_str("import typing\n");
        output.push_str("\n");
        output.push_str("import nexusrpc\n");
        output.push_str("import temporalio.converter\n");
    }
    if !service_object_names.is_empty() {
        render_named_python_import(&mut output, ".services", &service_object_names);
    }
    if services
        .iter()
        .any(|service| !service.operations.is_empty())
    {
        output.push_str("from . import services as _services\n");
    }
    if !services.is_empty() {
        for service in services {
            for operation in &service.operations {
                let module = if let Some(resource_owner) =
                    resource_operation_owners.get(&operation_key(service.name, operation.name))
                {
                    format!("._resources.{resource_owner}")
                } else {
                    format!(".operations.{}", operation.attr_name)
                };
                if service.endpoint.is_some() {
                    render_named_python_import(
                        &mut output,
                        &module,
                        std::slice::from_ref(&operation.attr_name),
                    );
                }
            }
        }
    }
    if !operation_registry_support_names.is_empty() {
        render_named_python_import(&mut output, "._support", &operation_registry_support_names);
    }
    output.push_str("\n__all__ = [\n");
    for name in root_package_export_names(root_package_imports) {
        output.push_str("    ");
        output.push_str(&python_string_literal(&name));
        output.push_str(",\n");
    }
    for name in model_names {
        output.push_str("    ");
        output.push_str(&python_string_literal(name));
        output.push_str(",\n");
    }
    for name in &service_object_names {
        output.push_str("    ");
        output.push_str(&python_string_literal(name));
        output.push_str(",\n");
    }
    for name in &operation_function_names {
        output.push_str("    ");
        output.push_str(&python_string_literal(name));
        output.push_str(",\n");
    }
    output.push_str("]\n");
    output.push_str(&operation_registry_body);
    output
}

fn render_operation_registry_body(services: &[RenderedService<'_>]) -> String {
    if !services
        .iter()
        .any(|service| !service.operations.is_empty())
    {
        return String::new();
    }

    let mut output = String::new();
    output.push_str("\n\n_InputT = typing.TypeVar(\"_InputT\")\n");
    output.push_str("_OutputT = typing.TypeVar(\"_OutputT\")\n");
    output.push_str(
        "\n\n_SerializationContextFactory = collections.abc.Callable[\n    [_InputT], temporalio.converter.SerializationContext\n]\n",
    );
    output.push_str("\n\nclass _NexusOperationInfo(typing.Generic[_InputT, _OutputT]):\n");
    output.push_str(
        "    def __init__(\n        self,\n        *,\n        operation: nexusrpc.Operation[_InputT, _OutputT],\n        serialization_context: _SerializationContextFactory[_InputT] | None = None,\n    ) -> None:\n",
    );
    output.push_str("        self.operation: nexusrpc.Operation[_InputT, _OutputT] = operation\n");
    output.push_str("        self.serialization_context: _SerializationContextFactory[_InputT] | None = serialization_context\n");
    output.push_str("\n\n__nexus_operation_registry__ = {\n");
    for service in services {
        for operation in &service.operations {
            output.push_str("    (\n");
            output.push_str("        \"");
            output.push_str(service.wire_name);
            output.push_str("\",\n");
            output.push_str("        \"");
            output.push_str(operation.wire_name);
            output.push_str("\",\n");
            output.push_str("    ): _NexusOperationInfo(\n");
            output.push_str("        operation=_services.");
            output.push_str(service.name);
            output.push('.');
            output.push_str(&operation.attr_name);
            output.push_str(",\n");
            if let Some(serialization_context) = &operation.serialization_context_expr {
                output.push_str("        serialization_context=");
                output.push_str(serialization_context);
                output.push_str(",\n");
            }
            output.push_str("    ),\n");
        }
    }
    output.push_str("}\n");
    output
}

fn render_endpoint_service_object(output: &mut String, service: &RenderedService<'_>) {
    if service.deprecated {
        output.push_str(
            "\n@typing_extensions.deprecated(\"This service is deprecated.\", category=None)\n",
        );
    } else {
        output.push('\n');
    }
    output.push_str("class ");
    output.push_str(&endpoint_service_object_name(service));
    output.push_str(":\n");
    output.push_str("    def __init__(self, endpoint: str) -> None:\n");
    output.push_str(
        "        self._nexus_client: typing.Any = temporalio.workflow.create_nexus_client(\n",
    );
    output.push_str("            service=");
    output.push_str(&python_string_literal(service.wire_name));
    output.push_str(",\n");
    output.push_str("            endpoint=endpoint,\n");
    output.push_str("        )\n");
    if service.operations.is_empty() {
        output.push('\n');
        output.push_str("    pass\n");
        return;
    }
    for operation in &service.operations {
        output.push('\n');
        render_endpoint_service_object_operation_method(output, service, operation);
    }
}

fn render_endpoint_service_object_operation_method(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) {
    if let Some(unpacked_input) = &operation.unpacked_input {
        render_endpoint_service_object_unpacked_method(output, service, operation, unpacked_input);
        return;
    }

    if operation.deprecated {
        output.push_str(
            "    @typing_extensions.deprecated(\"This operation is deprecated.\", category=None)\n",
        );
    }
    output.push_str("    async def ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    output.push_str("        self,\n");
    if let Some(input) = &operation.input {
        output.push_str("        request: ");
        output.push_str(&input.annotation);
        output.push_str(",\n");
    }
    output.push_str("    ) -> ");
    output.push_str(&operation_public_return_annotation(service, operation));
    output.push_str(":\n");
    render_endpoint_service_object_operation_body(output, service, operation);
}

fn render_endpoint_service_object_unpacked_method(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    unpacked_input: &RenderedUnpackedInput,
) {
    if operation.deprecated {
        output.push_str(
            "    @typing_extensions.deprecated(\"This operation is deprecated.\", category=None)\n",
        );
    }
    output.push_str("    async def ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    output.push_str("        self,\n");
    output.push_str("        *,\n");
    for field in &unpacked_input.parameters {
        output.push_str("        ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        output.push_str(&python_parameter_annotation(
            &field.annotation,
            &field.default_kind,
        ));
        if let Some(default_expr) = python_parameter_default_expr(&field.default_kind) {
            render_python_default_expr(output, &default_expr, "        ");
        }
        output.push_str(",\n");
    }
    output.push_str("    ) -> ");
    output.push_str(&operation_public_return_annotation(service, operation));
    output.push_str(":\n");
    render_unpacked_operation_docstring(output, operation, unpacked_input, None);
    for flattened_message in &unpacked_input.flattened_messages {
        render_flattened_message_setup(output, flattened_message);
    }
    output.push_str("        request = ");
    output.push_str(&unpacked_input.model_name);
    output.push_str("(\n");
    for field in &unpacked_input.request_fields {
        output.push_str("            ");
        output.push_str(&field.attr_name);
        output.push('=');
        output.push_str(&unpacked_request_field_value_expr(field));
        output.push_str(",\n");
    }
    output.push_str("        )\n");
    render_endpoint_service_object_operation_body(output, service, operation);
}

fn render_endpoint_service_object_operation_body(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) {
    if operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result
    {
        if operation.output_direct_result {
            output.push_str("        handle = await self._nexus_client.start_operation(\n");
            output.push_str("            operation=");
            output.push_str(&python_string_literal(operation.wire_name));
            output.push_str(",\n");
            output.push_str("            input=");
            output.push_str(operation_input_wire_expr(operation));
            output.push_str(",\n");
            output.push_str("            output_type=");
            output.push_str(&operation.output_type_expr);
            output.push_str(",\n");
            output.push_str("        )\n");
            if operation.output_module_path.as_deref() == Some("._resources") {
                output.push_str("        resource = await handle\n");
                if let Some(resource) = service
                    .resources
                    .iter()
                    .find(|resource| resource.type_name == operation.output_annotation)
                {
                    output.push_str("        return ");
                    output.push_str(&resource_client_bind_function_name(resource));
                    output.push_str("(resource, self._nexus_client)\n");
                    return;
                }
                output.push_str("        return resource\n");
            } else {
                output.push_str("        return await handle\n");
            }
            return;
        }

        output.push_str("        handle = await self._nexus_client.start_operation(\n");
        output.push_str("            operation=");
        output.push_str(&python_string_literal(operation.wire_name));
        output.push_str(",\n");
        output.push_str("            input=");
        output.push_str(operation_input_wire_expr(operation));
        output.push_str(",\n");
        if !operation.output_none {
            output.push_str("            output_type=");
            output.push_str(&operation.output_type_expr);
            output.push_str(",\n");
        }
        output.push_str("        )\n");
        if let Some(transform_expr) = &operation.output_transform_expr {
            output.push_str("        result = await handle\n");
            output.push_str("        return ");
            output.push_str(&temporalio_workflow_value_expr(service, transform_expr));
            output.push('\n');
        } else if let Some(resource_return) = &operation.output_resource_return {
            output.push_str("        result = await handle\n");
            output.push_str("        resource = ");
            output.push_str(&resource_return.resource_type_name);
            output.push_str("(\n");
            for binding in &resource_return.bindings {
                output.push_str("            ");
                output.push_str(&python_field_name(&binding.field_name));
                output.push('=');
                output.push_str(&resource_return_binding_expr_python(binding));
                output.push_str(",\n");
            }
            output.push_str("        )\n");
            if let Some(resource) = service
                .resources
                .iter()
                .find(|resource| resource.type_name == resource_return.resource_type_name)
            {
                output.push_str("        return ");
                output.push_str(&resource_client_bind_function_name(resource));
                output.push_str("(resource, self._nexus_client)\n");
            } else {
                output.push_str("        return resource\n");
            }
        }
        return;
    }

    output.push_str("        return await self._nexus_client.start_operation(\n");
    output.push_str("            operation=");
    output.push_str(&python_string_literal(operation.wire_name));
    output.push_str(",\n");
    output.push_str("            input=");
    output.push_str(operation_input_wire_expr(operation));
    output.push_str(",\n");
    if !operation.output_none {
        output.push_str("            output_type=");
        output.push_str(&operation.output_type_expr);
        output.push_str(",\n");
    }
    output.push_str("        )\n");
}

