fn render_model_name_imports_with_indent(
    output: &mut String,
    local_module: &str,
    current_module_path: &ModulePath,
    api_plan: &PlannedSpec,
    names: &[String],
    model_hoists: Option<&PythonModelHoists>,
    indent: &str,
) {
    for (module, names) in model_name_import_groups(
        local_module,
        current_module_path,
        api_plan,
        names,
        model_hoists,
    ) {
        render_named_python_import_with_indent(
            output,
            &module,
            &names.into_iter().collect::<Vec<_>>(),
            indent,
        );
    }
}

fn model_name_import_groups(
    local_module: &str,
    current_module_path: &ModulePath,
    api_plan: &PlannedSpec,
    names: &[String],
    model_hoists: Option<&PythonModelHoists>,
) -> BTreeMap<String, BTreeSet<String>> {
    let foreign_modules = foreign_model_modules_by_name(api_plan);
    let mut imports = BTreeMap::<String, BTreeSet<String>>::new();
    for name in names {
        if let Some(module_path) = foreign_modules.get(name) {
            let module = if model_hoists.is_some_and(|hoists| hoists.is_hoisted(module_path, name))
            {
                root_python_model_hoist_module(current_module_path)
            } else {
                python_relative_models_module(current_module_path, module_path)
            };
            imports.entry(module).or_default().insert(name.clone());
        } else if model_hoists.is_some_and(|hoists| hoists.is_hoisted(&api_plan.module_path, name))
        {
            imports
                .entry(root_python_model_hoist_module(current_module_path))
                .or_default()
                .insert(name.clone());
        } else {
            imports
                .entry(local_module.to_string())
                .or_default()
                .insert(name.clone());
        }
    }
    imports
}

fn foreign_model_modules_by_name(api_plan: &PlannedSpec) -> BTreeMap<String, ModulePath> {
    api_plan
        .data
        .module_imports
        .iter()
        .flat_map(|(module_path, names)| {
            names
                .iter()
                .map(|name| (name.clone(), module_path.clone()))
                .collect::<Vec<_>>()
        })
        .collect()
}

fn render_python_module_model_type_checking_imports(
    output: &mut String,
    api_plan: &PlannedSpec,
    wrote_previous_imports: bool,
) -> bool {
    if api_plan.data.module_imports.is_empty() {
        return false;
    }

    if wrote_previous_imports {
        output.push('\n');
    }
    output.push_str("if typing.TYPE_CHECKING:\n");
    for (module_path, names) in &api_plan.data.module_imports {
        let names = names.iter().cloned().collect::<Vec<_>>();
        render_named_python_import_with_indent(
            output,
            &python_relative_models_module(&api_plan.module_path, module_path),
            &names,
            "    ",
        );
    }
    true
}

fn render_python_module_model_runtime_imports(
    output: &mut String,
    api_plan: &PlannedSpec,
    model_hoists: &PythonModelHoists,
    body: &str,
    wrote_previous_imports: bool,
) -> bool {
    let mut imports = BTreeMap::<String, BTreeSet<String>>::new();
    for (module_path, names) in &api_plan.data.module_imports {
        for name in names {
            if !body_uses_python_symbol(body, name) {
                continue;
            }
            let module = if model_hoists.is_hoisted(module_path, name) {
                root_python_model_hoist_module(&api_plan.module_path)
            } else {
                python_relative_models_module(&api_plan.module_path, module_path)
            };
            imports.entry(module).or_default().insert(name.clone());
        }
    }

    if imports.is_empty() {
        return false;
    }
    if wrote_previous_imports {
        output.push('\n');
    }
    for (module, names) in imports {
        render_named_python_import(output, &module, &names.into_iter().collect::<Vec<_>>());
    }
    true
}

fn root_python_model_hoist_module(module_path: &ModulePath) -> String {
    format!("{}{}", ".".repeat(module_path.0.len() + 1), "_recursive")
}

fn python_relative_models_module(from: &ModulePath, to: &ModulePath) -> String {
    let common = module_common_prefix_len(&from.0, &to.0);
    let dot_count = from.0.len().saturating_sub(common) + 1;
    let mut module = ".".repeat(dot_count);
    let rest = to.0[common..]
        .iter()
        .map(|segment| segment.replace('-', "_"))
        .chain(std::iter::once("models".to_string()))
        .collect::<Vec<_>>();
    module.push_str(&rest.join("."));
    module
}

pub(in crate::generator) fn module_common_prefix_len(left: &[String], right: &[String]) -> usize {
    left.iter()
        .zip(right.iter())
        .take_while(|(left, right)| left == right)
        .count()
}

