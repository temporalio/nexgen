pub(in crate::generator) type RootPackageImports = BTreeMap<String, BTreeSet<String>>;

struct PythonGenerationResult {
    generated_files: GeneratedFiles,
    root_package_imports: RootPackageImports,
}

pub(crate) fn generate(
    tree: &crate::spec::ApiSpecTree<PlannedFamily>,
    support: &crate::SupportFiles,
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    match &tree.root {
        ApiSpecNode::Leaf(leaf) => {
            let support_fragments = support_fragments_for_plan(&leaf.spec, support);
            generate_leaf(&leaf.spec, &support_fragments, mode)
        }
        ApiSpecNode::Branch(branch) => generate_tree(branch, support, mode),
    }
}

fn generate_leaf(
    api_plan: &PlannedSpec,
    support_fragments: &[SupportFragmentSpec],
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    reject_support_namespaces(Language::Python, support_fragments)?;
    let inline_model_rebuilds = api_plan
        .data
        .module_imports
        .values()
        .all(BTreeSet::is_empty);
    let generated =
        ApiPlanner::new(api_plan, inline_model_rebuilds, None)?.build(support_fragments, mode)?;
    Ok(generated.generated_files)
}

fn generate_leaf_with_model_hoists(
    api_plan: &PlannedSpec,
    support_fragments: &[SupportFragmentSpec],
    mode: GenerationMode,
    model_hoists: &PythonModelHoists,
) -> Result<PythonGenerationResult> {
    reject_support_namespaces(Language::Python, support_fragments)?;
    ApiPlanner::new(api_plan, true, Some(model_hoists))?.build(support_fragments, mode)
}

fn generate_tree(
    branch: &ApiSpecBranch<PlannedFamily>,
    support: &crate::SupportFiles,
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    let model_hoists = tree_model_hoists(branch)?;
    let mut files = BTreeMap::new();
    let mut warnings = Vec::new();
    let mut root_package_imports = RootPackageImports::new();
    insert_files(&mut files, render_tree_support_files(branch))?;
    for (path, contents) in model_hoists.files() {
        insert_generated_file(&mut files, path.clone(), contents.clone())?;
    }
    for node in branch.children.values() {
        generate_tree_node(
            node,
            support,
            mode,
            &model_hoists,
            &mut files,
            &mut warnings,
            &mut root_package_imports,
        )?;
    }
    insert_branch_index_file(
        &mut files,
        branch,
        &model_hoists,
        mode,
        &root_package_imports,
    )?;
    Ok(GeneratedFiles {
        layout: crate::generator::GeneratedOutputLayout::Directory,
        files,
        warnings,
    })
}

fn generate_tree_node(
    node: &ApiSpecNode<PlannedFamily>,
    support: &crate::SupportFiles,
    mode: GenerationMode,
    model_hoists: &PythonModelHoists,
    files: &mut BTreeMap<PathBuf, String>,
    warnings: &mut Vec<String>,
    root_package_imports: &mut RootPackageImports,
) -> Result<()> {
    match node {
        ApiSpecNode::Leaf(leaf) => {
            let support_fragments = support_fragments_for_plan(&leaf.spec, support);
            let generated = generate_leaf_with_model_hoists(
                &leaf.spec,
                &support_fragments,
                mode,
                model_hoists,
            )?;
            extend_root_package_imports(root_package_imports, generated.root_package_imports);
            warnings.extend(generated.generated_files.warnings);
            let prefix = leaf.module_path.to_path_buf();
            for (path, contents) in generated.generated_files.files {
                insert_generated_file(files, prefix.join(path), contents)?;
            }
            Ok(())
        }
        ApiSpecNode::Branch(branch) => {
            insert_branch_index_file(
                files,
                branch,
                model_hoists,
                mode,
                &RootPackageImports::new(),
            )?;
            for node in branch.children.values() {
                generate_tree_node(
                    node,
                    support,
                    mode,
                    model_hoists,
                    files,
                    warnings,
                    root_package_imports,
                )?;
            }
            Ok(())
        }
    }
}

fn insert_files(
    files: &mut BTreeMap<PathBuf, String>,
    generated: BTreeMap<PathBuf, String>,
) -> Result<()> {
    for (path, contents) in generated {
        insert_generated_file(files, path, contents)?;
    }
    Ok(())
}

fn insert_generated_file(
    files: &mut BTreeMap<PathBuf, String>,
    path: impl Into<PathBuf>,
    contents: String,
) -> Result<()> {
    let path = path.into();
    if files.insert(path.clone(), contents).is_some() {
        return Err(Error::GeneratedFileConflict { path });
    }
    Ok(())
}

fn insert_branch_index_file(
    files: &mut BTreeMap<PathBuf, String>,
    branch: &ApiSpecBranch<PlannedFamily>,
    model_hoists: &PythonModelHoists,
    mode: GenerationMode,
    root_package_imports: &RootPackageImports,
) -> Result<()> {
    let mut path = branch.module_path.to_path_buf();
    path.push("__init__.py");
    let mut contents = String::from(GENERATED_HEADER);
    contents.push_str("\n\n");
    let mut wrote_import = false;
    if !root_package_imports.is_empty() {
        render_root_package_imports(&mut contents, root_package_imports);
        wrote_import = true;
    }
    for (name, node) in &branch.children {
        let module_name = name.replace('-', "_");
        let names = node_export_names(node, model_hoists, mode)
            .into_iter()
            .collect::<Vec<_>>();
        if names.is_empty() {
            continue;
        }
        render_named_python_import(&mut contents, &format!(".{module_name}"), &names);
        wrote_import = true;
    }
    if branch.module_path.is_root() && !model_hoists.is_empty() {
        if wrote_import {
            contents.push('\n');
        }
        render_named_python_import(
            &mut contents,
            "._recursive",
            &model_hoists
                .exported_names()
                .iter()
                .cloned()
                .collect::<Vec<_>>(),
        );
    }
    let mut export_names = branch_export_names(branch, model_hoists, mode);
    export_names.extend(root_package_export_names(root_package_imports));
    if !export_names.is_empty() {
        contents.push_str("\n__all__ = [\n");
        for name in export_names {
            contents.push_str("    ");
            contents.push_str(&python_string_literal(&name));
            contents.push_str(",\n");
        }
        contents.push_str("]\n");
    }
    insert_generated_file(files, path, contents)
}

fn node_export_names(
    node: &ApiSpecNode<PlannedFamily>,
    model_hoists: &PythonModelHoists,
    mode: GenerationMode,
) -> BTreeSet<String> {
    match node {
        ApiSpecNode::Leaf(leaf) => leaf_export_names(&leaf.spec, model_hoists, mode),
        ApiSpecNode::Branch(branch) => branch_export_names(branch, model_hoists, mode),
    }
}

fn branch_export_names(
    branch: &ApiSpecBranch<PlannedFamily>,
    model_hoists: &PythonModelHoists,
    mode: GenerationMode,
) -> BTreeSet<String> {
    let mut names = BTreeSet::new();
    for node in branch.children.values() {
        match node {
            ApiSpecNode::Leaf(leaf) => {
                names.extend(leaf_export_names(&leaf.spec, model_hoists, mode));
            }
            ApiSpecNode::Branch(branch) => {
                names.extend(branch_export_names(branch, model_hoists, mode));
            }
        }
    }
    if branch.module_path.is_root() {
        names.extend(model_hoists.exported_names().iter().cloned());
    }
    names
}

fn leaf_export_names(
    plan: &PlannedSpec,
    model_hoists: &PythonModelHoists,
    mode: GenerationMode,
) -> BTreeSet<String> {
    let mut model_names = plan
        .enums()
        .map(|(_, enumeration)| enumeration.name.clone())
        .chain(plan.flags().map(|(_, flag_set)| flag_set.name.clone()))
        .chain(plan.variants().map(|(_, variant)| variant.name.clone()))
        .chain(plan.external_types().filter_map(|(_, binding)| {
            let ExternalTypeSpec::Json(json_type) = &binding.external_type else {
                return None;
            };
            if model_hoists.is_hoisted(&plan.module_path, &json_type.model_name) {
                return None;
            }
            Some(json_type.model_name.clone())
        }))
        .collect::<BTreeSet<_>>();
    model_names.extend(planned_module_export_model_names(plan));

    match mode {
        GenerationMode::DefinitionsOnly => {
            model_names.extend(plan.services.iter().map(|service| {
                service
                    .code_name
                    .for_language(Language::Python)
                    .map(str::to_string)
                    .unwrap_or_else(|| service.name.clone())
            }));
            model_names
        }
        GenerationMode::NativeApi => {
            model_names.extend(
                plan.services
                    .iter()
                    .filter(|service| service.endpoint.is_none())
                    .map(|service| {
                        format!(
                            "{}Client",
                            service
                                .code_name
                                .for_language(Language::Python)
                                .unwrap_or(&service.name)
                        )
                    }),
            );
            model_names.extend(
                plan.services
                    .iter()
                    .filter(|service| service.endpoint.is_some())
                    .flat_map(|service| {
                        service.operations.iter().map(|operation| {
                            operation
                                .code_name
                                .for_language(Language::Python)
                                .map(str::to_string)
                                .unwrap_or_else(|| python_ident(&operation.name.to_snake_case()))
                        })
                    }),
            );
            model_names
        }
    }
}

fn planned_module_export_model_names(plan: &PlannedSpec) -> BTreeSet<String> {
    plan.types
        .values()
        .filter(|entry| entry.is_module_export())
        .filter_map(|entry| match &entry.declaration {
            TypeDeclSpec::Record(record) => Some(record.name.clone()),
            TypeDeclSpec::Enum(enumeration) => Some(enumeration.name.clone()),
            TypeDeclSpec::Flags(flags) => Some(flags.name.clone()),
            TypeDeclSpec::Variant(variant) => Some(variant.name.clone()),
            TypeDeclSpec::External(_) => None,
        })
        .collect()
}

fn support_fragments_for_plan(
    plan: &PlannedSpec,
    support: &crate::SupportFiles,
) -> Vec<SupportFragmentSpec> {
    if support.fragments.is_empty() {
        plan.support
            .fragments_for_language(Language::Python)
            .to_vec()
    } else {
        support.fragments.clone()
    }
}

struct ApiPlanner<'a> {
    api_plan: &'a PlannedSpec,
    inline_model_rebuilds: bool,
    model_hoists: Option<&'a PythonModelHoists>,
    external_models: PythonExternalModels,
    language_imports: Vec<LanguageImportSpec>,
    enums: IndexMap<String, RenderedEnum>,
    flags: IndexMap<String, RenderedFlags>,
    variants: IndexMap<String, RenderedVariant>,
    models: IndexMap<String, RenderedModel>,
}

#[derive(Debug, Default)]
struct PythonExternalModels {
    proto: python_proto::ModelBackend,
    json: python_json::ModelBackend,
}

impl PythonExternalModels {
    fn new(api_plan: &PlannedSpec) -> Result<Self> {
        let mut this = Self::default();
        this.prepare(api_plan)?;
        Ok(this)
    }

    fn new_with_hoists(api_plan: &PlannedSpec, hoists: &PythonModelHoists) -> Result<Self> {
        let mut this = Self::default();
        this.proto.prepare(api_plan)?;
        this.json.prepare_with_hoists(api_plan, hoists)?;
        Ok(this)
    }

    fn render_model_fragments(
        &self,
        models: &[&RenderedModel],
        api_plan: &PlannedSpec,
    ) -> Result<RenderedModelFragments> {
        let mut fragments = RenderedModelFragments::default();
        fragments.extend(render_record_models(models, api_plan, self)?);
        fragments.extend(self.json.render_models()?);
        Ok(fragments)
    }

    fn render_support_files(&self) -> Result<BTreeMap<PathBuf, String>> {
        let mut files = BTreeMap::new();
        files.extend(self.json.render_support_files()?);
        Ok(files)
    }

    fn service_model_ref(
        &self,
        model_type: &PlannedType,
        native_module: &str,
        api_plan: &PlannedSpec,
    ) -> (String, Option<String>) {
        match model_type {
            PlannedType::External(ExternalTypeSpec::Proto(_)) => {
                if let Some(conversion) = self.proto.wire_conversion(model_type, None) {
                    return (
                        conversion.annotation.clone(),
                        python_qualified_module_paths(&conversion.annotation)
                            .into_iter()
                            .next(),
                    );
                }
                let reference = self
                    .proto
                    .service_wire_model_ref(model_type)
                    .expect("proto wire model ref should exist");
                (reference.type_ref, Some(reference.module_path))
            }
            PlannedType::External(ExternalTypeSpec::Json(json_type)) => {
                let type_name = self
                    .json
                    .model_type_annotation(json_type)
                    .expect("json model annotation should exist");
                if self.json.is_hoisted(json_type) {
                    (
                        type_name,
                        Some(root_python_model_hoist_module(&api_plan.module_path)),
                    )
                } else {
                    (
                        format!("{native_module}.{type_name}"),
                        Some(format!(".{native_module}")),
                    )
                }
            }
            PlannedType::Record(record) => (
                format!("{native_module}.{}", record.model_name),
                Some(format!(".{native_module}")),
            ),
            _ => panic!("operation service ref should be model-shaped"),
        }
    }

    fn resolved_external_field_type(&self, value_type: &PlannedType) -> Option<ResolvedFieldType> {
        match value_type {
            PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(_))) => {
                self.proto.enum_field_type(value_type)
            }
            PlannedType::External(ExternalTypeSpec::Json(_)) => {
                let conversion = self.wire_conversion(value_type, None)?;
                Some(ResolvedFieldType {
                    annotation: conversion.annotation.clone(),
                    imports: conversion.imports.clone(),
                    kind: ResolvedFieldKind::Scalar,
                    wire_conversion: Some(conversion),
                })
            }
            _ => None,
        }
    }

    fn render_record_wire_block(
        &self,
        api_plan: &PlannedSpec,
        model: &RenderedModel,
        planned_model: &RecordSpec<PlannedFamily>,
    ) -> Result<Option<RenderedRecordWireBlock>> {
        self.proto
            .render_record_wire_block(api_plan, model, planned_model, &|value_type| {
                resolve_python_value_type(api_plan, self, value_type)
            })
    }
}

impl ExternalModelBackend for PythonExternalModels {
    type ModelFragments = RenderedModelFragments;
    type WireConversion = WireValueConversion;

    fn prepare(&mut self, api_plan: &PlannedSpec) -> Result<()> {
        self.proto.prepare(api_plan)?;
        self.json.prepare(api_plan)
    }

    fn render_models(&self) -> Result<RenderedModelFragments> {
        self.json.render_models()
    }

    fn model_type_annotation(&self, model_type: &PlannedType) -> Option<String> {
        match model_type {
            PlannedType::External(ExternalTypeSpec::Proto(_)) | PlannedType::Record(_) => {
                if let Some(conversion) = self.proto.wire_conversion(model_type, None) {
                    return Some(conversion.annotation);
                }
                self.proto.model_type_annotation(model_type)
            }
            PlannedType::External(ExternalTypeSpec::Json(json_type)) => {
                self.json.model_type_annotation(json_type)
            }
            _ => None,
        }
    }

    fn wire_type_identifier(&self, model_type: &PlannedType) -> Option<String> {
        match model_type {
            PlannedType::External(ExternalTypeSpec::Proto(_)) | PlannedType::Record(_) => {
                self.proto.wire_type_identifier(model_type)
            }
            PlannedType::External(ExternalTypeSpec::Json(json_type)) => {
                self.json.wire_type_identifier(json_type)
            }
            _ => None,
        }
    }

    fn wire_conversion(
        &self,
        model_type: &PlannedType,
        planned_record: Option<&RecordSpec<PlannedFamily>>,
    ) -> Option<WireValueConversion> {
        match model_type {
            PlannedType::External(ExternalTypeSpec::Proto(_)) | PlannedType::Record(_) => {
                self.proto.wire_conversion(model_type, planned_record)
            }
            PlannedType::External(ExternalTypeSpec::Json(json_type)) => {
                self.json.wire_conversion(json_type, planned_record)
            }
            _ => None,
        }
    }
}

impl<'a> ApiPlanner<'a> {
    fn new(
        api_plan: &'a PlannedSpec,
        inline_model_rebuilds: bool,
        model_hoists: Option<&'a PythonModelHoists>,
    ) -> Result<Self> {
        let external_models = if let Some(model_hoists) = model_hoists {
            PythonExternalModels::new_with_hoists(api_plan, model_hoists)?
        } else {
            PythonExternalModels::new(api_plan)?
        };
        Ok(Self {
            api_plan,
            inline_model_rebuilds,
            model_hoists,
            external_models,
            language_imports: collect_python_language_imports(api_plan),
            enums: IndexMap::new(),
            flags: IndexMap::new(),
            variants: IndexMap::new(),
            models: IndexMap::new(),
        })
    }

    fn build(
        mut self,
        support_fragments: &[SupportFragmentSpec],
        mode: GenerationMode,
    ) -> Result<PythonGenerationResult> {
        let api_plan = self.api_plan;
        let services = api_plan
            .services
            .iter()
            .map(|service| {
                let operations = service
                    .operations
                    .iter()
                    .map(|operation| self.resolve_operation(operation))
                    .collect::<Result<Vec<_>>>()?;

                Ok(RenderedService {
                    name: service
                        .code_name
                        .for_language(Language::Python)
                        .unwrap_or(&service.name),
                    wire_name: &service.wire_name,
                    doc: service
                        .doc
                        .for_language(Language::Python)
                        .map(str::to_string),
                    endpoint: service.endpoint.clone(),
                    experimental: service.experimental,
                    deprecated: service.deprecated,
                    delay_load_temporalio_workflow: service.delay_load_temporalio_workflow,
                    operations,
                    resources: service
                        .resources
                        .iter()
                        .map(|resource| resource.data.clone())
                        .collect(),
                })
            })
            .collect::<Result<Vec<_>>>()?;

        for service in &services {
            for resource in &service.resources {
                self.ensure_resource_field_types(resource)?;
            }
        }
        for record in api_plan.records().map(|(_, record)| record) {
            let model_type = TypeSpec::Record(PlannedRecordType {
                full_name: record.full_name.clone(),
                model_name: record.name.clone(),
            });
            self.resolve_message_value_conversion(&model_type)?;
        }
        let model_refs = self.models.values().collect::<Vec<_>>();
        let model_fragments = self.render_model_fragments(model_refs.as_slice())?;

        let generated_files =
            self.render_package(&model_fragments, &services, support_fragments, mode)?;
        Ok(PythonGenerationResult {
            generated_files,
            root_package_imports: model_fragments.root_package_imports,
        })
    }

    fn render_model_fragments(&self, models: &[&RenderedModel]) -> Result<RenderedModelFragments> {
        self.external_models
            .render_model_fragments(models, self.api_plan)
    }

    fn render_package(
        &self,
        model_fragments: &RenderedModelFragments,
        services: &[RenderedService<'_>],
        support_fragments: &[SupportFragmentSpec],
        mode: GenerationMode,
    ) -> Result<GeneratedFiles> {
        let mut files = BTreeMap::new();
        render_support_package(&mut files, support_fragments)?;
        for (path, contents) in self.external_models.render_support_files()? {
            insert_generated_file(&mut files, path, contents)?;
        }
        let model_names = self
            .enums
            .values()
            .map(|enumeration| enumeration.name.clone())
            .chain(self.flags.values().map(|flag_set| flag_set.name.clone()))
            .chain(self.variants.values().map(|variant| variant.name.clone()))
            .chain(model_fragments.exported_names.iter().cloned())
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>();
        let operation_model_names = model_names
            .iter()
            .cloned()
            .chain(planned_module_import_names(self.api_plan))
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>();
        let resource_operation_owners = resource_operation_owners(services);
        let has_standalone_operations = mode == GenerationMode::NativeApi
            && services.iter().any(|service| {
                service.endpoint.is_some()
                    && service.operations.iter().any(|operation| {
                        !resource_operation_owners
                            .contains_key(&operation_key(service.name, operation.name))
                    })
            });
        let resource_names = services
            .iter()
            .flat_map(|service| {
                service
                    .resources
                    .iter()
                    .map(|resource| resource.type_name.clone())
            })
            .collect::<BTreeSet<_>>()
            .into_iter()
            .collect::<Vec<_>>();
        let support_names = support_export_names(support_fragments);

        let rendered_model_names = model_names.iter().cloned().collect::<BTreeSet<_>>();
        let mut package_model_names = if self.model_hoists.is_some() {
            rendered_model_names.clone()
        } else {
            BTreeSet::new()
        };
        package_model_names.extend(
            planned_module_export_model_names(self.api_plan)
                .intersection(&rendered_model_names)
                .cloned(),
        );
        let package_model_names = package_model_names.into_iter().collect::<Vec<_>>();
        let render_init = |root_package_imports: &RootPackageImports| {
            if mode == GenerationMode::NativeApi {
                render_package_init(
                    services,
                    &package_model_names,
                    &resource_names,
                    &resource_operation_owners,
                    &support_names,
                    self.api_plan,
                    self.model_hoists,
                    root_package_imports,
                )
            } else {
                render_definitions_only_package_init(services, &model_names, root_package_imports)
            }
        };
        let empty_root_package_imports = RootPackageImports::new();
        let root_package_imports = if self.model_hoists.is_none() {
            &model_fragments.root_package_imports
        } else {
            &empty_root_package_imports
        };
        insert_generated_file(&mut files, "__init__.py", render_init(root_package_imports))?;
        insert_generated_file(
            &mut files,
            "models.py",
            render_models_module(
                self.enums.values().collect::<Vec<_>>().as_slice(),
                self.flags.values().collect::<Vec<_>>().as_slice(),
                self.variants.values().collect::<Vec<_>>().as_slice(),
                model_fragments,
                &support_names,
                &self.language_imports,
                self.api_plan,
                self.inline_model_rebuilds,
                self.model_hoists,
            ),
        )?;
        if !resource_names.is_empty() {
            insert_generated_file(
                &mut files,
                "_resources/__init__.py",
                render_resources_package_init(services),
            )?;
        }
        if !services.is_empty() {
            insert_generated_file(
                &mut files,
                "services.py",
                render_service_module(
                    services,
                    self.api_plan,
                    self.model_hoists,
                    mode == GenerationMode::NativeApi,
                ),
            )?;
        }
        if has_standalone_operations {
            insert_generated_file(
                &mut files,
                "operations/__init__.py",
                render_operations_package_init(),
            )?;
        }

        for service in services {
            for resource in &service.resources {
                let bound_operations = if mode == GenerationMode::NativeApi {
                    resource_bound_operations(service, resource)
                } else {
                    Vec::new()
                };
                insert_generated_file(
                    &mut files,
                    format!("_resources/{}.py", resource_module_name(resource)),
                    self.render_resource_module_file(
                        service,
                        resource,
                        &bound_operations,
                        &operation_model_names,
                        &resource_names,
                        &support_names,
                    ),
                )?;
            }
            if mode == GenerationMode::NativeApi {
                if service.endpoint.is_none() {
                    continue;
                }
                for operation in &service.operations {
                    if resource_operation_owners
                        .contains_key(&operation_key(service.name, operation.name))
                    {
                        continue;
                    }
                    insert_generated_file(
                        &mut files,
                        format!("operations/{}.py", operation.attr_name),
                        render_operation_module(
                            service,
                            operation,
                            &operation_model_names,
                            &resource_names,
                            &support_names,
                            &self.language_imports,
                            self.api_plan,
                            self.model_hoists,
                        ),
                    )?;
                }
            }
        }

        Ok(GeneratedFiles::directory(files))
    }

    fn render_resource_module_file(
        &self,
        service: &RenderedService<'_>,
        resource: &PlannedResource,
        bound_operations: &[ResourceBoundOperation<'_>],
        model_names: &[String],
        resource_names: &[String],
        support_names: &[String],
    ) -> String {
        let mut module_imports = bound_operations
            .iter()
            .flat_map(|bound_operation| {
                [
                    bound_operation
                        .operation
                        .input
                        .as_ref()
                        .and_then(|input| input.module_path.clone()),
                    bound_operation.operation.output_module_path.clone(),
                ]
            })
            .flatten()
            .collect::<BTreeSet<_>>();

        let mut body = String::new();
        let function_fields = bound_operations
            .iter()
            .filter_map(|bound_operation| bound_operation.operation.unpacked_input.as_ref())
            .flat_map(|unpacked_input| unpacked_input.functions.iter().cloned())
            .collect::<Vec<_>>();
        let output_type_parameters = bound_operations
            .iter()
            .flat_map(|bound_operation| bound_operation.operation.output_type_parameters.iter())
            .cloned()
            .collect::<BTreeSet<_>>();
        if !function_fields.is_empty() {
            render_function_type_parameter_definitions(
                &mut body,
                &function_fields,
                &output_type_parameters,
            );
            body.push_str("\n\n");
        }
        self.render_resource(&mut body, service, resource, bound_operations);
        if !bound_operations.is_empty() && service.endpoint.is_some() {
            body.push_str("\n\n");
            for (index, bound_operation) in bound_operations.iter().enumerate() {
                render_operation_functions(&mut body, service, bound_operation.operation);
                if index + 1 != bound_operations.len() {
                    body.push_str("\n\n");
                }
            }
        }
        if service.endpoint.is_none() {
            body.push_str("\n\n");
            render_resource_client_binder(&mut body, resource);
        }
        if !service.delay_load_temporalio_workflow {
            module_imports.insert("temporalio.workflow".to_string());
        }

        let mut output = String::new();
        render_generated_file_header(&mut output);
        output.push('\n');
        let type_checking_names = temporalio_workflow_type_checking_names(&body);
        let body_for_imports =
            if service.delay_load_temporalio_workflow && !type_checking_names.is_empty() {
                format!("{body}\ntyping.TYPE_CHECKING")
            } else {
                body.clone()
            };
        let skipped_language_modules =
            delayed_temporalio_workflow_skipped_language_modules(service);
        let wrote_imports = render_optional_python_imports_with_skipped_language_modules(
            &mut output,
            &body_for_imports,
            &module_imports,
            &self.language_imports,
            &skipped_language_modules,
        );
        if wrote_imports
            && service.delay_load_temporalio_workflow
            && !type_checking_names.is_empty()
        {
            output.push('\n');
        }
        let wrote_type_checking_imports =
            render_temporalio_workflow_type_checking_imports(&mut output, service, &body);
        if wrote_imports || wrote_type_checking_imports {
            output.push('\n');
        }
        let used_model_names = used_python_symbol_imports(&body, model_names);
        if !used_model_names.is_empty() {
            render_model_name_imports(
                &mut output,
                "..models",
                &self.api_plan.module_path.child("_resources"),
                self.api_plan,
                &used_model_names,
                self.model_hoists,
            );
        }
        let used_resource_names = used_python_symbol_imports(&body, resource_names)
            .into_iter()
            .filter(|name| name != &resource.type_name)
            .collect::<Vec<_>>();
        if !used_resource_names.is_empty() {
            render_named_python_import(&mut output, ".", &used_resource_names);
        }
        let used_support_names = used_python_symbol_imports(&body, support_names);
        if !used_support_names.is_empty() {
            render_named_python_import(&mut output, ".._support", &used_support_names);
        }
        if !body.is_empty() {
            output.push('\n');
            output.push('\n');
            output.push_str(&body);
        }
        output
    }

    fn render_resource(
        &self,
        output: &mut String,
        service: &RenderedService<'_>,
        resource: &PlannedResource,
        bound_operations: &[ResourceBoundOperation<'_>],
    ) {
        output.push_str("@dataclasses.dataclass\n");
        output.push_str("class ");
        output.push_str(&resource.type_name);
        output.push_str(":\n");
        for field in &resource.fields {
            output.push_str("    ");
            output.push_str(&python_field_name(&field.name));
            output.push_str(": ");
            output.push_str(&self.python_resource_field_annotation(
                &field.kind,
                field.optional,
                field.function.as_ref(),
            ));
            output.push('\n');
        }
        if resource.methods.is_empty() {
            output.push_str("\n    pass\n");
            return;
        }

        for method in &resource.methods {
            output.push_str("\n");
            self.render_resource_class_method(output, service, resource, method, bound_operations);
        }
    }

    fn render_resource_class_method(
        &self,
        output: &mut String,
        service: &RenderedService<'_>,
        resource: &PlannedResource,
        method: &PlannedResourceMethod,
        bound_operations: &[ResourceBoundOperation<'_>],
    ) {
        let result_annotation = self.python_resource_method_result_annotation(method);
        output.push_str("    async def ");
        output.push_str(&python_field_name(&method.name));
        output.push_str("(\n");
        output.push_str("        self,\n");
        for param in &method.params {
            output.push_str("        ");
            output.push_str(&python_field_name(&param.name));
            output.push_str(": ");
            output.push_str(&self.python_resource_field_annotation(
                &param.kind,
                param.optional,
                param.function.as_ref(),
            ));
            if param.optional {
                output.push_str(" = None");
            }
            output.push_str(",\n");
        }
        output.push_str("    ) -> ");
        output.push_str(&result_annotation);
        output.push_str(":\n");

        match &method.binding {
            PlannedResourceMethodBindingSpec::Operation { operation_name, .. } => {
                let operation = bound_operations
                    .iter()
                    .find(|bound_operation| bound_operation.operation.name == operation_name)
                    .map(|bound_operation| bound_operation.operation)
                    .expect("bound resource operation should be rendered in the same module");
                if service.endpoint.is_none() {
                    render_resource_method_inline_operation_body(
                        output,
                        service,
                        method,
                        operation,
                        &result_annotation,
                    );
                } else {
                    render_resource_method_operation_body(
                        output,
                        service,
                        method,
                        operation,
                        &result_annotation,
                    );
                }
            }
            PlannedResourceMethodBindingSpec::Stub => {
                output.push_str("        raise NotImplementedError(");
                output.push_str(&python_string_literal(&format!(
                    "{}.{} is not yet implemented",
                    resource.name,
                    python_field_name(&method.name)
                )));
                output.push_str(")\n");
            }
        }
    }

    fn python_resource_method_result_annotation(&self, method: &PlannedResourceMethod) -> String {
        let Some(result) = &method.result else {
            return "None".to_string();
        };
        let annotation = match &result.kind {
            PlannedResourceMethodResultKind::Resource { type_name } => type_name.clone(),
            PlannedResourceMethodResultKind::Value(kind) => {
                self.python_resource_field_annotation(kind, result.optional, None)
            }
        };
        if result.optional && !annotation.contains("| None") {
            format!("{annotation} | None")
        } else {
            annotation
        }
    }

    fn python_resource_field_annotation(
        &self,
        kind: &PlannedType,
        optional: bool,
        function: Option<&FunctionFieldSpec<PlannedFamily>>,
    ) -> String {
        let base = if let Some(function) = function {
            python_function_field_annotation(
                function,
                function
                    .alternate_type
                    .as_ref()
                    .map(python_authored_type_annotation),
            )
        } else {
            match kind {
                PlannedType::Option(value) | PlannedType::List(value) => {
                    format!(
                        "collections.abc.Sequence[{}]",
                        self.python_resource_value_annotation(value)
                    )
                }
                PlannedType::Map(key, value) => format!(
                    "collections.abc.Mapping[{}, {}]",
                    self.python_resource_value_annotation(key),
                    self.python_resource_value_annotation(value)
                ),
                value => self.python_resource_value_annotation(value),
            }
        };
        if optional {
            format!("{base} | None")
        } else {
            base
        }
    }

    fn python_resource_value_annotation(&self, value: &PlannedType) -> String {
        match value {
            PlannedType::Float => "float".to_string(),
            PlannedType::Int(_) => "int".to_string(),
            PlannedType::Bool => "bool".to_string(),
            PlannedType::String => "str".to_string(),
            PlannedType::Bytes => "bytes".to_string(),
            PlannedType::TypeParameter(parameter) => parameter.name.clone(),
            PlannedType::Enum(enum_type) => enum_type.name.clone(),
            PlannedType::External(ExternalTypeSpec::Proto(_))
            | PlannedType::External(ExternalTypeSpec::Json(_)) => self
                .external_models
                .model_type_annotation(value)
                .expect("external resource value annotation should exist"),
            PlannedType::Flags(flags_type) => flags_type.name.clone(),
            PlannedType::Variant(variant_type) => variant_type.name.clone(),
            PlannedType::Record(record) => record.model_name.clone(),
            PlannedType::Resource(resource) => resource.type_name.clone(),
            PlannedType::Option(inner) | PlannedType::List(inner) => {
                format!(
                    "collections.abc.Sequence[{}]",
                    self.python_resource_value_annotation(inner)
                )
            }
            PlannedType::Map(key, value) => format!(
                "collections.abc.Mapping[{}, {}]",
                self.python_resource_value_annotation(key),
                self.python_resource_value_annotation(value)
            ),
            PlannedType::Tuple(items) => format!(
                "tuple[{}]",
                items
                    .iter()
                    .map(|item| self.python_resource_value_annotation(item))
                    .collect::<Vec<_>>()
                    .join(", ")
            ),
            PlannedType::Result { ok, err } => python_result_annotation(
                ok.as_ref()
                    .map(|ok| self.python_resource_value_annotation(ok).to_string()),
                err.as_ref()
                    .map(|err| self.python_resource_value_annotation(err).to_string()),
            ),
            PlannedType::External(ExternalTypeSpec::Alias {
                type_name, target, ..
            }) => type_name
                .for_language(Language::Python)
                .map(str::to_string)
                .unwrap_or_else(|| self.python_resource_value_annotation(target)),
        }
    }

    fn ensure_resource_field_types(&mut self, resource: &PlannedResource) -> Result<()> {
        for field in &resource.fields {
            self.ensure_resource_field_type(&field.kind)?;
        }
        for method in &resource.methods {
            for param in &method.params {
                self.ensure_resource_field_type(&param.kind)?;
            }
        }
        Ok(())
    }

    fn ensure_resource_field_type(&mut self, kind: &PlannedType) -> Result<()> {
        match kind {
            PlannedType::List(value) => {
                self.resolve_planned_value_type(value)?;
            }
            PlannedType::Map(key, value) => {
                self.resolve_planned_value_type(key)?;
                self.resolve_planned_value_type(value)?;
            }
            value => {
                self.resolve_planned_value_type(value)?;
            }
        }
        Ok(())
    }

    fn resolve_operation<'operation>(
        &mut self,
        operation: &'operation OperationSpec<PlannedFamily>,
    ) -> Result<RenderedOperation<'operation>> {
        let output_resource_return = operation.data.output_resource_return.clone();
        let input = operation_input_model(operation);
        let rendered_input = input
            .map(|input| -> Result<_> {
                let (type_ref, module_path) =
                    self.external_models
                        .service_model_ref(input, "models", self.api_plan);
                let input_conversion = self.resolve_message_value_conversion(input)?;
                let annotation = if let PlannedType::Record(record) = input {
                    let parameters = self
                        .api_plan
                        .record_type_parameters(&record.full_name, Language::Python);
                    python_generic_record_annotation(&input_conversion.annotation, &parameters)
                } else {
                    input_conversion.annotation.clone()
                };
                Ok(RenderedOperationInput {
                    descriptor_type_ref: if let PlannedType::Record(record) = input {
                        python_erased_generic_record_annotation(
                            &type_ref,
                            &self
                                .api_plan
                                .record_type_parameters(&record.full_name, Language::Python),
                        )
                    } else {
                        type_ref.clone()
                    },
                    type_ref,
                    module_path,
                    annotation,
                    supports_unpacked: input_conversion.supports_unpacked_input(),
                })
            })
            .transpose()?;
        let output_transform = operation.output_transform.as_ref();
        let output_direct_result = operation_output_direct_result(operation);
        let (output_ref, output_module_path, output_annotation_default) = match operation
            .output_type()
        {
            Some(
                output_model @ (PlannedType::External(ExternalTypeSpec::Proto(
                    PlannedProtoType::Message(_),
                ))
                | PlannedType::External(ExternalTypeSpec::Json(_))
                | PlannedType::Record(_)),
            ) => {
                let (output_ref, output_module_path) =
                    self.external_models
                        .service_model_ref(output_model, "models", self.api_plan);
                if output_transform.is_none()
                    && output_resource_return.is_none()
                    && !output_direct_result
                    && matches!(output_model, PlannedType::Record(_))
                {
                    self.resolve_message_value_conversion(output_model)?;
                }
                let annotation = self.resolve_output_annotation(output_model)?;
                (output_ref, output_module_path, annotation)
            }
            Some(PlannedType::Resource(resource)) => {
                if let Some(output) = &resource.wire_type {
                    let output = planned_record_for_external_source(self.api_plan, output)
                        .map(planned_record_type)
                        .unwrap_or_else(|| PlannedType::External(output.clone()));
                    let (output_ref, output_module_path) =
                        self.external_models
                            .service_model_ref(&output, "models", self.api_plan);
                    let conversion = self.resolve_message_value_conversion(&output)?;
                    (output_ref, output_module_path, conversion.annotation)
                } else {
                    (
                        resource.type_name.clone(),
                        Some("._resources".to_string()),
                        resource.type_name.clone(),
                    )
                }
            }
            None => ("None".to_string(), None, "None".to_string()),
            Some(_) => {
                panic!("planned operation output should be proto, record, resource, or none")
            }
        };
        let model_input_parameters = input
            .map(|input| self.api_plan.type_parameters(input, Language::Python))
            .unwrap_or_default();
        let model_input_identities = model_input_parameters
            .iter()
            .map(|usage| usage.parameter.full_name.as_str())
            .collect::<BTreeSet<_>>();
        let model_output_parameters = operation
            .output_type()
            .map(|output| self.api_plan.type_parameters(output, Language::Python))
            .unwrap_or_default();
        let generic_model_types =
            !model_input_parameters.is_empty() || !model_output_parameters.is_empty();
        let model_output_only_parameters = model_output_parameters
            .into_iter()
            .filter(|usage| !model_input_identities.contains(usage.parameter.full_name.as_str()))
            .map(|usage| usage.parameter.name)
            .collect::<BTreeSet<_>>();
        let output_annotation_default =
            erase_python_type_parameters(&output_annotation_default, &model_output_only_parameters);
        let overload_output_annotation = output_transform
            .and_then(|transform| {
                transform
                    .type_name
                    .for_language(crate::language::Language::Python)
                    .map(str::to_string)
            })
            .or_else(|| {
                output_resource_return
                    .as_ref()
                    .map(|resource| resource.resource_type_name.clone())
            })
            .unwrap_or_else(|| output_annotation_default.clone());
        let unpacked_input = if let (Some(input), Some(rendered_input)) = (input, &rendered_input) {
            if rendered_input.supports_unpacked {
                Some(self.build_unpacked_input(match input {
                    PlannedType::Record(record) => &record.full_name,
                    _ => panic!("unpacked operation input should be a record"),
                })?)
            } else {
                None
            }
        } else {
            None
        };
        let output_type_parameters = unpacked_input
            .iter()
            .flat_map(|unpacked_input| &unpacked_input.functions)
            .filter_map(|function| function.result_type_parameter.clone())
            .filter(|name| python_annotation_uses_identifier(&overload_output_annotation, name))
            .collect::<BTreeSet<_>>();
        let output_annotation =
            erase_python_type_parameters(&overload_output_annotation, &output_type_parameters);
        let output_type_expr = erase_python_type_parameters(
            &local_python_model_type_expr(&output_ref),
            &output_type_parameters,
        );
        let descriptor_output_ref = match operation.output_type() {
            Some(PlannedType::Record(record)) => python_erased_generic_record_annotation(
                &output_ref,
                &self
                    .api_plan
                    .record_type_parameters(&record.full_name, Language::Python),
            ),
            _ => output_ref.clone(),
        };
        Ok(RenderedOperation {
            name: operation.name.as_str(),
            wire_name: operation.wire_name.as_str(),
            attr_name: operation
                .code_name
                .for_language(Language::Python)
                .map(str::to_string)
                .unwrap_or_else(|| python_ident(&operation.name.to_snake_case())),
            experimental: operation.experimental,
            deprecated: operation.deprecated,
            doc: operation
                .doc
                .for_language(Language::Python)
                .map(str::to_string),
            return_doc: operation
                .return_doc
                .for_language(Language::Python)
                .map(str::to_string),
            input: rendered_input,
            output_ref,
            descriptor_output_ref,
            output_module_path,
            output_annotation,
            overload_output_annotation,
            output_type_parameters,
            output_type_expr,
            output_transform_expr: output_transform.and_then(|transform| {
                transform
                    .transform
                    .for_language(crate::language::Language::Python)
                    .map(str::to_string)
            }),
            serialization_context_expr: operation
                .serialization_context
                .for_language(crate::language::Language::Python)
                .map(str::to_string),
            output_resource_return,
            output_direct_result,
            output_none: operation.output_type().is_none(),
            unpacked_input,
            model_input_type_parameters: model_input_parameters
                .into_iter()
                .map(|usage| usage.parameter.name)
                .collect(),
            generic_model_types,
        })
    }

    fn resolve_output_annotation(&mut self, model_type: &PlannedType) -> Result<String> {
        match model_type {
            PlannedType::External(ExternalTypeSpec::Proto(_))
            | PlannedType::External(ExternalTypeSpec::Json(_)) => Ok(self
                .external_models
                .model_type_annotation(model_type)
                .expect("external model annotation should exist")),
            PlannedType::Record(record) => {
                let conversion = self.resolve_message_value_conversion(model_type)?;
                Ok(python_generic_record_annotation(
                    &conversion.annotation,
                    &self
                        .api_plan
                        .record_type_parameters(&record.full_name, Language::Python),
                ))
            }
            _ => panic!("operation output annotation should be model-shaped"),
        }
    }

    fn resolve_message_value_conversion(
        &mut self,
        model_type: &PlannedType,
    ) -> Result<WireValueConversion> {
        let planned_record = match model_type {
            PlannedType::Record(record) => self.api_plan.record(&record.full_name),
            _ => None,
        };
        if let Some(conversion) = self
            .external_models
            .wire_conversion(model_type, planned_record)
        {
            if matches!(model_type, PlannedType::Record(_)) {
                self.ensure_rendered_model(model_type)?;
            }
            return Ok(conversion);
        }
        panic!("message conversion should be model-shaped")
    }

    fn build_unpacked_input(&self, input_full_name: &str) -> Result<RenderedUnpackedInput> {
        let model = self
            .models
            .get(input_full_name)
            .expect("input model should be rendered before building unpacked input");
        let planned_model = planned_record(self.api_plan, input_full_name);

        let mut parameters = Vec::new();
        let mut request_fields = Vec::new();
        let mut flattened_messages = Vec::new();
        let mut parameter_sources = BTreeMap::<String, String>::new();

        for ((_field_name, planned_field), rendered_field) in planned_model
            .fields
            .iter()
            .filter(|(_, field)| field.visibility != RecordFieldVisibility::Omitted)
            .zip(model.fields.iter())
        {
            if planned_field.visibility != RecordFieldVisibility::Public {
                continue;
            }
            if let Some(flattened) = self.build_flattened_message(planned_field, rendered_field) {
                request_fields.push(RenderedUnpackedRequestField {
                    attr_name: flattened.local_name.clone(),
                    value_expr: flattened.local_name.clone(),
                    default_kind: PythonFieldDefaultKind::Required,
                });
                for child in &flattened.fields {
                    register_unpacked_parameter_name(
                        &mut parameter_sources,
                        &child.value_expr,
                        &format!("{}.{}", flattened.local_name, child.attr_name),
                        &model.name,
                    )?;
                    parameters.push(RenderedUnpackedInputField {
                        attr_name: child.value_expr.clone(),
                        annotation: child.annotation.clone(),
                        default_kind: child.default_kind.clone(),
                        doc: child.doc.clone(),
                    });
                }
                flattened_messages.push(flattened);
                continue;
            }

            register_unpacked_parameter_name(
                &mut parameter_sources,
                &rendered_field.attr_name,
                &rendered_field.attr_name,
                &model.name,
            )?;
            parameters.push(RenderedUnpackedInputField {
                attr_name: rendered_field.attr_name.clone(),
                annotation: rendered_field.annotation.clone(),
                default_kind: rendered_field.default_kind.clone(),
                doc: planned_field
                    .doc
                    .as_ref()
                    .and_then(|doc| doc.for_language(Language::Python))
                    .map(str::to_string),
            });
            request_fields.push(RenderedUnpackedRequestField {
                attr_name: rendered_field.attr_name.clone(),
                value_expr: rendered_field.attr_name.clone(),
                default_kind: rendered_field.default_kind.clone(),
            });
        }

        Ok(RenderedUnpackedInput {
            model_name: model.name.clone(),
            parameters,
            request_fields,
            flattened_messages,
            functions: planned_model
                .functions()
                .map(|(field_name, function)| {
                    let result_annotation = python_function_result_annotation(&function.result);
                    let result_type_parameters = function
                        .result_type_parameter
                        .iter()
                        .cloned()
                        .collect::<BTreeSet<_>>();
                    let erased_result_annotation =
                        erase_python_type_parameters(&result_annotation, &result_type_parameters);
                    let args = python_function_args(&function.args);
                    let alternate_annotation = function
                        .alternate_type
                        .as_ref()
                        .map(python_authored_type_annotation);
                    RenderedFunctionField {
                        callable_field_name: planned_model
                            .field_name_override(field_name)
                            .map(python_field_name)
                            .unwrap_or_else(|| python_field_name(field_name)),
                        args_field_name: planned_model
                            .field_name_override(&function.args_field)
                            .map(python_field_name)
                            .unwrap_or_else(|| python_field_name(&function.args_field)),
                        args: args.clone(),
                        primary: function.primary,
                        callable_annotation: python_function_annotation_from_args(
                            &args,
                            alternate_annotation.as_deref(),
                            &erased_result_annotation,
                        ),
                        result_annotation,
                        erased_result_annotation,
                        result_type_parameter: function.result_type_parameter.clone(),
                        alternate_annotation,
                    }
                })
                .collect(),
        })
    }

    fn build_flattened_message(
        &self,
        planned_field: &RecordFieldSpec<PlannedFamily>,
        rendered_field: &RenderedField,
    ) -> Option<RenderedFlattenedMessage> {
        let model_type = &planned_field.field_type;
        let PlannedType::Record(record) = model_type else {
            return None;
        };
        let full_name = &record.full_name;
        let nested_planned_model = self.api_plan.record(full_name)?;
        if !nested_planned_model.flatten_in_api {
            return None;
        }
        let nested_rendered_model = self.models.get(full_name)?;

        Some(RenderedFlattenedMessage {
            local_name: rendered_field.attr_name.clone(),
            model_name: nested_rendered_model.name.clone(),
            required: planned_field.required,
            fields: nested_planned_model
                .fields
                .iter()
                .filter(|(_, field)| field.visibility != RecordFieldVisibility::Omitted)
                .zip(nested_rendered_model.fields.iter())
                .filter(|((_, field), _)| field.visibility == RecordFieldVisibility::Public)
                .map(
                    |((nested_field_name, nested_planned_field), nested_rendered_field)| {
                        RenderedFlattenedMessageField {
                            attr_name: nested_rendered_field.attr_name.clone(),
                            annotation: nested_planned_model
                                .field_flattened_annotation(nested_field_name)
                                .and_then(|annotation| annotation.for_language(Language::Python))
                                .map(|annotation| {
                                    if nested_planned_field.required {
                                        annotation.to_string()
                                    } else {
                                        format!("{annotation} | None")
                                    }
                                })
                                .unwrap_or_else(|| nested_rendered_field.annotation.clone()),
                            value_expr: nested_rendered_field.attr_name.clone(),
                            default_kind: if nested_planned_field.required {
                                PythonFieldDefaultKind::Required
                            } else {
                                nested_rendered_field.default_kind.clone()
                            },
                            doc: nested_planned_field
                                .doc
                                .as_ref()
                                .and_then(|doc| doc.for_language(Language::Python))
                                .map(str::to_string),
                        }
                    },
                )
                .collect(),
        })
    }

    fn ensure_rendered_model(&mut self, model_type: &PlannedType) -> Result<()> {
        let PlannedType::Record(record) = model_type else {
            panic!("rendered model should be a record");
        };
        let full_name = record.full_name.as_str();
        let api_plan = self.api_plan;
        let planned_model = planned_record(api_plan, full_name);

        if self.models.contains_key(full_name) {
            return Ok(());
        }

        self.models.insert(
            full_name.to_string(),
            RenderedModel {
                full_name: full_name.to_string(),
                name: planned_model.name.clone(),
                type_parameters: api_plan
                    .record_type_parameters(full_name, Language::Python)
                    .into_iter()
                    .map(|usage| usage.parameter.name)
                    .collect(),
                experimental: planned_model.experimental,
                fields: Vec::new(),
            },
        );

        let fields = planned_model
            .fields
            .iter()
            .filter(|(_, field)| field.visibility != RecordFieldVisibility::Omitted)
            .map(|(field_name, field)| {
                if let RecordFieldVisibility::Sourced { source_expr } = &field.visibility {
                    self.build_public_sourced_field(planned_model, field_name, field, source_expr)
                } else {
                    self.build_field(planned_model, field_name, field)
                }
            })
            .collect::<Result<Vec<_>>>()?;

        self.models
            .get_mut(full_name)
            .expect("model should be inserted before recursive field resolution")
            .fields = fields;
        Ok(())
    }

    fn ensure_rendered_enum(&mut self, enum_spec: &EnumSpec) {
        self.enums
            .entry(enum_spec.full_name.clone())
            .or_insert_with(|| RenderedEnum {
                name: enum_spec.name.clone(),
                values: enum_spec
                    .values
                    .iter()
                    .map(|value| RenderedEnumValue {
                        name: value.name.clone(),
                        number: value.number,
                    })
                    .collect(),
            });
    }

    fn ensure_rendered_flags(&mut self, flags_spec: &FlagsSpec) {
        self.flags
            .entry(flags_spec.full_name.clone())
            .or_insert_with(|| RenderedFlags {
                name: flags_spec.name.clone(),
                flags: flags_spec
                    .flags
                    .iter()
                    .map(|flag| RenderedFlag {
                        name: flag.name.clone(),
                        bit: flag.bit,
                    })
                    .collect(),
            });
    }

    fn ensure_rendered_variant(&mut self, variant_spec: &VariantSpec<PlannedFamily>) -> Result<()> {
        if self.variants.contains_key(&variant_spec.full_name) {
            return Ok(());
        }

        let cases = variant_spec
            .cases
            .iter()
            .map(|case| -> Result<_> {
                Ok(RenderedVariantCase {
                    name: case.name.clone(),
                    payload_annotation: case
                        .payload
                        .as_ref()
                        .map(|payload| {
                            self.resolve_planned_value_type(payload)
                                .map(|resolved| resolved.annotation)
                        })
                        .transpose()?,
                })
            })
            .collect::<Result<Vec<_>>>()?;
        self.variants.insert(
            variant_spec.full_name.clone(),
            RenderedVariant {
                name: variant_spec.name.clone(),
                type_parameters: self
                    .api_plan
                    .variant_type_parameters(&variant_spec.full_name, Language::Python)
                    .into_iter()
                    .map(|usage| usage.parameter.name)
                    .collect(),
                cases,
            },
        );
        Ok(())
    }

    fn build_field(
        &mut self,
        record: &RecordSpec<PlannedFamily>,
        field_name: &str,
        field: &RecordFieldSpec<PlannedFamily>,
    ) -> Result<RenderedField> {
        let attr_name = python_field_name(&field.name);

        if let PlannedType::Map(key, value) = &field.field_type {
            let key_type = self.resolve_planned_value_type(key)?;
            let value_type = self.resolve_planned_value_type(value)?;
            let mut imports = key_type.imports.clone();
            imports.extend(&value_type.imports);
            return Ok(RenderedField {
                attr_name: attr_name.clone(),
                annotation: python_field_annotation(
                    record,
                    field_name,
                    field,
                    format!("dict[{}, {}]", key_type.annotation, value_type.annotation),
                    false,
                ),
                default_kind: PythonFieldDefaultKind::EmptyDict,
                default_expr: Some("dataclasses.field(default_factory=dict)".to_string()),
                wire_value_type: value_type,
                imports,
            });
        }

        let (resolved_type, repeated) = match &field.field_type {
            PlannedType::List(value) => (self.resolve_planned_value_type(value)?, true),
            PlannedType::Map(_, _) => unreachable!("handled above"),
            value => (self.resolve_planned_value_type(value)?, false),
        };

        if repeated {
            return Ok(RenderedField {
                attr_name: attr_name.clone(),
                annotation: python_field_annotation(
                    record,
                    field_name,
                    field,
                    format!("list[{}]", resolved_type.annotation),
                    false,
                ),
                default_kind: PythonFieldDefaultKind::EmptyList,
                default_expr: Some("dataclasses.field(default_factory=list)".to_string()),
                wire_value_type: resolved_type.clone(),
                imports: resolved_type.imports,
            });
        }

        let imports = resolved_type.imports.clone();

        if let Some(default_value) = &field.default_value {
            let default_expr = enum_default_expr(&resolved_type, &default_value.enum_case);
            return Ok(RenderedField {
                attr_name: attr_name.clone(),
                annotation: python_field_annotation(
                    record,
                    field_name,
                    field,
                    resolved_type.annotation.clone(),
                    false,
                ),
                default_kind: PythonFieldDefaultKind::Expression(default_expr.clone()),
                default_expr: Some(default_expr.clone()),
                wire_value_type: resolved_type.clone(),
                imports,
            });
        }

        if field.required {
            return Ok(RenderedField {
                attr_name: attr_name.clone(),
                annotation: python_field_annotation(
                    record,
                    field_name,
                    field,
                    resolved_type.annotation.clone(),
                    false,
                ),
                default_kind: PythonFieldDefaultKind::Required,
                default_expr: None,
                wire_value_type: resolved_type.clone(),
                imports,
            });
        }

        Ok(RenderedField {
            attr_name: attr_name.clone(),
            annotation: python_field_annotation(
                record,
                field_name,
                field,
                resolved_type.annotation.clone(),
                true,
            ),
            default_kind: PythonFieldDefaultKind::None,
            default_expr: Some("None".to_string()),
            wire_value_type: resolved_type.clone(),
            imports,
        })
    }

    fn build_public_sourced_field(
        &mut self,
        record: &RecordSpec<PlannedFamily>,
        field_name: &str,
        field: &RecordFieldSpec<PlannedFamily>,
        source_expr: &str,
    ) -> Result<RenderedField> {
        let mut rendered = self.build_field(record, field_name, field)?;
        rendered.default_kind = PythonFieldDefaultKind::Expression(source_expr.to_string());
        rendered.default_expr = Some(python_dataclass_source_default_expr(source_expr));
        Ok(rendered)
    }

    fn resolve_planned_value_type(
        &mut self,
        value_type: &PlannedType,
    ) -> Result<ResolvedFieldType> {
        self.ensure_rendered_value_type(value_type)?;
        resolve_python_value_type(self.api_plan, &self.external_models, value_type)
    }

    fn ensure_rendered_value_type(&mut self, value_type: &PlannedType) -> Result<()> {
        match value_type {
            PlannedType::Enum(enum_type) => {
                if let Some(enum_spec) = self.api_plan.enum_decl(&enum_type.full_name) {
                    self.ensure_rendered_enum(enum_spec);
                }
            }
            PlannedType::Flags(flags_type) => {
                if let Some(flags_spec) = self.api_plan.flags_decl(&flags_type.full_name) {
                    self.ensure_rendered_flags(flags_spec);
                }
            }
            PlannedType::Variant(variant_type) => {
                if let Some(variant_spec) = self.api_plan.variant(&variant_type.full_name) {
                    self.ensure_rendered_variant(variant_spec)?;
                }
            }
            PlannedType::Record(_) => self.ensure_rendered_model(value_type)?,
            PlannedType::Option(inner) | PlannedType::List(inner) => {
                self.ensure_rendered_value_type(inner)?;
            }
            PlannedType::Map(key, value) => {
                self.ensure_rendered_value_type(key)?;
                self.ensure_rendered_value_type(value)?;
            }
            PlannedType::Tuple(items) => {
                for item in items {
                    self.ensure_rendered_value_type(item)?;
                }
            }
            PlannedType::Result { ok, err } => {
                if let Some(ok) = ok {
                    self.ensure_rendered_value_type(ok)?;
                }
                if let Some(err) = err {
                    self.ensure_rendered_value_type(err)?;
                }
            }
            PlannedType::External(ExternalTypeSpec::Alias { target, .. }) => {
                self.ensure_rendered_value_type(target)?;
            }
            PlannedType::TypeParameter(_)
            | PlannedType::Float
            | PlannedType::Int(_)
            | PlannedType::Bool
            | PlannedType::String
            | PlannedType::Bytes
            | PlannedType::External(_)
            | PlannedType::Resource(_) => {}
        }
        Ok(())
    }
}

fn resolve_python_value_type(
    api_plan: &PlannedSpec,
    external_models: &PythonExternalModels,
    value_type: &PlannedType,
) -> Result<ResolvedFieldType> {
    let resolved = match value_type {
        PlannedType::TypeParameter(parameter) => ResolvedFieldType {
            annotation: parameter.name.clone(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Float => ResolvedFieldType {
            annotation: "float".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Int(_) => ResolvedFieldType {
            annotation: "int".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Bool => ResolvedFieldType {
            annotation: "bool".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::String => ResolvedFieldType {
            annotation: "str".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Bytes => ResolvedFieldType {
            annotation: "bytes".to_string(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Enum(enum_type) => ResolvedFieldType {
            annotation: enum_type.name.clone(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Enum,
            wire_conversion: None,
        },
        value_type @ PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(_))) => {
            external_models
                .resolved_external_field_type(value_type)
                .expect("proto enum field type should exist")
        }
        PlannedType::Flags(flags_type) => ResolvedFieldType {
            annotation: flags_type.name.clone(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Variant(variant_type) => ResolvedFieldType {
            annotation: python_generic_record_annotation(
                &variant_type.name,
                &api_plan.variant_type_parameters(&variant_type.full_name, Language::Python),
            ),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        message_type @ (PlannedType::External(ExternalTypeSpec::Proto(
            PlannedProtoType::Message(_),
        ))
        | PlannedType::Record(_)) => {
            let planned_record = match message_type {
                PlannedType::Record(record) => api_plan.record(&record.full_name),
                _ => None,
            };
            let conversion = external_models
                .wire_conversion(message_type, planned_record)
                .expect("message conversion should be model-shaped");
            let annotation = if let PlannedType::Record(record) = message_type {
                python_generic_record_annotation(
                    &conversion.annotation,
                    &api_plan.record_type_parameters(&record.full_name, Language::Python),
                )
            } else {
                conversion.annotation.clone()
            };
            ResolvedFieldType {
                annotation,
                imports: conversion.imports.clone(),
                kind: ResolvedFieldKind::Message,
                wire_conversion: Some(conversion),
            }
        }
        value_type @ PlannedType::External(ExternalTypeSpec::Json(_)) => external_models
            .resolved_external_field_type(value_type)
            .expect("json model field type should exist"),
        PlannedType::Resource(resource) => ResolvedFieldType {
            annotation: resource.type_name.clone(),
            imports: PythonImports::default(),
            kind: ResolvedFieldKind::Scalar,
            wire_conversion: None,
        },
        PlannedType::Option(inner) | PlannedType::List(inner) => {
            let inner = resolve_python_value_type(api_plan, external_models, inner)?;
            ResolvedFieldType {
                annotation: format!("list[{}]", inner.annotation),
                imports: inner.imports,
                kind: ResolvedFieldKind::Scalar,
                wire_conversion: None,
            }
        }
        PlannedType::Map(key, value) => {
            let key = resolve_python_value_type(api_plan, external_models, key)?;
            let value = resolve_python_value_type(api_plan, external_models, value)?;
            let mut imports = key.imports;
            imports.extend(&value.imports);
            ResolvedFieldType {
                annotation: format!("dict[{}, {}]", key.annotation, value.annotation),
                imports,
                kind: ResolvedFieldKind::Scalar,
                wire_conversion: None,
            }
        }
        PlannedType::Tuple(items) => {
            let items = items
                .iter()
                .map(|item| {
                    resolve_python_value_type(api_plan, external_models, item)
                        .map(|resolved| resolved.annotation)
                })
                .collect::<Result<Vec<_>>>()?;
            ResolvedFieldType {
                annotation: format!("tuple[{}]", items.join(", ")),
                imports: PythonImports::default(),
                kind: ResolvedFieldKind::Scalar,
                wire_conversion: None,
            }
        }
        PlannedType::Result { ok, err } => {
            let ok = ok
                .as_ref()
                .map(|ok| resolve_python_value_type(api_plan, external_models, ok))
                .transpose()?;
            let err = err
                .as_ref()
                .map(|err| resolve_python_value_type(api_plan, external_models, err))
                .transpose()?;
            let mut imports = PythonImports::default();
            if let Some(ok) = &ok {
                imports.extend(&ok.imports);
            }
            if let Some(err) = &err {
                imports.extend(&err.imports);
            }
            ResolvedFieldType {
                annotation: python_result_annotation(
                    ok.as_ref().map(|ok| ok.annotation.clone()),
                    err.as_ref().map(|err| err.annotation.clone()),
                ),
                imports,
                kind: ResolvedFieldKind::Scalar,
                wire_conversion: None,
            }
        }
        PlannedType::External(ExternalTypeSpec::Alias {
            type_name, target, ..
        }) => {
            let mut resolved = resolve_python_value_type(api_plan, external_models, target)?;
            if let Some(annotation) = type_name.for_language(Language::Python) {
                resolved.annotation = annotation.to_string();
            }
            resolved
        }
    };
    Ok(resolved)
}

fn collect_python_language_imports(api_plan: &PlannedSpec) -> Vec<LanguageImportSpec> {
    let mut imports = BTreeSet::new();
    for variant in api_plan.variants().map(|(_, variant)| variant) {
        for case in &variant.cases {
            if let Some(payload) = &case.payload {
                collect_value_type_imports(payload, &mut imports);
            }
        }
    }
    for record in api_plan.records().map(|(_, record)| record) {
        if let Some(proto) = &record.data.proto {
            collect_proto_type_imports(proto, &mut imports);
        }
        for field in record.fields.values() {
            if let Some(annotation) = &field.annotation {
                collect_python_import(annotation, &mut imports);
            }
            if let Some(annotation) = &field.flattened_annotation {
                collect_python_import(annotation, &mut imports);
            }
        }
        for (_, field) in record
            .fields
            .iter()
            .filter(|(_, field)| field.visibility != RecordFieldVisibility::Omitted)
        {
            if let Some(function) = &field.function {
                collect_function_imports(function, &mut imports);
            }
            collect_value_type_imports(&field.field_type, &mut imports);
        }
    }
    for service in &api_plan.services {
        for operation in &service.operations {
            if let Some(input) = operation_input_model(operation) {
                collect_model_type_imports(input, &mut imports);
            }
            match operation.output_type() {
                Some(
                    model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
                        PlannedProtoType::Message(_),
                    ))
                    | PlannedType::External(ExternalTypeSpec::Json(_))
                    | PlannedType::Record(_)),
                ) => collect_model_type_imports(model_type, &mut imports),
                Some(PlannedType::Resource(resource)) => {
                    if let Some(model_type) = &resource.wire_type {
                        collect_model_type_imports(
                            &PlannedType::External(model_type.clone()),
                            &mut imports,
                        );
                    }
                }
                _ => {}
            }
            if let Some(transform) = &operation.output_transform {
                collect_python_import(&transform.type_name, &mut imports);
            }
        }
        for resource in service.resources.iter().map(|resource| &resource.data) {
            for field in &resource.fields {
                collect_value_type_imports(&field.kind, &mut imports);
                if let Some(function) = &field.function {
                    collect_function_imports(function, &mut imports);
                }
            }
            for method in &resource.methods {
                for param in &method.params {
                    collect_value_type_imports(&param.kind, &mut imports);
                    if let Some(function) = &param.function {
                        collect_function_imports(function, &mut imports);
                    }
                }
                if let Some(result) = &method.result {
                    if let PlannedResourceMethodResultKind::Value(kind) = &result.kind {
                        collect_value_type_imports(kind, &mut imports);
                    }
                }
            }
        }
    }
    imports.into_iter().collect()
}

fn render_record_models(
    models: &[&RenderedModel],
    api_plan: &PlannedSpec,
    external_models: &PythonExternalModels,
) -> Result<RenderedModelFragments> {
    let mut body = String::new();
    let type_parameters = models
        .iter()
        .flat_map(|model| model.type_parameters.iter())
        .cloned()
        .collect::<BTreeSet<_>>();
    for parameter in &type_parameters {
        body.push_str(parameter);
        body.push_str(" = typing.TypeVar(");
        body.push_str(&python_string_literal(parameter));
        body.push_str(")\n");
    }
    if !type_parameters.is_empty() && !models.is_empty() {
        body.push_str("\n\n");
    }
    let mut wire_blocks = BTreeMap::new();
    for (index, model) in models.iter().enumerate() {
        let planned_model = api_plan
            .record(&model.full_name)
            .unwrap_or_else(|| panic!("planned model should exist for {}", model.full_name));
        let wire_block =
            external_models.render_record_wire_block(api_plan, model, planned_model)?;
        if let Some(wire_block) = &wire_block {
            for line in &wire_block.pre_class_lines {
                body.push_str(line);
                body.push('\n');
            }
        }
        render_record_model(&mut body, model, wire_block.as_ref());
        if let Some(wire_block) = wire_block {
            wire_blocks.insert(model.full_name.clone(), wire_block);
        }
        if index + 1 != models.len() {
            body.push_str("\n\n");
        }
    }

    let mut module_imports = BTreeSet::new();
    for model in models {
        if let Some(wire_block) = wire_blocks.get(&model.full_name) {
            module_imports.extend(wire_block.imports.module_imports.iter().cloned());
        }
        for field in &model.fields {
            module_imports.extend(field.imports.module_imports.iter().cloned());
        }
    }

    Ok(RenderedModelFragments {
        body,
        post_model_statements: String::new(),
        module_imports,
        relative_imports: BTreeMap::new(),
        root_package_imports: RootPackageImports::new(),
        exported_names: models.iter().map(|model| model.name.clone()).collect(),
        allows_private_wire_access: false,
    })
}

fn render_record_model(
    output: &mut String,
    model: &RenderedModel,
    wire_block: Option<&RenderedRecordWireBlock>,
) {
    if model_needs_keyword_only_dataclass(model) {
        if let Some(decorator) = wire_block.and_then(|block| block.decorator.as_deref()) {
            output.push_str(decorator);
            output.push('\n');
        }
        output.push_str("@dataclasses.dataclass(slots=True, kw_only=True)\n");
    } else {
        if let Some(decorator) = wire_block.and_then(|block| block.decorator.as_deref()) {
            output.push_str(decorator);
            output.push('\n');
        }
        output.push_str("@dataclasses.dataclass(slots=True)\n");
    }
    output.push_str("class ");
    output.push_str(&model.name);
    if !model.type_parameters.is_empty() {
        output.push_str("(typing.Generic[");
        output.push_str(&model.type_parameters.join(", "));
        output.push_str("])");
    }
    output.push_str(":\n");
    render_python_docstring(output, "    ", None, &[], None, model.experimental);

    let wire_lines = wire_block
        .map(|block| block.class_body_lines.as_slice())
        .unwrap_or(&[]);
    if model.fields.is_empty() {
        if wire_lines.is_empty() {
            output.push_str("    pass\n");
        } else {
            render_record_wire_block_lines(output, wire_lines);
        }
        return;
    }

    for field in &model.fields {
        output.push_str("    ");
        output.push_str(&field.attr_name);
        output.push_str(": ");
        output.push_str(&python_parameter_annotation(
            &field.annotation,
            &field.default_kind,
        ));
        if let Some(default_expr) = &field.default_expr {
            render_python_default_expr(output, default_expr, "    ");
        }
        output.push('\n');
    }

    render_record_wire_block_lines(output, wire_lines);
}

fn render_record_wire_block_lines(output: &mut String, lines: &[String]) {
    for line in lines {
        output.push_str(line);
        output.push('\n');
    }
}

fn model_needs_keyword_only_dataclass(model: &RenderedModel) -> bool {
    let mut saw_defaulted_field = false;
    for field in &model.fields {
        if field.default_expr.is_some() {
            saw_defaulted_field = true;
        } else if saw_defaulted_field {
            return true;
        }
    }
    false
}

fn collect_proto_type_imports(
    proto: &PlannedProtoTypeInfo,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    collect_python_import(&proto.type_name, imports);
}

fn collect_model_type_imports(
    model_type: &PlannedType,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    let PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(proto))) =
        model_type
    else {
        return;
    };
    collect_proto_type_imports(&proto.proto, imports);
    if let Some(replacement) = &proto.replacement {
        collect_type_replacement_imports(replacement, imports);
    }
    if let Some(authored_type) = &proto.authored_type {
        collect_authored_type_imports(authored_type, imports);
    }
}

fn collect_type_replacement_imports(
    replacement: &TypeReplacementSpec,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    collect_python_import(&replacement.type_name, imports);
    collect_python_import(&replacement.from_proto, imports);
    collect_python_import(&replacement.to_proto, imports);
}

fn collect_value_type_imports(value: &PlannedType, imports: &mut BTreeSet<LanguageImportSpec>) {
    match value {
        PlannedType::Enum(_) | PlannedType::TypeParameter(_) => {}
        PlannedType::Flags(_) | PlannedType::Variant(_) => {}
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enumeration))) => {
            collect_proto_type_imports(&enumeration.proto, imports);
            if let Some(replacement) = &enumeration.replacement {
                collect_type_replacement_imports(replacement, imports);
            }
        }
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
        | PlannedType::External(ExternalTypeSpec::Json(_))
        | PlannedType::Record(_) => {
            collect_model_type_imports(value, imports);
        }
        PlannedType::Resource(resource) => {
            if let Some(wire_type) = &resource.wire_type {
                collect_model_type_imports(&PlannedType::External(wire_type.clone()), imports);
            }
        }
        PlannedType::Option(inner) | PlannedType::List(inner) => {
            collect_value_type_imports(inner, imports)
        }
        PlannedType::Map(key, value) => {
            collect_value_type_imports(key, imports);
            collect_value_type_imports(value, imports);
        }
        PlannedType::Tuple(items) => {
            for item in items {
                collect_value_type_imports(item, imports);
            }
        }
        PlannedType::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_value_type_imports(ok, imports);
            }
            if let Some(err) = err {
                collect_value_type_imports(err, imports);
            }
        }
        PlannedType::External(ExternalTypeSpec::Alias {
            type_name, target, ..
        }) => {
            collect_python_import(type_name, imports);
            collect_value_type_imports(target, imports);
        }
        PlannedType::Bool
        | PlannedType::Int(_)
        | PlannedType::Float
        | PlannedType::String
        | PlannedType::Bytes => {}
    }
}

fn collect_function_imports(
    function: &FunctionFieldSpec<PlannedFamily>,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    if let FunctionResultSpec::Annotation(result) = &function.result {
        collect_python_import(result, imports);
    }
    collect_function_args_imports(&function.args, imports);
    if let Some(alternate_type) = &function.alternate_type {
        collect_authored_type_imports(alternate_type, imports);
    }
    if let Some(descriptor) = &function.type_descriptor {
        collect_python_import(&descriptor.value_type, imports);
        collect_python_import(&descriptor.args_type, imports);
    }
}

fn collect_function_args_imports(
    args: &FunctionArgsSpec<PlannedFamily>,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    let fields = match args {
        FunctionArgsSpec::Varargs { prefix, .. } => prefix,
        FunctionArgsSpec::Fixed(fields) => fields,
    };
    for field in fields {
        collect_authored_type_imports(&field.field_type, imports);
    }
}

fn collect_authored_type_imports(
    field_type: &PlannedType,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    match field_type {
        TypeSpec::Option(inner) | TypeSpec::List(inner) => {
            collect_authored_type_imports(inner, imports);
        }
        TypeSpec::Tuple(items) => {
            for item in items {
                collect_authored_type_imports(item, imports);
            }
        }
        TypeSpec::Map(key, value) => {
            collect_authored_type_imports(key, imports);
            collect_authored_type_imports(value, imports);
        }
        TypeSpec::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_authored_type_imports(ok, imports);
            }
            if let Some(err) = err {
                collect_authored_type_imports(err, imports);
            }
        }
        TypeSpec::External(ExternalTypeSpec::Alias {
            target, type_name, ..
        }) => {
            collect_python_import(type_name, imports);
            collect_authored_type_imports(target, imports);
        }
        TypeSpec::TypeParameter(_)
        | TypeSpec::Bool
        | TypeSpec::Int(_)
        | TypeSpec::Float
        | TypeSpec::String
        | TypeSpec::Bytes
        | TypeSpec::External(ExternalTypeSpec::Proto(_))
        | TypeSpec::External(ExternalTypeSpec::Json(_))
        | TypeSpec::Record(_)
        | TypeSpec::Enum(_)
        | TypeSpec::Flags(_)
        | TypeSpec::Variant(_)
        | TypeSpec::Resource(_) => {}
    }
}

fn collect_python_import(spec: &LanguageStringSpec, imports: &mut BTreeSet<LanguageImportSpec>) {
    if let Some(module) = spec.import_for_language(Language::Python) {
        imports.insert(LanguageImportSpec {
            language: Language::Python,
            reference: module.to_string(),
            module: module.to_string(),
            name: None,
            type_only: false,
            import_style: LanguageImportStyle::Module,
        });
        return;
    }

    let Some(expression) = spec.for_language(Language::Python) else {
        return;
    };
    for module_path in python_qualified_module_paths(expression) {
        imports.insert(LanguageImportSpec {
            language: Language::Python,
            reference: module_path.clone(),
            module: module_path,
            name: None,
            type_only: false,
            import_style: LanguageImportStyle::Module,
        });
    }
}

fn python_qualified_module_paths(expression: &str) -> BTreeSet<String> {
    let chars = expression.char_indices().collect::<Vec<_>>();
    let mut module_paths = BTreeSet::new();
    let mut index = 0;
    while index < chars.len() {
        let (start_byte, ch) = chars[index];
        if !is_python_identifier_start(ch) {
            index += 1;
            continue;
        }

        let before = expression[..start_byte].chars().next_back();
        if before.is_some_and(|before| is_python_identifier_char(before) || before == '.') {
            index += 1;
            continue;
        }

        let mut end = index + 1;
        while end < chars.len() {
            let ch = chars[end].1;
            if is_python_identifier_char(ch) || ch == '.' {
                end += 1;
            } else {
                break;
            }
        }
        let end_byte = chars
            .get(end)
            .map(|(byte, _)| *byte)
            .unwrap_or(expression.len());
        let qualified_name = expression[start_byte..end_byte].trim_end_matches('.');
        if let Some(module_path) = python_module_path_for_qualified_name(qualified_name) {
            module_paths.insert(module_path.to_string());
        }
        index = end;
    }
    module_paths
}

fn python_module_path_for_qualified_name(qualified_name: &str) -> Option<&str> {
    let (module_path, _) = qualified_name.rsplit_once('.')?;
    if is_builtin_python_import(module_path) {
        return None;
    }
    Some(module_path)
}

fn is_builtin_python_import(module_path: &str) -> bool {
    matches!(
        module_path,
        "collections.abc" | "typing" | "typing_extensions"
    )
}

fn is_python_identifier_start(ch: char) -> bool {
    ch.is_ascii_alphabetic() || ch == '_'
}

fn reject_support_namespaces(
    language: Language,
    support_fragments: &[SupportFragmentSpec],
) -> Result<()> {
    if let Some(namespace) = support_fragments
        .iter()
        .find_map(|fragment| fragment.namespace.as_deref())
    {
        return Err(Error::UnsupportedSupportNamespace {
            language,
            namespace: namespace.to_string(),
        });
    }
    Ok(())
}

