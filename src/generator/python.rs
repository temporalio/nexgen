impl RenderedModelFragments {
    pub(in crate::generator) fn extend(&mut self, other: Self) {
        if !other.body.is_empty() {
            if !self.body.is_empty() {
                self.body.push_str("\n\n");
            }
            self.body.push_str(&other.body);
        }
        if !other.post_model_statements.is_empty() {
            if !self.post_model_statements.is_empty() {
                self.post_model_statements.push_str("\n\n");
            }
            self.post_model_statements
                .push_str(&other.post_model_statements);
        }
        self.module_imports.extend(other.module_imports);
        self.allows_private_wire_access |= other.allows_private_wire_access;
        for (module, names) in other.relative_imports {
            self.relative_imports
                .entry(module)
                .or_default()
                .extend(names);
        }
        extend_root_package_imports(&mut self.root_package_imports, other.root_package_imports);
        self.exported_names.extend(other.exported_names);
    }
}

