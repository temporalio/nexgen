fn render_service_definition(output: &mut String, service: &RenderedService<'_>) {
    if service.deprecated {
        output.push_str(
            "@typing_extensions.deprecated(\"This service is deprecated.\", category=None)\n",
        );
    }
    if service.wire_name == service.name {
        output.push_str("@service\n");
    } else {
        output.push_str("@service(name=");
        output.push_str(&python_string_literal(service.wire_name));
        output.push_str(")\n");
    }
    output.push_str("class ");
    output.push_str(service.name);
    output.push_str(":\n");
    render_python_docstring(
        output,
        "    ",
        service.doc.as_deref(),
        &[],
        None,
        service.experimental,
    );

    if service.operations.is_empty() {
        if !service.experimental {
            output.push_str("    pass\n");
        }
        return;
    }

    for (operation_index, operation) in service.operations.iter().enumerate() {
        if operation.experimental {
            output.push_str("    # ");
            output.push_str(".. warning:: ");
            output.push_str(EXPERIMENTAL_WARNING);
            output.push('\n');
        }
        output.push_str("    ");
        output.push_str(&operation.attr_name);
        if operation.deprecated {
            output.push_str(": typing.Annotated[Operation[\n");
        } else {
            output.push_str(": Operation[\n");
        }
        output.push_str("        ");
        output.push_str(&service_type_ref(
            operation
                .input
                .as_ref()
                .map(|input| input.descriptor_type_ref.as_str())
                .unwrap_or("None"),
        ));
        output.push_str(",\n");
        output.push_str("        ");
        output.push_str(&service_type_ref(&operation.descriptor_output_ref));
        output.push_str(",\n");
        if operation.deprecated {
            output.push_str(
                "    ], typing_extensions.deprecated(\"This operation is deprecated.\", category=None)] = Operation(name=",
            );
        } else {
            output.push_str("    ] = Operation(name=");
        }
        output.push_str(&python_string_literal(operation.wire_name));
        if operation.deprecated {
            // `nexusrpc.service` currently ignores `Annotated[Operation[...]]`
            // while discovering the generic arguments. Supply the same types on
            // the descriptor value so the PEP 702 metadata remains available to
            // type checkers without weakening the runtime service definition.
            let input_type = operation
                .input
                .as_ref()
                .map(|input| input.descriptor_type_ref.as_str())
                .unwrap_or("None");
            output.push_str(", input_type=");
            output.push_str(&service_operation_runtime_type_ref(input_type));
            output.push_str(", output_type=");
            output.push_str(&service_operation_runtime_type_ref(
                &operation.descriptor_output_ref,
            ));
        }
        output.push_str(")\n");
        if service.doc.is_some() {
            render_python_docstring(output, "    ", operation.doc.as_deref(), &[], None, false);
        }

        if operation_index + 1 != service.operations.len() {
            output.push('\n');
        }
    }
}

fn service_type_ref(type_ref: &str) -> String {
    type_ref
        .strip_prefix("models.")
        .unwrap_or(type_ref)
        .to_string()
}

fn service_operation_runtime_type_ref(type_ref: &str) -> String {
    let type_ref = service_type_ref(type_ref);
    if type_ref == "None" {
        "type(None)".to_string()
    } else {
        type_ref
    }
}

fn local_python_model_type_expr(type_ref: &str) -> String {
    type_ref
        .strip_prefix("models.")
        .or_else(|| type_ref.strip_prefix("_recursive."))
        .unwrap_or(type_ref)
        .to_string()
}

fn model_type_name(type_ref: &str) -> Option<String> {
    let type_name = type_ref
        .strip_prefix("models.")
        .or_else(|| type_ref.strip_prefix("_recursive."))
        .unwrap_or(type_ref);
    (type_name != "None" && !type_name.contains('.')).then(|| type_name.to_string())
}

fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("class ");
    output.push_str(&enumeration.name);
    output.push_str("(enum.IntEnum):\n");

    if enumeration.values.is_empty() {
        output.push_str("    pass\n");
        return;
    }

    for value in &enumeration.values {
        output.push_str("    ");
        output.push_str(&value.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
}

fn render_flags(output: &mut String, flags: &RenderedFlags) {
    // Keep native WIT flags default-converter friendly for now. We can return
    // to enum.IntFlag once native WIT types have a consistent cross-language
    // serialization story.
    output.push_str(&flags.name);
    output.push_str(": typing.TypeAlias = int\n");

    if flags.flags.is_empty() {
        return;
    }

    for flag in &flags.flags {
        output.push_str(&flags.name);
        output.push_str(&flag.name);
        output.push_str(" = 1 << ");
        output.push_str(&flag.bit.to_string());
        output.push('\n');
    }
}

fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str(variant.name.as_str());
    output.push_str(" = ");
    if variant.cases.is_empty() {
        output.push_str("typing.Never\n");
        return;
    }
    if variant.cases.len() > 1 {
        output.push_str("(\n    ");
    }
    for (index, case) in variant.cases.iter().enumerate() {
        if index > 0 {
            output.push_str("\n    | ");
        }
        output.push_str("tuple[typing.Literal[");
        output.push_str(&python_string_literal(&case.name));
        output.push(']');
        if let Some(payload_annotation) = &case.payload_annotation {
            output.push_str(", ");
            output.push_str(payload_annotation);
        }
        output.push(']');
    }
    if variant.cases.len() > 1 {
        output.push_str("\n)");
    }
    output.push('\n');
}

