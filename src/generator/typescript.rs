fn typescript_function_constraint(args: &RenderedFunctionArgs, result_annotation: &str) -> String {
    match args {
        RenderedFunctionArgs::Varargs {
            prefix,
            typescript_drop_prefix,
        } => {
            if *typescript_drop_prefix {
                return format!("(...args: any[]) => {result_annotation}");
            }
            let mut parameters = prefix
                .iter()
                .map(|parameter| format!("{}: {}", parameter.name, parameter.annotation))
                .collect::<Vec<_>>();
            parameters.push("...args: any[]".to_string());
            format!("({}) => {result_annotation}", parameters.join(", "))
        }
        RenderedFunctionArgs::Typed { parameters } => format!(
            "({}) => {result_annotation}",
            parameters
                .iter()
                .map(|parameter| format!("{}: {}", parameter.name, parameter.annotation))
                .collect::<Vec<_>>()
                .join(", ")
        ),
    }
}

fn typescript_function_args(args: &FunctionArgsSpec<PlannedFamily>) -> RenderedFunctionArgs {
    match args {
        FunctionArgsSpec::Varargs {
            prefix,
            typescript_drop_prefix,
        } => RenderedFunctionArgs::Varargs {
            prefix: prefix
                .iter()
                .map(|arg| RenderedFunctionArg {
                    name: typescript_ident(&arg.name.to_lower_camel_case()),
                    annotation: typescript_authored_type_annotation(&arg.field_type),
                })
                .collect(),
            typescript_drop_prefix: *typescript_drop_prefix,
        },
        FunctionArgsSpec::Fixed(args) => RenderedFunctionArgs::Typed {
            parameters: args
                .iter()
                .map(|arg| RenderedFunctionArg {
                    name: typescript_ident(&arg.name.to_lower_camel_case()),
                    annotation: typescript_authored_type_annotation(&arg.field_type),
                })
                .collect(),
        },
    }
}

