fn contains_identifier(source: &str, identifier: &str) -> bool {
    source.match_indices(identifier).any(|(index, _)| {
        let before = source[..index].chars().next_back();
        let after = source[index + identifier.len()..].chars().next();
        !before.is_some_and(is_typescript_identifier_char)
            && !after.is_some_and(is_typescript_identifier_char)
    })
}

fn contains_qualified_identifier(source: &str, identifier: &str) -> bool {
    let chars = source.char_indices().collect::<Vec<_>>();
    let mut index = 0;
    while index < chars.len() {
        let (start_byte, ch) = chars[index];
        match ch {
            '\'' | '"' | '`' => {
                index = skip_typescript_string(&chars, index, ch);
                continue;
            }
            '/' if chars.get(index + 1).is_some_and(|(_, next)| *next == '/') => {
                index += 2;
                while index < chars.len() && chars[index].1 != '\n' {
                    index += 1;
                }
                continue;
            }
            '/' if chars.get(index + 1).is_some_and(|(_, next)| *next == '*') => {
                index += 2;
                while index + 1 < chars.len() {
                    if chars[index].1 == '*' && chars[index + 1].1 == '/' {
                        index += 2;
                        break;
                    }
                    index += 1;
                }
                continue;
            }
            _ => {}
        }

        if !is_typescript_identifier_start(ch) {
            index += 1;
            continue;
        }

        let before = source[..start_byte].chars().next_back();
        if before.is_some_and(|before| is_typescript_identifier_char(before) || before == '.') {
            index += 1;
            continue;
        }

        let mut end = index + 1;
        while end < chars.len() && is_typescript_identifier_char(chars[end].1) {
            end += 1;
        }
        let end_byte = chars
            .get(end)
            .map(|(byte, _)| *byte)
            .unwrap_or(source.len());
        if &source[start_byte..end_byte] == identifier {
            let mut after = end;
            while after < chars.len() && chars[after].1.is_whitespace() {
                after += 1;
            }
            if after < chars.len() && chars[after].1 == '.' {
                return true;
            }
        }
        index = end;
    }
    false
}

fn skip_typescript_string(chars: &[(usize, char)], start: usize, quote: char) -> usize {
    let mut index = start + 1;
    let mut escaped = false;
    while index < chars.len() {
        let ch = chars[index].1;
        if escaped {
            escaped = false;
        } else if ch == '\\' {
            escaped = true;
        } else if ch == quote {
            return index + 1;
        }
        index += 1;
    }
    index
}

fn is_typescript_identifier_start(ch: char) -> bool {
    ch.is_ascii_alphabetic() || ch == '_' || ch == '$'
}

fn is_typescript_identifier_char(ch: char) -> bool {
    ch.is_ascii_alphanumeric() || ch == '_' || ch == '$'
}

fn used_import_names(source: &str, names: &[String]) -> Vec<String> {
    names
        .iter()
        .filter(|name| contains_identifier(source, name))
        .cloned()
        .collect()
}

fn render_generated_module(imports: String, body: String) -> String {
    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push_str("\n\n");
    if !imports.is_empty() {
        output.push_str(&imports);
        output.push('\n');
    }
    output.push_str(&body);
    if !body.ends_with('\n') {
        output.push('\n');
    }
    output
}

/// Whether a rendered module carries nothing but the generated header, so
/// emitting it would produce a file with no exports.
fn is_blank_generated_module(source: &str) -> bool {
    source
        .strip_prefix(GENERATED_HEADER)
        .unwrap_or(source)
        .trim()
        .is_empty()
}

fn render_definitions_only_index_module(
    services: &[RenderedService<'_>],
    has_models_module: bool,
    additional_exports: &[String],
) -> String {
    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push_str("\n\n");
    if !services.is_empty() {
        output.push_str("export * from './services';\n");
    }
    if has_models_module {
        output.push_str("export * from './models';\n");
    }
    if services.iter().any(|service| !service.resources.is_empty()) {
        output.push_str("export * from './resources';\n");
    }
    for export in additional_exports {
        output.push_str(export);
        output.push('\n');
    }
    output
}

fn render_support_module(support_source: &str) -> String {
    render_generated_module(String::new(), support_source.to_string())
}

fn render_index_module(
    services: &[RenderedService<'_>],
    model_type_names: &BTreeSet<String>,
    additional_exports: &[String],
) -> String {
    let mut body = String::new();
    for service in services {
        if service.endpoint.is_some() {
            for operation in &service.operations {
                body.push_str("export { ");
                body.push_str(&operation.attr_name);
                body.push_str(" } from './operations/");
                body.push_str(&operation_file_name(operation));
                body.push_str("';\n");
            }
        } else {
            body.push_str("export { ");
            body.push_str(&service.attr_name);
            body.push_str(", ");
            body.push_str(&endpoint_service_class_name(service));
            body.push_str(" } from './services';\n");
        }
    }
    let mut model_names = services
        .iter()
        .flat_map(|service| {
            service.operations.iter().flat_map(|operation| {
                let output_model_name = service
                    .endpoint
                    .is_none()
                    .then(|| operation.output_model_name.as_deref())
                    .flatten();
                operation
                    .input
                    .as_ref()
                    .and_then(|input| input.model_name.as_deref())
                    .into_iter()
                    .chain(output_model_name)
            })
        })
        .collect::<Vec<_>>();
    model_names.sort();
    model_names.dedup();
    if !model_names.is_empty() {
        body.push_str("export type { ");
        body.push_str(&model_names.join(", "));
        body.push_str(" } from './models';\n");
    } else if services.is_empty() && !model_type_names.is_empty() {
        // A model-only module (no services of its own) has no operation-derived
        // name list to narrow to, so export the model types it declares directly
        // — a named list, not `export type *`, since the latter would also sweep
        // up same-named value-only helpers (e.g. `requiredField`) declared per
        // leaf, causing ambiguous-export errors once sibling leaves are
        // re-exported together from a shared branch index.
        body.push_str("export type { ");
        body.push_str(
            &model_type_names
                .iter()
                .cloned()
                .collect::<Vec<_>>()
                .join(", "),
        );
        body.push_str(" } from './models';\n");
    }
    for export in additional_exports {
        body.push_str(export);
        body.push('\n');
    }
    render_generated_module(String::new(), body)
}

fn render_endpoint_service_class(output: &mut String, service: &RenderedService<'_>) {
    let doc_tags = declaration_doc_tags(service.experimental, service.deprecated);
    render_typescript_doc_comment(output, "", service.doc.as_deref(), &doc_tags);
    output.push_str("export class ");
    output.push_str(&endpoint_service_class_name(service));
    output.push_str(" {\n");
    output.push_str("  private readonly client: workflow.NexusServiceClient<typeof ");
    output.push_str(&service.attr_name);
    output.push_str(">;\n\n");
    output.push_str("  public constructor(endpoint: string) {\n");
    output.push_str("    this.client = workflow.createNexusServiceClient({\n");
    output.push_str("      service: ");
    output.push_str(&service.attr_name);
    output.push_str(",\n");
    output.push_str("      endpoint,\n");
    output.push_str("    });\n");
    output.push_str("  }\n");
    for operation in &service.operations {
        output.push('\n');
        render_endpoint_service_operation_method(output, service, operation);
    }
    output.push_str("}\n");
}

fn endpoint_service_class_name(service: &RenderedService<'_>) -> String {
    format!("{}Client", service.name)
}

fn render_endpoint_service_operation_method(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) {
    let mut doc_tags = Vec::new();
    if operation.input.is_some() {
        doc_tags.push((
            "@param request -".to_string(),
            "Request for the operation.".to_string(),
        ));
    }
    if let Some(return_doc) = &operation.return_doc {
        doc_tags.push(("@returns".to_string(), return_doc.clone()));
    }
    if operation.experimental {
        doc_tags.push((
            "@experimental".to_string(),
            EXPERIMENTAL_WARNING.to_string(),
        ));
    }
    if operation.deprecated {
        doc_tags.push(("@deprecated".to_string(), String::new()));
    }
    render_typescript_doc_comment(output, "  ", operation.doc.as_deref(), &doc_tags);
    output.push_str("  public async ");
    output.push_str(&operation.attr_name);
    output.push_str("(\n");
    if let Some(input) = &operation.input {
        output.push_str("    request: ");
        output.push_str(&input.annotation);
        output.push_str(",\n");
    }
    output.push_str("  ): Promise<");
    output.push_str(&typescript_operation_public_return_annotation(
        service, operation,
    ));
    output.push_str("> {\n");
    render_endpoint_service_operation_body(output, service, operation);
    output.push_str("  }\n");
}

fn render_endpoint_service_operation_body(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
) {
    let returns_direct = operation.output_transform_expr.is_some()
        || operation.output_resource_return.is_some()
        || operation.output_direct_result;
    if !returns_direct {
        output.push_str("    return await this.client.startOperation(\n");
        output.push_str("      ");
        output.push_str(&service.attr_name);
        output.push_str(".operations.");
        output.push_str(&operation.attr_name);
        output.push_str(",\n");
        output.push_str("      ");
        output.push_str(&typescript_operation_input_expr(operation));
        output.push_str(",\n");
        output.push_str("    );\n");
        return;
    }

    output.push_str("    const requestProto = ");
    output.push_str(&typescript_operation_input_expr(operation));
    output.push_str(";\n");
    output.push_str("    const handle = await this.client.startOperation(\n");
    output.push_str("      ");
    output.push_str(&service.attr_name);
    output.push_str(".operations.");
    output.push_str(&operation.attr_name);
    output.push_str(",\n");
    output.push_str("      requestProto,\n");
    output.push_str("    );\n");
    if let Some(transform_expr) = &operation.output_transform_expr {
        output.push_str("    const result = await handle.result();\n");
        output.push_str("    return ");
        output.push_str(transform_expr);
        output.push_str(";\n");
    } else if let Some(resource_return) = &operation.output_resource_return {
        output.push_str("    const result = await handle.result();\n");
        output.push_str("    return ");
        output.push_str(&resource_client_bind_function_name_for_type(
            &resource_return.resource_type_name,
        ));
        output.push_str("(\n");
        output.push_str("      new ");
        output.push_str(&resource_return.resource_type_name);
        output.push_str("(\n");
        for binding in &resource_return.bindings {
            output.push_str("        ");
            output.push_str(&resource_return_binding_expr_typescript(binding));
            output.push_str(",\n");
        }
        output.push_str("      ),\n");
        output.push_str("      this.client,\n");
        output.push_str("    );\n");
    } else if operation.output_direct_result {
        if let Some(resource) = service
            .resources
            .iter()
            .find(|resource| resource.type_name == operation.output_annotation)
        {
            output.push_str("    const resource = await handle.result();\n");
            output.push_str("    return ");
            output.push_str(&resource_client_bind_function_name(resource));
            output.push_str("(resource, this.client);\n");
        } else {
            output.push_str("    return await handle.result();\n");
        }
    }
}

fn render_operation_registry_module(services: &[RenderedService<'_>]) -> String {
    let mut body = String::new();
    let has_serialization_context = services
        .iter()
        .flat_map(|service| &service.operations)
        .any(|operation| operation.serialization_context_expr.is_some());
    if has_serialization_context {
        body.push_str("export interface OperationRegistryEntry<Input = unknown> {\n");
        body.push_str("  readonly service: string;\n");
        body.push_str("  readonly operation: string;\n");
        body.push_str("  readonly inputType: string;\n");
        body.push_str("  readonly outputType: string;\n");
        body.push_str("  /** Generated payload visitor for the input protobuf envelope. */\n");
        body.push_str("  readonly inputPayloadVisitor: string;\n");
        body.push_str("  /** Generated payload visitor for the output protobuf envelope. */\n");
        body.push_str("  readonly outputPayloadVisitor: string;\n");
        body.push_str("  /** Context for nested payloads, determined by the operation. */\n");
        body.push_str("  readonly serializationContext?: (input: Input) => import('@temporalio/common').SerializationContext;\n");
        body.push_str("}\n\n");
    }
    body.push_str("export const operationRegistry = [\n");
    for service in services {
        for operation in &service.operations {
            body.push_str("  {\n");
            body.push_str("    service: ");
            body.push_str(&typescript_string_literal(service.wire_name));
            body.push_str(",\n");
            body.push_str("    operation: ");
            body.push_str(&typescript_string_literal(operation.wire_name));
            body.push_str(",\n");
            body.push_str("    inputType: ");
            body.push_str(&typescript_string_literal(
                operation
                    .input
                    .as_ref()
                    .map(|input| input.type_id.as_str())
                    .unwrap_or("void"),
            ));
            body.push_str(",\n");
            body.push_str("    outputType: ");
            body.push_str(&typescript_string_literal(&operation.output_type_id));
            body.push_str(",\n");
            let input_type = operation
                .input
                .as_ref()
                .map(|input| input.type_id.as_str())
                .unwrap_or("void");
            body.push_str("    inputPayloadVisitor: ");
            body.push_str(&typescript_string_literal(&format!(
                "walk{}",
                input_type.rsplit('.').next().unwrap_or(input_type)
            )));
            body.push_str(",\n");
            body.push_str("    outputPayloadVisitor: ");
            body.push_str(&typescript_string_literal(&format!(
                "walk{}",
                operation
                    .output_type_id
                    .rsplit('.')
                    .next()
                    .unwrap_or(&operation.output_type_id)
            )));
            body.push_str(",\n");
            if let Some(serialization_context) = &operation.serialization_context_expr {
                body.push_str("    serializationContext: ");
                body.push_str(serialization_context);
                body.push_str(",\n");
            }
            body.push_str("  },\n");
        }
    }
    body.push_str("] as const;\n");
    body
}

/// Renders the operation-specific interception surface consumed by the SDK's
/// workflow outbound interceptor. It deliberately remains separate from the
/// generic System Nexus hook, as it does in the other SDKs.
fn render_system_nexus_interceptor_interface(services: &[RenderedService<'_>]) -> String {
    let operations = services
        .iter()
        .filter(|service| service.endpoint.is_some())
        .flat_map(|service| service.operations.iter())
        .collect::<Vec<_>>();
    if operations.is_empty() {
        return String::new();
    }
    let mut body = String::from("export interface SystemNexusWorkflowOutboundCallsInterceptor {\n");
    for operation in operations {
        let input = operation
            .input
            .as_ref()
            .and_then(|input| input.model_name.as_deref())
            .or_else(|| {
                operation
                    .input
                    .as_ref()
                    .map(|input| input.annotation.as_str())
            })
            .unwrap_or("undefined");
        body.push_str("  ");
        body.push_str(&operation.attr_name);
        body.push_str("?: ");
        body.push_str("(input: ");
        body.push_str(input);
        body.push_str(", next: (input: ");
        body.push_str(input);
        body.push_str(") => Promise<unknown>) => Promise<unknown>;\n");
    }
    body.push_str("}\n");
    body
}

fn render_models_module(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    external_models: &TypeScriptExternalModels,
    model_fragments: &RenderedExternalModelFragments,
    requirements: &TypeScriptRequirements,
    language_imports: &[LanguageImportSpec],
    support_exports: Option<&SupportExports>,
    api_plan: &PlannedSpec,
) -> String {
    let mode = crate::nexgen_config::current().mode;
    let mut body = String::new();

    if mode == GenerationMode::NativeApi {
        render_required_field(&mut body, true);
    }
    let uses_function_payload_helpers = models.iter().any(|model| {
        model.fields.iter().any(|field| {
            field.to_wire_expr.contains("requestArgsToPayloads(")
                || field.from_wire_expr.contains("requestArgsFromPayloads(")
                || field.flattened_fields.iter().any(|field| {
                    field.to_wire_expr.contains("requestArgsToPayloads(")
                        || field.from_wire_expr.contains("requestArgsFromPayloads(")
                })
        })
    });
    if uses_function_payload_helpers {
        body.push('\n');
        render_function_runtime_helpers(
            &mut body,
            models.iter().any(|model| {
                model.fields.iter().any(|field| {
                    field.from_wire_expr.contains("requestArgsFromPayloads(")
                        || field
                            .flattened_fields
                            .iter()
                            .any(|field| field.from_wire_expr.contains("requestArgsFromPayloads("))
                })
            }),
        );
    }
    if !enums.is_empty() {
        body.push('\n');
        for enumeration in enums {
            render_enum(&mut body, enumeration);
            body.push('\n');
        }
    }
    if !flags.is_empty() {
        body.push('\n');
        for flag_set in flags {
            render_flags(&mut body, flag_set);
            body.push('\n');
        }
    }
    if !variants.is_empty() {
        body.push('\n');
        for variant in variants {
            render_variant(&mut body, variant);
            body.push('\n');
        }
    }
    if !models.is_empty() {
        body.push('\n');
        for model in models {
            render_model(&mut body, model, external_models, api_plan);
            body.push('\n');
        }
    }
    if !model_fragments.body.is_empty() {
        body.push('\n');
        body.push_str(&model_fragments.body);
    }
    let mut imports = String::new();
    let mut generated_value_imports = Vec::new();
    if crate::nexgen_config::current().system_nexus
        && contains_qualified_identifier(&body, "workflow")
    {
        generated_value_imports.push(("workflow", typescript_workflow_module()));
    }
    let mut model_language_imports = language_imports.to_vec();
    let value_namespace_imports = models
        .iter()
        .flat_map(|model| model.fields.iter())
        .flat_map(|field| field.requirements.value_namespace_imports.iter())
        .collect::<BTreeSet<_>>();
    for import in &mut model_language_imports {
        if import.type_only
            && import
                .name
                .as_ref()
                .is_some_and(|name| value_namespace_imports.contains(name))
        {
            import.type_only = false;
        }
    }
    if uses_function_payload_helpers {
        model_language_imports.push(LanguageImportSpec {
            language: Language::TypeScript,
            reference: "temporal".to_string(),
            module: "@temporalio/proto".to_string(),
            name: Some("temporal".to_string()),
            type_only: true,
            import_style: LanguageImportStyle::Named,
        });
    }
    render_typescript_namespace_imports(
        &mut imports,
        &body,
        &model_language_imports,
        &generated_value_imports,
    );
    render_typescript_requirement_imports(&mut imports, requirements);
    render_support_imports(&mut imports, support_exports, "./support", &body);
    if !model_fragments.imports.is_empty() {
        if !imports.is_empty() && !imports.ends_with('\n') {
            imports.push('\n');
        }
        imports.push_str(&model_fragments.imports);
    }
    render_cross_module_model_value_imports(
        &mut imports,
        &api_plan.module_path.to_path_buf(),
        api_plan,
        &body,
    );
    render_cross_module_model_type_imports(
        &mut imports,
        &api_plan.module_path.to_path_buf(),
        api_plan,
        &body,
    );
    render_generated_module(imports, body)
}

fn typescript_relative_models_module_from_dir(from_dir: &Path, to: &ModulePath) -> String {
    let target = to.to_path_buf().join("models");
    relative_module_path(from_dir, &target)
}

fn render_cross_module_model_type_imports(
    output: &mut String,
    source_dir: &Path,
    api_plan: &PlannedSpec,
    source: &str,
) {
    for (module_path, names) in &api_plan.data.module_imports {
        let candidates = names.iter().cloned().collect::<Vec<_>>();
        let used_names = used_import_names(source, &candidates);
        if !used_names.is_empty() {
            render_type_imports(
                output,
                &typescript_relative_models_module_from_dir(source_dir, module_path),
                &used_names,
            );
        }
    }
}

fn render_cross_module_model_value_imports(
    output: &mut String,
    source_dir: &Path,
    api_plan: &PlannedSpec,
    source: &str,
) {
    for (module_path, names) in &api_plan.data.module_imports {
        let candidates = names
            .iter()
            .map(|name| typescript_json::ts_transfer_type_converter_name(name))
            .collect::<Vec<_>>();
        let used_names = used_import_names(source, &candidates);
        if !used_names.is_empty() {
            render_value_imports(
                output,
                &typescript_relative_models_module_from_dir(source_dir, module_path),
                &used_names,
            );
        }
    }
}

fn relative_module_path(from_dir: &std::path::Path, target: &std::path::Path) -> String {
    let from = from_dir.components().collect::<Vec<_>>();
    let to = target.components().collect::<Vec<_>>();
    let common = from
        .iter()
        .zip(to.iter())
        .take_while(|(left, right)| left == right)
        .count();
    let mut parts = Vec::new();
    for _ in common..from.len() {
        parts.push("..".to_string());
    }
    for component in &to[common..] {
        parts.push(component.as_os_str().to_string_lossy().to_string());
    }
    let path = parts.join("/");
    if path.starts_with('.') {
        path
    } else {
        format!("./{path}")
    }
}

#[allow(clippy::too_many_arguments)]
fn render_service_module(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    external_model_names: &BTreeSet<String>,
    services: &[RenderedService<'_>],
    language_imports: &[LanguageImportSpec],
    support_exports: Option<&SupportExports>,
    include_native_api: bool,
    api_plan: &PlannedSpec,
) -> String {
    let mut body = String::new();
    for service in services {
        render_service_definition(&mut body, service);
        body.push('\n');
        if include_native_api && service.endpoint.is_none() {
            render_endpoint_service_class(&mut body, service);
            body.push('\n');
        }
    }
    if include_native_api {
        body.push_str(&render_operation_registry_module(services));
        if crate::nexgen_config::current().system_nexus {
            body.push_str(&render_system_nexus_interceptor_interface(services));
        }
    }
    let mut imports = String::new();
    render_typescript_namespace_imports(
        &mut imports,
        &body,
        language_imports,
        &[
            ("nexus", "nexus-rpc"),
            ("workflow", typescript_workflow_module()),
        ],
    );
    render_typescript_default_type_import_if_used(&mut imports, &body, "Long", "long");
    render_support_imports(&mut imports, support_exports, "./support", &body);
    // Operation type info references converter *values*, so they import alongside
    // (and before) the type-only model imports.
    render_value_imports(
        &mut imports,
        "./models",
        &used_import_names(
            &body,
            &models
                .iter()
                .filter_map(|model| {
                    model.wire_function_names.as_ref().map(|_| {
                        format!("{}TransferTypeConverter", model.name.to_lower_camel_case())
                    })
                })
                .chain(
                    external_model_names
                        .iter()
                        .map(|name| typescript_json::ts_transfer_type_converter_name(name)),
                )
                .collect::<Vec<_>>(),
        ),
    );
    render_type_imports(
        &mut imports,
        "./models",
        &used_import_names(
            &body,
            &model_type_names(enums, flags, variants, models, external_model_names),
        ),
    );
    render_cross_module_model_value_imports(
        &mut imports,
        &api_plan.module_path.to_path_buf(),
        api_plan,
        &body,
    );
    render_cross_module_model_type_imports(
        &mut imports,
        &api_plan.module_path.to_path_buf(),
        api_plan,
        &body,
    );
    render_type_imports(
        &mut imports,
        "./resources",
        &used_import_names(&body, &resource_type_names(services)),
    );
    let resource_client_binders = services
        .iter()
        .filter(|service| include_native_api && service.endpoint.is_none())
        .flat_map(|service| service.resources.iter())
        .filter(|resource| {
            contains_identifier(&body, &resource_client_bind_function_name(resource))
        })
        .map(resource_client_bind_function_name)
        .collect::<Vec<_>>();
    render_value_imports(&mut imports, "./resources", &resource_client_binders);
    render_generated_module(imports, body)
}

#[allow(clippy::too_many_arguments)]
fn render_resources_module(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    external_model_names: &BTreeSet<String>,
    services: &[RenderedService<'_>],
    requirements: &TypeScriptRequirements,
    language_imports: &[LanguageImportSpec],
    support_exports: Option<&SupportExports>,
    api_plan: &PlannedSpec,
) -> String {
    let mut body = String::new();
    for service in services {
        for resource in &service.resources {
            render_resource(&mut body, resource, service);
            body.push('\n');
        }
    }
    let mut imports = String::new();
    render_typescript_namespace_imports(
        &mut imports,
        &body,
        language_imports,
        &[("workflow", typescript_workflow_module())],
    );
    render_typescript_requirement_imports(&mut imports, requirements);
    render_type_imports(
        &mut imports,
        "./models",
        &used_import_names(
            &body,
            &model_type_names(enums, flags, variants, models, external_model_names),
        ),
    );
    render_cross_module_model_type_imports(
        &mut imports,
        &api_plan.module_path.to_path_buf(),
        api_plan,
        &body,
    );
    render_support_imports(&mut imports, support_exports, "./support", &body);
    for service in services {
        if contains_identifier(&body, &service.attr_name) {
            render_value_imports(
                &mut imports,
                "./services",
                std::slice::from_ref(&service.attr_name),
            );
        }
        if service.endpoint.is_some() {
            for operation in &service.operations {
                let operation_function_name =
                    typescript_operation_function_name(service, operation);
                if contains_identifier(&body, &operation_function_name) {
                    render_value_imports(
                        &mut imports,
                        &format!("./operations/{}", operation_file_name(operation)),
                        std::slice::from_ref(&operation_function_name),
                    );
                }
            }
        }
    }
    render_generated_module(imports, body)
}

fn render_operation_module(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    external_model_names: &BTreeSet<String>,
    services: &[RenderedService<'_>],
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    language_imports: &[LanguageImportSpec],
    support_exports: Option<&SupportExports>,
    api_plan: &PlannedSpec,
) -> String {
    let mut body = String::new();
    render_operation_input_alias(&mut body, service, operation);
    render_operation_function(&mut body, service, operation);
    let mut imports = String::new();
    render_typescript_namespace_imports(
        &mut imports,
        &body,
        language_imports,
        &[("workflow", typescript_workflow_module())],
    );
    render_value_imports(&mut imports, "../services", &[service.attr_name.clone()]);
    let mut model_values = model_to_wire_function_names(models);
    model_values.push("requiredField".to_string());
    model_values.sort();
    model_values.dedup();
    render_value_imports(
        &mut imports,
        "../models",
        &used_import_names(&body, &model_values),
    );
    render_type_imports(
        &mut imports,
        "../models",
        &used_import_names(
            &body,
            &model_type_names(enums, flags, variants, models, external_model_names),
        ),
    );
    render_cross_module_model_type_imports(
        &mut imports,
        &api_plan.module_path.to_path_buf().join("operations"),
        api_plan,
        &body,
    );
    render_support_imports(&mut imports, support_exports, "../support", &body);
    let resources = used_import_names(&body, &resource_type_names(services));
    let value_resources = resources
        .iter()
        .filter(|resource| body.contains(&format!("new {resource}(")))
        .cloned()
        .collect::<Vec<_>>();
    let type_resources = resources
        .iter()
        .filter(|resource| !value_resources.contains(resource))
        .cloned()
        .collect::<Vec<_>>();
    let resource_client_binders = services
        .iter()
        .filter(|service| service.endpoint.is_none())
        .flat_map(|service| service.resources.iter())
        .filter(|resource| {
            contains_identifier(&body, &resource_client_bind_function_name(resource))
        })
        .map(resource_client_bind_function_name)
        .collect::<Vec<_>>();
    if !type_resources.is_empty() {
        imports.push_str("import '../resources';\n");
    }
    let mut resource_value_imports = value_resources;
    resource_value_imports.extend(resource_client_binders);
    render_value_imports(&mut imports, "../resources", &resource_value_imports);
    render_type_imports(&mut imports, "../resources", &type_resources);
    render_generated_module(imports, body)
}

fn render_support_imports(
    output: &mut String,
    support_exports: Option<&SupportExports>,
    path: &str,
    source: &str,
) {
    if let Some(support_exports) = support_exports {
        render_value_imports(
            output,
            path,
            &used_import_names(source, &support_exports.value_names),
        );
        render_type_imports(
            output,
            path,
            &used_import_names(source, &support_exports.type_names),
        );
    }
}

fn render_value_imports(output: &mut String, path: &str, names: &[String]) {
    if names.is_empty() {
        return;
    }
    output.push_str("import { ");
    output.push_str(&names.join(", "));
    output.push_str(" } from '");
    output.push_str(path);
    output.push_str("';\n");
}

fn render_type_imports(output: &mut String, path: &str, names: &[String]) {
    if names.is_empty() {
        return;
    }
    output.push_str("import type { ");
    output.push_str(&names.join(", "));
    output.push_str(" } from '");
    output.push_str(path);
    output.push_str("';\n");
}

fn model_type_names(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    external_model_names: &BTreeSet<String>,
) -> Vec<String> {
    enums
        .iter()
        .map(|enumeration| enumeration.name.clone())
        .chain(flags.iter().map(|flags| flags.name.clone()))
        .chain(variants.iter().map(|variant| variant.name.clone()))
        .chain(models.iter().map(|model| model.name.clone()))
        .chain(external_model_names.iter().cloned())
        .collect()
}

fn resource_type_names(services: &[RenderedService<'_>]) -> Vec<String> {
    services
        .iter()
        .flat_map(|service| {
            service
                .resources
                .iter()
                .map(|resource| resource.type_name.clone())
        })
        .collect()
}

fn model_to_wire_function_names(models: &[&RenderedModel]) -> Vec<String> {
    models
        .iter()
        .filter_map(|model| {
            model
                .wire_function_names
                .as_ref()
                .map(|names| names.to_wire.clone())
        })
        .collect()
}

fn render_required_field(output: &mut String, exported: bool) {
    if exported {
        output.push_str("export ");
    }
    output.push_str("function requiredField<T>(\n");
    output.push_str("  value: T | null | undefined,\n");
    output.push_str("  owner: string,\n");
    output.push_str("  field: string,\n");
    output.push_str("): T {\n");
    output.push_str("  if (value == null) {\n");
    output.push_str("    throw new Error(`missing required field ${owner}.${field}`);\n");
    output.push_str("  }\n");
    output.push_str("  return value;\n");
    output.push_str("}\n");
}

fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("export enum ");
    output.push_str(&enumeration.name);
    output.push_str(" {\n");
    if enumeration.values.is_empty() {
        output.push_str("}\n");
        return;
    }
    for value in &enumeration.values {
        output.push_str("  ");
        output.push_str(&value.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push_str(",\n");
    }
    output.push_str("}\n");
}

fn render_flags(output: &mut String, flags: &RenderedFlags) {
    output.push_str("export enum ");
    output.push_str(&flags.name);
    output.push_str(" {\n");
    if flags.flags.is_empty() {
        output.push_str("}\n");
        return;
    }
    for flag in &flags.flags {
        output.push_str("  ");
        output.push_str(&flag.name);
        output.push_str(" = 2 ** ");
        output.push_str(&flag.bit.to_string());
        output.push_str(",\n");
    }
    output.push_str("}\n");
}

fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str("export type ");
    output.push_str(&variant.name);
    if !variant.type_parameters.is_empty() {
        output.push('<');
        output.push_str(&variant.type_parameters.join(", "));
        output.push('>');
    }
    output.push_str(" =\n");
    if variant.cases.is_empty() {
        output.push_str("  never;\n");
        return;
    }
    for (index, case) in variant.cases.iter().enumerate() {
        output.push_str("  | { tag: ");
        output.push_str(&typescript_string_literal(&case.name));
        if let Some(payload_annotation) = &case.payload_annotation {
            output.push_str("; value: ");
            output.push_str(payload_annotation);
        }
        output.push_str(" }");
        if index + 1 == variant.cases.len() {
            output.push_str(";\n");
        } else {
            output.push('\n');
        }
    }
}

