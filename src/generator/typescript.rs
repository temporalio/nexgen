pub(crate) fn generate(
    tree: &crate::spec::ApiSpecTree<PlannedFamily>,
    support: &crate::SupportFiles,
    ts_date_time_types: TsDateTimeTypes,
) -> Result<GeneratedFiles> {
    // A `$ref` resolves against the whole input closure ([[ref]]
    // §"Type-name derivation"). Only this entry point sees every leaf, so the
    // tree-wide model registry the JSON backend consults for a cross-module
    // `oneOf` branch is populated here, before any leaf renders.
    typescript_json::set_tree_json_models(collect_tree_json_models(&tree.root));
    let generated = match &tree.root {
        ApiSpecNode::Leaf(leaf) => {
            let support_fragments = support_fragments_for_plan(&leaf.spec, support);
            generate_leaf(
                &leaf.spec,
                &support_fragments,
                ts_date_time_types,
                GeneratedFileOrigin::fixed("generated TypeScript package module"),
            )
        }
        ApiSpecNode::Branch(branch) => generate_tree(branch, support, ts_date_time_types),
    }?;
    Ok(GeneratedFiles {
        layout: crate::generator::GeneratedOutputLayout::Directory,
        files: generated.files.into_files(),
        warnings: generated.warnings,
    })
}

struct TypeScriptGenerationResult {
    files: GeneratedFileMap,
    warnings: Vec<String>,
}

/// Every JSON model declared anywhere in the spec tree, keyed by `full_name`.
fn collect_tree_json_models(
    node: &ApiSpecNode<PlannedFamily>,
) -> BTreeMap<String, crate::planning::PlannedJsonType> {
    let mut models = BTreeMap::new();
    collect_tree_json_models_into(node, &mut models);
    models
}

fn collect_tree_json_models_into(
    node: &ApiSpecNode<PlannedFamily>,
    models: &mut BTreeMap<String, crate::planning::PlannedJsonType>,
) {
    match node {
        ApiSpecNode::Leaf(leaf) => {
            for (_, binding) in leaf.spec.external_types() {
                if let Some(json_type) = binding.json_model() {
                    models.insert(json_type.full_name.clone(), json_type.clone());
                }
            }
        }
        ApiSpecNode::Branch(branch) => {
            for child in branch.children.values() {
                collect_tree_json_models_into(child, models);
            }
        }
    }
}

fn generate_leaf(
    api_plan: &PlannedSpec,
    support_fragments: &[SupportFragmentSpec],
    ts_date_time_types: TsDateTimeTypes,
    module_origin: GeneratedFileOrigin,
) -> Result<TypeScriptGenerationResult> {
    reject_support_namespaces(Language::TypeScript, support_fragments)?;
    let language_imports = collect_typescript_language_imports(api_plan);
    let mut planner = ApiPlanner::new(api_plan, ts_date_time_types)?;
    let services = api_plan
        .services
        .iter()
        .map(|service| {
            let operations = service
                .operations
                .iter()
                .map(|operation| planner.resolve_operation(operation))
                .collect::<Result<Vec<_>>>()?;

            Ok(RenderedService {
                name: service.name.as_str(),
                attr_name: service
                    .code_name
                    .for_language(Language::TypeScript)
                    .map(str::to_string)
                    .unwrap_or_else(|| typescript_ident(&service.name.to_lower_camel_case())),
                wire_name: service.wire_name.as_str(),
                doc: service
                    .doc
                    .for_language(Language::TypeScript)
                    .map(str::to_string),
                endpoint: service.endpoint.clone(),
                experimental: service.experimental,
                deprecated: service.deprecated,
                operations,
                resources: service
                    .resources
                    .iter()
                    .map(|resource| resource.data.clone())
                    .collect(),
            })
        })
        .collect::<Result<Vec<_>>>()?;

    for service in &services {
        for resource in &service.resources {
            planner.ensure_resource_field_types(resource);
        }
    }
    for record in api_plan.records().map(|(_, record)| record) {
        let model_type = TypeSpec::Record(PlannedRecordType {
            full_name: record.full_name.clone(),
            model_name: record.name.clone(),
        });
        planner.resolve_message_value_conversion(&model_type);
    }

    let support_source = support_source(support_fragments);
    let model_fragments = planner.render_external_models()?;

    render_module_files(
        planner.enums.values().collect::<Vec<_>>().as_slice(),
        planner.flags.values().collect::<Vec<_>>().as_slice(),
        planner.variants.values().collect::<Vec<_>>().as_slice(),
        planner.models.values().collect::<Vec<_>>().as_slice(),
        &planner.external_models,
        &model_fragments,
        &services,
        &language_imports,
        support_source.as_deref(),
        api_plan,
        module_origin,
    )
    .map(|files| TypeScriptGenerationResult {
        files,
        warnings: Vec::new(),
    })
}

fn collect_typescript_language_imports(api_plan: &PlannedSpec) -> Vec<LanguageImportSpec> {
    let mut imports = BTreeSet::new();
    for variant in api_plan.variants().map(|(_, variant)| variant) {
        for case in &variant.cases {
            if let Some(payload) = &case.payload {
                collect_value_type_imports(payload, &mut imports);
            }
        }
    }
    for model in api_plan.records().map(|(_, record)| record) {
        if let Some(proto) = &model.data.proto {
            collect_proto_type_imports(proto, &mut imports);
        }
        for field in model.fields.values() {
            if let Some(annotation) = &field.annotation {
                collect_typescript_import(annotation, true, false, &mut imports);
            }
            if let Some(annotation) = &field.flattened_annotation {
                collect_typescript_import(annotation, true, false, &mut imports);
            }
            match &field.data.wire_binding {
                Some(PlannedWireFieldBinding::Value { wire_type, .. }) => {
                    collect_value_type_imports(wire_type, &mut imports);
                }
                Some(PlannedWireFieldBinding::VariantMembers { members, .. }) => {
                    for member in members {
                        collect_value_type_imports(&member.wire_type, &mut imports);
                    }
                }
                None => {}
            }
        }
        for (_, field) in model.model_fields() {
            if let Some(function) = &field.function {
                collect_function_imports(function, &mut imports);
            }
            collect_value_type_imports(&field.field_type, &mut imports);
        }
        for (_, sourced_field, _) in model.sourced_fields() {
            collect_value_type_imports(&sourced_field.field_type, &mut imports);
        }
    }
    for service in &api_plan.services {
        for operation in &service.operations {
            if let Some(input) = operation_input_model(operation) {
                collect_model_type_imports(input, &mut imports);
            }
            match operation.output_type() {
                Some(
                    model_type @ (PlannedType::External(ExternalTypeSpec::Proto(
                        PlannedProtoType::Message(_),
                    ))
                    | PlannedType::External(ExternalTypeSpec::Json(_))
                    | PlannedType::Record(_)),
                ) => collect_model_type_imports(model_type, &mut imports),
                Some(PlannedType::Resource(resource)) => {
                    if let Some(model_type) = &resource.wire_type {
                        collect_model_type_imports(
                            &PlannedType::External(model_type.clone()),
                            &mut imports,
                        );
                    }
                }
                _ => {}
            }
            if let Some(transform) = &operation.output_transform {
                collect_typescript_import(&transform.type_name, true, false, &mut imports);
            }
        }
        for resource in service.resources.iter().map(|resource| &resource.data) {
            for field in &resource.fields {
                collect_value_type_imports(&field.kind, &mut imports);
                if let Some(function) = &field.function {
                    collect_function_imports(function, &mut imports);
                }
            }
            for method in &resource.methods {
                for param in &method.params {
                    collect_value_type_imports(&param.kind, &mut imports);
                    if let Some(function) = &param.function {
                        collect_function_imports(function, &mut imports);
                    }
                }
                if let Some(result) = &method.result {
                    if let PlannedResourceMethodResultKind::Value(kind) = &result.kind {
                        collect_value_type_imports(kind, &mut imports);
                    }
                }
            }
        }
    }
    imports.into_iter().collect()
}

fn collect_proto_type_imports(
    proto: &PlannedProtoTypeInfo,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    collect_typescript_import(&proto.reference, true, true, imports);
    collect_typescript_import(&proto.type_name, true, false, imports);
}

fn collect_model_type_imports(
    model_type: &PlannedType,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    match model_type {
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(proto))) => {
            collect_proto_type_imports(&proto.proto, imports);
            if let Some(replacement) = &proto.replacement {
                collect_type_replacement_imports(replacement, imports);
            }
            if let Some(authored_type) = &proto.authored_type {
                collect_authored_type_imports(authored_type, imports);
            }
        }
        PlannedType::Record(_) => {}
        _ => {}
    }
}

fn collect_type_replacement_imports(
    replacement: &TypeReplacementSpec,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    collect_typescript_import(&replacement.type_name, true, false, imports);
    collect_typescript_import(&replacement.from_proto, false, false, imports);
    collect_typescript_import(&replacement.to_proto, false, false, imports);
}

fn collect_value_type_imports(value: &PlannedType, imports: &mut BTreeSet<LanguageImportSpec>) {
    match value {
        PlannedType::Enum(_) | PlannedType::TypeParameter(_) => {}
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enumeration))) => {
            collect_proto_type_imports(&enumeration.proto, imports);
            if let Some(replacement) = &enumeration.replacement {
                collect_type_replacement_imports(replacement, imports);
            }
        }
        PlannedType::Flags(_) | PlannedType::Variant(_) => {}
        PlannedType::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(_)))
        | PlannedType::External(ExternalTypeSpec::Json(_))
        | PlannedType::Record(_) => {
            collect_model_type_imports(value, imports);
        }
        PlannedType::Resource(resource) => {
            if let Some(wire_type) = &resource.wire_type {
                collect_model_type_imports(&PlannedType::External(wire_type.clone()), imports);
            }
        }
        PlannedType::Option(inner) | PlannedType::List(inner) => {
            collect_value_type_imports(inner, imports)
        }
        PlannedType::Map(key, value) => {
            collect_value_type_imports(key, imports);
            collect_value_type_imports(value, imports);
        }
        PlannedType::Tuple(items) => {
            for item in items {
                collect_value_type_imports(item, imports);
            }
        }
        PlannedType::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_value_type_imports(ok, imports);
            }
            if let Some(err) = err {
                collect_value_type_imports(err, imports);
            }
        }
        PlannedType::External(ExternalTypeSpec::Alias(AliasTypeSpec {
            type_name,
            target: fallback,
            ..
        })) => {
            collect_typescript_import(type_name, true, false, imports);
            collect_value_type_imports(fallback, imports);
        }
        PlannedType::Bool
        | PlannedType::Int(_)
        | PlannedType::Float
        | PlannedType::String
        | PlannedType::Bytes => {}
    }
}

fn collect_function_imports(
    function: &FunctionFieldSpec<PlannedFamily>,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    if let FunctionResultSpec::Annotation(result) = &function.result {
        collect_typescript_import(result, true, false, imports);
    }
    collect_function_args_imports(&function.args, imports);
    if let Some(alternate_type) = &function.alternate_type {
        collect_authored_type_imports(alternate_type, imports);
    }
    if let Some(descriptor) = &function.type_descriptor {
        collect_typescript_import(&descriptor.value_type, true, false, imports);
        collect_typescript_import(&descriptor.args_type, true, false, imports);
    }
}

fn collect_function_args_imports(
    args: &FunctionArgsSpec<PlannedFamily>,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    let fields = match args {
        FunctionArgsSpec::Varargs { prefix, .. } => prefix,
        FunctionArgsSpec::Fixed(fields) => fields,
    };
    for field in fields {
        collect_authored_type_imports(&field.field_type, imports);
    }
}

fn collect_authored_type_imports(
    field_type: &PlannedType,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    match field_type {
        TypeSpec::Option(inner) | TypeSpec::List(inner) => {
            collect_authored_type_imports(inner, imports);
        }
        TypeSpec::Tuple(items) => {
            for item in items {
                collect_authored_type_imports(item, imports);
            }
        }
        TypeSpec::Map(key, value) => {
            collect_authored_type_imports(key, imports);
            collect_authored_type_imports(value, imports);
        }
        TypeSpec::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_authored_type_imports(ok, imports);
            }
            if let Some(err) = err {
                collect_authored_type_imports(err, imports);
            }
        }
        TypeSpec::External(ExternalTypeSpec::Alias(AliasTypeSpec {
            target, type_name, ..
        })) => {
            collect_typescript_import(type_name, true, false, imports);
            collect_authored_type_imports(target, imports);
        }
        TypeSpec::TypeParameter(_)
        | TypeSpec::Bool
        | TypeSpec::Int(_)
        | TypeSpec::Float
        | TypeSpec::String
        | TypeSpec::Bytes
        | TypeSpec::External(ExternalTypeSpec::Proto(_))
        | TypeSpec::External(ExternalTypeSpec::Json(_))
        | TypeSpec::Record(_)
        | TypeSpec::Enum(_)
        | TypeSpec::Flags(_)
        | TypeSpec::Variant(_)
        | TypeSpec::Resource(_) => {}
    }
}

fn collect_typescript_import(
    spec: &LanguageStringSpec,
    type_only: bool,
    named_import: bool,
    imports: &mut BTreeSet<LanguageImportSpec>,
) {
    let Some(module) = spec.import_for_language(Language::TypeScript) else {
        return;
    };
    let Some(expression) = spec.for_language(Language::TypeScript) else {
        return;
    };
    for namespace in typescript_qualified_namespaces(expression) {
        imports.insert(LanguageImportSpec {
            language: Language::TypeScript,
            reference: namespace.clone(),
            module: module.to_string(),
            name: Some(namespace),
            type_only,
            import_style: if named_import {
                LanguageImportStyle::Named
            } else {
                LanguageImportStyle::Namespace
            },
        });
    }
}

fn typescript_qualified_namespaces(expression: &str) -> BTreeSet<String> {
    let chars = expression.char_indices().collect::<Vec<_>>();
    let mut namespaces = BTreeSet::new();
    let mut index = 0;
    while index < chars.len() {
        let (start_byte, ch) = chars[index];
        if !is_typescript_identifier_start(ch) {
            index += 1;
            continue;
        }

        let before = expression[..start_byte].chars().next_back();
        if before.is_some_and(|before| is_typescript_identifier_char(before) || before == '.') {
            index += 1;
            continue;
        }

        let mut end = index + 1;
        while end < chars.len() && is_typescript_identifier_char(chars[end].1) {
            end += 1;
        }
        let end_byte = chars
            .get(end)
            .map(|(byte, _)| *byte)
            .unwrap_or(expression.len());
        let mut after = end;
        while after < chars.len() && chars[after].1.is_whitespace() {
            after += 1;
        }
        if after < chars.len() && chars[after].1 == '.' {
            namespaces.insert(expression[start_byte..end_byte].to_string());
        }
        index = end;
    }
    namespaces
}

fn reject_support_namespaces(
    language: Language,
    support_fragments: &[SupportFragmentSpec],
) -> Result<()> {
    if let Some(namespace) = support_fragments
        .iter()
        .find_map(|fragment| fragment.namespace.as_deref())
    {
        return Err(Error::UnsupportedSupportNamespace {
            language,
            namespace: namespace.to_string(),
        });
    }
    Ok(())
}

fn model_type_parameters(
    model: &RecordSpec<PlannedFamily>,
    api_plan: &PlannedSpec,
) -> Vec<RenderedTypeParameter> {
    if model.is_empty_model() {
        return Vec::new();
    }

    let mut model_parameters = api_plan
        .record_type_parameters(&model.full_name, Language::TypeScript)
        .into_iter()
        .map(|usage| RenderedTypeParameter {
            name: usage.parameter.name,
            constraint: "unknown".to_string(),
            default: "unknown".to_string(),
            infer_from_operation_request: true,
            explicit: true,
        })
        .collect::<Vec<_>>();
    let mut type_parameters = Vec::new();
    for (field_name, function) in model.functions() {
        let generated_name = model.field_name_override(field_name).unwrap_or(field_name);
        if let Some(descriptor) = typescript_function_type_descriptor(function) {
            let value_parameter_name = with_arguments_type_parameter_name(generated_name);
            let args_parameter_name = with_arguments_args_type_parameter_name(generated_name);
            type_parameters.push((
                true,
                generated_name.to_string(),
                0,
                RenderedTypeParameter {
                    name: value_parameter_name.clone(),
                    constraint: descriptor.value_type.clone(),
                    default: descriptor.value_type,
                    infer_from_operation_request: true,
                    explicit: false,
                },
            ));
            type_parameters.push((
                true,
                generated_name.to_string(),
                1,
                RenderedTypeParameter {
                    name: args_parameter_name,
                    constraint: "any[]".to_string(),
                    default: with_arguments_args_type_expression(
                        &descriptor.args_type,
                        &value_parameter_name,
                    ),
                    infer_from_operation_request: false,
                    explicit: false,
                },
            ));
        } else {
            let generated_name = model.field_name_override(field_name).unwrap_or(field_name);
            let type_parameter_name = function_type_parameter_name(generated_name);
            let constraint = function_constraint(function);
            type_parameters.push((
                !function.primary,
                generated_name.to_string(),
                0,
                RenderedTypeParameter {
                    name: type_parameter_name,
                    constraint: constraint.clone(),
                    default: constraint,
                    infer_from_operation_request: true,
                    explicit: false,
                },
            ));
        }
    }

    type_parameters.sort_by(|left, right| {
        left.0
            .cmp(&right.0)
            .then_with(|| left.1.cmp(&right.1))
            .then_with(|| left.2.cmp(&right.2))
    });
    model_parameters.extend(
        type_parameters
            .into_iter()
            .map(|(_, _, _, type_parameter)| type_parameter),
    );
    model_parameters
}

fn typescript_function_result_annotation(result: &FunctionResultSpec<PlannedFamily>) -> String {
    match result {
        FunctionResultSpec::Annotation(annotation) => annotation
            .for_language(Language::TypeScript)
            .unwrap_or("unknown")
            .to_string(),
        FunctionResultSpec::Authored(authored_type) => {
            typescript_authored_type_annotation(authored_type)
        }
    }
}

/// Formats a TypeScript array annotation, parenthesizing the element type when
/// it contains a top-level union or intersection so the `[]` suffix binds to
/// the whole element type (e.g. `({ tag: "ok" } | { tag: "err" })[]`).
fn typescript_array_annotation(element: &str) -> String {
    if typescript_annotation_needs_parens(element) {
        format!("({element})[]")
    } else {
        format!("{element}[]")
    }
}

/// Returns `true` when a type annotation contains a `|` or `&` outside any
/// bracket pair, meaning a postfix `[]` would bind to only its last member.
fn typescript_annotation_needs_parens(annotation: &str) -> bool {
    let mut depth = 0i32;
    let mut chars = annotation.chars().peekable();
    while let Some(c) = chars.next() {
        match c {
            '(' | '<' | '{' | '[' => depth += 1,
            ')' | '>' | '}' | ']' => depth -= 1,
            // Skip the `=>` of function types so its `>` is not counted.
            '=' if chars.peek() == Some(&'>') => {
                let _ = chars.next();
            }
            '|' | '&' if depth == 0 => return true,
            _ => {}
        }
    }
    false
}

pub(in crate::generator) fn typescript_authored_type_annotation(
    authored_type: &PlannedType,
) -> String {
    match authored_type {
        TypeSpec::Bool => "boolean".to_string(),
        TypeSpec::Int(IntSpec::I32) | TypeSpec::Float => "number".to_string(),
        TypeSpec::Int(IntSpec::I64) => "Long".to_string(),
        TypeSpec::String => "string".to_string(),
        TypeSpec::Bytes => "Uint8Array".to_string(),
        TypeSpec::TypeParameter(parameter) => parameter.name.clone(),
        TypeSpec::Option(inner) => {
            format!("{} | undefined", typescript_authored_type_annotation(inner))
        }
        TypeSpec::List(inner) => {
            typescript_array_annotation(&typescript_authored_type_annotation(inner))
        }
        TypeSpec::Tuple(items) => format!(
            "[{}]",
            items
                .iter()
                .map(typescript_authored_type_annotation)
                .collect::<Vec<_>>()
                .join(", ")
        ),
        TypeSpec::Map(key, value) => format!(
            "Record<{}, {}>",
            typescript_authored_type_annotation(key),
            typescript_authored_type_annotation(value)
        ),
        TypeSpec::Result { ok, err } => typescript_result_annotation(
            ok.as_ref()
                .map(|ok| typescript_authored_type_annotation(ok).to_string()),
            err.as_ref()
                .map(|err| typescript_authored_type_annotation(err).to_string()),
        ),
        TypeSpec::External(ExternalTypeSpec::Alias(AliasTypeSpec {
            type_name, target, ..
        })) => type_name
            .for_language(Language::TypeScript)
            .map(str::to_string)
            .unwrap_or_else(|| typescript_authored_type_annotation(target)),
        TypeSpec::External(ExternalTypeSpec::Proto(wire_name)) => wire_name
            .full_name()
            .rsplit('.')
            .next()
            .unwrap_or(wire_name.full_name())
            .to_string(),
        TypeSpec::External(ExternalTypeSpec::Json(json_type)) => json_type.model_name.clone(),
        TypeSpec::Record(name) => name
            .full_name
            .as_str()
            .rsplit('.')
            .next()
            .unwrap_or(&name.full_name)
            .to_upper_camel_case(),
        TypeSpec::Enum(name) => name
            .full_name
            .as_str()
            .rsplit('.')
            .next()
            .unwrap_or(&name.full_name)
            .to_upper_camel_case(),
        TypeSpec::Flags(name) => name
            .full_name
            .as_str()
            .rsplit('.')
            .next()
            .unwrap_or(&name.full_name)
            .to_upper_camel_case(),
        TypeSpec::Variant(name) => name
            .full_name
            .as_str()
            .rsplit('.')
            .next()
            .unwrap_or(&name.full_name)
            .to_upper_camel_case(),
        TypeSpec::Resource(name) => name
            .type_name
            .as_str()
            .rsplit('.')
            .next()
            .unwrap_or(&name.type_name)
            .to_upper_camel_case(),
    }
}

fn typescript_result_annotation(ok: Option<String>, err: Option<String>) -> String {
    let ok_case = if let Some(ok) = ok {
        format!("{{ tag: \"ok\"; value: {ok} }}")
    } else {
        "{ tag: \"ok\" }".to_string()
    };
    let err_case = if let Some(err) = err {
        format!("{{ tag: \"err\"; value: {err} }}")
    } else {
        "{ tag: \"err\" }".to_string()
    };
    format!("{ok_case} | {err_case}")
}

