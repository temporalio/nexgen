fn collect_typescript_model_requirements(
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
) -> TypeScriptRequirements {
    let mut requirements = TypeScriptRequirements::default();
    for variant in variants {
        for case in &variant.cases {
            requirements.merge(&case.requirements);
        }
    }
    for model in models {
        for field in &model.fields {
            requirements.merge(&field.requirements);
        }
        for function in &model.functions {
            requirements.merge(&function.requirements);
        }
        for function in &model.with_arguments {
            requirements.merge(&function.requirements);
        }
    }
    requirements
}

fn collect_typescript_resource_requirements(
    services: &[RenderedService<'_>],
) -> TypeScriptRequirements {
    let mut requirements = TypeScriptRequirements::default();
    for service in services {
        for resource in &service.resources {
            for field in &resource.fields {
                requirements.merge(&typescript_resource_field_requirements(
                    &field.kind,
                    field.function.as_ref(),
                ));
            }
            for method in &resource.methods {
                for param in &method.params {
                    requirements.merge(&typescript_resource_field_requirements(
                        &param.kind,
                        param.function.as_ref(),
                    ));
                }
                if let Some(result) = &method.result
                    && let PlannedResourceMethodResultKind::Value(kind) = &result.kind
                {
                    requirements.merge(&typescript_resource_field_requirements(kind, None));
                }
            }
        }
    }
    requirements
}

#[allow(clippy::too_many_arguments)]
fn render_module_files(
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[&RenderedModel],
    external_models: &TypeScriptExternalModels,
    model_fragments: &RenderedExternalModelFragments,
    services: &[RenderedService<'_>],
    language_imports: &[LanguageImportSpec],
    support_source: Option<&str>,
    api_plan: &PlannedSpec,
    module_origin: GeneratedFileOrigin,
) -> Result<GeneratedFileMap> {
    let mode = crate::nexgen_config::current().mode;
    let model_requirements = collect_typescript_model_requirements(variants, models);
    let resource_requirements = collect_typescript_resource_requirements(services);
    let support_source = support_source.filter(|source| !source.trim().is_empty());
    let support_exports = support_source.map(support_exports);
    let module_model_names = model_fragments
        .type_exported_names
        .iter()
        .cloned()
        .collect();
    let rendered_support = external_models.render_support()?;
    let mut files = GeneratedFileMap::default();
    let models_source = render_models_module(
        enums,
        flags,
        variants,
        models,
        external_models,
        model_fragments,
        &model_requirements,
        language_imports,
        support_exports.as_ref(),
        api_plan,
    );
    // A module whose every operation type is `$ref`d from another file declares
    // nothing of its own. Emitting the empty `models.ts` anyway would leave the
    // barrel re-exporting a file with no exports, which TypeScript rejects
    // outright (TS2306, "is not a module").
    let has_models_module = !is_blank_generated_module(&models_source);
    files.insert(
        "index.ts",
        if mode == GenerationMode::NativeApi {
            render_index_module(
                services,
                &model_fragments.type_exported_names,
                &rendered_support.root_exports,
            )
        } else {
            render_definitions_only_index_module(
                services,
                has_models_module,
                &rendered_support.root_exports,
            )
        },
        module_origin.clone(),
    )?;
    if has_models_module {
        files.insert("models.ts", models_source, module_origin.clone())?;
    }
    if !services.is_empty() {
        files.insert(
            "services.ts",
            render_service_module(
                enums,
                flags,
                variants,
                models,
                &module_model_names,
                services,
                language_imports,
                support_exports.as_ref(),
                mode == GenerationMode::NativeApi,
                api_plan,
            ),
            module_origin.clone(),
        )?;
    }
    if services.iter().any(|service| !service.resources.is_empty()) {
        files.insert(
            "resources.ts",
            render_resources_module(
                enums,
                flags,
                variants,
                models,
                &module_model_names,
                services,
                &resource_requirements,
                language_imports,
                support_exports.as_ref(),
                api_plan,
            ),
            module_origin.clone(),
        )?;
    }
    if mode == GenerationMode::NativeApi {
        for service in services {
            if service.endpoint.is_none() {
                continue;
            }
            for operation in &service.operations {
                files.insert(
                    format!("operations/{}.ts", operation_file_name(operation)),
                    render_operation_module(
                        enums,
                        flags,
                        variants,
                        models,
                        &module_model_names,
                        services,
                        service,
                        operation,
                        language_imports,
                        support_exports.as_ref(),
                        api_plan,
                    ),
                    GeneratedFileOrigin::operation(
                        Language::TypeScript,
                        service.name,
                        operation.name,
                    ),
                )?;
            }
        }
    }
    if let Some(support_source) = support_source {
        files.insert(
            "support.ts",
            render_support_module(support_source),
            GeneratedFileOrigin::fixed("generated TypeScript support module"),
        )?;
    }
    files.insert_multi(
        rendered_support.files,
        GeneratedFileOrigin::fixed("generated TypeScript external-model runtime"),
    )?;
    files.map_contents(relativize_output_root_imports);
    Ok(files)
}

const OUTPUT_ROOT_IMPORT_PREFIX: &str = "__nexgen_output_root__:";

/// WIT relative TypeScript imports are rooted at the generated output directory.
/// Relativize them for each emitted module, whose depth may differ (e.g. operations).
fn relativize_output_root_imports(path: &Path, contents: &str) -> String {
    let source_depth = path
        .parent()
        .map_or(0, |parent| parent.components().count());
    let mut output = contents.to_string();
    while let Some(start) = output.find(OUTPUT_ROOT_IMPORT_PREFIX) {
        let target_start = start + OUTPUT_ROOT_IMPORT_PREFIX.len();
        let target_end = output[target_start..]
            .find('\'')
            .map(|offset| target_start + offset)
            .expect("generated output-root import must end with a quote");
        let target = &output[target_start..target_end];
        let mut relative = "../".repeat(source_depth);
        relative.push_str(target);
        if !relative.starts_with('.') {
            relative.insert_str(0, "./");
        }
        output.replace_range(start..target_end, &relative);
    }
    output
}

fn support_source(support_fragments: &[SupportFragmentSpec]) -> Option<String> {
    (!support_fragments.is_empty()).then(|| {
        support_fragments
            .iter()
            .map(|fragment| fragment.contents.as_str())
            .collect::<Vec<_>>()
            .join("\n\n")
    })
}

fn operation_file_name(operation: &RenderedOperation<'_>) -> String {
    operation.attr_name.to_kebab_case()
}

fn support_exports(source: &str) -> SupportExports {
    let mut exports = SupportExports::default();
    for line in source.lines().map(str::trim_start) {
        if let Some(name) = export_name(line, "export function ") {
            exports.value_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export const ") {
            exports.value_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export let ") {
            exports.value_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export var ") {
            exports.value_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export class ") {
            exports.value_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export enum ") {
            exports.value_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export type ") {
            exports.type_names.push(name.to_string());
        } else if let Some(name) = export_name(line, "export interface ") {
            exports.type_names.push(name.to_string());
        }
    }
    exports
}

fn export_name<'a>(line: &'a str, prefix: &str) -> Option<&'a str> {
    let remainder = line.strip_prefix(prefix)?;
    let end = remainder
        .find(|ch: char| !(ch.is_ascii_alphanumeric() || ch == '_' || ch == '$'))
        .unwrap_or(remainder.len());
    (end > 0).then_some(&remainder[..end])
}

fn render_typescript_namespace_imports(
    output: &mut String,
    source: &str,
    language_imports: &[LanguageImportSpec],
    generated_value_imports: &[(&str, &str)],
) {
    let mut namespace_imports = BTreeMap::<(String, String), bool>::new();
    let mut named_type_imports = BTreeMap::<String, BTreeSet<String>>::new();
    for (namespace, package) in generated_value_imports {
        if contains_qualified_identifier(source, namespace) {
            namespace_imports.insert(((*namespace).to_string(), (*package).to_string()), true);
        }
    }
    for import in language_imports {
        if !contains_qualified_identifier(source, &import.reference) {
            continue;
        }
        match import.import_style {
            LanguageImportStyle::Namespace => {
                // System Nexus output lives inside @temporalio/workflow. Its
                // workflow helpers are imported through the local bridge, so
                // WIT annotations authored for the public package must resolve
                // to that same binding rather than introduce a duplicate
                // `workflow` namespace import.
                let module = if crate::nexgen_config::current().system_nexus
                    && import.module == "@temporalio/workflow"
                {
                    typescript_workflow_module().to_string()
                } else {
                    import.module.clone()
                };
                let key = (import.reference.clone(), module);
                let needs_value_import = !import.type_only;
                namespace_imports
                    .entry(key)
                    .and_modify(|existing| *existing |= needs_value_import)
                    .or_insert(needs_value_import);
            }
            LanguageImportStyle::Named => {
                named_type_imports
                    .entry(import.module.clone())
                    .or_default()
                    .insert(
                        import
                            .name
                            .clone()
                            .unwrap_or_else(|| import.reference.clone()),
                    );
            }
            LanguageImportStyle::Module => {}
        }
    }

    for ((namespace, package), needs_value_import) in namespace_imports {
        if needs_value_import {
            output.push_str("import * as ");
        } else {
            output.push_str("import type * as ");
        }
        output.push_str(&namespace);
        output.push_str(" from '");
        output.push_str(&typescript_output_root_import(&package));
        output.push_str("';\n");
    }
    for (package, imports) in named_type_imports {
        output.push_str("import type { ");
        output.push_str(&imports.into_iter().collect::<Vec<_>>().join(", "));
        output.push_str(" } from '");
        output.push_str(&typescript_output_root_import(&package));
        output.push_str("';\n");
    }
}

fn typescript_output_root_import(package: &str) -> String {
    package
        .starts_with('.')
        .then(|| format!("{OUTPUT_ROOT_IMPORT_PREFIX}{package}"))
        .unwrap_or_else(|| package.to_string())
}

fn typescript_workflow_module() -> &'static str {
    if crate::nexgen_config::current().system_nexus {
        "../workflow-exports"
    } else {
        "@temporalio/workflow"
    }
}

