fn local_type_info(full_name: &str) -> PlannedTypeInfo {
    PlannedTypeInfo {
        full_name: full_name.to_string(),
        package: String::new(),
        file_name: None,
        file_options: None,
        reference: LanguageStringSpec::default(),
        type_name: LanguageStringSpec::default(),
    }
}

fn message_model_name(full_name: &str) -> String {
    full_name
        .rsplit('.')
        .next()
        .expect("descriptor names should not be empty")
        .to_upper_camel_case()
        .to_string()
}

pub(in crate::generator) fn operation_output(
    operation: &PlannedOperation,
    spec: &PlannedSpec,
) -> PlannedOperationOutput {
    match operation.output.as_ref() {
        Some(TypeSpec::Resource(resource)) => resource
            .wire_type
            .as_ref()
            .and_then(|wire_type| {
                planned_message_type(&TypeSpec::External(wire_type.clone()), spec)
            })
            .map(PlannedOperationOutput::Message)
            .unwrap_or_else(|| PlannedOperationOutput::Resource {
                type_name: resource.type_name.clone(),
            }),
        Some(output) => planned_message_type(output, spec)
            .map(PlannedOperationOutput::Message)
            .unwrap_or(PlannedOperationOutput::None),
        None => PlannedOperationOutput::None,
    }
}

pub(in crate::generator) fn planned_message_type(
    model_type: &PlannedType,
    spec: &PlannedSpec,
) -> Option<PlannedMessageType> {
    match model_type.without_option() {
        TypeSpec::Record(record_type) => spec
            .record(&record_type.full_name)
            .map(planned_message_type_for_record),
        TypeSpec::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(message))) => {
            Some(PlannedMessageType {
                info: message.proto.clone(),
                model_name: message.model_name.clone(),
                replacement: message.replacement.clone(),
                authored_type: message.authored_type.as_deref().cloned(),
                source: PlannedMessageSource::Proto,
            })
        }
        TypeSpec::External(ExternalTypeSpec::Json(json_type)) => Some(PlannedMessageType {
            info: local_type_info(&json_type.full_name),
            model_name: json_type.model_name.clone(),
            replacement: None,
            authored_type: None,
            source: PlannedMessageSource::Json,
        }),
        TypeSpec::External(ExternalTypeSpec::Alias {
            target, type_name, ..
        }) => {
            let mut info = local_type_info("alias");
            info.type_name = type_name.clone();
            Some(PlannedMessageType {
                info,
                model_name: go_authored_type_annotation(target),
                replacement: None,
                authored_type: Some((**target).clone()),
                source: PlannedMessageSource::Wit,
            })
        }
        _ => None,
    }
}

fn planned_message_type_for_record(record: &RecordSpec<PlannedFamily>) -> PlannedMessageType {
    if let Some(proto) = &record.data.proto {
        PlannedMessageType {
            info: proto.clone(),
            model_name: record.name.clone(),
            replacement: None,
            authored_type: None,
            source: PlannedMessageSource::Proto,
        }
    } else {
        PlannedMessageType {
            info: local_type_info(&record.full_name),
            model_name: record.name.clone(),
            replacement: None,
            authored_type: None,
            source: PlannedMessageSource::Wit,
        }
    }
}

fn record_message_key(record: &RecordSpec<PlannedFamily>) -> &str {
    record
        .data
        .proto
        .as_ref()
        .map(|proto| proto.full_name.as_str())
        .unwrap_or(record.full_name.as_str())
}

fn record_for_message<'a>(
    api_plan: &'a PlannedSpec,
    message: &PlannedMessageType,
) -> Option<&'a RecordSpec<PlannedFamily>> {
    record_for_model_key(api_plan, &message.info.full_name)
}

pub(in crate::generator) fn record_for_model_key<'a>(
    api_plan: &'a PlannedSpec,
    full_name: &str,
) -> Option<&'a RecordSpec<PlannedFamily>> {
    api_plan
        .records()
        .map(|(_, record)| record)
        .find(|record| record_message_key(record) == full_name)
}

pub(in crate::generator) fn planned_field(
    record: &RecordSpec<PlannedFamily>,
    field_name: &str,
    field: &RecordFieldSpec<PlannedFamily>,
    spec: &PlannedSpec,
) -> PlannedField {
    let role = if let Some(function) = &field.function {
        PlannedFieldRole::Function(function.clone())
    } else if let Some(function) = record.function_for_args_field(field_name) {
        PlannedFieldRole::FunctionArgs(function.clone())
    } else {
        PlannedFieldRole::Plain
    };
    PlannedField {
        proto_name: field_name.to_string(),
        authored_name: field.name.clone(),
        doc: field.doc.clone(),
        annotation_override: field.annotation.clone(),
        flattened_annotation_override: field.flattened_annotation.clone(),
        required: field.required,
        role,
        kind: planned_field_kind(&field.field_type, spec),
    }
}

fn planned_enum(enumeration: &EnumSpec) -> PlannedEnum {
    PlannedEnum {
        info: local_type_info(&enumeration.full_name),
        name: enumeration.name.clone(),
        values: enumeration
            .values
            .iter()
            .map(|value| PlannedEnumValue {
                name: value.name.clone(),
                number: value.number,
            })
            .collect(),
    }
}

fn planned_flags(flags: &FlagsSpec) -> PlannedFlags {
    PlannedFlags {
        info: local_type_info(&flags.full_name),
        name: flags.name.clone(),
        flags: flags
            .flags
            .iter()
            .map(|flag| PlannedFlag {
                name: flag.name.clone(),
                bit: flag.bit,
            })
            .collect(),
    }
}

fn planned_variant(variant: &VariantSpec<PlannedFamily>, spec: &PlannedSpec) -> PlannedVariant {
    PlannedVariant {
        info: local_type_info(&variant.full_name),
        name: variant.name.clone(),
        type_parameters: spec.variant_type_parameters(&variant.full_name, Language::Go),
        cases: variant
            .cases
            .iter()
            .map(|case| PlannedVariantCase {
                name: case.name.clone(),
                payload: case
                    .payload
                    .as_ref()
                    .map(|payload| planned_value_type(payload, spec)),
            })
            .collect(),
    }
}

pub(in crate::generator) fn planned_field_kind(
    field_type: &PlannedType,
    spec: &PlannedSpec,
) -> PlannedFieldKind {
    match field_type.without_option() {
        TypeSpec::List(inner) => {
            PlannedFieldKind::Repeated(planned_value_type(inner.without_option(), spec))
        }
        TypeSpec::Map(key, value) => PlannedFieldKind::Map {
            key: planned_value_type(key.without_option(), spec),
            value: planned_value_type(value.without_option(), spec),
        },
        value => PlannedFieldKind::Singular(planned_value_type(value, spec)),
    }
}

fn planned_value_type(value_type: &PlannedType, spec: &PlannedSpec) -> PlannedValueType {
    match value_type.without_option() {
        TypeSpec::Bool => PlannedValueType::Scalar(PlannedScalarType::Bool),
        TypeSpec::Int(IntSpec::I32) => PlannedValueType::Scalar(PlannedScalarType::Int32),
        TypeSpec::Int(IntSpec::I64) => PlannedValueType::Scalar(PlannedScalarType::Int64),
        TypeSpec::Float => PlannedValueType::Scalar(PlannedScalarType::Float),
        TypeSpec::String => PlannedValueType::Scalar(PlannedScalarType::String),
        TypeSpec::Bytes => PlannedValueType::Scalar(PlannedScalarType::Bytes),
        TypeSpec::TypeParameter(parameter) => {
            PlannedValueType::TypeParameter(parameter.name.clone())
        }
        TypeSpec::Record(_) => planned_message_type(value_type, spec)
            .map(PlannedValueType::Message)
            .unwrap_or(PlannedValueType::Unknown),
        TypeSpec::Enum(enum_type) => PlannedValueType::Enum(PlannedEnumType {
            info: Some(local_type_info(&enum_type.full_name)),
            name: Some(enum_type.name.clone()),
            replacement: None,
        }),
        TypeSpec::Flags(flags_type) => PlannedValueType::Flags(PlannedFlagsType {
            info: local_type_info(&flags_type.full_name),
            name: flags_type.name.clone(),
        }),
        TypeSpec::Variant(variant_type) => PlannedValueType::Variant(PlannedVariantType {
            info: local_type_info(&variant_type.full_name),
            name: variant_type.name.clone(),
        }),
        TypeSpec::Resource(_) => PlannedValueType::Unknown,
        TypeSpec::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(message))) => {
            PlannedValueType::Message(PlannedMessageType {
                info: message.proto.clone(),
                model_name: message.model_name.clone(),
                replacement: message.replacement.clone(),
                authored_type: message.authored_type.as_deref().cloned(),
                source: PlannedMessageSource::Proto,
            })
        }
        TypeSpec::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enum_type))) => {
            PlannedValueType::Enum(PlannedEnumType {
                info: Some(enum_type.proto.clone()),
                name: Some(enum_type.name.clone()),
                replacement: enum_type.replacement.clone(),
            })
        }
        TypeSpec::External(ExternalTypeSpec::Json(json_type)) => {
            PlannedValueType::Message(PlannedMessageType {
                info: local_type_info(&json_type.full_name),
                model_name: json_type.model_name.clone(),
                replacement: None,
                authored_type: None,
                source: PlannedMessageSource::Json,
            })
        }
        TypeSpec::External(ExternalTypeSpec::Alias {
            target, type_name, ..
        }) => PlannedValueType::External {
            type_name: type_name.clone(),
            fallback: Box::new(planned_value_type(target.without_option(), spec)),
        },
        TypeSpec::Tuple(items) => PlannedValueType::Tuple(
            items
                .iter()
                .map(|item| planned_value_type(item, spec))
                .collect(),
        ),
        TypeSpec::Result { ok, err } => PlannedValueType::Result {
            ok: ok.as_ref().map(|ok| Box::new(planned_value_type(ok, spec))),
            err: err
                .as_ref()
                .map(|err| Box::new(planned_value_type(err, spec))),
        },
        TypeSpec::Option(inner) | TypeSpec::List(inner) => planned_value_type(inner, spec),
        TypeSpec::Map(_, _) => PlannedValueType::Unknown,
    }
}

#[derive(Debug, Clone)]
pub(in crate::generator) struct GoPackageContext {
    package_name: String,
    import_path: Option<String>,
}

impl GoPackageContext {
    fn new(api_plan: &PlannedSpec, options: &GoOptions) -> Result<Self> {
        // `@nexus.namespace go="..."` is WIT-only (the JSON schema parser
        // never populates a per-language namespace), and it names an
        // *existing* Go package this generated code is meant to become part
        // of -- so any reference to that import path elsewhere in the
        // generated code is a self-reference, not an import, and must be
        // unqualified accordingly.
        let import_path = api_plan
            .services
            .first()
            .and_then(|service| service.namespace.for_language(Language::Go))
            .map(str::to_string);
        let package_name = Self::derive_package_name(&options.output_dir_name)?;

        if let Some(import_path) = &import_path {
            let namespace_package_name = go_package_name(
                import_path
                    .rsplit('/')
                    .next()
                    .filter(|segment| !segment.is_empty())
                    .unwrap_or(import_path),
            );
            if namespace_package_name != package_name {
                return Err(Error::GoNamespacePackageMismatch {
                    namespace: import_path.clone(),
                    expected_package: namespace_package_name,
                    actual_package: package_name,
                });
            }
        }

        Ok(Self {
            package_name,
            import_path,
        })
    }

    /// The package name is the output directory's basename, matching the Go
    /// convention that a package's name is its directory's name.
    /// `go_package_name` strips everything but ASCII alphanumerics and `_`,
    /// so a directory name with none of those (e.g. non-ASCII or
    /// punctuation-only) sanitizes to empty; that's rejected outright rather
    /// than guessed at.
    fn derive_package_name(output_dir_name: &str) -> Result<String> {
        let package_name = go_package_name(output_dir_name);
        if package_name.is_empty() {
            return Err(Error::GoPackageNameEmpty {
                output_dir_name: output_dir_name.to_string(),
            });
        }
        Ok(package_name)
    }

    fn is_self_import(&self, import_path: &str) -> bool {
        self.import_path
            .as_deref()
            .is_some_and(|self_import| self_import == import_path)
    }

    pub(in crate::generator) fn go_type_expr(&self, type_expr: &str) -> String {
        let (import_path, code_expr) = parse_go_import(type_expr);
        if import_path
            .as_deref()
            .is_some_and(|import_path| self.is_self_import(import_path))
        {
            return self.unqualify_self_expr(&code_expr);
        }
        code_expr
    }

    pub(in crate::generator) fn workflow_context_type(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.Context")
    }

    fn workflow_future_type(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.Future")
    }

    pub(in crate::generator) fn new_future(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.NewFuture")
    }

    fn workflow_go(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.Go")
    }

    pub(in crate::generator) fn new_nexus_client(&self) -> String {
        self.qualified_expr("go.temporal.io/sdk/workflow", "workflow.NewNexusClient")
    }

    pub(in crate::generator) fn nexus_operation_options(&self) -> String {
        self.qualified_expr(
            "go.temporal.io/sdk/workflow",
            "workflow.NexusOperationOptions{}",
        )
    }

    fn qualified_expr(&self, import_path: &str, code_expr: &str) -> String {
        if self.is_self_import(import_path) {
            self.unqualify_self_expr(code_expr)
        } else {
            code_expr.to_string()
        }
    }

    fn unqualify_self_expr(&self, code_expr: &str) -> String {
        let qualifier = format!("{}.", self.package_name);
        code_expr.replace(&qualifier, "")
    }
}

/// Entry point for the Go code generator.
///
/// Walks the [`PlannedSpec`] to collect all referenced enums, flags, variants, and
/// models, then renders them into a single service-named `.go` file inside a
/// directory output. The Go package name is derived from the first service
/// endpoint unless the first service declares `@nexus.namespace go="..."`.
pub(crate) fn generate(
    api_plan: &PlannedSpec,
    support_fragments: &[SupportFragmentSpec],
    options: &GoOptions,
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    ApiPlanner::new(api_plan, options, mode)?.generate(support_fragments)
}

pub(crate) fn generate_tree(
    tree: &ApiSpecTree<PlannedFamily>,
    support: &SupportFiles,
    options: &GoOptions,
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    match &tree.root {
        ApiSpecNode::Leaf(leaf) => generate_single_leaf(leaf, support, options, mode),
        ApiSpecNode::Branch(branch) => generate_branch_tree(branch, support, options, mode),
    }
}

/// Generates a closure of exactly one input file. Go's package layout is
/// uniform regardless of closure size, so -- just like the multi-input
/// flattened layout -- the schema-independent runtime lives in its own
/// `definitions.go` alongside the one model file, rather than inlined into it.
fn generate_single_leaf(
    leaf: &ApiSpecLeaf<PlannedFamily>,
    support: &SupportFiles,
    options: &GoOptions,
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    let mut generated = generate(&leaf.spec, &support.fragments, options, mode)?;
    if go_tree_has_json_models(&[leaf]) {
        let package_name = GoPackageContext::new(&leaf.spec, options)?.package_name;
        insert_generated_file(
            &mut generated.files,
            PathBuf::from("definitions.go"),
            json::render_definitions_file(&package_name),
        )?;
    }
    Ok(generated)
}

fn generate_branch_tree(
    branch: &ApiSpecBranch<PlannedFamily>,
    support: &SupportFiles,
    options: &GoOptions,
    mode: GenerationMode,
) -> Result<GeneratedFiles> {
    let mut leaves = Vec::new();
    collect_leaf_specs(branch, &mut leaves);
    if leaves.is_empty() {
        return Err(Error::InvalidJsonSchema {
            path: PathBuf::from("<go-tree-generator>"),
            reason: "input tree contains no API specs".to_string(),
        });
    };

    // Go flattens every input file in the closure into one flat package, so
    // references between files -- including cross-directory cycles --
    // resolve as within-package (unqualified) references, which the Go
    // compiler handles natively. This is also what lets the
    // schema-independent runtime live once in the package.
    let root = ModulePath::default();

    // Every file derives its package name from the shared output directory, so
    // the whole closure renders into one package. Derive it once here for the
    // shared `definitions.go` runtime file below.
    let package_name = GoPackageContext::new(&leaves[0].spec, options)?.package_name;

    let mut files = BTreeMap::new();
    let mut warnings = Vec::new();

    for leaf in &leaves {
        // Render this input file at the package root so its own types and its
        // references to sibling files are unqualified within the one package.
        let mut leaf_spec = leaf.spec.clone();
        leaf_spec.module_path = root.clone();
        let generated = generate(&leaf_spec, &[], options, mode)?;
        warnings.extend(generated.warnings);

        // `generate` names the single JSON member file `<package>.go`; re-key it
        // to the flattened module path so each input file gets its own file in
        // the flat package.
        let file_name = go_flat_module_file_name(&leaf.module_path);
        for (_, contents) in generated.files {
            insert_generated_file(&mut files, file_name.clone(), contents)?;
        }
    }

    // The schema-independent runtime lives once in this package as
    // `definitions.go`, in the same package as the models.
    if go_tree_has_json_models(&leaves) {
        insert_generated_file(
            &mut files,
            PathBuf::from("definitions.go"),
            json::render_definitions_file(&package_name),
        )?;
    }

    // Hand-written support fragments (rare for JSON inputs) are emitted once.
    let support_fragments = support_fragments_for_plans(&leaves, support);
    if !support_fragments.is_empty() {
        insert_generated_file(
            &mut files,
            PathBuf::from("support.go"),
            render_support_file(&support_fragments, &package_name),
        )?;
    }

    Ok(GeneratedFiles {
        layout: crate::generator::GeneratedOutputLayout::Directory,
        files,
        warnings,
    })
}

/// Flattens an input file's module path into its `<module>.go` file name in the
/// one flat Go package: directory separators become `_`, literal underscores are
/// preserved (see `specs/json-schema/generated-file-layout.md`).
fn go_flat_module_file_name(module_path: &ModulePath) -> PathBuf {
    // Branch leaves always carry at least one path segment; the empty fallback
    // keeps this total.
    let stem = if module_path.is_root() {
        "api".to_string()
    } else {
        module_path.0.join("_")
    };
    PathBuf::from(format!("{stem}.go"))
}

fn go_tree_has_json_models(leaves: &[&ApiSpecLeaf<PlannedFamily>]) -> bool {
    leaves.iter().any(|leaf| {
        leaf.spec
            .external_types()
            .map(|(_, binding)| binding)
            .any(|binding| matches!(binding.external_type, ExternalTypeSpec::Json(_)))
    })
}

fn insert_generated_file(
    files: &mut BTreeMap<PathBuf, String>,
    path: PathBuf,
    contents: String,
) -> Result<()> {
    if path.is_absolute()
        || path
            .components()
            .any(|c| c == std::path::Component::ParentDir)
    {
        return Err(Error::InvalidGeneratedPath {
            path,
            reason: "generated Go tree paths must be relative and stay within the output directory"
                .to_string(),
        });
    }
    if files.insert(path.clone(), contents).is_some() {
        return Err(Error::GeneratedFileConflict { path });
    }
    Ok(())
}

fn support_fragments_for_plans(
    plans: &[&ApiSpecLeaf<PlannedFamily>],
    support: &SupportFiles,
) -> Vec<SupportFragmentSpec> {
    if !support.fragments.is_empty() {
        return support.fragments.clone();
    }
    plans
        .iter()
        .flat_map(|leaf| leaf.spec.support.fragments_for_language(Language::Go))
        .cloned()
        .collect()
}

fn collect_leaf_specs<'a>(
    branch: &'a ApiSpecBranch<PlannedFamily>,
    leaves: &mut Vec<&'a ApiSpecLeaf<PlannedFamily>>,
) {
    for child in branch.children.values() {
        match child {
            ApiSpecNode::Leaf(leaf) => leaves.push(leaf),
            ApiSpecNode::Branch(branch) => collect_leaf_specs(branch, leaves),
        }
    }
}

#[derive(Debug, Default)]
struct GoModelFragments {
    imports: BTreeSet<String>,
    body: String,
}

enum GoExternalModels {
    Json(json::ModelBackend),
    Proto(proto::ModelBackend),
}

impl GoExternalModels {
    fn new(api_plan: &PlannedSpec, package: GoPackageContext, mode: GenerationMode) -> Self {
        if api_plan
            .external_types()
            .any(|(_, binding)| matches!(binding.external_type, ExternalTypeSpec::Json(_)))
        {
            Self::Json(json::ModelBackend::new(mode == GenerationMode::NativeApi))
        } else {
            Self::Proto(proto::ModelBackend::new(package))
        }
    }

    fn prepare(&mut self, api_plan: &PlannedSpec) -> Result<()> {
        match self {
            Self::Json(backend) => backend.prepare(api_plan),
            Self::Proto(backend) => backend.prepare(api_plan),
        }
    }

    fn render_models(&self) -> Result<GoModelFragments> {
        match self {
            Self::Json(backend) => {
                let fragments = backend.render_models()?;
                Ok(GoModelFragments {
                    imports: fragments.imports,
                    body: fragments.body,
                })
            }
            Self::Proto(backend) => {
                let _ = backend.render_models()?;
                Ok(GoModelFragments::default())
            }
        }
    }

    fn imports(&self) -> Vec<(String, String)> {
        match self {
            // Go flattens every JSON-schema input file into one flat
            // package, so there is never a real cross-package import to
            // emit here.
            Self::Json(_) => Vec::new(),
            Self::Proto(backend) => backend
                .imports()
                .paths()
                .map(|(path, alias)| (path.clone(), alias.clone()))
                .collect(),
        }
    }

    fn model_type_annotation(&self, model_type: &PlannedValueType) -> Option<String> {
        match self {
            Self::Json(backend) => backend.model_type_annotation(model_type),
            Self::Proto(backend) => backend.model_type_annotation(model_type),
        }
    }

    fn has_message_wire_type(&self, message: &PlannedMessageType) -> bool {
        match self {
            Self::Json(backend) => backend.has_message_wire_type(message),
            Self::Proto(backend) => backend.has_message_wire_type(message),
        }
    }

    fn record_model(&mut self, key: &str, message: &PlannedMessageType) {
        if let Self::Proto(backend) = self {
            backend.record_model(key, message);
        }
    }

    fn populate_model_wire_conversions(
        &mut self,
        api_plan: &PlannedSpec,
        models: &IndexMap<String, RenderedModel>,
    ) -> Result<()> {
        match self {
            Self::Json(_) => Ok(()),
            Self::Proto(backend) => backend.populate_model_wire_conversions(api_plan, models),
        }
    }

    fn populate_operation_bindings(
        &self,
        api_plan: &PlannedSpec,
        services: &mut [RenderedService<'_>],
    ) -> Result<()> {
        match self {
            Self::Json(_) => Ok(()),
            Self::Proto(backend) => backend.populate_operation_bindings(api_plan, services),
        }
    }

    fn render_model_wire_methods(&self, output: &mut String, key: &str, model: &RenderedModel) {
        if let Self::Proto(backend) = self {
            backend.render_model_wire_methods(output, key, model);
        }
    }

    fn renders_operation_references(&self) -> bool {
        matches!(self, Self::Json(_))
    }

    fn render_operation_references(
        &self,
        api_plan: &PlannedSpec,
        package: &GoPackageContext,
    ) -> Result<Option<String>> {
        match self {
            Self::Json(backend) if backend.is_active() => {
                Ok(Some(backend.render_services(api_plan, package)?))
            }
            _ => Ok(None),
        }
    }
}

struct ApiPlanner<'a> {
    api_plan: &'a PlannedSpec,
    mode: GenerationMode,
    package: GoPackageContext,
    imports: BTreeSet<String>,
    external_models: GoExternalModels,
    enums: IndexMap<String, RenderedEnum>,
    flags: IndexMap<String, RenderedFlags>,
    variants: IndexMap<String, RenderedVariant>,
    models: IndexMap<String, RenderedModel>,
}

impl<'a> ApiPlanner<'a> {
    fn new(api_plan: &'a PlannedSpec, options: &GoOptions, mode: GenerationMode) -> Result<Self> {
        let package = GoPackageContext::new(api_plan, options)?;
        let mut imports = BTreeSet::new();

        // Re-scan all resolved type expressions to collect import paths.
        // Type expressions like "temporal.RetryPolicy" were produced by
        // resolve_go_type_annotation which stripped the full module path, but
        // we need to recover the imports from the original annotations.
        // We do this by re-parsing annotations from the planned spec.
        collect_imports_from_plan(api_plan, &mut imports);
        imports.retain(|import_path| !package.is_self_import(import_path));

        let mut external_models = GoExternalModels::new(api_plan, package.clone(), mode);
        external_models.prepare(api_plan)?;

        Ok(Self {
            api_plan,
            mode,
            package,
            imports,
            external_models,
            enums: IndexMap::new(),
            flags: IndexMap::new(),
            variants: IndexMap::new(),
            models: IndexMap::new(),
        })
    }

    fn generate(mut self, support_fragments: &[SupportFragmentSpec]) -> Result<GeneratedFiles> {
        let mut services = Vec::new();
        if !self.external_models.renders_operation_references() {
            for service in &self.api_plan.services {
                let mut operations = Vec::new();
                for operation in &service.operations {
                    operations.push(self.resolve_operation(operation)?);
                }

                services.push(RenderedService {
                    wire_name: &service.wire_name,
                    endpoint: service
                        .endpoint
                        .clone()
                        .or_else(|| Some(service.name.to_kebab_case())),
                    operations,
                    resources: service
                        .resources
                        .iter()
                        .map(|resource| resource.data.clone())
                        .collect(),
                });
            }
        }

        for service in &services {
            for resource in &service.resources {
                self.ensure_resource_field_types(resource)?;
            }
        }

        for record in self.api_plan.records().map(|(_, record)| record) {
            self.ensure_rendered_model(&planned_message_type_for_record(record))?;
        }

        let visibility = compute_go_visibility(
            self.api_plan,
            &self.enums,
            &self.flags,
            &self.variants,
            &self.models,
        );
        apply_go_visibility(
            &visibility,
            &mut self.enums,
            &mut self.flags,
            &mut self.variants,
            &mut self.models,
            &mut services,
        );

        // Second pass: compute backend wire metadata for rendered models and
        // collect any aliased imports they require. This runs after visibility
        // so the backend renders final Go names directly.
        self.populate_model_wire_conversions()?;
        self.populate_operation_bindings(&mut services)?;

        let needs_function_name_inlining = services.iter().any(service_uses_function_name_inlining);

        // Operation wrapper functions require the workflow package.
        let has_operations = services.iter().any(|s| !s.operations.is_empty());
        if has_operations && !self.package.is_self_import("go.temporal.io/sdk/workflow") {
            self.imports
                .insert("go.temporal.io/sdk/workflow".to_string());
        }
        if services
            .iter()
            .flat_map(|service| &service.operations)
            .any(|operation| {
                operation
                    .wire_binding
                    .as_ref()
                    .is_some_and(|binding| binding.requires_fmt())
            })
            || self.api_plan.records().any(|(_, record)| {
                record.fields.values().any(|field| {
                    field
                        .flattened_annotation
                        .as_ref()
                        .and_then(|annotation| annotation.for_language(Language::Go))
                        .is_some()
                })
            })
        {
            self.imports.insert("fmt".to_string());
        }
        if needs_function_name_inlining {
            self.imports.insert("reflect".to_string());
            self.imports.insert("runtime".to_string());
            self.imports.insert("strings".to_string());
        }
        let model_fragments = self.external_models.render_models()?;
        self.imports.extend(model_fragments.imports);
        // The Nexus service definition (operation references) is emitted in
        // both modes, so the `nexus` import is needed whenever a spec has
        // services — not just in NativeApi.
        if self.external_models.renders_operation_references()
            && !self.api_plan.services.is_empty()
            && !self
                .package
                .is_self_import("github.com/nexus-rpc/sdk-go/nexus")
        {
            self.imports
                .insert("github.com/nexus-rpc/sdk-go/nexus".to_string());
        }
        if self.mode == GenerationMode::NativeApi
            && self.external_models.renders_operation_references()
            && !self.api_plan.services.is_empty()
            && !self.package.is_self_import("go.temporal.io/sdk/workflow")
        {
            self.imports
                .insert("go.temporal.io/sdk/workflow".to_string());
        }
        let external_imports = self.external_models.imports();
        let output = render_file(
            &self.package,
            &self.imports,
            &external_imports,
            &model_fragments.body,
            self.external_models
                .render_operation_references(self.api_plan, &self.package)?
                .as_deref(),
            self.enums.values().collect::<Vec<_>>().as_slice(),
            self.flags.values().collect::<Vec<_>>().as_slice(),
            self.variants.values().collect::<Vec<_>>().as_slice(),
            self.models.iter().collect::<Vec<_>>().as_slice(),
            &services,
            &self.external_models,
            self.api_plan,
            &visibility,
        );

        let mut files = BTreeMap::new();
        let file_name = if self.external_models.renders_operation_references() {
            PathBuf::from(format!("{}.go", self.package.package_name))
        } else {
            go_api_file_name(self.api_plan)
        };
        files.insert(file_name, output);

        // Emit hand-written support fragments (e.g. proto converter functions)
        // in one support file. Like the TypeScript backend, all fragments are
        // emitted unconditionally, even when nothing in the generated code
        // references them.
        if !support_fragments.is_empty() {
            files.insert(
                PathBuf::from("support.go"),
                render_support_file(support_fragments, &self.package.package_name),
            );
        }

        Ok(GeneratedFiles::directory(files))
    }

    fn resolve_operation(
        &mut self,
        operation: &'a PlannedOperation,
    ) -> Result<RenderedOperation<'a>> {
        let input = operation
            .input
            .as_ref()
            .and_then(|input| planned_message_type(input, self.api_plan))
            .ok_or_else(|| Error::InvalidWit {
                path: PathBuf::from("<go-plan>"),
                reason: format!(
                    "operation `{}` has no proto-backed or WIT-native input type",
                    operation.name
                ),
            })?;
        let output = operation_output(operation, self.api_plan);
        self.resolve_message_types(&input)?;
        let model_type_parameters = record_for_message(self.api_plan, &input)
            .map(|record| {
                self.api_plan
                    .record_type_parameters(&record.full_name, Language::Go)
            })
            .unwrap_or_default();
        let input_type = go_generic_reference(
            &resolve_message_go_type(&input, &self.external_models),
            &model_type_parameters,
            false,
        );
        let go_output_transform = operation.output_transform.as_ref().and_then(|transform| {
            Some((
                transform.type_name.for_language(Language::Go)?,
                transform.transform.for_language(Language::Go)?,
            ))
        });
        let raw_output_type = if go_output_transform.is_some() {
            match &output {
                PlannedOperationOutput::Message(output) => {
                    if self.external_models.has_message_wire_type(output) {
                        None
                    } else {
                        self.resolve_message_types(output)?;
                        Some(resolve_message_go_type(output, &self.external_models))
                    }
                }
                PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
                PlannedOperationOutput::None => None,
            }
        } else {
            None
        };

        let output_type = match &output {
            PlannedOperationOutput::Message(output) => {
                if let Some(resource_return) = &operation.data.output_resource_return {
                    // The operation returns a resource constructed from the proto
                    // response -- use the resource type name.
                    Some(resource_return.resource_type_name.clone())
                } else if let Some((transform_type, _)) = go_output_transform {
                    // Output transforms expose their transformed type to callers,
                    // while the raw operation output is still resolved below for
                    // result decoding.
                    Some(self.package.go_type_expr(transform_type))
                } else {
                    self.resolve_message_types(output)?;
                    Some(resolve_message_go_type(output, &self.external_models))
                }
            }
            PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
            PlannedOperationOutput::None => None,
        };

        // Build unpacked input params from the rendered model, if the input type
        // is a generated model (not an external/replacement type).
        let unpacked_input = self.models.get(&input.info.full_name).map(|model| {
            let planned_record = record_for_message(self.api_plan, &input);
            let planned_fields = planned_record.map(|record| {
                record
                    .public_fields()
                    .map(|(field_name, field)| {
                        planned_field(record, field_name, field, self.api_plan)
                    })
                    .collect::<Vec<_>>()
            });
            model
                .fields
                .iter()
                .enumerate()
                .filter_map(|(index, field)| {
                    let planned_field =
                        planned_fields.as_ref().and_then(|fields| fields.get(index));
                    let planned_field = planned_field?;
                    let function = match &planned_field.role {
                        PlannedFieldRole::Function(function) if planned_field.required => {
                            Some(function.clone())
                        }
                        _ => None,
                    };
                    let function_args = match &planned_field.role {
                        PlannedFieldRole::FunctionArgs(function) => Some(function.clone()),
                        _ => None,
                    };
                    let embed_in_options = !planned_field.required
                        && field_kind_is_flattened_message(&planned_field.kind, self.api_plan);
                    let default_punning_zero = (!planned_field.required && !embed_in_options)
                        .then(|| {
                            public_default_punning_zero_for_field(
                                &planned_field.kind,
                                &field.go_type,
                            )
                        })
                        .flatten();
                    let public_go_type = if default_punning_zero.is_some() {
                        field
                            .go_type
                            .strip_prefix('*')
                            .unwrap_or(&field.go_type)
                            .to_string()
                    } else {
                        field.go_type.clone()
                    };
                    Some(RenderedUnpackedParam {
                        field_name: field.name.clone(),
                        doc: field.doc.clone(),
                        param_name: go_unexported_name(&field.name),
                        go_type: field.go_type.clone(),
                        public_go_type,
                        default_punning_zero,
                        function,
                        function_args,
                        required: field.required,
                        embed_in_options,
                    })
                })
                .collect()
        });

        Ok(RenderedOperation {
            name: operation.name.as_str(),
            wire_name: operation.wire_name.as_str(),
            doc: operation.doc.for_language(Language::Go),
            return_doc: operation.return_doc.for_language(Language::Go),
            func_name: go_unexported_name(&operation.name),
            input_type,
            model_type_parameters,
            output_type,
            raw_output_type,
            output_transform_expr: go_output_transform.map(|(_, expr)| expr),
            output_transform_type: go_output_transform
                .map(|(type_name, _)| self.package.go_type_expr(type_name)),
            unpacked_input,
            wire_binding: None,
        })
    }

    fn ensure_resource_field_types(&mut self, resource: &PlannedResource) -> Result<()> {
        for field in &resource.fields {
            self.ensure_resource_field_type(&planned_field_kind(&field.kind, self.api_plan))?;
        }
        for method in &resource.methods {
            for param in &method.params {
                self.ensure_resource_field_type(&planned_field_kind(&param.kind, self.api_plan))?;
            }
        }
        Ok(())
    }

    fn ensure_resource_field_type(&mut self, kind: &PlannedFieldKind) -> Result<()> {
        match kind {
            PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
                self.resolve_planned_value_type(value)?;
            }
            PlannedFieldKind::Map { key, value } => {
                self.resolve_planned_value_type(key)?;
                self.resolve_planned_value_type(value)?;
            }
        }
        Ok(())
    }

    fn resolve_message_types(&mut self, message: &PlannedMessageType) -> Result<()> {
        if message.replacement.is_some() || message.authored_type.is_some() {
            return Ok(());
        }
        if message.source == PlannedMessageSource::Json {
            return Ok(());
        }

        self.ensure_rendered_model(message)
    }

    fn resolve_planned_value_type(
        &mut self,
        value_type: &PlannedValueType,
    ) -> Result<ResolvedGoType> {
        match value_type {
            PlannedValueType::TypeParameter(name) => Ok(ResolvedGoType {
                type_expr: name.clone(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Float) => Ok(ResolvedGoType {
                type_expr: "float64".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Int32) => Ok(ResolvedGoType {
                type_expr: "int32".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Int64) => Ok(ResolvedGoType {
                type_expr: "int64".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Bool) => Ok(ResolvedGoType {
                type_expr: "bool".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::String) => Ok(ResolvedGoType {
                type_expr: "string".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Bytes) => Ok(ResolvedGoType {
                type_expr: "[]byte".to_string(),
            }),
            PlannedValueType::Enum(enum_type) => {
                let backend_type = self.external_models.model_type_annotation(value_type);
                if let (Some(info), Some(name)) = (&enum_type.info, &enum_type.name) {
                    if let Some(enum_decl) = self.api_plan.enum_decl(&info.full_name) {
                        self.ensure_rendered_enum(&planned_enum(enum_decl));
                    } else if enum_type.replacement.is_none() {
                        self.ensure_rendered_enum(&PlannedEnum {
                            info: info.clone(),
                            name: name.clone(),
                            values: Vec::new(),
                        });
                    }
                    Ok(ResolvedGoType {
                        type_expr: backend_type.unwrap_or_else(|| name.clone()),
                    })
                } else {
                    Ok(ResolvedGoType {
                        type_expr: backend_type.unwrap_or_else(|| "int32".to_string()),
                    })
                }
            }
            PlannedValueType::Flags(flags_type) => {
                if let Some(flags_decl) = self.api_plan.flags_decl(&flags_type.info.full_name) {
                    self.ensure_rendered_flags(&planned_flags(flags_decl));
                }
                Ok(ResolvedGoType {
                    type_expr: flags_type.name.clone(),
                })
            }
            PlannedValueType::Variant(variant_type) => {
                if let Some(variant_decl) = self.api_plan.variant(&variant_type.info.full_name) {
                    let planned = planned_variant(variant_decl, self.api_plan);
                    self.ensure_rendered_variant(&planned)?;
                }
                // Interfaces have nil zero value, so no pointer needed for optional fields.
                Ok(ResolvedGoType {
                    type_expr: go_generic_reference(
                        &variant_type.name,
                        &self
                            .api_plan
                            .variant_type_parameters(&variant_type.info.full_name, Language::Go),
                        false,
                    ),
                })
            }
            PlannedValueType::Message(message_type) => {
                if let Some(type_name) = self.external_models.model_type_annotation(value_type)
                    && (message_type.replacement.is_some() || message_type.authored_type.is_some())
                {
                    return Ok(ResolvedGoType {
                        type_expr: type_name,
                    });
                }
                self.ensure_rendered_model(message_type)?;
                let base = self
                    .external_models
                    .model_type_annotation(value_type)
                    .unwrap_or_else(|| message_type.model_name.clone());
                let type_expr = record_for_message(self.api_plan, message_type)
                    .map(|record| {
                        go_generic_reference(
                            &base,
                            &self
                                .api_plan
                                .record_type_parameters(&record.full_name, Language::Go),
                            false,
                        )
                    })
                    .unwrap_or(base);
                Ok(ResolvedGoType { type_expr })
            }
            // Tuples and results inside containers (lists, maps, variant payloads,
            // resource fields) instantiate shared generic helper types; direct
            // record fields keep their field-named structs (see `build_field`).
            PlannedValueType::Tuple(items) => {
                let type_name = self.ensure_generic_tuple(items.len())?;
                let args = items
                    .iter()
                    .map(|item| {
                        self.resolve_planned_value_type(item)
                            .map(|resolved| resolved.type_expr)
                    })
                    .collect::<Result<Vec<_>>>()?;
                Ok(ResolvedGoType {
                    type_expr: format!("{type_name}[{}]", args.join(", ")),
                })
            }
            PlannedValueType::Result { ok, err } => {
                self.ensure_generic_result();
                let ok_type = match ok {
                    Some(ok) => self.resolve_planned_value_type(ok)?.type_expr,
                    None => "struct{}".to_string(),
                };
                let err_type = match err {
                    Some(err) => self.resolve_planned_value_type(err)?.type_expr,
                    None => "error".to_string(),
                };
                Ok(ResolvedGoType {
                    type_expr: format!("Result[{ok_type}, {err_type}]"),
                })
            }
            PlannedValueType::External {
                type_name,
                fallback,
            } => {
                if let Some(annotation) = type_name.for_language(Language::Go) {
                    Ok(ResolvedGoType {
                        type_expr: self.package.go_type_expr(annotation),
                    })
                } else {
                    self.resolve_planned_value_type(fallback)
                }
            }
            PlannedValueType::Unknown => Ok(ResolvedGoType {
                type_expr: "any".to_string(),
            }),
        }
    }

    fn ensure_rendered_enum(&mut self, planned_enum: &PlannedEnum) {
        self.enums
            .entry(planned_enum.info.full_name.clone())
            .or_insert_with(|| RenderedEnum {
                name: planned_enum.name.clone(),
                values: planned_enum
                    .values
                    .iter()
                    .map(|value| RenderedEnumValue {
                        name: value.name.clone(),
                        number: value.number,
                    })
                    .collect(),
            });
    }

    fn ensure_rendered_flags(&mut self, planned_flags: &PlannedFlags) {
        self.flags
            .entry(planned_flags.info.full_name.clone())
            .or_insert_with(|| RenderedFlags {
                name: planned_flags.name.clone(),
                flags: planned_flags
                    .flags
                    .iter()
                    .map(|flag| RenderedFlag {
                        name: flag.name.clone(),
                        bit: flag.bit,
                    })
                    .collect(),
            });
    }

    fn ensure_rendered_variant(&mut self, planned_variant: &PlannedVariant) -> Result<()> {
        if self.variants.contains_key(&planned_variant.info.full_name) {
            return Ok(());
        }

        let variant_name = &planned_variant.name;
        let mut cases = Vec::new();
        for case in &planned_variant.cases {
            let case_suffix = go_field_name(&case.name);
            let payload_type = case
                .payload
                .as_ref()
                .map(|payload| {
                    self.resolve_planned_value_type(payload)
                        .map(|resolved| resolved.type_expr)
                })
                .transpose()?;
            cases.push(RenderedVariantCase {
                struct_name: format!("{variant_name}{case_suffix}"),
                payload_type,
            });
        }
        self.variants.insert(
            planned_variant.info.full_name.clone(),
            RenderedVariant {
                name: variant_name.clone(),
                type_parameters: planned_variant.type_parameters.clone(),
                marker_method: format!("is{variant_name}"),
                cases,
            },
        );
        Ok(())
    }

    fn ensure_rendered_model(&mut self, message: &PlannedMessageType) -> Result<()> {
        let Some((model_name, model_parameters, planned_fields)) =
            record_for_message(self.api_plan, message).map(|planned_model| {
                let parameters = self
                    .api_plan
                    .record_type_parameters(&planned_model.full_name, Language::Go);
                let planned_fields = planned_model
                    .model_fields()
                    .map(|(field_name, field)| {
                        planned_field(planned_model, field_name, field, self.api_plan)
                    })
                    .collect::<Vec<_>>();
                (planned_model.name.clone(), parameters, planned_fields)
            })
        else {
            // The planner may skip models for output types with transforms or
            // resource returns. Generate a minimal empty struct so the type
            // is at least defined.
            if !self.models.contains_key(&message.info.full_name) {
                self.models.insert(
                    message.info.full_name.clone(),
                    RenderedModel {
                        name: message.model_name.clone(),
                        fields: Vec::new(),
                    },
                );
                self.external_models
                    .record_model(&message.info.full_name, message);
            }
            return Ok(());
        };

        if self.models.contains_key(&message.info.full_name) {
            return Ok(());
        }

        self.models.insert(
            message.info.full_name.clone(),
            RenderedModel {
                name: go_generic_declaration_name(&model_name, &model_parameters),
                fields: Vec::new(),
            },
        );
        self.external_models
            .record_model(&message.info.full_name, message);

        let fields = planned_fields
            .iter()
            .map(|planned_field| self.build_field(planned_field))
            .collect::<Result<Vec<_>>>()?;

        self.models
            .get_mut(&message.info.full_name)
            .expect("model should be inserted before recursive field resolution")
            .fields = fields;
        Ok(())
    }

    fn build_field(&mut self, field: &PlannedField) -> Result<RenderedField> {
        let field_name = go_field_name(&field.authored_name);

        let annotated_go_type = field
            .flattened_annotation_override
            .as_ref()
            .or(field.annotation_override.as_ref())
            .and_then(|annotation| annotation.for_language(Language::Go))
            .map(|annotation| self.package.go_type_expr(annotation));

        let go_type = if let Some(annotated) = annotated_go_type {
            annotated
        } else {
            match &field.kind {
                PlannedFieldKind::Map { key, value } => {
                    let key_type = self.resolve_planned_value_type(key)?;
                    let value_type = self.resolve_planned_value_type(value)?;
                    format!("map[{}]{}", key_type.type_expr, value_type.type_expr)
                }
                PlannedFieldKind::Repeated(value) => {
                    let element_type = self.resolve_planned_value_type(value)?;
                    format!("[]{}", element_type.type_expr)
                }
                PlannedFieldKind::Singular(value) => {
                    let resolved = self.resolve_planned_value_type(value)?;
                    if !field.required
                        && type_needs_pointer_when_optional(value, &resolved.type_expr)
                    {
                        format!("*{}", resolved.type_expr)
                    } else {
                        resolved.type_expr
                    }
                }
            }
        };

        Ok(RenderedField {
            name: field_name,
            doc: field
                .doc
                .as_ref()
                .and_then(|doc| doc.for_language(Language::Go))
                .map(str::to_string),
            go_type,
            required: field.required,
        })
    }

    fn ensure_generic_tuple(&mut self, arity: usize) -> Result<String> {
        ensure_generic_tuple(arity, &mut self.models)
    }

    fn ensure_generic_result(&mut self) {
        ensure_generic_result(&mut self.models);
    }

    fn populate_model_wire_conversions(&mut self) -> Result<()> {
        self.external_models
            .populate_model_wire_conversions(self.api_plan, &self.models)
    }

    fn populate_operation_bindings(&self, services: &mut [RenderedService<'_>]) -> Result<()> {
        self.external_models
            .populate_operation_bindings(self.api_plan, services)
    }
}

fn service_uses_function_name_inlining(service: &RenderedService<'_>) -> bool {
    service.operations.iter().any(|operation| {
        operation.unpacked_input.as_ref().is_some_and(|params| {
            params
                .iter()
                .any(|param| param.required && param.function.is_some())
        })
    })
}

/// Derives the primary Go output filename from the first service name
/// (`WorkflowService` -> `workflowservice.go`). Most WIT inputs export a single
/// service; for empty plans, keep the historical `api.go` fallback.
fn go_api_file_name(api_plan: &PlannedSpec) -> PathBuf {
    let stem = api_plan
        .services
        .first()
        .map(|service| {
            service
                .name
                .chars()
                .filter(|c| c.is_ascii_alphanumeric())
                .collect::<String>()
                .to_lowercase()
        })
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| "api".to_string());
    PathBuf::from(format!("{stem}.go"))
}

fn render_support_file(fragments: &[SupportFragmentSpec], package_name: &str) -> String {
    if let [fragment] = fragments {
        return rewrite_support_package(&fragment.contents, package_name);
    }

    let mut prelude = String::new();
    let mut imports = BTreeSet::new();
    let mut bodies = Vec::new();
    for fragment in fragments {
        let parsed = parse_support_fragment(&fragment.contents);
        if prelude.is_empty() {
            prelude = parsed.prelude;
        } else if !parsed.prelude.trim().is_empty() {
            bodies.push(parsed.prelude.trim().to_string());
        }
        imports.extend(parsed.imports);
        if !parsed.body.trim().is_empty() {
            bodies.push(parsed.body.trim().to_string());
        }
    }

    let mut output = String::new();
    if !prelude.trim().is_empty() {
        output.push_str(prelude.trim_end());
        output.push('\n');
    }
    output.push_str("package ");
    output.push_str(package_name);
    output.push_str("\n\n");
    if !imports.is_empty() {
        output.push_str("import (\n");
        for import in imports {
            output.push('\t');
            output.push_str(&import);
            output.push('\n');
        }
        output.push_str(")\n\n");
    }
    output.push_str(&bodies.join("\n\n"));
    output.push('\n');
    output
}

/// Replaces the `package <name>` declaration in a Go support fragment with the
/// generated package name, preserving the rest of the file. If no package
/// declaration is found, the original contents are returned unchanged.
fn rewrite_support_package(contents: &str, package_name: &str) -> String {
    let mut result = String::with_capacity(contents.len());
    let mut replaced = false;
    for line in contents.lines() {
        if !replaced && line.trim_start().starts_with("package ") {
            result.push_str("package ");
            result.push_str(package_name);
            replaced = true;
        } else {
            result.push_str(line);
        }
        result.push('\n');
    }
    result
}

#[derive(Default)]
struct ParsedSupportFragment {
    prelude: String,
    imports: BTreeSet<String>,
    body: String,
}

fn parse_support_fragment(contents: &str) -> ParsedSupportFragment {
    let lines = contents.lines().collect::<Vec<_>>();
    let Some(package_index) = lines
        .iter()
        .position(|line| line.trim_start().starts_with("package "))
    else {
        return ParsedSupportFragment {
            body: contents.to_string(),
            ..Default::default()
        };
    };

    let mut parsed = ParsedSupportFragment {
        prelude: lines[..package_index].join("\n"),
        ..Default::default()
    };
    let mut index = package_index + 1;
    skip_blank_lines(&lines, &mut index);

    while index < lines.len() {
        let line = lines[index].trim_start();
        if line == "import (" {
            index += 1;
            while index < lines.len() && lines[index].trim() != ")" {
                let import = lines[index].trim();
                if !import.is_empty() {
                    parsed.imports.insert(import.to_string());
                }
                index += 1;
            }
            if index < lines.len() {
                index += 1;
            }
        } else if let Some(import) = line.strip_prefix("import ") {
            parsed.imports.insert(import.trim().to_string());
            index += 1;
        } else {
            break;
        }
        skip_blank_lines(&lines, &mut index);
    }

    parsed.body = lines[index..].join("\n");
    parsed
}

fn skip_blank_lines(lines: &[&str], index: &mut usize) {
    while *index < lines.len() && lines[*index].trim().is_empty() {
        *index += 1;
    }
}

/// Derives a valid Go package name from a Nexus endpoint string by stripping
/// non-alphanumeric characters and lowercasing (e.g. `"type-showcase"` becomes
/// `"typeshowcase"`).
pub(crate) fn go_package_name(endpoint: &str) -> String {
    endpoint
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect::<String>()
        .to_lowercase()
}

