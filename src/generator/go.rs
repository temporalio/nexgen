fn field_kind_is_flattened_message(kind: &PlannedFieldKind, api_plan: &PlannedSpec) -> bool {
    let PlannedFieldKind::Singular(PlannedValueType::Message(message)) = kind else {
        return false;
    };
    record_for_message(api_plan, message).is_some_and(|model| model.flatten_in_api)
}

pub(in crate::generator) fn public_default_punning_zero_for_field(
    kind: &PlannedFieldKind,
    internal_go_type: &str,
) -> Option<String> {
    let public_go_type = internal_go_type.strip_prefix('*')?;
    if let Some(zero) = public_default_punning_zero_for_go_type(public_go_type) {
        return Some(zero.to_string());
    }
    match kind {
        PlannedFieldKind::Singular(value) => {
            public_default_punning_zero_for_value(value, public_go_type)
        }
        PlannedFieldKind::Repeated(_) | PlannedFieldKind::Map { .. } => None,
    }
}

fn public_default_punning_zero_for_value(
    value: &PlannedValueType,
    public_go_type: &str,
) -> Option<String> {
    match value {
        PlannedValueType::Scalar(scalar) => match scalar {
            PlannedScalarType::Bool => Some("false".to_string()),
            PlannedScalarType::String => Some("\"\"".to_string()),
            PlannedScalarType::Int32 | PlannedScalarType::Int64 | PlannedScalarType::Float => {
                Some("0".to_string())
            }
            PlannedScalarType::Bytes => None,
        },
        PlannedValueType::Enum(_) | PlannedValueType::Flags(_) => Some("0".to_string()),
        PlannedValueType::External { .. } => {
            public_default_punning_zero_for_go_type(public_go_type).map(str::to_string)
        }
        PlannedValueType::TypeParameter(_)
        | PlannedValueType::Variant(_)
        | PlannedValueType::Message(_)
        | PlannedValueType::Tuple(_)
        | PlannedValueType::Result { .. }
        | PlannedValueType::Unknown => None,
    }
}

fn public_default_punning_zero_for_go_type(public_go_type: &str) -> Option<&'static str> {
    match public_go_type {
        "string" => Some("\"\""),
        "bool" => Some("false"),
        "int" | "int8" | "int16" | "int32" | "int64" | "uint" | "uint8" | "uint16" | "uint32"
        | "uint64" | "float32" | "float64" | "time.Duration" => Some("0"),
        _ => None,
    }
}

fn resolve_message_go_type(
    message: &PlannedMessageType,
    external_models: &GoExternalModels,
) -> String {
    external_models
        .model_type_annotation(&PlannedValueType::Message(message.clone()))
        .unwrap_or_else(|| message.model_name.clone())
}

/// Returns the Go type code expression from a [`TypeReplacementSpec`], if one
/// was specified for the Go language. The import path (if embedded in the
/// annotation) is stripped and will be collected separately by
/// [`collect_imports`].
pub(in crate::generator) fn go_replacement_type_name(
    replacement: &TypeReplacementSpec<PlannedFamily>,
    package: &GoPackageContext,
) -> Option<String> {
    replacement
        .type_name
        .value()
        .map(|annotation| package.go_type_expr(annotation))
}

/// Translates a WIT authored field type (used in `@nexus.type` directives)
/// into a Go type expression. Tuples and results are deferred and represented
/// as `any`.
pub(in crate::generator) fn go_authored_type_annotation(wit_type: &PlannedType) -> String {
    match wit_type {
        TypeSpec::Bool => "bool".to_string(),
        TypeSpec::Int(IntSpec::I32) => "int32".to_string(),
        TypeSpec::Int(IntSpec::U32) => "int32".to_string(),
        TypeSpec::Int(IntSpec::I64 | IntSpec::U64) => "int64".to_string(),
        TypeSpec::Float => "float64".to_string(),
        TypeSpec::String => "string".to_string(),
        TypeSpec::Bytes => "[]byte".to_string(),
        TypeSpec::TypeParameter(parameter) => parameter.name.clone(),
        TypeSpec::Option(inner) => format!("*{}", go_authored_type_annotation(inner)),
        TypeSpec::List(inner) => format!("[]{}", go_authored_type_annotation(inner)),
        TypeSpec::Tuple(_) => "any".to_string(),
        TypeSpec::Map(key, value) => format!(
            "map[{}]{}",
            go_authored_type_annotation(key),
            go_authored_type_annotation(value)
        ),
        TypeSpec::Result { .. } => "any".to_string(),
        TypeSpec::External(ExternalTypeSpec::Alias(AliasTypeSpec {
            type_name, target, ..
        })) => type_name
            .value()
            .map(str::to_string)
            .unwrap_or_else(|| go_authored_type_annotation(target)),
        TypeSpec::External(ExternalTypeSpec::Proto(PlannedProtoType::Message(message))) => {
            message.model_name.clone()
        }
        TypeSpec::External(ExternalTypeSpec::Proto(PlannedProtoType::Enum(enumeration))) => {
            enumeration.name.clone()
        }
        TypeSpec::External(ExternalTypeSpec::Json(json_type)) => json_type.model_name.clone(),
        TypeSpec::Record(record) => record.model_name.clone(),
        TypeSpec::Enum(enumeration) => enumeration.name.clone(),
        TypeSpec::Flags(flags) => flags.name.clone(),
        TypeSpec::Variant(variant) => variant.name.clone(),
        TypeSpec::Resource(resource) => resource.type_name.clone(),
    }
}

fn go_generic_declaration_name(
    model_name: &str,
    parameters: &[crate::spec::TypeParameterUsage],
) -> String {
    if parameters.is_empty() {
        return model_name.to_string();
    }
    let declarations = parameters
        .iter()
        .map(|usage| format!("{} any", usage.parameter.name))
        .collect::<Vec<_>>()
        .join(", ");
    format!("{model_name}[{declarations}]")
}

fn render_go_model_type_parameter_declaration(
    output: &mut String,
    parameters: &[crate::spec::TypeParameterUsage],
) {
    if parameters.is_empty() {
        return;
    }
    output.push('[');
    for (index, usage) in parameters.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        output.push_str(&usage.parameter.name);
        output.push_str(" any");
    }
    output.push(']');
}

fn go_generic_reference(
    model_name: &str,
    parameters: &[crate::spec::TypeParameterUsage],
    erase: bool,
) -> String {
    if parameters.is_empty() {
        return model_name.to_string();
    }
    let arguments = parameters
        .iter()
        .map(|usage| {
            if erase {
                "any"
            } else {
                usage.parameter.name.as_str()
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("{model_name}[{arguments}]")
}

/// Returns `true` when an optional singular field of this value type must be
/// rendered as a pointer (`*T`) so that absence is representable as `nil`.
///
/// Pointers are used for every value-like type -- scalars, enums, flags,
/// messages, and override/replacement types -- so that "unset" is distinct from
/// "set to the zero value". Types whose zero value is already `nil` need no
/// pointer: variants (interfaces) and any `any`-typed value.
fn type_needs_pointer_when_optional(
    value: &PlannedValueType,
    type_expr: &str,
    package: &GoPackageContext,
) -> bool {
    if matches!(
        value,
        PlannedValueType::Variant(_) | PlannedValueType::Unknown
    ) {
        return false;
    }
    if matches!(
        type_expr,
        "client.VersioningOverride"
            | "temporal.SearchAttributes"
            | "internal.VersioningOverride"
            | "internal.SearchAttributes"
    ) || (package.is_self_import("go.temporal.io/sdk/internal")
        && matches!(type_expr, "VersioningOverride" | "SearchAttributes"))
    {
        return false;
    }
    // Already-nilable Go types represent absence directly.
    if go_type_is_nilable(type_expr) {
        return false;
    }
    true
}

pub(in crate::generator) fn go_type_is_nilable(type_expr: &str) -> bool {
    matches!(type_expr, "any" | "error")
        || type_expr.starts_with("[]")
        || type_expr.starts_with("map[")
}

/// Key prefix for generic helper models in the rendered-model map, chosen so
/// it can never collide with a WIT record or proto message full name.
const GENERIC_MODEL_KEY_PREFIX: &str = "nexgen::generic::";

/// Ensures the generic tuple helper type for the given arity is rendered
/// (e.g. `type Tuple2[T1, T2 any] struct { First T1; Second T2 }`) and returns
/// its Go type name (`Tuple2`).
fn ensure_generic_tuple(
    arity: usize,
    models: &mut IndexMap<String, RenderedModel>,
) -> Result<String> {
    if arity == 0 || arity > TUPLE_FIELD_NAMES.len() {
        return Err(Error::UnsupportedGoType {
            context: format!("tuple with {arity} element(s)"),
            reason: format!(
                "tuples are supported with 1 to {} elements",
                TUPLE_FIELD_NAMES.len()
            ),
        });
    }

    let type_name = format!("Tuple{arity}");
    let key = format!("{GENERIC_MODEL_KEY_PREFIX}{type_name}");
    if !models.contains_key(&key) {
        let type_parameters = (1..=arity)
            .map(|index| format!("T{index}"))
            .collect::<Vec<_>>();
        let params = type_parameters.join(", ");
        let fields = (0..arity)
            .map(|index| RenderedField {
                name: TUPLE_FIELD_NAMES[index].to_string(),
                doc: None,
                go_type: format!("T{}", index + 1),
                default_punning_zero: None,
                required: true,
                sourced: false,
            })
            .collect();
        models.insert(
            key,
            RenderedModel {
                name: format!("{type_name}[{params} any]"),
                type_parameters,
                fields,
            },
        );
    }
    Ok(type_name)
}

/// Ensures the generic result helper type is rendered:
/// `type Result[T, E any] struct { Result T; Error E }`.
fn ensure_generic_result(models: &mut IndexMap<String, RenderedModel>) {
    let key = format!("{GENERIC_MODEL_KEY_PREFIX}Result");
    if !models.contains_key(&key) {
        models.insert(
            key,
            RenderedModel {
                name: "Result[T, E any]".to_string(),
                type_parameters: vec!["T".to_string(), "E".to_string()],
                fields: vec![
                    RenderedField {
                        name: "Result".to_string(),
                        doc: None,
                        go_type: "T".to_string(),
                        default_punning_zero: None,
                        required: false,
                        sourced: false,
                    },
                    RenderedField {
                        name: "Error".to_string(),
                        doc: None,
                        go_type: "E".to_string(),
                        default_punning_zero: None,
                        required: false,
                        sourced: false,
                    },
                ],
            },
        );
    }
}

/// Converts a PascalCase name to an unexported Go identifier, lowercasing
/// leading initialisms (e.g. `"ID"` becomes `"id"` and `"UserID"` becomes `"userID"`).
pub(in crate::generator) fn go_unexported_name(name: &str) -> String {
    if let Some(name) = name.strip_prefix("SystemNexus_") {
        return format!("systemnexus_{}", go_unexported_name(name));
    }
    let mut chars = name.chars().peekable();
    let mut result = String::new();
    while let Some(ch) = chars.next() {
        if !result.is_empty()
            && (!ch.is_uppercase() || chars.peek().is_some_and(|next| next.is_lowercase()))
        {
            result.push(ch);
            result.extend(chars);
            break;
        }
        result.extend(ch.to_lowercase());
    }
    go_ident(&result)
}

pub(in crate::generator) fn go_declaration_name(name: &str) -> String {
    if !crate::nexgen_config::current().system_nexus {
        return name.to_string();
    }
    let prefix = if is_go_exported_decl(name) {
        "SystemNexus_"
    } else {
        "systemnexus_"
    };
    format!("{prefix}{name}")
}

/// Converts a WIT field name (kebab-case) to an exported Go field name
/// (UpperCamelCase), escaping Go keywords with a trailing underscore.
pub(in crate::generator) fn go_field_name(name: &str) -> String {
    let camel = name
        .to_snake_case()
        .split('_')
        .filter(|word| !word.is_empty())
        .map(|word| {
            if word.eq_ignore_ascii_case("id") {
                "ID".to_string()
            } else {
                word.to_upper_camel_case()
            }
        })
        .collect::<String>();
    go_ident(&camel)
}

/// Returns the identifier unchanged unless it is a Go keyword, in which case
/// a trailing underscore is appended.
fn go_ident(name: &str) -> String {
    if is_go_keyword(name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// Rebinds package selectors in expressions without changing literals or
/// selectors on values, such as `request.workflow`.
fn rewrite_go_package_qualifier(expr: &str, from: &str, to: &str) -> String {
    if from == to {
        return expr.to_string();
    }
    let bytes = expr.as_bytes();
    let mut output = String::with_capacity(expr.len());
    let mut copied = 0;
    let mut index = 0;
    while index < bytes.len() {
        if matches!(bytes[index], b'"' | b'`' | b'\'') {
            let quote = bytes[index];
            index += 1;
            while index < bytes.len() {
                let byte = bytes[index];
                index += 1;
                if byte == b'\\' && quote != b'`' && index < bytes.len() {
                    index += 1;
                } else if byte == quote {
                    break;
                }
            }
        } else if is_go_ident_start(bytes[index]) {
            let start = index;
            index += 1;
            while index < bytes.len() && is_go_ident_continue(bytes[index]) {
                index += 1;
            }
            if &expr[start..index] == from
                && previous_non_whitespace(bytes, start) != Some(b'.')
                && next_non_whitespace(bytes, index) == Some(b'.')
            {
                output.push_str(&expr[copied..start]);
                output.push_str(to);
                copied = index;
            }
        } else {
            index += 1;
        }
    }
    output.push_str(&expr[copied..]);
    output
}

/// Parses a Go type expression that may contain an embedded import path.
///
/// Returns `(import_path, code_expr)` where `import_path` is the Go import
/// path to add to the `import` block (if any), and `code_expr` is the type
/// expression to use in generated Go code.
///
/// # Syntax
///
/// - `"go.temporal.io/sdk/temporal.RetryPolicy"` → import `"go.temporal.io/sdk/temporal"`,
///   code `"temporal.RetryPolicy"`
/// - `"time.Duration"` → import `"time"`, code `"time.Duration"`
/// - `"string"` → no import, code `"string"`
/// - `"map[string]any"` → no import, code `"map[string]any"`
fn parse_go_import(type_expr: &str) -> (Option<String>, String) {
    // Case 0: explicit import path with ':' separator, e.g.
    // "go.temporal.io/api/enums/v1:enums.WorkflowIdReusePolicy"
    // This handles packages where the directory name differs from the
    // declared Go package name (e.g. enums/v1 declares `package enums`).
    if let Some(colon) = type_expr.find(':') {
        let import_path = &type_expr[..colon];
        let code_expr = &type_expr[colon + 1..];
        return (Some(import_path.to_string()), code_expr.to_string());
    }

    // Case 1: contains '/' -- this is a full Go module path like
    // "go.temporal.io/sdk/temporal.RetryPolicy"
    if let Some(last_slash) = type_expr.rfind('/') {
        // Find the next '.' after the last '/' -- that separates the import
        // path from the type name.
        if let Some(dot_offset) = type_expr[last_slash..].find('.') {
            let split = last_slash + dot_offset;
            let import_path = &type_expr[..split];
            let pkg_name = &type_expr[last_slash + 1..split];
            let type_name = &type_expr[split + 1..];
            return (
                Some(import_path.to_string()),
                format!("{pkg_name}.{type_name}"),
            );
        }
    }

    // Case 2: no '/' but looks like "pkg.Type" where pkg is all lowercase
    // (e.g. "time.Duration")
    if let Some(dot) = type_expr.find('.') {
        let prefix = &type_expr[..dot];
        if !prefix.is_empty()
            && prefix.chars().all(|c| c.is_ascii_lowercase() || c == '_')
            && type_expr[dot + 1..]
                .chars()
                .next()
                .is_some_and(|c| c.is_ascii_uppercase())
        {
            return (Some(prefix.to_string()), type_expr.to_string());
        }
    }

    // Case 3: no import needed (builtins, map[K]V, any, etc.)
    (None, type_expr.to_string())
}

/// Parse package references at any depth without treating Go punctuation as
/// part of a module path. The same walk drives public rendering and imports.
fn parse_go_expr(expr: &str) -> (BTreeMap<String, String>, String) {
    // A leading explicit import applies to the entire expression, including
    // composite forms such as `example.org/types:[]types.Value`.
    if let Some((path, code)) = expr.split_once(':')
        && !path
            .chars()
            .any(|ch| matches!(ch, '[' | ']' | '(' | ')' | '*' | ' '))
    {
        return (
            BTreeMap::from([(path.to_string(), go_import_alias(code, path))]),
            code.to_string(),
        );
    }
    let mut imports = BTreeMap::new();
    let mut rendered = String::new();
    let mut token = String::new();
    let flush =
        |token: &mut String, rendered: &mut String, imports: &mut BTreeMap<String, String>| {
            if token.is_empty() {
                return;
            }
            let (prefix, reference) = token
                .strip_prefix("...")
                .map(|s| ("...", s))
                .unwrap_or(("", token.as_str()));
            let (import, code) = parse_go_import(reference);
            if let Some(import) = import {
                let alias = go_import_alias(&code, &import);
                imports.insert(import, alias);
            }
            rendered.push_str(prefix);
            rendered.push_str(&code);
            token.clear();
        };
    for ch in expr.chars() {
        if ch.is_ascii_alphanumeric() || matches!(ch, '_' | '.' | '/' | ':' | '-') {
            token.push(ch);
        } else {
            flush(&mut token, &mut rendered, &mut imports);
            rendered.push(ch);
        }
    }
    flush(&mut token, &mut rendered, &mut imports);
    (imports, rendered)
}

fn go_import_alias(expression: &str, import_path: &str) -> String {
    expression
        .split(|ch: char| !ch.is_ascii_alphanumeric() && !matches!(ch, '_' | '.'))
        .find_map(|token| token.split_once('.').map(|(alias, _)| alias))
        .unwrap_or_else(|| import_path.rsplit('/').next().unwrap_or(import_path))
        .to_string()
}

/// Walks the [`PlannedSpec`] and collects Go import paths from any `@nexus.type`
/// annotations that embed a module path (e.g. `go.temporal.io/sdk/temporal.RetryPolicy`).
fn collect_imports_from_plan(api_plan: &PlannedSpec, imports: &mut BTreeMap<String, String>) {
    for (_, model) in api_plan.records() {
        for (_, field) in model.model_fields() {
            if let Some(annotation) = field
                .flattened_annotation
                .as_ref()
                .or(field.annotation.as_ref())
                .and_then(|annotation| annotation.value())
            {
                // Match field rendering: the override replaces the underlying
                // type, including its import requirements.
                imports.extend(parse_go_expr(annotation).0);
            } else {
                collect_imports_from_value_type(
                    &planned_field_kind(&field.field_type, api_plan),
                    imports,
                );
            }
            if field.required
                && let Some(function) = &field.function
            {
                collect_imports_from_function(function, imports);
            }
        }
    }
    for service in &api_plan.services {
        for operation in &service.operations {
            if let Some(input) = operation
                .input
                .as_ref()
                .and_then(|input| planned_message_type(input, api_plan))
            {
                collect_imports_from_message_type(&input, imports);
            }
            if let PlannedOperationOutput::Message(output) = operation_output(operation, api_plan) {
                collect_imports_from_message_type(&output, imports);
            }
            if let Some(transform) = &operation.output_transform {
                if let (Some(annotation), Some(_expr)) =
                    (transform.type_name.value(), transform.transform.value())
                {
                    imports.extend(parse_go_expr(annotation).0);
                }
            }
        }
    }
}

fn collect_imports_from_function(
    function: &FunctionFieldSpec,
    imports: &mut BTreeMap<String, String>,
) {
    if !function_value_is_string(function)
        && let Some(helper) = &function.name_extractor
        && !helper.starts_with("support.")
    {
        imports.extend(parse_go_expr(helper).0);
    }
    if let Some(descriptor) = &function.type_descriptor {
        for text in [&descriptor.value_type, &descriptor.args_type] {
            if let Some(import) = text.import() {
                imports.insert(
                    import.to_string(),
                    go_import_alias(text.value().unwrap_or_default(), import),
                );
            } else if let Some(value) = text.value() {
                imports.extend(parse_go_expr(value).0);
            }
        }
        return;
    }
    match &function.args {
        FunctionArgsSpec::Varargs { prefix, .. } => {
            for arg in prefix {
                collect_imports_from_authored_type(&arg.field_type, imports);
            }
        }
        FunctionArgsSpec::Fixed(args) => {
            for arg in args {
                collect_imports_from_authored_type(&arg.field_type, imports);
            }
        }
    }
    match &function.result {
        FunctionResultSpec::Authored(result) => collect_imports_from_authored_type(result, imports),
        FunctionResultSpec::Annotation(result) => {
            if let Some(annotation) = result.value() {
                imports.extend(parse_go_expr(annotation).0);
            }
        }
    }
}

fn collect_imports_from_authored_type(
    wit_type: &PlannedType,
    imports: &mut BTreeMap<String, String>,
) {
    match wit_type {
        TypeSpec::Option(inner) | TypeSpec::List(inner) => {
            collect_imports_from_authored_type(inner, imports);
        }
        TypeSpec::Tuple(items) => {
            for item in items {
                collect_imports_from_authored_type(item, imports);
            }
        }
        TypeSpec::Map(key, value) => {
            collect_imports_from_authored_type(key, imports);
            collect_imports_from_authored_type(value, imports);
        }
        TypeSpec::Result { ok, err } => {
            if let Some(ok) = ok.as_deref() {
                collect_imports_from_authored_type(ok, imports);
            }
            if let Some(err) = err.as_deref() {
                collect_imports_from_authored_type(err, imports);
            }
        }
        TypeSpec::External(ExternalTypeSpec::Alias(AliasTypeSpec {
            type_name, target, ..
        })) => {
            if let Some(annotation) = type_name.value() {
                imports.extend(parse_go_expr(annotation).0);
            } else {
                collect_imports_from_authored_type(target, imports);
            }
        }
        _ => {}
    }
}

/// Collects Go imports from a message type's replacement or authored type.
fn collect_imports_from_message_type(
    message: &PlannedMessageType,
    imports: &mut BTreeMap<String, String>,
) {
    if let Some(replacement) = &message.replacement {
        if let Some(annotation) = replacement.type_name.value() {
            imports.extend(parse_go_expr(annotation).0);
        }
    }
}

/// Collects Go imports from value types within a field kind.
fn collect_imports_from_value_type(
    kind: &PlannedFieldKind,
    imports: &mut BTreeMap<String, String>,
) {
    match kind {
        PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
            collect_imports_from_planned_value(value, imports);
        }
        PlannedFieldKind::Map { key, value } => {
            collect_imports_from_planned_value(key, imports);
            collect_imports_from_planned_value(value, imports);
        }
    }
}

/// Recursively collects Go imports from a planned value type.
fn collect_imports_from_planned_value(
    value: &PlannedValueType,
    imports: &mut BTreeMap<String, String>,
) {
    match value {
        PlannedValueType::TypeParameter(_) => {}
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            if let Some(annotation) = type_name.value() {
                imports.extend(parse_go_expr(annotation).0);
            } else {
                collect_imports_from_planned_value(fallback, imports);
            }
        }
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement {
                if let Some(annotation) = replacement.type_name.value() {
                    imports.extend(parse_go_expr(annotation).0);
                }
            }
        }
        PlannedValueType::Message(message_type) => {
            if let Some(replacement) = &message_type.replacement {
                if let Some(annotation) = replacement.type_name.value() {
                    imports.extend(parse_go_expr(annotation).0);
                }
            }
        }
        PlannedValueType::Tuple(items) => {
            for item in items {
                collect_imports_from_planned_value(item, imports);
            }
        }
        PlannedValueType::Result { ok, err } => {
            if let Some(ok) = ok {
                collect_imports_from_planned_value(ok, imports);
            }
            if let Some(err) = err {
                collect_imports_from_planned_value(err, imports);
            }
        }
        _ => {}
    }
}

/// Returns `true` if `name` is a Go language keyword.
fn is_go_keyword(name: &str) -> bool {
    matches!(
        name,
        "break"
            | "case"
            | "chan"
            | "const"
            | "continue"
            | "default"
            | "defer"
            | "else"
            | "fallthrough"
            | "for"
            | "func"
            | "go"
            | "goto"
            | "if"
            | "import"
            | "interface"
            | "map"
            | "package"
            | "range"
            | "return"
            | "select"
            | "struct"
            | "switch"
            | "type"
            | "var"
    )
}

