impl GoPackageContext {
    fn documentation_name<'a>(&'a self, name: &'a str) -> &'a str {
        let name = split_go_type_decl_name(name).0;
        self.facade_exports
            .get(name)
            .map(|public| public.rsplit('.').next().unwrap())
            .unwrap_or(name)
    }

    fn render_declaration_doc(
        &self,
        output: &mut String,
        indent: &str,
        name: &str,
        doc: Option<&str>,
    ) {
        if doc.is_some()
            || self
                .facade_exports
                .contains_key(split_go_type_decl_name(name).0)
        {
            render_go_declaration_doc(output, indent, self.documentation_name(name), doc);
        }
        self.render_exposed_as(output, indent, name);
    }

    fn render_exposed_as(&self, output: &mut String, indent: &str, name: &str) {
        let name = split_go_type_decl_name(name).0;
        let Some(public) = self.facade_exports.get(name) else {
            return;
        };
        if output
            .lines()
            .next_back()
            .is_some_and(|line| line.trim_start().starts_with("//"))
        {
            output.push_str(&format!("{indent}//\n"));
        }
        output.push_str(&format!("{indent}// Exposed as: [{public}]\n"));
    }

    fn new(api_plan: &PlannedSpec, options: &GoOptions) -> Result<Self> {
        // `@nexus.namespace go="..."` is WIT-only (the JSON schema parser
        // never populates a per-language namespace), and it names an
        // *existing* Go package this generated code is meant to become part
        // of -- so any reference to that import path elsewhere in the
        // generated code is a self-reference, not an import, and must be
        // unqualified accordingly.
        let import_path = api_plan
            .primary_namespace()
            .and_then(|namespace| namespace.value())
            .map(str::to_string);
        let package_name = match &import_path {
            Some(path) => Self::derive_package_name(path.rsplit('/').next().unwrap_or(path))?,
            None => Self::derive_package_name(&options.output_dir_name)?,
        };
        let facade = api_plan
            .primary_facade()
            .and_then(|facade| facade.value())
            .map(|facade| {
                Ok(GoFacadeOptions {
                    package_name: Self::derive_package_name(
                        facade.rsplit('/').next().unwrap_or(facade),
                    )?,
                    import_path: facade.to_string(),
                    implementation_import_path: import_path
                        .clone()
                        .expect("facade requires an implementation namespace"),
                })
            })
            .transpose()?;

        Ok(Self {
            package_name,
            workflow_interceptors: crate::nexgen_config::current().system_nexus
                && crate::nexgen_config::current()
                    .targets
                    .contains(&GenerationTarget::Workflow),
            import_path,
            workflow_package_alias: if api_plan
                .records()
                .any(|(_, record)| record.fields.values().any(|field| field.name == "workflow"))
                || api_plan.services.iter().any(|service| {
                    service.resources.iter().any(|resource| {
                        resource
                            .data
                            .fields
                            .iter()
                            .any(|field| field.name == "workflow")
                            || resource.data.methods.iter().any(|method| {
                                method.params.iter().any(|param| param.name == "workflow")
                            })
                    })
                }) {
                "temporalworkflow"
            } else {
                "workflow"
            },
            has_serialization_context: crate::nexgen_config::current().system_nexus
                && api_plan
                    .services
                    .iter()
                    .flat_map(|service| &service.operations)
                    .any(|operation| operation.serialization_context.value().is_some()),
            support_package: options.support_package.clone(),
            facade,
            facade_exports: BTreeMap::new(),
        })
    }

    /// The package name is the output directory's basename, matching the Go
    /// convention that a package's name is its directory's name.
    /// `go_package_name` strips everything but ASCII alphanumerics and `_`,
    /// so a directory name with none of those (e.g. non-ASCII or
    /// punctuation-only) sanitizes to empty; that's rejected outright rather
    /// than guessed at.
    fn derive_package_name(output_dir_name: &str) -> Result<String> {
        let package_name = go_package_name(output_dir_name);
        if package_name.is_empty() {
            return Err(Error::GoPackageNameEmpty {
                output_dir_name: output_dir_name.to_string(),
            });
        }
        Ok(package_name)
    }

    pub(in crate::generator) fn is_self_import(&self, import_path: &str) -> bool {
        self.import_path
            .as_deref()
            .is_some_and(|self_import| self_import == import_path)
    }

    pub(in crate::generator) fn go_type_expr(&self, type_expr: &str) -> String {
        let (imports, code_expr) = parse_go_expr(type_expr);
        if imports.keys().any(|path| {
            self.is_self_import(path) || (self.import_path.is_some() && path == &self.package_name)
        }) {
            self.unqualify_self_expr(&code_expr)
        } else {
            self.alias_workflow_expr(&code_expr)
        }
    }

    fn import_alias<'a>(&self, path: &'a str) -> &'a str {
        if path == "go.temporal.io/sdk/workflow" {
            self.workflow_package_alias
        } else {
            path.rsplit('/').next().unwrap_or(path)
        }
    }

    fn alias_workflow_expr(&self, expr: &str) -> String {
        rewrite_go_package_qualifier(expr, "workflow", self.workflow_package_alias)
    }

    fn function_name_extractor(&self, reference: &str) -> String {
        if self.support_package.is_some() && !reference.contains('.') {
            self.support_reference(reference)
        } else {
            self.go_type_expr(reference)
        }
    }

    pub(in crate::generator) fn support_reference(&self, reference: &str) -> String {
        match &self.support_package {
            Some(path) if !self.is_self_import(path) => format!("support.{reference}"),
            _ => self.go_type_expr(reference),
        }
    }

    fn sdk_reference(&self, symbol: SdkSymbol) -> SdkReference {
        let mut reference = symbol.resolve(
            self.import_path.as_deref(),
            crate::nexgen_config::current().system_nexus,
        );
        reference.expression = self.alias_workflow_expr(&reference.expression);
        reference
    }

    pub(in crate::generator) fn workflow_context_type(&self) -> String {
        self.sdk_reference(SdkSymbol::Context).expression
    }

    fn workflow_future_type(&self) -> String {
        self.sdk_reference(SdkSymbol::Future).expression
    }

    pub(in crate::generator) fn new_future(&self) -> String {
        self.sdk_reference(SdkSymbol::NewFuture).expression
    }

    fn workflow_go(&self) -> String {
        self.sdk_reference(SdkSymbol::Go).expression
    }

    pub(in crate::generator) fn new_nexus_client(&self) -> String {
        self.sdk_reference(SdkSymbol::NewNexusClient).expression
    }

    pub(in crate::generator) fn nexus_operation_options(&self) -> String {
        format!(
            "{}{{}}",
            self.sdk_reference(SdkSymbol::NexusOperationOptions)
                .expression
        )
    }

    pub(in crate::generator) fn transfer_type_converter_type(&self) -> String {
        self.sdk_reference(SdkSymbol::TransferTypeConverter)
            .expression
    }

    pub(in crate::generator) fn new_transfer_type_converter(&self) -> String {
        let symbol = if crate::nexgen_config::current().system_nexus {
            SdkSymbol::NewSystemNexusTransferTypeConverter
        } else {
            SdkSymbol::NewTransferTypeConverter
        };
        self.sdk_reference(symbol).expression
    }

    pub(in crate::generator) fn system_nexus_context_type(&self) -> String {
        self.sdk_reference(SdkSymbol::SystemNexusContext).expression
    }

    pub(in crate::generator) fn workflow_data_converter(&self) -> String {
        self.sdk_reference(SdkSymbol::GetDataConverterFromWorkflowContext)
            .expression
    }

    pub(in crate::generator) fn serialization_context_type(&self) -> String {
        self.sdk_reference(SdkSymbol::SerializationContext)
            .expression
    }

    fn unqualify_self_expr(&self, code_expr: &str) -> String {
        let qualifier = format!("{}.", self.package_name);
        code_expr.replace(&qualifier, "")
    }
}

/// Entry point for the Go code generator.
///
struct GoGenerationResult {
    files: GeneratedFileMap,
    warnings: Vec<String>,
}

/// Generates one input file, given every JSON model the whole generate closure
/// declares.
///
/// Go flattens the closure into one flat package, so a `$ref` into another file
/// is a within-package reference — but resolving what that reference *is* (an
/// object branch of a union, a named union) needs the target's schema, which
/// reachability pruning has removed from this leaf's own plan. `tree_models`
/// carries it. It is only ever read; every model is still emitted exactly once,
/// by the file that declares it.
fn generate_in_tree(
    api_plan: &PlannedSpec,
    options: &GoOptions,
    tree_models: &[PlannedJsonType],
    primary_origin: GeneratedFileOrigin,
    file_name: Option<PathBuf>,
) -> Result<GoGenerationResult> {
    // Go resources have no type parameters, so nexgen can't render a generic one.
    if let Some(resource) = api_plan
        .services
        .iter()
        .flat_map(|service| &service.resources)
        .find(|resource| !resource.data.type_parameters.is_empty())
    {
        return Err(Error::UnsupportedGenericResource {
            language: Language::Go,
            resource: resource.name.clone(),
        });
    }
    if let Some((resource, method)) = api_plan
        .services
        .iter()
        .flat_map(|service| &service.resources)
        .find_map(|resource| {
            resource
                .methods
                .iter()
                .find(|method| method.varargs.is_some())
                .map(|method| (resource, method))
        })
    {
        return Err(Error::UnsupportedGoType {
            context: format!("resource method `{}.{}`", resource.name, method.name),
            reason: "Go doesn't support `@nexus.varargs`".to_string(),
        });
    }
    if let Some((resource, method)) = api_plan
        .services
        .iter()
        .flat_map(|service| &service.resources)
        .find_map(|resource| {
            resource
                .methods
                .iter()
                .find(|method| method.api_omitted.contains(&GenerationTarget::Workflow))
                .map(|method| (resource, method))
        })
    {
        return Err(Error::UnsupportedGoType {
            context: format!("resource method `{}.{}`", resource.name, method.name),
            reason: "Go doesn't support `@nexus.api-omit targets=\"workflow\"` on a resource \
                     method"
                .to_string(),
        });
    }
    if let Some((record, field_name)) = api_plan.records().find_map(|(_, record)| {
        record
            .fields
            .iter()
            .find(|(_, field)| field.flatten_in_api)
            .map(|(field_name, _)| (record, field_name))
    }) {
        return Err(Error::UnsupportedGoType {
            context: format!("record `{}` field `{field_name}`", record.full_name),
            reason: "Go doesn't flatten the record of one field".to_string(),
        });
    }
    if let Some((record, field_name)) = api_plan.records().find_map(|(_, record)| {
        record
            .fields
            .iter()
            .find(|(_, field)| {
                matches!(&field.field_type, crate::planning::PlannedType::List(item)
                    if crate::planning::flattened_list_field(api_plan, item).is_some())
            })
            .map(|(field_name, _)| (record, field_name))
    }) {
        return Err(Error::UnsupportedGoType {
            context: format!("record `{}` field `{field_name}`", record.full_name),
            reason: "Go doesn't flatten a list of a record".to_string(),
        });
    }
    ApiPlanner::new(api_plan, options, tree_models)?.generate(primary_origin, file_name)
}

/// Every JSON model declared anywhere in the generate closure.
fn collect_tree_json_models(leaves: &[&ApiSpecLeaf<PlannedFamily>]) -> Vec<PlannedJsonType> {
    leaves
        .iter()
        .flat_map(|leaf| leaf.spec.external_types())
        .filter_map(|(_, binding)| binding.json_model().cloned())
        .collect()
}

pub(crate) fn generate_tree(
    tree: &ApiSpecTree<PlannedFamily>,
    options: &GoOptions,
) -> Result<GeneratedFiles> {
    match &tree.root {
        ApiSpecNode::Leaf(leaf) => generate_single_leaf(leaf, options),
        ApiSpecNode::Branch(branch) => generate_branch_tree(branch, options),
    }
}

/// Generates a closure of exactly one input file. Go's package layout is
/// uniform regardless of closure size, so -- just like the multi-input
/// flattened layout -- the schema-independent runtime lives in its own
/// `definitions.go` alongside the one model file, rather than inlined into it.
fn generate_single_leaf(
    leaf: &ApiSpecLeaf<PlannedFamily>,
    options: &GoOptions,
) -> Result<GeneratedFiles> {
    let primary_origin = if go_tree_has_json_models(&[leaf]) {
        GeneratedFileOrigin::output_directory_named_module(Language::Go, &options.output_dir_name)
    } else if let Some(service) = leaf.spec.services.first() {
        GeneratedFileOrigin::service_declaration(Language::Go, &leaf.source_path, &service.name)
    } else {
        GeneratedFileOrigin::fixed("generated Go API module")
    };
    let mut generated = generate_in_tree(&leaf.spec, options, &[], primary_origin, None)?;
    if go_tree_has_json_models(&[leaf]) {
        let package_name = GoPackageContext::new(&leaf.spec, options)?.package_name;
        let definitions_path = PathBuf::from("definitions.go");
        let tree_models = collect_tree_json_models(&[leaf]);
        generated.files.insert(
            definitions_path,
            json::render_definitions_file(&package_name, &tree_models)?,
            GeneratedFileOrigin::fixed("generated Go validation runtime"),
        )?;
    }
    Ok(GeneratedFiles {
        layout: crate::generator::GeneratedOutputLayout::Directory,
        files: generated.files.into_files(),
        warnings: generated.warnings,
    })
}

fn generate_branch_tree(
    branch: &ApiSpecBranch<PlannedFamily>,
    options: &GoOptions,
) -> Result<GeneratedFiles> {
    let mut leaves = Vec::new();
    collect_leaf_specs(branch, &mut leaves);
    if leaves.is_empty() {
        return Err(Error::InvalidJsonSchema {
            path: PathBuf::from("<go-tree-generator>"),
            reason: "input tree contains no API specs".to_string(),
        });
    };

    // Go flattens every input file in the closure into one flat package, so
    // references between files -- including cross-directory cycles --
    // resolve as within-package (unqualified) references, which the Go
    // compiler handles natively. This is also what lets the
    // schema-independent runtime live once in the package.
    let root = ModulePath::default();

    // Every file derives its package name from the shared output directory, so
    // the whole closure renders into one package. Derive it once here for the
    // shared `definitions.go` runtime file below.
    let package_name = GoPackageContext::new(&leaves[0].spec, options)?.package_name;

    let tree_models = collect_tree_json_models(&leaves);

    let mut files = GeneratedFileMap::default();
    let mut warnings = Vec::new();

    for leaf in &leaves {
        // Render this input file at the package root so its own types and its
        // references to sibling files are unqualified within the one package.
        let mut leaf_spec = leaf.spec.clone();
        leaf_spec.module_path = root.clone();
        let generated = generate_in_tree(
            &leaf_spec,
            options,
            &tree_models,
            GeneratedFileOrigin::input_module(Language::Go, &leaf.source_path),
            Some(go_flat_module_file_name(&leaf.module_path)),
        )?;
        warnings.extend(generated.warnings);

        files.extend(generated.files)?;
    }

    // The schema-independent runtime lives once in this package as
    // `definitions.go`, in the same package as the models.
    if go_tree_has_json_models(&leaves) {
        files.insert(
            PathBuf::from("definitions.go"),
            json::render_definitions_file(&package_name, &tree_models)?,
            GeneratedFileOrigin::fixed("generated Go validation runtime"),
        )?;
    }

    Ok(GeneratedFiles {
        layout: crate::generator::GeneratedOutputLayout::Directory,
        files: files.into_files(),
        warnings,
    })
}

/// Flattens an input file's module path into its `<module>.go` file name in the
/// one flat Go package: directory separators become `_`, literal underscores are
/// preserved (see `specs/json-schema/generated-file-layout.md`).
fn go_flat_module_file_name(module_path: &ModulePath) -> PathBuf {
    // Branch leaves always carry at least one path segment; the empty fallback
    // keeps this total.
    let stem = if module_path.is_root() {
        "api".to_string()
    } else {
        module_path.0.join("_")
    };
    PathBuf::from(format!("{stem}.go"))
}

fn go_tree_has_json_models(leaves: &[&ApiSpecLeaf<PlannedFamily>]) -> bool {
    leaves.iter().any(|leaf| {
        leaf.spec
            .external_types()
            .map(|(_, binding)| binding)
            .any(|binding| binding.json_model().is_some())
    })
}

fn collect_leaf_specs<'a>(
    branch: &'a ApiSpecBranch<PlannedFamily>,
    leaves: &mut Vec<&'a ApiSpecLeaf<PlannedFamily>>,
) {
    for child in branch.children.values() {
        match child {
            ApiSpecNode::Leaf(leaf) => leaves.push(leaf),
            ApiSpecNode::Branch(branch) => collect_leaf_specs(branch, leaves),
        }
    }
}

