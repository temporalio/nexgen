enum GoExternalModels {
    Json(json::ModelBackend),
    Proto(proto::ModelBackend),
}

/// True when a planned type is (or wraps) a JSON-Schema model.
fn is_json_planned_type(kind: &PlannedType) -> bool {
    match kind {
        TypeSpec::External(ExternalTypeSpec::Json(_)) => true,
        TypeSpec::Option(inner) | TypeSpec::List(inner) => is_json_planned_type(inner),
        _ => false,
    }
}

/// True when this plan's generated surface is JSON-Schema-shaped.
///
/// A service module that declares no models of its own — every operation type is
/// a `$ref` into another file — owns no external declaration after reachability
/// pruning (Go flattens the tree into one package, so the foreign declaration is
/// emitted by its own module and dropped here). Reading only `spec.types` there
/// said "no JSON models" and selected the WIT/proto backend, which emits
/// `workflow.Context` operation functions instead of the `var <Service>` binding.
/// The operations' own type expressions survive pruning, so ask them too.
fn plan_uses_json_models(api_plan: &PlannedSpec) -> bool {
    api_plan
        .external_types()
        .any(|(_, binding)| binding.json_model().is_some())
        || api_plan
            .services
            .iter()
            .flat_map(|service| &service.operations)
            .any(|operation| {
                [operation.input_type(), operation.output_type()]
                    .into_iter()
                    .flatten()
                    .any(is_json_planned_type)
            })
}

impl GoExternalModels {
    fn new(
        api_plan: &PlannedSpec,
        package: GoPackageContext,
        support_package: Option<&str>,
    ) -> Self {
        if plan_uses_json_models(api_plan) {
            Self::Json(json::ModelBackend::new(
                crate::nexgen_config::current()
                    .targets
                    .contains(&GenerationTarget::Workflow),
            ))
        } else {
            Self::Proto(proto::ModelBackend::new(
                package,
                support_package.map(str::to_string),
            ))
        }
    }

    /// Hands the JSON backend every model the closure declares, so a cross-file
    /// `$ref` resolves to its target's schema (see [`generate_in_tree`]).
    fn adopt_tree_models(&mut self, tree_models: &[PlannedJsonType]) {
        if let Self::Json(backend) = self {
            backend.adopt_tree_models(tree_models);
        }
    }

    fn prepare(&mut self, api_plan: &PlannedSpec) -> Result<()> {
        match self {
            Self::Json(backend) => backend.prepare(api_plan),
            Self::Proto(backend) => backend.prepare(api_plan),
        }
    }

    fn render_models(&self) -> Result<GoModelFragments> {
        match self {
            Self::Json(backend) => {
                let fragments = backend.render_models()?;
                Ok(GoModelFragments {
                    imports: fragments.imports,
                    body: fragments.body,
                })
            }
            Self::Proto(backend) => {
                let _ = backend.render_models()?;
                Ok(GoModelFragments::default())
            }
        }
    }

    fn imports(&self) -> Vec<(String, String)> {
        match self {
            // Go flattens every JSON-schema input file into one flat
            // package, so there is never a real cross-package import to
            // emit here.
            Self::Json(_) => Vec::new(),
            Self::Proto(backend) => backend
                .imports()
                .paths()
                .map(|(path, alias)| (path.clone(), alias.clone()))
                .collect(),
        }
    }

    fn model_type_annotation(&self, model_type: &PlannedValueType) -> Option<String> {
        match self {
            Self::Json(backend) => backend.model_type_annotation(model_type),
            Self::Proto(backend) => backend.model_type_annotation(model_type),
        }
    }

    fn support_helper_call(&self, call: &str) -> String {
        match self {
            Self::Proto(backend) => backend.support_converter(call.to_string()),
            Self::Json(_) => call.to_string(),
        }
    }

    fn function_with_support_helper(&self, function: &FunctionFieldSpec) -> FunctionFieldSpec {
        let mut function = function.clone();
        if let Self::Proto(backend) = self {
            function.name_extractor = function
                .name_extractor
                .map(|name| backend.support_converter(name));
        }
        function
    }

    fn has_message_wire_type(&self, message: &PlannedMessageType) -> bool {
        match self {
            Self::Json(backend) => backend.has_message_wire_type(message),
            Self::Proto(backend) => backend.has_message_wire_type(message),
        }
    }

    fn record_model(&mut self, key: &str, message: &PlannedMessageType) {
        if let Self::Proto(backend) = self {
            backend.record_model(key, message);
        }
    }

    fn populate_model_wire_conversions(
        &mut self,
        api_plan: &PlannedSpec,
        models: &IndexMap<String, RenderedModel>,
    ) -> Result<()> {
        match self {
            Self::Json(_) => Ok(()),
            Self::Proto(backend) => backend.populate_model_wire_conversions(api_plan, models),
        }
    }

    fn populate_operation_bindings(
        &self,
        api_plan: &PlannedSpec,
        services: &mut [RenderedService<'_>],
    ) -> Result<()> {
        match self {
            Self::Json(_) => Ok(()),
            Self::Proto(backend) => backend.populate_operation_bindings(api_plan, services),
        }
    }

    fn render_model_converters(&self, output: &mut String, key: &str, model: &RenderedModel) {
        if let Self::Proto(backend) = self {
            backend.render_model_converters(output, key, model);
        }
    }

    /// Whether any model emits a `converter.TransferTypeConverter`, which pulls
    /// in the `context` and `errors` standard-library imports.
    fn renders_transfer_type_converters(&self) -> bool {
        match self {
            Self::Proto(backend) => backend.renders_transfer_type_converters(),
            Self::Json(_) => false,
        }
    }

    fn renders_operation_references(&self) -> bool {
        matches!(self, Self::Json(_))
    }

    fn render_operation_references(
        &self,
        api_plan: &PlannedSpec,
        package: &GoPackageContext,
    ) -> Result<Option<String>> {
        match self {
            Self::Json(backend) if backend.is_active() => {
                Ok(Some(backend.render_services(api_plan, package)?))
            }
            _ => Ok(None),
        }
    }
}

struct ApiPlanner<'a> {
    api_plan: &'a PlannedSpec,
    package: GoPackageContext,
    imports: BTreeSet<String>,
    aliased_imports: BTreeMap<String, String>,
    external_models: GoExternalModels,
    enums: IndexMap<String, RenderedEnum>,
    flags: IndexMap<String, RenderedFlags>,
    variants: IndexMap<String, RenderedVariant>,
    models: IndexMap<String, RenderedModel>,
}

impl<'a> ApiPlanner<'a> {
    fn new(
        api_plan: &'a PlannedSpec,
        options: &GoOptions,
        tree_models: &[PlannedJsonType],
    ) -> Result<Self> {
        let package = GoPackageContext::new(api_plan, options)?;
        let mut imports = BTreeMap::new();

        // Re-scan all resolved type expressions to collect import paths.
        // Type expressions like "temporal.RetryPolicy" were produced by
        // resolve_go_type_annotation which stripped the full module path, but
        // we need to recover the imports from the original annotations.
        // We do this by re-parsing annotations from the planned spec.
        collect_imports_from_plan(api_plan, &mut imports);
        imports.retain(|import_path, _| !package.is_self_import(import_path));
        let mut aliased_imports = BTreeMap::new();
        let imports = imports
            .into_iter()
            .filter_map(|(path, alias)| {
                if path.rsplit('/').next() == Some(alias.as_str()) {
                    Some(path)
                } else {
                    aliased_imports.insert(path, alias);
                    None
                }
            })
            .collect();

        let mut external_models = GoExternalModels::new(
            api_plan,
            package.clone(),
            options.support_package.as_deref(),
        );
        external_models.adopt_tree_models(tree_models);
        external_models.prepare(api_plan)?;

        Ok(Self {
            api_plan,
            package,
            imports,
            aliased_imports,
            external_models,
            enums: IndexMap::new(),
            flags: IndexMap::new(),
            variants: IndexMap::new(),
            models: IndexMap::new(),
        })
    }

    fn generate(
        mut self,
        primary_origin: GeneratedFileOrigin,
        file_name: Option<PathBuf>,
    ) -> Result<GoGenerationResult> {
        let mut services = Vec::new();
        for service in &self.api_plan.services {
            for operation in &service.operations {
                interceptor::validate_context_propagation_mode(operation, &self.package)?;
                if self.package.is_self_import("go.temporal.io/sdk/internal")
                    && operation.context_propagation_header.value().is_some()
                    && service.resources.iter().any(|resource| {
                        resource.data.methods.iter().any(|method| {
                            matches!(
                                &method.binding,
                                PlannedResourceMethodBinding::Operation { operation_name, .. }
                                    if operation_name == &operation.name
                            )
                        })
                    })
                {
                    return Err(interceptor::context_propagation_error(
                        &operation.name,
                        "operations bound to resource methods do not support context propagation",
                    ));
                }
            }
        }
        if self.package.has_serialization_context
            && self.external_models.renders_operation_references()
        {
            return Err(Error::UnsupportedGoProtoConversion {
                context: "Go serialization context".to_string(),
                reason: "serialization-context requires proto-backed operation wrappers, not operation references".to_string(),
            });
        }
        if !self.external_models.renders_operation_references() {
            for service in &self.api_plan.services {
                let mut operations = Vec::new();
                for operation in &service.operations {
                    operations.push(self.resolve_operation(operation)?);
                }

                services.push(RenderedService {
                    wire_name: &service.wire_name,
                    endpoint: service
                        .endpoint
                        .clone()
                        .or_else(|| Some(service.name.to_kebab_case())),
                    operations,
                    resources: service
                        .resources
                        .iter()
                        .map(|resource| resource.data.clone())
                        .collect(),
                });
            }
        }

        for service in &services {
            for resource in &service.resources {
                self.ensure_resource_field_types(resource)?;
            }
        }

        for record in self.api_plan.records().map(|(_, record)| record) {
            self.ensure_rendered_model(&planned_message_type_for_record(record))?;
        }

        let visibility = compute_go_visibility(
            self.api_plan,
            &self.enums,
            &self.flags,
            &self.variants,
            &self.models,
        );
        apply_go_visibility(
            &visibility,
            &mut self.enums,
            &mut self.flags,
            &mut self.variants,
            &mut self.models,
            &mut services,
        );

        // Second pass: compute backend wire metadata for rendered models and
        // collect any aliased imports they require. This runs after visibility
        // so the backend renders final Go names directly.
        self.populate_model_wire_conversions()?;
        self.populate_operation_bindings(&mut services)?;
        for operation in services.iter().flat_map(|service| &service.operations) {
            if operation.serialization_context_expr.is_some() && operation.wire_binding.is_none() {
                return Err(Error::UnsupportedGoProtoConversion {
                    context: format!("operation `{}`", operation.name),
                    reason: "serialization-context requires a proto-backed operation".to_string(),
                });
            }
            if operation.context_propagation_header.is_some() && operation.wire_binding.is_none() {
                return Err(interceptor::context_propagation_error(
                    operation.name,
                    "requires a proto-backed operation",
                ));
            }
        }

        for service in &services {
            for operation in &service.operations {
                if let Some(params) = &operation.unpacked_input {
                    validate_wrapper_type_parameters(
                        operation,
                        params,
                        &self.package,
                        &visibility,
                    )?;
                    for param in params {
                        if let Some(function) = &param.function
                            && function
                                .type_descriptor
                                .as_ref()
                                .and_then(|d| d.args_type.value())
                                .is_some()
                            && (!matches!(function.args, FunctionArgsSpec::Varargs { .. })
                                || function.arg_fields.len() != 1
                                || !params.iter().any(|arg| {
                                    arg.function_args.as_ref() == Some(function)
                                        && arg.go_type.starts_with("[]")
                                }))
                        {
                            return Err(Error::UnsupportedGoType {
                                context: format!("function `{}`", param.field_name),
                                reason: "an explicit Go args descriptor requires one list-backed varargs args field; fixed signatures are unsupported".to_string(),
                            });
                        }
                    }
                }
            }
        }
        let needs_manual_function_name_inlining = services
            .iter()
            .any(service_uses_manual_function_name_inlining);

        // Operation wrapper functions require the workflow package.
        let has_operations = services.iter().any(|s| !s.operations.is_empty());
        if has_operations
            && let Some((path, _)) = self.package.sdk_reference(SdkSymbol::Context).import
        {
            self.imports.insert(path.to_string());
        }
        let has_system_operations = crate::nexgen_config::current().system_nexus && has_operations;
        if self.package.workflow_interceptors && has_operations {
            self.imports
                .insert("github.com/nexus-rpc/sdk-go/nexus".to_string());
        }
        let has_eager_conversion = services.iter().flat_map(|s| &s.operations).any(|op| {
            op.wire_binding
                .as_ref()
                .is_some_and(|binding| binding.requires_data_converter())
        });
        if (has_system_operations || has_eager_conversion)
            && !self.package.is_self_import("go.temporal.io/sdk/internal")
        {
            self.imports
                .insert("go.temporal.io/sdk/internal".to_string());
        }
        if services
            .iter()
            .flat_map(|service| &service.operations)
            .any(|operation| {
                operation
                    .wire_binding
                    .as_ref()
                    .is_some_and(|binding| binding.requires_fmt())
            })
            || self.api_plan.records().any(|(_, record)| {
                record.fields.values().any(|field| {
                    field
                        .flattened_annotation
                        .as_ref()
                        .and_then(|annotation| annotation.value())
                        .is_some()
                })
            })
        {
            self.imports.insert("fmt".to_string());
        }
        if needs_manual_function_name_inlining {
            self.imports.insert("reflect".to_string());
            self.imports.insert("runtime".to_string());
            self.imports.insert("strings".to_string());
        }
        // System transfer callbacks use the converter selected by the SDK;
        // ordinary callbacks are context-free.
        if self.external_models.renders_transfer_type_converters()
            && let Some((path, _)) = self
                .package
                .sdk_reference(SdkSymbol::TransferTypeConverter)
                .import
        {
            self.imports.insert(path.to_string());
        }
        let model_fragments = self.external_models.render_models()?;
        self.imports.extend(model_fragments.imports);
        // The Nexus service definition (operation references) is emitted with or without the
        // Workflow API, so the `nexus` import is needed whenever a spec has services.
        if self.external_models.renders_operation_references()
            && !self.api_plan.services.is_empty()
            && !self
                .package
                .is_self_import("github.com/nexus-rpc/sdk-go/nexus")
        {
            self.imports
                .insert("github.com/nexus-rpc/sdk-go/nexus".to_string());
        }
        if crate::nexgen_config::current()
            .targets
            .contains(&GenerationTarget::Workflow)
            && self.external_models.renders_operation_references()
            && !self.api_plan.services.is_empty()
            && let Some((path, _)) = self.package.sdk_reference(SdkSymbol::Context).import
        {
            self.imports.insert(path.to_string());
        }
        let mut external_imports = self.external_models.imports();
        for (path, alias) in &self.aliased_imports {
            if let Some((_, existing)) = external_imports
                .iter()
                .find(|(existing_path, _)| existing_path == path)
            {
                if existing != alias {
                    return Err(Error::UnsupportedGoType {
                        context: format!("import `{path}`"),
                        reason: format!(
                            "type annotations use alias `{alias}`, but protobuf bindings use `{existing}`"
                        ),
                    });
                }
            } else {
                external_imports.push((path.clone(), alias.clone()));
            }
        }
        let registry = if crate::nexgen_config::current().system_nexus
            && self.package.has_serialization_context
        {
            render_operation_registry(&self.package, &services, &self.imports, &external_imports)?
        } else {
            GoOperationRegistry::default()
        };
        for (path, alias) in &registry.imports {
            if let Some((_, previous_alias)) = external_imports
                .iter()
                .find(|(existing, _)| existing == path)
            {
                if previous_alias != alias {
                    return Err(Error::InvalidWitDirective {
                        path: PathBuf::from("<go-plan>"),
                        context: "Go operation registry".to_string(),
                        directive: "@nexus.serialization-context".to_string(),
                        reason: format!(
                            "import `{path}` uses both `{previous_alias}` and `{alias}` in the generated API file"
                        ),
                    });
                }
            } else if alias == path.rsplit('/').next().unwrap_or(path) {
                self.imports.insert(path.clone());
            } else {
                external_imports.push((path.clone(), alias.clone()));
            }
        }
        if (services
            .iter()
            .flat_map(|s| &s.operations)
            .filter_map(|o| o.unpacked_input.as_ref())
            .flatten()
            .any(|p| {
                p.default_expression
                    .as_ref()
                    .is_some_and(|s| s.contains("support."))
                    || p.flattened_fields.as_ref().is_some_and(|fields| {
                        fields.iter().any(|f| {
                            f.default_expression
                                .as_ref()
                                .is_some_and(|s| s.contains("support."))
                        })
                    })
            })
            || services
                .iter()
                .flat_map(|s| &s.operations)
                .filter_map(|o| o.unpacked_input.as_ref())
                .flatten()
                .any(|p| {
                    p.function.as_ref().is_some_and(|f| {
                        !function_value_is_string(f)
                            && f.name_extractor.as_ref().is_some_and(|helper| {
                                self.package
                                    .function_name_extractor(helper)
                                    .starts_with("support.")
                            })
                    })
                }))
            && let Some(path) = &self.package.support_package
            && !self.package.is_self_import(path)
            && !external_imports
                .iter()
                .any(|(existing, _)| existing == path)
        {
            external_imports.push((path.clone(), "support".to_string()));
        }
        for model in self.models.values() {
            validate_model_getter_names(model)?;
        }
        let facade = self.package.facade.as_ref().map(|options| {
            facade::plan(
                options,
                &self.package,
                &self.imports,
                &external_imports,
                &self.enums,
                &self.flags,
                &self.variants,
                &self.models,
                &services,
                self.api_plan,
                &visibility,
            )
        });
        if let (Some(plan), Some(options)) = (&facade, &self.package.facade) {
            self.package.facade_exports = plan.exposed_names(&options.import_path);
        }
        let interceptors = if self.package.workflow_interceptors && has_operations {
            interceptor::render(&services, &self.package, &visibility)?
        } else {
            String::new()
        };
        let output = render_file(
            &self.package,
            &self.imports,
            &external_imports,
            &model_fragments.body,
            self.external_models
                .render_operation_references(self.api_plan, &self.package)?
                .as_deref(),
            self.enums.values().collect::<Vec<_>>().as_slice(),
            self.flags.values().collect::<Vec<_>>().as_slice(),
            self.variants.values().collect::<Vec<_>>().as_slice(),
            self.models.iter().collect::<Vec<_>>().as_slice(),
            &services,
            &self.external_models,
            self.api_plan,
            &visibility,
            &registry.body,
            &interceptors,
        );

        let mut files = GeneratedFileMap::default();
        let file_name = file_name.unwrap_or_else(|| {
            if self.external_models.renders_operation_references() {
                PathBuf::from(format!("{}.go", self.package.package_name))
            } else {
                go_api_file_name(self.api_plan)
            }
        });
        files.insert(&file_name, output, primary_origin)?;

        if let Some(facade) = facade {
            files.insert(
                file_name.with_file_name(format!(
                    "{}_facade.go",
                    file_name
                        .file_stem()
                        .expect("Go output has a file stem")
                        .to_string_lossy()
                )),
                facade.render(),
                GeneratedFileOrigin::fixed("generated Go facade"),
            )?;
        }

        Ok(GoGenerationResult {
            files,
            warnings: Vec::new(),
        })
    }

    fn resolve_operation(
        &mut self,
        operation: &'a PlannedOperation,
    ) -> Result<RenderedOperation<'a>> {
        let input = operation
            .input
            .as_ref()
            .and_then(|input| planned_message_type(input, self.api_plan))
            .ok_or_else(|| Error::InvalidWit {
                path: PathBuf::from("<go-plan>"),
                reason: format!(
                    "operation `{}` has no proto-backed or WIT-native input type",
                    operation.name
                ),
            })?;
        let output = operation_output(operation, self.api_plan);
        self.resolve_message_types(&input)?;
        let model_type_parameters = record_for_message(self.api_plan, &input)
            .map(|record| self.api_plan.record_type_parameters(&record.full_name))
            .unwrap_or_default();
        let input_type = go_generic_reference(
            &resolve_message_go_type(&input, &self.external_models),
            &model_type_parameters,
            false,
        );
        let go_output_transform = operation.output_transform.as_ref().and_then(|transform| {
            Some((transform.type_name.value()?, transform.transform.value()?))
        });
        let raw_output_type = if go_output_transform.is_some() {
            match &output {
                PlannedOperationOutput::Message(output) => {
                    if self.external_models.has_message_wire_type(output) {
                        None
                    } else {
                        self.resolve_message_types(output)?;
                        Some(resolve_message_go_type(output, &self.external_models))
                    }
                }
                PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
                PlannedOperationOutput::None => None,
            }
        } else {
            None
        };

        let output_type = match &output {
            PlannedOperationOutput::Message(output) => {
                if let Some(resource_return) = &operation.data.output_resource_return {
                    // The operation returns a resource constructed from the proto
                    // response -- use the resource type name.
                    Some(resource_return.resource_type_name.clone())
                } else if let Some((transform_type, _)) = go_output_transform {
                    // Output transforms expose their transformed type to callers,
                    // while the raw operation output is still resolved below for
                    // result decoding.
                    Some(self.package.go_type_expr(transform_type))
                } else {
                    self.resolve_message_types(output)?;
                    Some(resolve_message_go_type(output, &self.external_models))
                }
            }
            PlannedOperationOutput::Resource { type_name } => Some(type_name.clone()),
            PlannedOperationOutput::None => None,
        };

        // Build unpacked input params from the rendered model, if the input type
        // is a generated model (not an external/replacement type).
        let unpacked_input = self.models.get(&input.info.full_name).map(|model| {
            let planned_record = record_for_message(self.api_plan, &input);
            let planned_fields = planned_record.map(|record| {
                record
                    .api_fields(GenerationTarget::Workflow)
                    .map(|(field_name, field)| {
                        planned_field(record, field_name, field, self.api_plan)
                    })
                    .collect::<Vec<_>>()
            });
            model
                .fields
                .iter()
                .filter_map(|field| {
                    let planned_field = planned_fields.as_ref().and_then(|fields| {
                        fields
                            .iter()
                            .find(|planned| go_field_name(&planned.authored_name) == field.name)
                    });
                    let planned_field = planned_field?;
                    let function = match &planned_field.role {
                        PlannedFieldRole::Function(function) if planned_field.required => {
                            Some(self.external_models.function_with_support_helper(function))
                        }
                        _ => None,
                    };
                    let function_args = match &planned_field.role {
                        PlannedFieldRole::FunctionArgs(function) => {
                            Some(self.external_models.function_with_support_helper(function))
                        }
                        _ => None,
                    };
                    let flatten_in_options = !planned_field.required
                        && field_kind_is_flattened_message(&planned_field.kind, self.api_plan);
                    let flattened_fields = if flatten_in_options {
                        let PlannedFieldKind::Singular(PlannedValueType::Message(message)) =
                            &planned_field.kind
                        else {
                            unreachable!()
                        };
                        let record = record_for_message(self.api_plan, message)
                            .expect("flattened message should have a record");
                        Some(
                            self.models[&message.info.full_name]
                                .fields
                                .iter()
                                .zip(record.public_fields())
                                .map(|(field, (name, spec))| {
                                    let planned =
                                        self::planned_field(record, name, spec, self.api_plan);
                                    RenderedFlattenedField {
                                        field: field.clone(),
                                        default_punning_zero: public_default_punning_zero_for_field(
                                            &planned.kind,
                                            &if field.go_type.starts_with('*') {
                                                field.go_type.clone()
                                            } else {
                                                format!("*{}", field.go_type)
                                            },
                                        ),
                                        default_expression: planned
                                            .default_expression
                                            .as_deref()
                                            .map(|value| self.package.go_type_expr(value)),
                                    }
                                })
                                .collect(),
                        )
                    } else {
                        None
                    };
                    let default_punning_zero = (!planned_field.required && !flatten_in_options)
                        .then(|| {
                            public_default_punning_zero_for_field(
                                &planned_field.kind,
                                &field.go_type,
                            )
                        })
                        .flatten()
                        .or_else(|| {
                            planned_field.default_expression.as_ref().and_then(|_| {
                                public_default_punning_zero_for_field(
                                    &planned_field.kind,
                                    &format!("*{}", field.go_type),
                                )
                            })
                        });
                    let default_input = planned_field.default_expression.clone().filter(|_| {
                        planned_field.required
                            && public_default_punning_zero_for_field(
                                &planned_field.kind,
                                &format!("*{}", field.go_type),
                            )
                            .is_none()
                            && !go_type_is_nilable(&field.go_type)
                            && !matches!(
                                planned_field.kind,
                                PlannedFieldKind::Singular(
                                    PlannedValueType::Variant(_) | PlannedValueType::Unknown
                                )
                            )
                    });
                    let public_go_type = if default_input.is_some() {
                        format!("*{}", field.go_type)
                    } else if default_punning_zero.is_some() {
                        field
                            .go_type
                            .strip_prefix('*')
                            .unwrap_or(&field.go_type)
                            .to_string()
                    } else {
                        field.go_type.clone()
                    };
                    Some(RenderedUnpackedParam {
                        field_name: field.name.clone(),
                        doc: field.doc.clone(),
                        param_name: if flatten_in_options {
                            format!("{}Value", go_unexported_name(&field.name))
                        } else {
                            go_unexported_name(&field.name)
                        },
                        go_type: field.go_type.clone(),
                        public_go_type,
                        default_punning_zero,
                        default_input,
                        default_expression: planned_field
                            .default_expression
                            .as_deref()
                            .map(|value| self.package.go_type_expr(value)),
                        function,
                        function_args,
                        required: planned_field.api_required,
                        flattened_fields,
                    })
                })
                .collect()
        });

        let serialization_context_expr = if crate::nexgen_config::current().system_nexus {
            operation.serialization_context.value()
        } else {
            None
        };
        if let Some(helper) = serialization_context_expr {
            validate_go_serialization_context_helper(helper, &operation.name)?;
        }
        let sourced_fields = record_for_message(self.api_plan, &input)
            .map(|record| {
                record
                    .sources_for(GenerationTarget::Workflow)
                    .map(|(field_name, _, source)| {
                        (
                            go_field_name(field_name),
                            self.external_models.support_helper_call(source),
                        )
                    })
                    .collect()
            })
            .unwrap_or_default();
        let context_propagation_header =
            interceptor::context_propagation_header(operation, self.api_plan, &self.package)?;
        if context_propagation_header.is_some() && unpacked_input.is_none() {
            return Err(interceptor::context_propagation_error(
                &operation.name,
                "requires a generated request record",
            ));
        }
        Ok(RenderedOperation {
            name: operation.name.as_str(),
            wire_name: operation.wire_name.as_str(),
            doc: operation.doc.value(),
            return_doc: operation.return_doc.value(),
            input_type,
            model_type_parameters,
            output_type,
            raw_output_type,
            serialization_context_expr,
            context_propagation_header,
            sourced_fields,
            output_transform_expr: go_output_transform
                .map(|(_, expr)| self.package.alias_workflow_expr(expr)),
            output_transform_type: go_output_transform
                .map(|(type_name, _)| self.package.go_type_expr(type_name)),
            unpacked_input,
            wire_binding: None,
            api_omitted: &operation.api_omitted,
        })
    }

    fn ensure_resource_field_types(&mut self, resource: &PlannedResource) -> Result<()> {
        for field in &resource.fields {
            self.ensure_resource_field_type(&planned_field_kind(&field.kind, self.api_plan))?;
        }
        for method in &resource.methods {
            for param in &method.params {
                self.ensure_resource_field_type(&planned_field_kind(&param.kind, self.api_plan))?;
            }
        }
        Ok(())
    }

    fn ensure_resource_field_type(&mut self, kind: &PlannedFieldKind) -> Result<()> {
        match kind {
            PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
                self.resolve_planned_value_type(value)?;
            }
            PlannedFieldKind::Map { key, value } => {
                self.resolve_planned_value_type(key)?;
                self.resolve_planned_value_type(value)?;
            }
        }
        Ok(())
    }

    fn resolve_message_types(&mut self, message: &PlannedMessageType) -> Result<()> {
        if message.replacement.is_some() || message.authored_type.is_some() {
            return Ok(());
        }
        if message.source == PlannedMessageSource::Json {
            return Ok(());
        }

        self.ensure_rendered_model(message)
    }

    fn resolve_planned_value_type(
        &mut self,
        value_type: &PlannedValueType,
    ) -> Result<ResolvedGoType> {
        match value_type {
            PlannedValueType::TypeParameter(name) => Ok(ResolvedGoType {
                type_expr: name.clone(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Float) => Ok(ResolvedGoType {
                type_expr: "float64".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Int32) => Ok(ResolvedGoType {
                type_expr: "int32".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Int64) => Ok(ResolvedGoType {
                type_expr: "int64".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Bool) => Ok(ResolvedGoType {
                type_expr: "bool".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::String) => Ok(ResolvedGoType {
                type_expr: "string".to_string(),
            }),
            PlannedValueType::Scalar(PlannedScalarType::Bytes) => Ok(ResolvedGoType {
                type_expr: "[]byte".to_string(),
            }),
            PlannedValueType::Enum(enum_type) => {
                let backend_type = self.external_models.model_type_annotation(value_type);
                if let (Some(info), Some(name)) = (&enum_type.info, &enum_type.name) {
                    if let Some(enum_decl) = self.api_plan.enum_decl(&info.full_name) {
                        self.ensure_rendered_enum(&planned_enum(enum_decl));
                    } else if enum_type.replacement.is_none() {
                        self.ensure_rendered_enum(&PlannedEnum {
                            info: info.clone(),
                            name: name.clone(),
                            values: Vec::new(),
                        });
                    }
                    Ok(ResolvedGoType {
                        type_expr: backend_type.unwrap_or_else(|| name.clone()),
                    })
                } else {
                    Ok(ResolvedGoType {
                        type_expr: backend_type.unwrap_or_else(|| "int32".to_string()),
                    })
                }
            }
            PlannedValueType::Flags(flags_type) => {
                if let Some(flags_decl) = self.api_plan.flags_decl(&flags_type.info.full_name) {
                    self.ensure_rendered_flags(&planned_flags(flags_decl));
                }
                Ok(ResolvedGoType {
                    type_expr: flags_type.name.clone(),
                })
            }
            PlannedValueType::Variant(variant_type) => {
                if let Some(variant_decl) = self.api_plan.variant(&variant_type.info.full_name) {
                    let planned = planned_variant(variant_decl, self.api_plan);
                    self.ensure_rendered_variant(&planned)?;
                }
                // Interfaces have nil zero value, so no pointer needed for optional fields.
                Ok(ResolvedGoType {
                    type_expr: go_generic_reference(
                        &variant_type.name,
                        &self
                            .api_plan
                            .variant_type_parameters(&variant_type.info.full_name),
                        false,
                    ),
                })
            }
            PlannedValueType::Message(message_type) => {
                if let Some(type_name) = self.external_models.model_type_annotation(value_type)
                    && (message_type.replacement.is_some() || message_type.authored_type.is_some())
                {
                    return Ok(ResolvedGoType {
                        type_expr: type_name,
                    });
                }
                self.ensure_rendered_model(message_type)?;
                let base = self
                    .external_models
                    .model_type_annotation(value_type)
                    .unwrap_or_else(|| message_type.model_name.clone());
                let type_expr = record_for_message(self.api_plan, message_type)
                    .map(|record| {
                        go_generic_reference(
                            &base,
                            &self.api_plan.record_type_parameters(&record.full_name),
                            false,
                        )
                    })
                    .unwrap_or(base);
                Ok(ResolvedGoType { type_expr })
            }
            // Tuples and results inside containers (lists, maps, variant payloads,
            // resource fields) instantiate shared generic helper types; direct
            // record fields keep their field-named structs (see `build_field`).
            PlannedValueType::Tuple(items) => {
                let type_name = self.ensure_generic_tuple(items.len())?;
                let args = items
                    .iter()
                    .map(|item| {
                        self.resolve_planned_value_type(item)
                            .map(|resolved| resolved.type_expr)
                    })
                    .collect::<Result<Vec<_>>>()?;
                Ok(ResolvedGoType {
                    type_expr: format!("{type_name}[{}]", args.join(", ")),
                })
            }
            PlannedValueType::Result { ok, err } => {
                self.ensure_generic_result();
                let ok_type = match ok {
                    Some(ok) => self.resolve_planned_value_type(ok)?.type_expr,
                    None => "struct{}".to_string(),
                };
                let err_type = match err {
                    Some(err) => self.resolve_planned_value_type(err)?.type_expr,
                    None => "error".to_string(),
                };
                Ok(ResolvedGoType {
                    type_expr: format!("Result[{ok_type}, {err_type}]"),
                })
            }
            PlannedValueType::External {
                type_name,
                fallback,
            } => {
                if let Some(annotation) = type_name.value() {
                    Ok(ResolvedGoType {
                        type_expr: self.package.go_type_expr(annotation),
                    })
                } else {
                    self.resolve_planned_value_type(fallback)
                }
            }
            PlannedValueType::Unknown => Ok(ResolvedGoType {
                type_expr: "any".to_string(),
            }),
        }
    }

    fn ensure_rendered_enum(&mut self, planned_enum: &PlannedEnum) {
        self.enums
            .entry(planned_enum.info.full_name.clone())
            .or_insert_with(|| RenderedEnum {
                name: planned_enum.name.clone(),
                values: planned_enum
                    .values
                    .iter()
                    .map(|value| RenderedEnumValue {
                        name: value.name.clone(),
                        number: value.number,
                    })
                    .collect(),
            });
    }

    fn ensure_rendered_flags(&mut self, planned_flags: &PlannedFlags) {
        self.flags
            .entry(planned_flags.info.full_name.clone())
            .or_insert_with(|| RenderedFlags {
                name: planned_flags.name.clone(),
                flags: planned_flags
                    .flags
                    .iter()
                    .map(|flag| RenderedFlag {
                        name: flag.name.clone(),
                        bit: flag.bit,
                    })
                    .collect(),
            });
    }

    fn ensure_rendered_variant(&mut self, planned_variant: &PlannedVariant) -> Result<()> {
        if self.variants.contains_key(&planned_variant.info.full_name) {
            return Ok(());
        }

        let variant_name = &planned_variant.name;
        let mut cases = Vec::new();
        for case in &planned_variant.cases {
            let case_suffix = go_field_name(&case.name);
            let payload_type = case
                .payload
                .as_ref()
                .map(|payload| {
                    self.resolve_planned_value_type(payload)
                        .map(|resolved| resolved.type_expr)
                })
                .transpose()?;
            cases.push(RenderedVariantCase {
                struct_name: format!("{variant_name}{case_suffix}"),
                doc: case.doc.clone(),
                payload_type,
            });
        }
        self.variants.insert(
            planned_variant.info.full_name.clone(),
            RenderedVariant {
                name: variant_name.clone(),
                doc: planned_variant.doc.clone(),
                experimental: planned_variant.experimental,
                type_parameters: planned_variant.type_parameters.clone(),
                marker_method: format!("is{variant_name}"),
                cases,
            },
        );
        Ok(())
    }

    fn ensure_rendered_model(&mut self, message: &PlannedMessageType) -> Result<()> {
        let Some((model_name, model_parameters, planned_fields)) =
            record_for_message(self.api_plan, message).map(|planned_model| {
                let parameters = self
                    .api_plan
                    .record_type_parameters(&planned_model.full_name);
                let planned_fields = planned_model
                    .model_fields()
                    .map(|(field_name, field)| {
                        (
                            planned_field(planned_model, field_name, field, self.api_plan),
                            false,
                        )
                    })
                    .chain(
                        planned_model
                            .sourced_fields()
                            .map(|(field_name, field, _)| {
                                (
                                    planned_field(planned_model, field_name, field, self.api_plan),
                                    true,
                                )
                            }),
                    )
                    .collect::<Vec<_>>();
                (planned_model.name.clone(), parameters, planned_fields)
            })
        else {
            // The planner may skip models for output types with transforms or
            // resource returns. Generate a minimal empty struct so the type
            // is at least defined.
            if !self.models.contains_key(&message.info.full_name) {
                self.models.insert(
                    message.info.full_name.clone(),
                    RenderedModel {
                        name: message.model_name.clone(),
                        type_parameters: Vec::new(),
                        fields: Vec::new(),
                    },
                );
                self.external_models
                    .record_model(&message.info.full_name, message);
            }
            return Ok(());
        };

        if self.models.contains_key(&message.info.full_name) {
            return Ok(());
        }

        self.models.insert(
            message.info.full_name.clone(),
            RenderedModel {
                name: go_generic_declaration_name(&model_name, &model_parameters),
                type_parameters: model_parameters
                    .iter()
                    .map(|usage| usage.parameter.name.clone())
                    .collect(),
                fields: Vec::new(),
            },
        );
        self.external_models
            .record_model(&message.info.full_name, message);

        let is_system_request = crate::nexgen_config::current().system_nexus
            && self.api_plan.services.iter().any(|service| {
                service.operations.iter().any(|operation| {
                    operation
                        .input
                        .as_ref()
                        .and_then(|input| planned_message_type(input, self.api_plan))
                        .is_some_and(|input| input.info.full_name == message.info.full_name)
                })
            });
        let fields = planned_fields
            .iter()
            .map(|(planned_field, sourced)| {
                let mut field = self.build_field(planned_field, *sourced)?;
                if is_system_request && !field.required {
                    field.default_punning_zero =
                        public_default_punning_zero_for_field(&planned_field.kind, &field.go_type);
                    if field.default_punning_zero.is_some() {
                        field.go_type = field.go_type.trim_start_matches('*').to_string();
                    }
                }
                Ok(field)
            })
            .collect::<Result<Vec<_>>>()?;

        self.models
            .get_mut(&message.info.full_name)
            .expect("model should be inserted before recursive field resolution")
            .fields = fields;
        Ok(())
    }

    fn build_field(&mut self, field: &PlannedField, sourced: bool) -> Result<RenderedField> {
        let field_name = go_field_name(&field.authored_name);

        let annotated_go_type = field
            .flattened_annotation_override
            .as_ref()
            .or(field.annotation_override.as_ref())
            .and_then(|annotation| annotation.value())
            .map(|annotation| self.package.go_type_expr(annotation));

        let go_type = if let Some(annotated) = annotated_go_type {
            if !field.required
                && field.flattened_annotation_override.is_some()
                && !annotated.starts_with('*')
                && !go_type_is_nilable(&annotated)
            {
                format!("*{annotated}")
            } else {
                annotated
            }
        } else {
            match &field.kind {
                PlannedFieldKind::Map { key, value } => {
                    let key_type = self.resolve_planned_value_type(key)?;
                    let value_type = self.resolve_planned_value_type(value)?;
                    format!("map[{}]{}", key_type.type_expr, value_type.type_expr)
                }
                PlannedFieldKind::Repeated(value) => {
                    let element_type = self.resolve_planned_value_type(value)?;
                    format!("[]{}", element_type.type_expr)
                }
                PlannedFieldKind::Singular(value) => {
                    let resolved = self.resolve_planned_value_type(value)?;
                    if !field.required
                        && type_needs_pointer_when_optional(
                            value,
                            &resolved.type_expr,
                            &self.package,
                        )
                    {
                        format!("*{}", resolved.type_expr)
                    } else {
                        resolved.type_expr
                    }
                }
            }
        };

        Ok(RenderedField {
            name: field_name,
            doc: field
                .doc
                .as_ref()
                .and_then(|doc| doc.value())
                .map(str::to_string),
            go_type,
            default_punning_zero: None,
            required: field.required,
            sourced,
        })
    }

    fn ensure_generic_tuple(&mut self, arity: usize) -> Result<String> {
        ensure_generic_tuple(arity, &mut self.models)
    }

    fn ensure_generic_result(&mut self) {
        ensure_generic_result(&mut self.models);
    }

    fn populate_model_wire_conversions(&mut self) -> Result<()> {
        self.external_models
            .populate_model_wire_conversions(self.api_plan, &self.models)
    }

    fn populate_operation_bindings(&self, services: &mut [RenderedService<'_>]) -> Result<()> {
        self.external_models
            .populate_operation_bindings(self.api_plan, services)
    }
}

fn service_uses_manual_function_name_inlining(service: &RenderedService<'_>) -> bool {
    service.operations.iter().any(|operation| {
        operation.unpacked_input.as_ref().is_some_and(|params| {
            params.iter().any(|param| {
                param.required
                    && param.function.as_ref().is_some_and(|function| {
                        !function_value_is_string(function) && function.name_extractor.is_none()
                    })
            })
        })
    })
}

/// Derives the primary Go output filename from the first service name
/// (`WorkflowService` -> `workflowservice.go`). Most WIT inputs export a single
/// service; for empty plans, keep the historical `api.go` fallback.
fn go_api_file_name(api_plan: &PlannedSpec) -> PathBuf {
    let stem = api_plan
        .services
        .first()
        .map(|service| {
            service
                .name
                .chars()
                .filter(|c| c.is_ascii_alphanumeric())
                .collect::<String>()
                .to_lowercase()
        })
        .filter(|name| !name.is_empty())
        .unwrap_or_else(|| "api".to_string());
    PathBuf::from(format!("{stem}.go"))
}

fn validate_go_serialization_context_helper(helper: &str, operation: &str) -> Result<()> {
    let parts: Vec<_> = helper.split('.').collect();
    if parts.len() > 2
        || parts.iter().any(|part| {
            part.is_empty()
                || *part == "_"
                || is_go_keyword(part)
                || !part
                    .as_bytes()
                    .first()
                    .is_some_and(|byte| is_go_ident_start(*byte))
                || !part.bytes().all(is_go_ident_continue)
        })
    {
        return Err(Error::InvalidWitDirective {
            path: PathBuf::from("<go-plan>"),
            context: format!("operation `{operation}`"),
            directive: "@nexus.serialization-context".to_string(),
            reason: format!("Go support helper `{helper}` must be an identifier or pkg.Func"),
        });
    }
    Ok(())
}

fn render_operation_registry(
    package: &GoPackageContext,
    services: &[RenderedService<'_>],
    model_imports: &BTreeSet<String>,
    external_imports: &[(String, String)],
) -> Result<GoOperationRegistry> {
    let has_helpers = services
        .iter()
        .flat_map(|service| &service.operations)
        .any(|operation| operation.serialization_context_expr.is_some());
    let helper_packages: BTreeSet<_> = services
        .iter()
        .flat_map(|service| &service.operations)
        .filter_map(|operation| {
            operation
                .serialization_context_expr?
                .split_once('.')
                .map(|(name, _)| name)
        })
        .collect();
    let mut candidates = external_imports.to_vec();
    candidates.extend(model_imports.iter().map(|path| {
        (
            path.clone(),
            path.rsplit('/').next().unwrap_or(path).to_string(),
        )
    }));
    if let Some(path) = &package.support_package {
        candidates.push((path.clone(), "support".to_string()));
    }
    let mut imports = BTreeMap::new();
    if has_helpers
        && let Some((path, alias)) = package
            .sdk_reference(SdkSymbol::SerializationContext)
            .import
    {
        imports.insert(alias.to_string(), path.to_string());
    }
    if !package.is_self_import("go.temporal.io/sdk/internal") {
        imports.insert(
            "internal".to_string(),
            "go.temporal.io/sdk/internal".to_string(),
        );
    }
    for (path, alias) in candidates {
        let used_by_input_type =
            services
                .iter()
                .flat_map(|service| &service.operations)
                .any(|operation| {
                    operation.serialization_context_expr.is_some()
                        && operation.input_type.contains(&format!("{alias}."))
                });
        let used_by_unqualified_helper = alias == "support"
            && services
                .iter()
                .flat_map(|service| &service.operations)
                .filter_map(|operation| operation.serialization_context_expr)
                .any(|helper| !helper.contains('.'));
        if (!helper_packages.contains(alias.as_str())
            && !used_by_input_type
            && !used_by_unqualified_helper)
            || package.is_self_import(&path)
        {
            continue;
        }
        if let Some(previous) = imports.insert(alias.clone(), path.clone()) {
            if previous != path {
                return Err(Error::InvalidWitDirective {
                    path: PathBuf::from("<go-plan>"),
                    context: "Go operation registry".to_string(),
                    directive: "@nexus.serialization-context".to_string(),
                    reason: format!(
                        "helper qualifier `{alias}` refers to both `{previous}` and `{path}`"
                    ),
                });
            }
        }
    }
    let mut output = String::from("\n// --- Registry ---\n");
    let sc = package.serialization_context_type();
    let key = package
        .sdk_reference(SdkSymbol::SystemNexusRegistryKey)
        .expression;
    let info = package
        .sdk_reference(SdkSymbol::SystemNexusRegistryEntry)
        .expression;
    let registry_name = go_declaration_name("nexusOperationRegistry");
    output.push_str(&format!("\nvar {registry_name} = map[{key}]{info}{{\n"));
    let mut keys = BTreeSet::new();
    for service in services {
        for operation in &service.operations {
            let Some(helper) = operation.serialization_context_expr else {
                continue;
            };
            let helper = package.function_name_extractor(helper);
            if !keys.insert((service.wire_name, operation.wire_name)) {
                return Err(Error::InvalidWitDirective {
                    path: PathBuf::from("<go-plan>"),
                    context: "Go operation registry".to_string(),
                    directive: "@nexus.serialization-context".to_string(),
                    reason: format!(
                        "duplicate registry key: service `{}`, operation `{}`",
                        service.wire_name, operation.wire_name
                    ),
                });
            }
            let service_name = go_string_literal(service.wire_name);
            let operation_name = go_string_literal(operation.wire_name);
            output.push_str(&format!(
                "\t{{\n\t\tService: {service_name},\n\t\tOperation: {operation_name},\n\t}}: {{\n"
            ));
            let input_type = &operation.input_type;
            output.push_str(&format!(
                "\t\tSerializationContext: func(request any) {sc} {{\n\t\t\treturn {helper}(request.({input_type}))\n\t\t}},\n"
            ));
            output.push_str("\t},\n");
        }
    }
    output.push_str("}\n");
    if !keys.is_empty() {
        let register = package
            .sdk_reference(SdkSymbol::UpdateSystemNexusRegistry)
            .expression;
        output.push_str(&format!(
            "\nfunc init() {{\n\t{register}({registry_name})\n}}\n"
        ));
    }
    Ok(GoOperationRegistry {
        imports: imports
            .into_iter()
            .map(|(alias, path)| (path, alias))
            .collect(),
        body: output,
    })
}

/// Derives a valid Go package name from a Nexus endpoint string by stripping
/// non-alphanumeric characters and lowercasing (e.g. `"type-showcase"` becomes
/// `"typeshowcase"`).
pub(crate) fn go_package_name(endpoint: &str) -> String {
    endpoint
        .chars()
        .filter(|c| c.is_ascii_alphanumeric() || *c == '_')
        .collect::<String>()
        .to_lowercase()
}

