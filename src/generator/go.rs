/// A resolved Nexus service ready for rendering.
#[derive(Debug)]
pub(in crate::generator) struct RenderedService<'a> {
    /// Wire-format service name from `@nexus.service-name`, defaulting to the
    /// UpperCamelCase service name. This is the value sent on the wire (e.g.
    /// `"temporal.api.workflowservice.v1.WorkflowService"`), so the generated
    /// `ServiceName` constant must use it rather than `name`.
    pub(in crate::generator) wire_name: &'a str,
    /// Nexus endpoint identifier (e.g. `"type-showcase"`), when authored.
    pub(in crate::generator) endpoint: Option<String>,
    /// Operations belonging to this service.
    pub(in crate::generator) operations: Vec<RenderedOperation<'a>>,
    /// Resources belonging to this service.
    pub(in crate::generator) resources: Vec<PlannedResource>,
}

/// A resolved Nexus operation with enough information to render the operation
/// constant and a public operation wrapper.
#[derive(Debug)]
pub(in crate::generator) struct RenderedOperation<'a> {
    /// UpperCamelCase operation name (e.g. `"GetUser"`).
    name: &'a str,
    /// Wire-format operation name (e.g. `"GetUser"`).
    pub(in crate::generator) wire_name: &'a str,
    /// Doc text for the operation (from `@nexus.doc`), rendered as a godoc
    /// comment on the exported wrapper function.
    doc: Option<&'a str>,
    /// Return-value doc text (from `@nexus.doc returns=`), rendered as a
    /// `Returns:` paragraph in the wrapper's godoc comment.
    return_doc: Option<&'a str>,
    /// Go type for the request parameter (e.g. `"GetUserRequest"`).
    pub(in crate::generator) input_type: String,
    /// Model-derived parameters inferred from the request.
    model_type_parameters: Vec<crate::spec::TypeParameterUsage>,
    /// Go type for the result, or `None` for void operations.
    /// For resource-returning operations this is the resource type name
    /// (e.g. `"User"`).
    pub(in crate::generator) output_type: Option<String>,
    /// Go type for the raw operation result before applying an output
    /// transform. This is only distinct from `output_type` for transformed
    /// operations.
    pub(in crate::generator) raw_output_type: Option<String>,
    /// Go expression for an `@nexus.output-transform`, if one is configured.
    /// The expression is rendered with `request` and raw `result` in scope and
    /// must evaluate to `(output_transform_type, error)`.
    pub(in crate::generator) output_transform_expr: Option<String>,
    /// Helper selecting the context for user payloads nested in this operation.
    pub(in crate::generator) serialization_context_expr: Option<&'a str>,
    /// Resolved Go request field receiving propagated context headers.
    context_propagation_header: Option<String>,
    /// The Go name and source expression of each sourced field of the request for the Workflow
    /// API. The public wrapper fills them, and a resource method fills those that it has no value
    /// for, so a resource field wins over its source.
    sourced_fields: Vec<(String, String)>,
    /// Go return type for an `@nexus.output-transform`, with any embedded
    /// import path stripped from the WIT annotation.
    pub(in crate::generator) output_transform_type: Option<String>,
    /// Unpacked input parameters for the exported convenience wrapper, or
    /// `None` when the input type is an external/replacement type that cannot
    /// be unpacked into individual arguments.
    unpacked_input: Option<Vec<RenderedUnpackedParam>>,
    /// Wire serialization binding for the request/response, populated in a
    /// second pass when the backend can convert the input/output messages.
    /// When present, the operation function converts native values to/from
    /// wire values and types the SDK call in terms of the wire messages.
    pub(in crate::generator) wire_binding: Option<proto::OperationBinding>,
    /// Targets whose exported convenience wrapper `@nexus.api-omit` suppresses. The internal
    /// operation function stays, so resource methods still bind.
    api_omitted: &'a BTreeSet<GenerationTarget>,
}

/// A single parameter in an unpacked convenience wrapper function signature.
#[derive(Debug)]
struct RenderedUnpackedParam {
    /// Exported Go field name used when setting the request struct field
    /// (e.g. `"UserId"`).
    field_name: String,
    /// Doc text for the field (from `@nexus.doc`), rendered as a godoc
    /// comment on the options struct field for optional parameters.
    doc: Option<String>,
    /// Unexported Go parameter name used in the function signature
    /// (e.g. `"userId"`).
    param_name: String,
    /// Internal request Go type expression (e.g. `"string"`, `"*string"`).
    go_type: String,
    /// Public options/parameter Go type expression.
    public_go_type: String,
    /// Public zero value that represents absence, when default-punning applies.
    default_punning_zero: Option<String>,
    /// A required non-punned value uses a presence-bearing public pointer.
    default_input: Option<String>,
    /// Selected expression evaluated before request construction when omitted.
    default_expression: Option<String>,
    /// Function field metadata for required `@nexus.function` fields. Optional
    /// function fields remain string-shaped in generated options structs.
    function: Option<FunctionFieldSpec>,
    /// Function metadata for fields generated from a function's arguments.
    function_args: Option<FunctionFieldSpec>,
    /// Whether this parameter is required (positional argument) or optional
    /// (placed in the options struct).
    required: bool,
    /// Fields promoted into the options struct for a `flatten-in-api` record.
    /// Their presence determines whether the optional nested request is built.
    flattened_fields: Option<Vec<RenderedFlattenedField>>,
}

/// A promoted field retains the internal type and the same default-punning
/// policy as an ordinary operation option.
#[derive(Debug)]
struct RenderedFlattenedField {
    field: RenderedField,
    default_punning_zero: Option<String>,
    default_expression: Option<String>,
}

impl RenderedFlattenedField {
    fn presence_condition(&self) -> String {
        if let Some(zero) = &self.default_punning_zero {
            format!("opts.{} != {zero}", self.field.name)
        } else if self.field.required
            || (!self.field.go_type.starts_with('*') && !go_type_is_nilable(&self.field.go_type))
        {
            "true".to_string()
        } else {
            format!("opts.{} != nil", self.field.name)
        }
    }
}

/// A WIT enum rendered as a Go `type <Name> int32` with associated constants.
#[derive(Debug)]
struct RenderedEnum {
    /// Go type name (e.g. `"UserStatus"`).
    name: String,
    /// Ordered enum variants with their numeric values.
    values: Vec<RenderedEnumValue>,
}

/// A single variant of a [`RenderedEnum`].
#[derive(Debug)]
struct RenderedEnumValue {
    /// UpperCamelCase variant name (e.g. `"Active"`).
    name: String,
    /// Numeric value assigned in the WIT definition.
    number: i32,
}

/// A WIT flags type rendered as a Go `type <Name> int32` with bit-mask
/// constants.
#[derive(Debug)]
struct RenderedFlags {
    /// Go type name (e.g. `"UserCapability"`).
    name: String,
    /// Individual flag definitions.
    flags: Vec<RenderedFlag>,
}

/// A single flag within a [`RenderedFlags`] set.
#[derive(Debug)]
struct RenderedFlag {
    /// UpperCamelCase flag name (e.g. `"ReadProfile"`).
    name: String,
    /// Zero-based bit position (`1 << bit`).
    bit: usize,
}

/// A WIT variant rendered as a Go sealed interface with concrete case structs.
///
/// The interface carries an unexported marker method to prevent external
/// implementations. Each case becomes a struct that implements the interface.
#[derive(Debug)]
struct RenderedVariant {
    /// Go interface type name (e.g. `"NotificationTarget"`).
    name: String,
    /// Selected documentation for the public variant interface.
    doc: SelectedTextSpec,
    /// Whether the public variant interface carries an experimental warning.
    experimental: bool,
    /// Enclosing generic parameters, carried by every case.
    type_parameters: Vec<crate::spec::TypeParameterUsage>,
    /// Unexported marker method name (e.g. `"isNotificationTarget"`).
    marker_method: String,
    /// Ordered variant cases.
    cases: Vec<RenderedVariantCase>,
}

/// A single case of a [`RenderedVariant`], rendered as a Go struct that
/// implements the variant's sealed interface.
#[derive(Debug)]
struct RenderedVariantCase {
    /// Go struct name combining variant and case (e.g. `"NotificationTargetEmail"`).
    struct_name: String,
    /// Selected documentation for the public case struct.
    doc: SelectedTextSpec,
    /// Go type of the payload field, or `None` for payload-less cases.
    payload_type: Option<String>,
}

/// A WIT record (or proto message) rendered as a Go struct. Also used for
/// generated tuple structs.
#[derive(Debug)]
pub(in crate::generator) struct RenderedModel {
    /// Go type name (e.g. `"UserProfile"`, `"Coordinates"`).
    pub(in crate::generator) name: String,
    pub(in crate::generator) type_parameters: Vec<String>,
    /// Struct fields in declaration order.
    pub(in crate::generator) fields: Vec<RenderedField>,
}

/// A single field of a [`RenderedModel`].
#[derive(Debug, Clone)]
pub(in crate::generator) struct RenderedField {
    /// Exported Go field name in UpperCamelCase (e.g. `"UserId"`, `"First"`).
    pub(in crate::generator) name: String,
    /// Doc text for the field (from `@nexus.doc`), rendered as a godoc
    /// comment above the struct field.
    pub(in crate::generator) doc: Option<String>,
    /// Go type expression (e.g. `"string"`, `"*PostalAddress"`, `"[]string"`).
    pub(in crate::generator) go_type: String,
    /// Zero value representing absence on a System Nexus request field.
    pub(in crate::generator) default_punning_zero: Option<String>,
    /// Whether the field is required in the WIT definition. Rendered as a
    /// leading `// Required.` godoc comment on the generated Go struct field.
    pub(in crate::generator) required: bool,
    /// Whether this field is populated from `@nexus.source` at the operation
    /// call site rather than documented as a caller-supplied field.
    pub(in crate::generator) sourced: bool,
}

/// The result of resolving a [`PlannedValueType`] to a Go type expression.
#[derive(Debug, Clone)]
struct ResolvedGoType {
    /// Go type expression (e.g. `"string"`, `"PostalAddress"`, `"[]string"`).
    type_expr: String,
}

/// Visibility decisions for local generated Go datatypes.
#[derive(Debug, Clone, Default)]
struct GoVisibility {
    public_keys: BTreeSet<String>,
    type_name_replacements: BTreeMap<String, String>,
}

impl GoVisibility {
    fn is_public(&self, key: &str) -> bool {
        self.public_keys.contains(key)
    }

    fn adjusted_model_name(&self, key: &str, fallback: &str) -> String {
        self.type_name_replacements
            .get(fallback)
            .cloned()
            .unwrap_or_else(|| {
                if self.is_public(key) {
                    fallback.to_string()
                } else {
                    go_unexported_name(fallback)
                }
            })
    }

    fn rewrite_go_expr(&self, expr: &str) -> String {
        if self.type_name_replacements.is_empty() {
            return expr.to_string();
        }

        let bytes = expr.as_bytes();
        let mut output = String::with_capacity(expr.len());
        let mut index = 0;

        while index < bytes.len() {
            let byte = bytes[index];
            if is_go_ident_start(byte) {
                let start = index;
                index += 1;
                while index < bytes.len() && is_go_ident_continue(bytes[index]) {
                    index += 1;
                }
                let ident = &expr[start..index];
                let prev = previous_non_whitespace(bytes, start);
                let next = next_non_whitespace(bytes, index);
                if prev == Some(b'.') || next == Some(b':') {
                    output.push_str(ident);
                } else if let Some(replacement) = self.type_name_replacements.get(ident) {
                    output.push_str(replacement);
                } else {
                    output.push_str(ident);
                }
            } else {
                output.push(byte as char);
                index += 1;
            }
        }

        output
    }
}

fn is_go_ident_start(byte: u8) -> bool {
    byte == b'_' || byte.is_ascii_alphabetic()
}

fn is_go_ident_continue(byte: u8) -> bool {
    is_go_ident_start(byte) || byte.is_ascii_digit()
}

fn previous_non_whitespace(bytes: &[u8], start: usize) -> Option<u8> {
    bytes[..start]
        .iter()
        .rev()
        .copied()
        .find(|byte| !byte.is_ascii_whitespace())
}

fn next_non_whitespace(bytes: &[u8], start: usize) -> Option<u8> {
    bytes[start..]
        .iter()
        .copied()
        .find(|byte| !byte.is_ascii_whitespace())
}

fn compute_go_visibility(
    api_plan: &PlannedSpec,
    enums: &IndexMap<String, RenderedEnum>,
    flags: &IndexMap<String, RenderedFlags>,
    variants: &IndexMap<String, RenderedVariant>,
    models: &IndexMap<String, RenderedModel>,
) -> GoVisibility {
    let mut marker = GoVisibilityMarker {
        api_plan,
        public_keys: BTreeSet::new(),
    };

    // Model-only modules expose declarations directly, without an operation
    // through which the visibility walk could discover them.
    marker.public_keys.extend(
        api_plan
            .types
            .iter()
            .filter(|(_, entry)| entry.is_module_export())
            .map(|(name, _)| name.clone()),
    );
    for service in &api_plan.services {
        for operation in &service.operations {
            marker.mark_operation_public_surface(operation);
        }
        for resource in &service.resources {
            marker.mark_resource_public_surface(&resource.data);
        }
    }

    let mut visibility = GoVisibility {
        public_keys: marker.public_keys,
        type_name_replacements: BTreeMap::new(),
    };

    for (key, enumeration) in enums {
        let name = if visibility.is_public(key) {
            enumeration.name.clone()
        } else {
            go_unexported_name(&enumeration.name)
        };
        visibility
            .type_name_replacements
            .insert(enumeration.name.clone(), go_declaration_name(&name));
    }
    for (key, flag_set) in flags {
        let name = if visibility.is_public(key) {
            flag_set.name.clone()
        } else {
            go_unexported_name(&flag_set.name)
        };
        visibility
            .type_name_replacements
            .insert(flag_set.name.clone(), go_declaration_name(&name));
    }
    for (key, variant) in variants {
        for name in
            std::iter::once(&variant.name).chain(variant.cases.iter().map(|case| &case.struct_name))
        {
            let emitted = if visibility.is_public(key) {
                name.clone()
            } else {
                go_unexported_name(name)
            };
            visibility
                .type_name_replacements
                .insert(name.clone(), go_declaration_name(&emitted));
        }
    }
    for (key, model) in models {
        let (ident, _) = split_go_type_decl_name(&model.name);
        let name = if visibility.is_public(key) {
            ident.to_string()
        } else {
            go_unexported_name(ident)
        };
        visibility
            .type_name_replacements
            .insert(ident.to_string(), go_declaration_name(&name));
    }
    for service in &api_plan.services {
        for resource in &service.resources {
            let name = &resource.data.type_name;
            visibility
                .type_name_replacements
                .insert(name.clone(), go_declaration_name(name));
        }
    }

    visibility
}

struct GoVisibilityMarker<'a> {
    api_plan: &'a PlannedSpec,
    public_keys: BTreeSet<String>,
}

impl GoVisibilityMarker<'_> {
    fn mark_operation_public_surface(&mut self, operation: &PlannedOperation) {
        if let Some(input) = operation
            .input
            .as_ref()
            .and_then(|input| planned_message_type(input, self.api_plan))
            && let Some(planned_model) = record_for_message(self.api_plan, &input)
        {
            for (_, field) in planned_model.public_fields() {
                let kind = planned_field_kind(&field.field_type, self.api_plan);
                if !field.required && field_kind_is_flattened_message(&kind, self.api_plan) {
                    let PlannedFieldKind::Singular(PlannedValueType::Message(message)) = &kind
                    else {
                        unreachable!()
                    };
                    // Options expose the children, not the containing model.
                    // Other public uses can still mark that model normally.
                    let record = record_for_message(self.api_plan, message)
                        .expect("flattened message should have a record");
                    for (_, child) in record.public_fields() {
                        self.mark_operation_field_kind(
                            &planned_field_kind(&child.field_type, self.api_plan),
                            child.name.as_str(),
                        );
                    }
                } else {
                    self.mark_operation_field_kind(&kind, field.name.as_str());
                }
            }
        }

        if operation
            .output_transform
            .as_ref()
            .is_some_and(|transform| {
                transform.type_name.value().is_some() && transform.transform.value().is_some()
            })
        {
            return;
        }

        match operation_output(operation, self.api_plan) {
            PlannedOperationOutput::Message(output) => {
                if operation.data.output_resource_return.is_none() {
                    self.mark_message_type(&output);
                }
            }
            PlannedOperationOutput::Resource { .. } | PlannedOperationOutput::None => {}
        }
        // A result record that holds a resource is what the caller gets.
        if let Some(holder) = operation
            .data
            .output_resource_return
            .as_ref()
            .and_then(|resource_return| resource_return.holder.as_ref())
            && self.public_keys.insert(holder.record_full_name.clone())
            && let Some(record) = self.api_plan.record(&holder.record_full_name)
        {
            for (_, field) in record.public_fields() {
                self.mark_operation_field_kind(
                    &planned_field_kind(&field.field_type, self.api_plan),
                    field.name.as_str(),
                );
            }
        }
    }

    fn mark_resource_public_surface(&mut self, resource: &PlannedResource) {
        for field in &resource.fields {
            self.mark_resource_field_kind(&planned_field_kind(&field.kind, self.api_plan));
        }
        for method in &resource.methods {
            for param in &method.params {
                self.mark_resource_field_kind(&planned_field_kind(&param.kind, self.api_plan));
            }
            if let Some(result) = &method.result
                && let PlannedResourceMethodResult::Value(kind) = &result.kind
            {
                self.mark_resource_field_kind(&planned_field_kind(kind, self.api_plan));
            }
        }
    }

    fn mark_message_type(&mut self, message: &PlannedMessageType) {
        if message.replacement.is_some() || message.authored_type.is_some() {
            return;
        }
        if !self.public_keys.insert(message.info.full_name.clone()) {
            return;
        }
        if let Some(model) = record_for_message(self.api_plan, message) {
            for (_, field) in model.public_fields() {
                self.mark_operation_field_kind(
                    &planned_field_kind(&field.field_type, self.api_plan),
                    field.name.as_str(),
                );
            }
        }
    }

    fn mark_operation_field_kind(&mut self, kind: &PlannedFieldKind, field_name: &str) {
        match kind {
            PlannedFieldKind::Singular(PlannedValueType::Tuple(items)) => {
                self.public_keys.insert(go_field_name(field_name));
                for item in items {
                    self.mark_value_type(item);
                }
            }
            PlannedFieldKind::Singular(PlannedValueType::Result { ok, err }) => {
                self.public_keys.insert(go_field_name(field_name));
                if let Some(ok) = ok.as_deref() {
                    self.mark_value_type(ok);
                }
                if let Some(err) = err.as_deref() {
                    self.mark_value_type(err);
                }
            }
            PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
                self.mark_value_type(value);
            }
            PlannedFieldKind::Map { key, value } => {
                self.mark_value_type(key);
                self.mark_value_type(value);
            }
        }
    }

    fn mark_resource_field_kind(&mut self, kind: &PlannedFieldKind) {
        match kind {
            PlannedFieldKind::Singular(value) | PlannedFieldKind::Repeated(value) => {
                self.mark_value_type(value);
            }
            PlannedFieldKind::Map { key, value } => {
                self.mark_value_type(key);
                self.mark_value_type(value);
            }
        }
    }

    fn mark_value_type(&mut self, value: &PlannedValueType) {
        match value {
            PlannedValueType::TypeParameter(_)
            | PlannedValueType::Scalar(_)
            | PlannedValueType::Unknown => {}
            PlannedValueType::External {
                type_name,
                fallback,
            } => {
                if type_name.value().is_none() {
                    self.mark_value_type(fallback);
                }
            }
            PlannedValueType::Enum(enum_type) => {
                if enum_type.replacement.is_some() {
                    return;
                }
                if let Some(info) = &enum_type.info {
                    self.public_keys.insert(info.full_name.clone());
                }
            }
            PlannedValueType::Flags(flags_type) => {
                self.public_keys.insert(flags_type.info.full_name.clone());
            }
            PlannedValueType::Variant(variant_type) => {
                if !self.public_keys.insert(variant_type.info.full_name.clone()) {
                    return;
                }
                if let Some(variant) = self.api_plan.variant(&variant_type.info.full_name) {
                    for case in &variant.cases {
                        if let Some(payload) = &case.payload {
                            self.mark_value_type(&planned_value_type(payload, self.api_plan));
                        }
                    }
                }
            }
            PlannedValueType::Message(message_type) => self.mark_message_type(message_type),
            PlannedValueType::Tuple(items) => {
                self.public_keys
                    .insert(format!("{GENERIC_MODEL_KEY_PREFIX}Tuple{}", items.len()));
                for item in items {
                    self.mark_value_type(item);
                }
            }
            PlannedValueType::Result { ok, err } => {
                self.public_keys
                    .insert(format!("{GENERIC_MODEL_KEY_PREFIX}Result"));
                if let Some(ok) = ok.as_deref() {
                    self.mark_value_type(ok);
                }
                if let Some(err) = err.as_deref() {
                    self.mark_value_type(err);
                }
            }
        }
    }
}

fn apply_go_visibility(
    visibility: &GoVisibility,
    enums: &mut IndexMap<String, RenderedEnum>,
    flags: &mut IndexMap<String, RenderedFlags>,
    variants: &mut IndexMap<String, RenderedVariant>,
    models: &mut IndexMap<String, RenderedModel>,
    services: &mut [RenderedService<'_>],
) {
    for enumeration in enums.values_mut() {
        enumeration.name = visibility.rewrite_go_expr(&enumeration.name);
    }
    for flag_set in flags.values_mut() {
        flag_set.name = visibility.rewrite_go_expr(&flag_set.name);
    }
    for variant in variants.values_mut() {
        variant.name = visibility.rewrite_go_expr(&variant.name);
        for case in &mut variant.cases {
            case.struct_name = visibility.rewrite_go_expr(&case.struct_name);
            if let Some(payload_type) = &mut case.payload_type {
                *payload_type = visibility.rewrite_go_expr(payload_type);
            }
        }
    }
    for model in models.values_mut() {
        model.name = visibility.rewrite_go_type_decl(&model.name);
        for field in &mut model.fields {
            field.go_type = visibility.rewrite_go_expr(&field.go_type);
        }
    }

    for service in services {
        for operation in &mut service.operations {
            operation.input_type = visibility.rewrite_go_expr(&operation.input_type);
            if let Some(output_type) = &mut operation.output_type {
                *output_type = visibility.rewrite_go_expr(output_type);
            }
            if let Some(raw_output_type) = &mut operation.raw_output_type {
                *raw_output_type = visibility.rewrite_go_expr(raw_output_type);
            }
            if let Some(output_transform_type) = &mut operation.output_transform_type {
                *output_transform_type = visibility.rewrite_go_expr(output_transform_type);
            }
            if let Some(params) = &mut operation.unpacked_input {
                for param in params {
                    param.go_type = visibility.rewrite_go_expr(&param.go_type);
                    param.public_go_type = visibility.rewrite_go_expr(&param.public_go_type);
                    if let Some(fields) = &mut param.flattened_fields {
                        for flattened in fields {
                            flattened.field.go_type =
                                visibility.rewrite_go_expr(&flattened.field.go_type);
                        }
                    }
                }
            }
        }
    }
}

impl GoVisibility {
    fn rewrite_go_type_decl(&self, decl: &str) -> String {
        let (ident, suffix) = split_go_type_decl_name(decl);
        match self.type_name_replacements.get(ident) {
            Some(replacement) => format!("{replacement}{suffix}"),
            None => decl.to_string(),
        }
    }
}

pub(in crate::generator) fn split_go_type_decl_name(decl: &str) -> (&str, &str) {
    decl.find('[')
        .map(|index| (&decl[..index], &decl[index..]))
        .unwrap_or((decl, ""))
}

fn is_go_exported_type_decl(decl: &str) -> bool {
    let (ident, _) = split_go_type_decl_name(decl);
    is_go_exported_decl(ident)
}

fn is_go_exported_decl(name: &str) -> bool {
    name.chars()
        .next()
        .is_some_and(|first| first.is_ascii_uppercase())
}

pub(in crate::generator) fn go_string_literal(value: &str) -> String {
    format!("{value:?}")
}

