/// Renders all collected types into a complete Go source file with a package
/// declaration, import block, and the generated-code header comment.
fn render_file(
    package: &GoPackageContext,
    imports: &BTreeSet<String>,
    external_imports: &[(String, String)],
    external_model_body: &str,
    operation_references: Option<&str>,
    enums: &[&RenderedEnum],
    flags: &[&RenderedFlags],
    variants: &[&RenderedVariant],
    models: &[(&String, &RenderedModel)],
    services: &[RenderedService<'_>],
    external_models: &GoExternalModels,
    api_plan: &PlannedSpec,
    visibility: &GoVisibility,
) -> String {
    let mut output = String::new();
    output.push_str(GENERATED_HEADER);
    output.push('\n');
    output.push_str("package ");
    output.push_str(&package.package_name);
    output.push('\n');

    if !imports.is_empty() || !external_imports.is_empty() {
        // Separate stdlib imports (no '.') from third-party imports (contain '.')
        let stdlib: Vec<_> = imports.iter().filter(|p| !p.contains('.')).collect();
        // Exclude any third-party path that is also emitted (aliased) by the
        // proto import collector to avoid duplicate import declarations.
        let third_party: Vec<_> = imports
            .iter()
            .filter(|p| p.contains('.'))
            .filter(|p| {
                !external_imports
                    .iter()
                    .any(|(external_path, _)| external_path == *p)
            })
            .collect();

        output.push_str("\nimport (\n");
        for import_path in &stdlib {
            output.push('\t');
            output.push('"');
            output.push_str(import_path);
            output.push('"');
            output.push('\n');
        }
        if !stdlib.is_empty() && (!third_party.is_empty() || !external_imports.is_empty()) {
            output.push('\n');
        }
        for import_path in &third_party {
            output.push('\t');
            output.push('"');
            output.push_str(import_path);
            output.push('"');
            output.push('\n');
        }
        for (path, alias) in external_imports {
            output.push('\t');
            let default_alias = path.rsplit('/').next().unwrap_or(path);
            if alias != default_alias {
                output.push_str(alias);
                output.push(' ');
            }
            output.push('"');
            output.push_str(path);
            output.push('"');
            output.push('\n');
        }
        output.push_str(")\n");
    }

    if let Some(operation_references) = operation_references {
        if !operation_references.is_empty() {
            output.push('\n');
            output.push_str(operation_references);
        }
        if !external_model_body.is_empty() {
            output.push_str(external_model_body);
        }
        return output;
    }
    if !external_model_body.is_empty()
        && services.is_empty()
        && enums.is_empty()
        && flags.is_empty()
        && variants.is_empty()
        && models.is_empty()
    {
        output.push('\n');
        output.push_str(external_model_body);
        return output;
    }

    let has_operations = services.iter().any(|s| !s.operations.is_empty());

    // --- Datatypes ---
    let private_enums = enums
        .iter()
        .copied()
        .filter(|enumeration| !is_go_exported_decl(&enumeration.name))
        .collect::<Vec<_>>();
    let private_flags = flags
        .iter()
        .copied()
        .filter(|flag_set| !is_go_exported_decl(&flag_set.name))
        .collect::<Vec<_>>();
    let private_variants = variants
        .iter()
        .copied()
        .filter(|variant| !is_go_exported_decl(&variant.name))
        .collect::<Vec<_>>();
    let private_models = models
        .iter()
        .copied()
        .filter(|(_, model)| !is_go_exported_type_decl(&model.name))
        .collect::<Vec<_>>();

    let has_private_datatypes = !private_enums.is_empty()
        || !private_flags.is_empty()
        || !private_variants.is_empty()
        || !private_models.is_empty();
    if has_private_datatypes {
        output.push_str("\n// --- Datatypes ---\n");
        for enumeration in private_enums {
            output.push('\n');
            render_enum(&mut output, enumeration);
        }
        for flag_set in private_flags {
            output.push('\n');
            render_flags(&mut output, flag_set);
        }
        for variant in private_variants {
            output.push('\n');
            render_variant(&mut output, variant);
        }
        for (key, model) in private_models {
            output.push('\n');
            render_model(&mut output, key, model, external_models, false);
        }
    }

    // --- Resources ---
    let has_resources = services.iter().any(|s| !s.resources.is_empty());
    if has_resources {
        output.push_str("\n// --- Resources ---\n");
        for service in services {
            for resource in &service.resources {
                output.push('\n');
                let constructor_returns_value = service.operations.iter().any(|operation| {
                    operation
                        .wire_binding
                        .as_ref()
                        .and_then(|binding| binding.returned_resource_type_name())
                        .is_some_and(|returned| returned == resource.type_name)
                });
                render_resource(
                    &mut output,
                    resource,
                    api_plan,
                    package,
                    visibility,
                    constructor_returns_value,
                );
                render_resource_methods(
                    &mut output,
                    service,
                    resource,
                    api_plan,
                    package,
                    visibility,
                );
            }
        }
    }

    // --- Operations (internal) ---
    if has_operations {
        output.push_str("\n// --- Operations (internal) ---\n");
        for service in services {
            for operation in &service.operations {
                output.push('\n');
                render_operation_function(&mut output, service, operation, package);
            }
        }
    }

    // --- Operations (public API) ---
    let public_enums = enums
        .iter()
        .copied()
        .filter(|enumeration| is_go_exported_decl(&enumeration.name))
        .collect::<Vec<_>>();
    let public_flags = flags
        .iter()
        .copied()
        .filter(|flag_set| is_go_exported_decl(&flag_set.name))
        .collect::<Vec<_>>();
    let public_variants = variants
        .iter()
        .copied()
        .filter(|variant| is_go_exported_decl(&variant.name))
        .collect::<Vec<_>>();
    let public_models = models
        .iter()
        .copied()
        .filter(|(_, model)| is_go_exported_type_decl(&model.name))
        .collect::<Vec<_>>();
    let has_public_datatypes = !public_enums.is_empty()
        || !public_flags.is_empty()
        || !public_variants.is_empty()
        || !public_models.is_empty();

    let has_endpoint_operations = services
        .iter()
        .any(|service| service.endpoint.is_some() && !service.operations.is_empty());

    if has_endpoint_operations || has_public_datatypes {
        output.push_str("\n// --- Operations (public API) ---\n");
        for enumeration in public_enums {
            output.push('\n');
            render_enum(&mut output, enumeration);
        }
        for flag_set in public_flags {
            output.push('\n');
            render_flags(&mut output, flag_set);
        }
        for variant in public_variants {
            output.push('\n');
            render_variant(&mut output, variant);
        }
        for (key, model) in public_models {
            output.push('\n');
            render_model(&mut output, key, model, external_models, true);
        }
        for service in services {
            if service.endpoint.is_none() {
                continue;
            }
            for operation in &service.operations {
                if let Some(params) = &operation.unpacked_input {
                    output.push('\n');
                    render_options_struct(&mut output, operation, params);
                    output.push('\n');
                    render_convenience_wrapper(
                        &mut output,
                        service,
                        operation,
                        params,
                        package,
                        visibility,
                    );
                    if unary_primary_varargs_function_param(params).is_some() {
                        output.push('\n');
                        render_typed_convenience_wrapper(
                            &mut output,
                            service,
                            operation,
                            params,
                            package,
                            visibility,
                        );
                    }
                } else {
                    // External input type — generate a simple forwarding wrapper
                    output.push('\n');
                    render_empty_options_struct(&mut output, operation);
                    output.push('\n');
                    render_forwarding_wrapper(&mut output, service, operation, package);
                }
            }
        }
    }

    output
}

/// Renders a Go doc comment (`// ...`), wrapping each paragraph to the
/// format line length. Blank lines in the input are preserved as `//`
/// separator lines.
///
/// ```go
/// // Behavior when a workflow is currently running with the same ID. Set to
/// // use-existing for idempotent deduplication on workflow ID.
/// ```
pub(in crate::generator) fn render_go_doc_comment(output: &mut String, indent: &str, text: &str) {
    let max_width = GO_DOC_COMMENT_LINE_LENGTH.saturating_sub(indent.chars().count() + 3);
    for line in text.trim().lines() {
        let line = line.trim();
        if line.is_empty() {
            output.push_str(indent);
            output.push_str("//\n");
            continue;
        }
        let mut current = String::new();
        for word in line.split_whitespace() {
            let separator_width = usize::from(!current.is_empty());
            if !current.is_empty()
                && current.chars().count() + separator_width + word.chars().count() > max_width
            {
                output.push_str(indent);
                output.push_str("// ");
                output.push_str(&current);
                output.push('\n');
                current.clear();
            }
            if !current.is_empty() {
                current.push(' ');
            }
            current.push_str(word);
        }
        output.push_str(indent);
        output.push_str("// ");
        output.push_str(&current);
        output.push('\n');
    }
}

/// Renders the leading godoc comment for a struct field. Required fields are
/// prefixed with `Required.`; the prefix is folded onto the first line of the
/// field's `@nexus.doc`/WIT doc text when present.
///
/// ```go
/// // Required. Unique identifier for the workflow execution.
/// Id string
/// ```
fn render_field_doc_comment(output: &mut String, indent: &str, doc: Option<&str>, required: bool) {
    match (required, doc) {
        (true, Some(doc)) => {
            let trimmed = doc.trim();
            let combined = if trimmed.is_empty() {
                "Required.".to_string()
            } else {
                format!("Required. {trimmed}")
            };
            render_go_doc_comment(output, indent, &combined);
        }
        (true, None) => render_go_doc_comment(output, indent, "Required."),
        (false, Some(doc)) => render_go_doc_comment(output, indent, doc),
        (false, None) => {}
    }
}

/// Renders the godoc comment for an exported operation wrapper function from
/// the operation's `@nexus.doc` text and `returns=` text.
///
/// ```go
/// // Signal a workflow, starting it first if needed.
/// //
/// // Returns: A workflow handle to the started workflow.
/// ```
fn render_operation_doc_comment(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    input_docs: &[(String, String)],
) {
    let doc = operation.doc.map(str::trim).filter(|doc| !doc.is_empty());
    let return_doc = operation
        .return_doc
        .map(str::trim)
        .filter(|doc| !doc.is_empty());
    if let Some(doc) = doc {
        render_go_doc_comment(output, "", doc);
    }
    if !input_docs.is_empty() {
        if doc.is_some() {
            output.push_str("//\n");
        }
        for (name, doc) in input_docs {
            render_go_doc_comment(output, "", &format!("Input {name}: {doc}"));
        }
    }
    if let Some(return_doc) = return_doc {
        if doc.is_some() || !input_docs.is_empty() {
            output.push_str("//\n");
        }
        render_go_doc_comment(output, "", &format!("Returns: {return_doc}"));
    }
}

/// Renders a WIT enum as a Go named integer type with a `const` block.
///
/// ```go
/// type UserStatus int32
///
/// const (
///     UserStatusActive    UserStatus = 0
///     UserStatusSuspended UserStatus = 1
/// )
/// ```
fn render_enum(output: &mut String, enumeration: &RenderedEnum) {
    output.push_str("type ");
    output.push_str(&enumeration.name);
    output.push_str(" int32\n");

    if enumeration.values.is_empty() {
        return;
    }

    output.push_str("\nconst (\n");
    for value in &enumeration.values {
        output.push('\t');
        output.push_str(&enumeration.name);
        output.push_str(&value.name);
        output.push(' ');
        output.push_str(&enumeration.name);
        output.push_str(" = ");
        output.push_str(&value.number.to_string());
        output.push('\n');
    }
    output.push_str(")\n");
}

/// Renders a WIT flags type as a Go named integer type with bit-shifted
/// constants.
///
/// ```go
/// type UserCapability int32
///
/// const (
///     UserCapabilityReadProfile UserCapability = 1 << 0
///     UserCapabilityUpdateEmail UserCapability = 1 << 1
/// )
/// ```
fn render_flags(output: &mut String, flags: &RenderedFlags) {
    output.push_str("type ");
    output.push_str(&flags.name);
    output.push_str(" int32\n");

    if flags.flags.is_empty() {
        return;
    }

    output.push_str("\nconst (\n");
    for flag in &flags.flags {
        output.push('\t');
        output.push_str(&flags.name);
        output.push_str(&flag.name);
        output.push(' ');
        output.push_str(&flags.name);
        output.push_str(" = 1 << ");
        output.push_str(&flag.bit.to_string());
        output.push('\n');
    }
    output.push_str(")\n");
}

/// Renders a WIT variant as a Go sealed interface with concrete case structs.
///
/// ```go
/// type NotificationTarget interface {
///     isNotificationTarget()
/// }
///
/// type NotificationTargetEmail struct {
///     Value string
/// }
///
/// func (NotificationTargetEmail) isNotificationTarget() {}
///
/// type NotificationTargetNone struct{}
///
/// func (NotificationTargetNone) isNotificationTarget() {}
/// ```
fn render_variant(output: &mut String, variant: &RenderedVariant) {
    output.push_str("type ");
    output.push_str(&go_generic_declaration_name(
        &variant.name,
        &variant.type_parameters,
    ));
    output.push_str(" interface {\n");
    output.push('\t');
    output.push_str(&variant.marker_method);
    output.push('(');
    output.push_str(
        &variant
            .type_parameters
            .iter()
            .map(|usage| usage.parameter.name.as_str())
            .collect::<Vec<_>>()
            .join(", "),
    );
    output.push_str(")\n");
    output.push_str("}\n");

    for case in &variant.cases {
        output.push('\n');
        output.push_str("type ");
        output.push_str(&go_generic_declaration_name(
            &case.struct_name,
            &variant.type_parameters,
        ));
        if let Some(payload_type) = &case.payload_type {
            output.push_str(" struct {\n");
            output.push_str("\tValue ");
            output.push_str(payload_type);
            output.push('\n');
            output.push_str("}\n");
        } else {
            output.push_str(" struct{}\n");
        }
        output.push('\n');
        output.push_str("func (");
        output.push_str(&go_generic_reference(
            &case.struct_name,
            &variant.type_parameters,
            false,
        ));
        output.push_str(") ");
        output.push_str(&variant.marker_method);
        output.push('(');
        output.push_str(
            &variant
                .type_parameters
                .iter()
                .map(|usage| usage.parameter.name.as_str())
                .collect::<Vec<_>>()
                .join(", "),
        );
        output.push_str(") {}\n");
    }
}

/// Renders a WIT record (or proto message) as a Go struct. Required fields
/// are annotated with a leading `// Required.` godoc comment.
///
/// ```go
/// type DeactivateRequest struct {
///     // Required.
///     UserId string
///     Reason string
/// }
/// ```
fn render_model(
    output: &mut String,
    key: &str,
    model: &RenderedModel,
    external_models: &GoExternalModels,
    public: bool,
) {
    output.push_str("type ");
    output.push_str(&model.name);
    output.push_str(" struct {\n");

    if model.fields.is_empty() {
        output.push_str("}\n");
    } else {
        for field in &model.fields {
            if public {
                if field.required {
                    render_field_doc_comment(output, "\t", field.doc.as_deref(), true);
                } else {
                    render_go_doc_comment(output, "\t", "Optional.");
                    if let Some(doc) = field.doc.as_deref() {
                        render_go_doc_comment(output, "\t", doc);
                    }
                }
            }
            output.push('\t');
            output.push_str(&field.name);
            output.push(' ');
            output.push_str(&field.go_type);
            output.push('\n');
        }
        output.push_str("}\n");
    }

    external_models.render_model_wire_methods(output, key, model);
}

/// Renders a WIT resource as a Go struct with its constructor fields.
///
/// ```go
/// type User struct {
///     // Required.
///     UserId string
///     // Required.
///     Email  string
/// }
/// ```
fn render_resource(
    output: &mut String,
    resource: &PlannedResource,
    api_plan: &PlannedSpec,
    package: &GoPackageContext,
    visibility: &GoVisibility,
    constructor_returns_value: bool,
) {
    output.push_str("type ");
    output.push_str(&resource.type_name);
    output.push_str(" struct {\n");

    if resource.fields.is_empty() {
        output.push_str("}\n");
    } else {
        for field in &resource.fields {
            let field_name = go_field_name(&field.name);
            let field_kind = planned_field_kind(&field.kind, api_plan);
            let go_type = visibility.rewrite_go_expr(&resolve_resource_field_kind(
                &field_kind,
                field.optional,
                package,
            ));
            if field.optional {
                render_go_doc_comment(output, "\t", "Optional.");
            } else {
                render_field_doc_comment(output, "\t", None, true);
            }
            output.push('\t');
            output.push_str(&field_name);
            output.push(' ');
            output.push_str(&go_type);
            output.push('\n');
        }
        output.push_str("}\n");
    }

    output.push_str("\nfunc New");
    output.push_str(&resource.type_name);
    output.push('(');
    for (index, field) in resource.fields.iter().enumerate() {
        if index > 0 {
            output.push_str(", ");
        }
        let name = go_unexported_name(&go_field_name(&field.name));
        let kind = planned_field_kind(&field.kind, api_plan);
        let internal = resolve_resource_field_kind(&kind, field.optional, package);
        let public = if field.optional
            && public_default_punning_zero_for_field(&kind, &internal).is_some()
        {
            internal.trim_start_matches('*').to_string()
        } else {
            internal
        };
        output.push_str(&name);
        output.push(' ');
        output.push_str(&visibility.rewrite_go_expr(&public));
    }
    output.push_str(") ");
    if !constructor_returns_value {
        output.push('*');
    }
    output.push_str(&resource.type_name);
    output.push_str(" {\n");
    for field in resource.fields.iter().filter(|field| field.optional) {
        let name = go_unexported_name(&go_field_name(&field.name));
        let kind = planned_field_kind(&field.kind, api_plan);
        let internal = resolve_resource_field_kind(&kind, true, package);
        if let Some(zero) = public_default_punning_zero_for_field(&kind, &internal) {
            output.push_str("\tvar ");
            output.push_str(&name);
            output.push_str("Ptr ");
            output.push_str(&visibility.rewrite_go_expr(&internal));
            output.push_str("\n\tif ");
            output.push_str(&name);
            output.push_str(" != ");
            output.push_str(&zero);
            output.push_str(" {\n\t\t");
            output.push_str(&name);
            output.push_str("Ptr = &");
            output.push_str(&name);
            output.push_str("\n\t}\n");
        }
    }
    output.push_str("\treturn ");
    if !constructor_returns_value {
        output.push('&');
    }
    output.push_str(&resource.type_name);
    output.push_str("{\n");
    for field in &resource.fields {
        let name = go_unexported_name(&go_field_name(&field.name));
        let kind = planned_field_kind(&field.kind, api_plan);
        let internal = resolve_resource_field_kind(&kind, field.optional, package);
        let value = if field.optional
            && public_default_punning_zero_for_field(&kind, &internal).is_some()
        {
            format!("{name}Ptr")
        } else {
            name
        };
        output.push_str("\t\t");
        output.push_str(&go_field_name(&field.name));
        output.push_str(": ");
        output.push_str(&value);
        output.push_str(",\n");
    }
    output.push_str("\t}\n}\n");
}

/// Resolves a resource field's [`PlannedFieldKind`] to a Go type expression,
/// applying the same optionality rules as record fields: pointer for optional
/// struct types, plain type for optional scalars/interfaces.
pub(in crate::generator) fn resolve_resource_field_kind(
    kind: &PlannedFieldKind,
    optional: bool,
    package: &GoPackageContext,
) -> String {
    match kind {
        PlannedFieldKind::Map { key, value } => {
            let key_type = resolve_resource_value_type(key, package);
            let value_type = resolve_resource_value_type(value, package);
            format!("map[{key_type}]{value_type}")
        }
        PlannedFieldKind::Repeated(value) => {
            let element_type = resolve_resource_value_type(value, package);
            format!("[]{element_type}")
        }
        PlannedFieldKind::Singular(value) => {
            let (base_type, _is_struct) =
                resolve_resource_value_type_with_struct_flag(value, package);
            if optional && type_needs_pointer_when_optional(value, &base_type) {
                format!("*{base_type}")
            } else {
                base_type
            }
        }
    }
}

/// Resolves a [`PlannedValueType`] to a Go type expression for use in resource
/// field declarations. This is a simplified version of
/// [`resolve_planned_value_type`] that doesn't register types into collections
/// (that's already done by [`ensure_resource_field_types`]).
fn resolve_resource_value_type(value: &PlannedValueType, package: &GoPackageContext) -> String {
    resolve_resource_value_type_with_struct_flag(value, package).0
}

/// Like [`resolve_resource_value_type`] but also returns whether the type is a
/// struct (for optionality/pointer decisions).
fn resolve_resource_value_type_with_struct_flag(
    value: &PlannedValueType,
    package: &GoPackageContext,
) -> (String, bool) {
    match value {
        PlannedValueType::TypeParameter(name) => (name.clone(), false),
        PlannedValueType::Scalar(PlannedScalarType::Float) => ("float64".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Int32) => ("int32".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Int64) => ("int64".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Bool) => ("bool".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::String) => ("string".to_string(), false),
        PlannedValueType::Scalar(PlannedScalarType::Bytes) => ("[]byte".to_string(), false),
        PlannedValueType::Enum(enum_type) => {
            if let Some(replacement) = &enum_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement, package)
            {
                return (type_name, false);
            }
            (
                enum_type
                    .name
                    .clone()
                    .unwrap_or_else(|| "int32".to_string()),
                false,
            )
        }
        PlannedValueType::Flags(flags_type) => (flags_type.name.clone(), false),
        PlannedValueType::Variant(variant_type) => (variant_type.name.clone(), false),
        PlannedValueType::Message(message_type) => {
            if let Some(replacement) = &message_type.replacement
                && let Some(type_name) = go_replacement_type_name(replacement, package)
            {
                return (type_name, false);
            }
            if let Some(authored_type) = &message_type.authored_type {
                return (go_authored_type_annotation(authored_type), false);
            }
            (message_type.model_name.clone(), true)
        }
        // Mirrors `resolve_planned_value_type`: containers of tuples/results
        // instantiate the shared generic helper types, which were registered
        // by `ensure_resource_field_types`.
        PlannedValueType::Tuple(items) => {
            let args = items
                .iter()
                .map(|value| resolve_resource_value_type(value, package))
                .collect::<Vec<_>>()
                .join(", ");
            (format!("Tuple{}[{args}]", items.len()), true)
        }
        PlannedValueType::Result { ok, err } => {
            let ok_type = ok
                .as_deref()
                .map(|value| resolve_resource_value_type(value, package))
                .unwrap_or_else(|| "struct{}".to_string());
            let err_type = err
                .as_deref()
                .map(|value| resolve_resource_value_type(value, package))
                .unwrap_or_else(|| "error".to_string());
            (format!("Result[{ok_type}, {err_type}]"), true)
        }
        PlannedValueType::External {
            type_name,
            fallback,
        } => {
            if let Some(annotation) = type_name.for_language(Language::Go) {
                (package.go_type_expr(annotation), false)
            } else {
                resolve_resource_value_type_with_struct_flag(fallback, package)
            }
        }
        PlannedValueType::Unknown => ("any".to_string(), false),
    }
}

/// Renders methods on a resource struct. Each method that is bound to an
/// operation delegates to the corresponding unexported operation function,
/// constructing the request from the receiver's fields and the method params.
///
/// ```go
/// func (u *User) UpdateEmail(ctx workflow.Context, email string) (*User, error) {
///     return updateEmail(ctx, UpdateEmailRequest{UserId: u.UserId, Email: email})
/// }
/// ```
///
/// Methods bound to `Stub` emit a panic placeholder.
fn render_resource_methods(
    output: &mut String,
    service: &RenderedService<'_>,
    resource: &PlannedResource,
    api_plan: &PlannedSpec,
    package: &GoPackageContext,
    visibility: &GoVisibility,
) {
    if service.endpoint.is_none() {
        return;
    }
    for method in &resource.methods {
        output.push('\n');
        let method_name = go_field_name(&method.name);

        match &method.binding {
            PlannedResourceMethodBinding::Operation {
                operation_name,
                request_plan,
                ..
            } => {
                let operation = service
                    .operations
                    .iter()
                    .find(|op| op.name == operation_name)
                    .expect("bound resource operation should exist on the service");
                let primary_varargs_function = method.params.iter().find(|param| {
                    param.function.as_ref().is_some_and(|function| {
                        function.primary
                            && matches!(function.args, FunctionArgsSpec::Varargs { .. })
                    })
                });

                // Method signature: func (u *Type) Method(ctx workflow.Context, params...) (return)
                output.push_str("func (u *");
                output.push_str(&resource.type_name);
                output.push_str(") ");
                output.push_str(&method_name);
                output.push_str("(ctx ");
                output.push_str(&package.workflow_context_type());
                for param in &method.params {
                    if primary_varargs_function.is_some_and(|primary| primary.name == param.name) {
                        continue;
                    }
                    output.push_str(", ");
                    output.push_str(&go_unexported_name(&go_field_name(&param.name)));
                    output.push(' ');
                    let param_kind = planned_field_kind(&param.kind, api_plan);
                    let internal_type =
                        resolve_resource_field_kind(&param_kind, param.optional, package);
                    let param_type = if param.optional
                        && public_default_punning_zero_for_field(&param_kind, &internal_type)
                            .is_some()
                    {
                        internal_type.trim_start_matches('*').to_string()
                    } else {
                        internal_type
                    };
                    output.push_str(&visibility.rewrite_go_expr(&param_type));
                }
                if let Some(primary) = primary_varargs_function {
                    output.push_str(", ");
                    output.push_str(&go_unexported_name(&go_field_name(&primary.name)));
                    output.push_str(" any, args ...any");
                }
                output.push_str(") ");

                render_operation_future_return_type(output, package);
                output.push_str(" {\n");

                let function_name_var = primary_varargs_function.map(|primary| {
                    let param_name = go_unexported_name(&go_field_name(&primary.name));
                    let name_var = format!("{param_name}Name");
                    let synthetic = RenderedUnpackedParam {
                        field_name: go_field_name(&primary.name),
                        doc: None,
                        param_name,
                        go_type: "string".to_string(),
                        public_go_type: "any".to_string(),
                        default_punning_zero: None,
                        function: primary.function.clone(),
                        function_args: None,
                        required: true,
                        embed_in_options: false,
                    };
                    render_function_name_inline_assignment(output, &synthetic);
                    name_var
                });

                for param in method.params.iter().filter(|param| param.optional) {
                    let kind = planned_field_kind(&param.kind, api_plan);
                    let internal = resolve_resource_field_kind(&kind, true, package);
                    if let Some(zero) = public_default_punning_zero_for_field(&kind, &internal) {
                        let name = go_unexported_name(&go_field_name(&param.name));
                        output.push_str("\tvar ");
                        output.push_str(&name);
                        output.push_str("Ptr ");
                        output.push_str(&visibility.rewrite_go_expr(&internal));
                        output.push_str("\n\tif ");
                        output.push_str(&name);
                        output.push_str(" != ");
                        output.push_str(&zero);
                        output.push_str(" {\n\t\t");
                        output.push_str(&name);
                        output.push_str("Ptr = &");
                        output.push_str(&name);
                        output.push_str("\n\t}\n");
                    }
                }

                // Body: construct request and delegate
                let method_param_sources = method
                    .params
                    .iter()
                    .map(|param| {
                        let name = go_unexported_name(&go_field_name(&param.name));
                        let value = if primary_varargs_function
                            .is_some_and(|primary| primary.name == param.name)
                        {
                            function_name_var.clone().unwrap()
                        } else if param.optional {
                            let kind = planned_field_kind(&param.kind, api_plan);
                            let internal = resolve_resource_field_kind(&kind, true, package);
                            if public_default_punning_zero_for_field(&kind, &internal).is_some() {
                                format!("{name}Ptr")
                            } else {
                                name
                            }
                        } else {
                            name
                        };
                        (param.name.clone(), value)
                    })
                    .collect::<BTreeMap<_, _>>();
                let mut request_expr = render_request_plan(
                    request_plan,
                    go_field_name,
                    |name, value| format!("{name}: {value}"),
                    |msg_name, fields| {
                        // Look up the rendered model name; fall back to
                        // deriving it from the message name.
                        let type_name = record_for_model_key(api_plan, msg_name)
                            .map(|m| visibility.adjusted_model_name(record_message_key(m), &m.name))
                            .unwrap_or_else(|| message_model_name(msg_name));
                        if fields.is_empty() {
                            format!("{type_name}{{}}")
                        } else {
                            format!("{type_name}{{{}}}", fields.join(", "))
                        }
                    },
                    |name| format!("u.{}", go_field_name(name)),
                    |name| {
                        method_param_sources
                            .get(name)
                            .cloned()
                            .unwrap_or_else(|| go_unexported_name(&go_field_name(name)))
                    },
                );
                if let Some(primary) = primary_varargs_function
                    && let Some(args_param) = operation.unpacked_input.as_ref().and_then(|params| {
                        params
                            .iter()
                            .find(|param| param.function_args.as_ref() == primary.function.as_ref())
                    })
                    && let Some(prefix) = request_expr.strip_suffix('}')
                {
                    request_expr = format!("{prefix}, {}: args}}", args_param.field_name);
                }

                output.push_str("\treturn ");
                output.push_str(&operation.func_name);
                output.push_str("(ctx, ");
                output.push_str(&request_expr);
                output.push_str(")\n");
                output.push_str("}\n");
            }
            PlannedResourceMethodBinding::Stub => {
                // Stub method -- emit a panic placeholder
                output.push_str("func (u *");
                output.push_str(&resource.type_name);
                output.push_str(") ");
                output.push_str(&method_name);
                output.push_str("(ctx ");
                output.push_str(&package.workflow_context_type());
                for param in &method.params {
                    output.push_str(", ");
                    output.push_str(&go_unexported_name(&go_field_name(&param.name)));
                    output.push(' ');
                    let param_kind = planned_field_kind(&param.kind, api_plan);
                    let param_type =
                        resolve_resource_field_kind(&param_kind, param.optional, package);
                    output.push_str(&visibility.rewrite_go_expr(&param_type));
                }
                output.push_str(") ");
                render_operation_future_return_type(output, package);
                output.push_str(" {\n");
                output.push_str("\tpanic(\"");
                output.push_str(&resource.type_name);
                output.push('.');
                output.push_str(&method_name);
                output.push_str(" is not yet implemented\")\n");
                output.push_str("}\n");
            }
        }
    }
}

pub(in crate::generator) fn render_operation_future_return_type(
    output: &mut String,
    package: &GoPackageContext,
) {
    output.push_str(&package.workflow_future_type());
}

fn render_future_value_set(output: &mut String, value_expr: &str, value_is_pointer: bool) {
    if value_is_pointer {
        output.push_str("\t\tif ");
        output.push_str(value_expr);
        output.push_str(" == nil {\n");
        output.push_str("\t\t\tresultSettable.SetError(fmt.Errorf(\"nexgen decoded required operation result was nil\"))\n");
        output.push_str("\t\t\treturn\n");
        output.push_str("\t\t}\n");
        output.push_str("\t\tresultSettable.Set(*");
        output.push_str(value_expr);
        output.push_str(", nil)\n");
    } else {
        output.push_str("\t\tresultSettable.Set(");
        output.push_str(value_expr);
        output.push_str(", nil)\n");
    }
}

pub(in crate::generator) fn render_operation_future_adapter(
    output: &mut String,
    package: &GoPackageContext,
    _result_type: &str,
    value_is_pointer: bool,
    get_body: impl FnOnce(&mut String),
) {
    output.push_str("\tresult, resultSettable := ");
    output.push_str(&package.new_future());
    output.push_str("(ctx)\n");
    output.push_str("\t");
    output.push_str(&package.workflow_go());
    output.push_str("(ctx, func(ctx ");
    output.push_str(&package.workflow_context_type());
    output.push_str(") {\n");
    get_body(output);
    render_future_value_set(output, "value", value_is_pointer);
    output.push_str("\t})\n");
    output.push_str("\treturn result\n");
}

fn new_nexus_client_expr(endpoint: &str, service_name: &str, package: &GoPackageContext) -> String {
    format!(
        "{}({}, {})",
        package.new_nexus_client(),
        go_string_literal(endpoint),
        go_string_literal(service_name)
    )
}

/// Renders an unexported operation wrapper function that creates a Nexus
/// client and executes the operation.
///
/// For operations returning a value:
/// ```go
/// func getUser(ctx workflow.Context, request GetUserRequest) (*User, error) {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, GetUserOp, request, workflow.NexusOperationOptions{})
///     var result User
///     if err := fut.Get(ctx, &result); err != nil {
///         return nil, err
///     }
///     return &result, nil
/// }
/// ```
///
/// For void operations:
/// ```go
/// func deactivate(ctx workflow.Context, request DeactivateRequest) error {
///     c := workflow.NewNexusClient(Endpoint, ServiceName)
///     fut := c.ExecuteOperation(ctx, DeactivateOp, request, workflow.NexusOperationOptions{})
///     return fut.Get(ctx, nil)
/// }
/// ```
fn render_operation_function(
    output: &mut String,
    service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    package: &GoPackageContext,
) {
    if let Some(binding) = &operation.wire_binding {
        proto::render_operation_function_proto(output, service, operation, binding, package);
        return;
    }

    let operation_name = go_string_literal(operation.wire_name);

    output.push_str("func ");
    output.push_str(&operation.func_name);
    render_go_model_type_parameter_declaration(output, &operation.model_type_parameters);
    output.push_str("(ctx ");
    output.push_str(&package.workflow_context_type());
    output.push_str(", request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");
    render_operation_future_return_type(output, package);
    output.push_str(" {\n");
    let endpoint = service
        .endpoint
        .as_deref()
        .expect("operations require endpoint");
    output.push_str("\tc := ");
    output.push_str(&new_nexus_client_expr(endpoint, service.wire_name, package));
    output.push_str("\n\tfut := c.ExecuteOperation(ctx, ");
    output.push_str(&operation_name);
    output.push_str(", request, ");
    output.push_str(&package.nexus_operation_options());
    output.push_str(")\n");
    if let (Some(transform_expr), Some(transform_type)) = (
        operation.output_transform_expr,
        operation.output_transform_type.as_ref(),
    ) {
        render_operation_future_adapter(output, package, transform_type, false, |output| {
            if let Some(raw_result_type) = &operation.raw_output_type {
                output.push_str("\t\tvar result ");
                output.push_str(raw_result_type);
                output.push('\n');
                output.push_str("\t\tif err := fut.Get(ctx, &result); err != nil {\n");
            } else {
                output.push_str("\t\tif err := fut.Get(ctx, nil); err != nil {\n");
            }
            output.push_str("\t\t\tresultSettable.SetError(err)\n");
            output.push_str("\t\t\treturn\n");
            output.push_str("\t\t}\n");
            output.push_str("\t\tvalue, err := ");
            output.push_str(transform_expr);
            output.push('\n');
            output.push_str("\t\tif err != nil {\n");
            output.push_str("\t\t\tresultSettable.SetError(err)\n");
            output.push_str("\t\t\treturn\n");
            output.push_str("\t\t}\n");
        });
    } else {
        output.push_str("\treturn fut\n");
    }
    output.push_str("}\n");
}

/// Renders an options struct for non-function parameters of a convenience wrapper.
///
/// ```go
/// type GetUserOptions struct {
///     ConsistencyToken string
/// }
/// ```
fn render_options_struct(
    output: &mut String,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
) {
    output.push_str("type ");
    output.push_str(&go_field_name(operation.name));
    output.push_str("Options");
    render_go_model_type_parameter_declaration(output, &operation.model_type_parameters);
    output.push_str(" struct {\n");
    for param in params.iter().filter(|p| param_belongs_in_options(p)) {
        if param.required {
            render_field_doc_comment(output, "\t", param.doc.as_deref(), true);
        } else {
            render_go_doc_comment(output, "\t", "Optional.");
            if let Some(doc) = &param.doc {
                render_go_doc_comment(output, "\t", doc);
            }
        }
        output.push('\t');
        if param.embed_in_options {
            output.push_str(param.public_go_type.trim_start_matches('*'));
        } else {
            output.push_str(&param.field_name);
            output.push(' ');
            output.push_str(&param.public_go_type);
        }
        output.push('\n');
    }
    output.push_str("}\n");
}

fn render_empty_options_struct(output: &mut String, operation: &RenderedOperation<'_>) {
    output.push_str("type ");
    output.push_str(&go_field_name(operation.name));
    output.push_str("Options");
    render_go_model_type_parameter_declaration(output, &operation.model_type_parameters);
    output.push_str(" struct {\n}\n");
}

fn param_belongs_in_options(param: &RenderedUnpackedParam) -> bool {
    param.function.is_none() && param.function_args.is_none()
}

fn param_is_positional(param: &RenderedUnpackedParam) -> bool {
    !param_belongs_in_options(param)
}

fn function_type_parameter_name(param: &RenderedUnpackedParam) -> String {
    format!("{}F", param.field_name)
}

fn required_function_type_parameters(
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> Vec<(String, String)> {
    params
        .iter()
        .filter_map(|param| {
            let function = param.function.as_ref()?;
            if is_go_signal_function(function)
                || function.alternate_type.is_none()
                || (function.primary
                    && matches!(function.args, FunctionArgsSpec::Varargs { ref prefix, .. } if !prefix.is_empty()))
            {
                return None;
            }
            Some((
                function_type_parameter_name(param),
                go_function_constraint(function, params, package, visibility),
            ))
        })
        .collect()
}

fn go_function_constraint(
    function: &FunctionFieldSpec,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> String {
    let args = match &function.args {
        FunctionArgsSpec::Fixed(args) => args
            .iter()
            .map(|arg| {
                let arg_field = arg.name.to_snake_case();
                params
                    .iter()
                    .find(|param| {
                        param
                            .field_name
                            .eq_ignore_ascii_case(&go_field_name(&arg_field))
                    })
                    .map(|param| param.go_type.clone())
                    .unwrap_or_else(|| {
                        go_authored_function_type_expr(&arg.field_type, package, visibility)
                    })
            })
            .collect::<Vec<_>>(),
        FunctionArgsSpec::Varargs { prefix, .. } => {
            let mut args = prefix
                .iter()
                .map(|arg| go_authored_function_type_expr(&arg.field_type, package, visibility))
                .collect::<Vec<_>>();
            let vararg_type = params
                .iter()
                .find(|param| {
                    param
                        .field_name
                        .eq_ignore_ascii_case(&go_field_name(&function.args_field))
                })
                .map(|param| go_variadic_element_type(&param.go_type))
                .unwrap_or_else(|| "any".to_string());
            args.push(format!("...{vararg_type}"));
            args
        }
    };
    let result_type = match &function.result {
        FunctionResultSpec::Authored(result) => {
            go_authored_function_type_expr(result, package, visibility)
        }
        FunctionResultSpec::Annotation(result) => result
            .for_language(Language::Go)
            .map(|result| package.go_type_expr(result))
            .map(|result| visibility.rewrite_go_expr(&result))
            .unwrap_or_else(|| "any".to_string()),
    };
    let function_type = format!("func({}) {}", args.join(", "), result_type);
    if let Some(alternate_type) = &function.alternate_type {
        let alternate_type = go_authored_function_type_expr(alternate_type, package, visibility);
        format!("interface{{ ~{alternate_type} | {function_type} }}")
    } else {
        format!("interface{{ ~{function_type} }}")
    }
}

fn go_function_type_expr(
    function: &FunctionFieldSpec,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> String {
    let constraint = go_function_constraint(function, params, package, visibility);
    constraint
        .strip_prefix("interface{ ~")
        .and_then(|value| value.strip_suffix(" }"))
        .unwrap_or(&constraint)
        .to_string()
}

fn is_go_signal_function(function: &FunctionFieldSpec) -> bool {
    !function.primary
        && function.args_field == "signal_input"
        && matches!(function.alternate_type.as_ref(), Some(TypeSpec::String))
}

fn is_go_signal_param(param: &RenderedUnpackedParam) -> bool {
    param.function.as_ref().is_some_and(is_go_signal_function)
}

fn is_go_signal_args_param(param: &RenderedUnpackedParam) -> bool {
    param
        .function_args
        .as_ref()
        .is_some_and(is_go_signal_function)
}

fn ordered_positional_params(params: &[RenderedUnpackedParam]) -> Vec<&RenderedUnpackedParam> {
    let mut ordered = Vec::new();
    for signal in params.iter().filter(|param| is_go_signal_param(param)) {
        ordered.push(signal);
        if let Some(function) = &signal.function
            && let Some(args) = params
                .iter()
                .find(|param| param.function_args.as_ref() == Some(function))
        {
            ordered.push(args);
        }
    }
    for param in params.iter().filter(|param| param_is_positional(param)) {
        if !ordered
            .iter()
            .any(|item| item.field_name == param.field_name)
        {
            ordered.push(param);
        }
    }
    ordered
}

fn go_variadic_element_type(go_type: &str) -> String {
    go_type
        .strip_prefix("[]")
        .map(str::to_string)
        .unwrap_or_else(|| "any".to_string())
}

fn go_authored_function_type_expr(
    wit_type: &PlannedType,
    package: &GoPackageContext,
    visibility: &GoVisibility,
) -> String {
    let expr = match wit_type {
        TypeSpec::Option(inner) => {
            format!(
                "*{}",
                go_authored_function_type_expr(inner, package, visibility)
            )
        }
        TypeSpec::List(inner) => {
            format!(
                "[]{}",
                go_authored_function_type_expr(inner, package, visibility)
            )
        }
        TypeSpec::Map(key, value) => format!(
            "map[{}]{}",
            go_authored_function_type_expr(key, package, visibility),
            go_authored_function_type_expr(value, package, visibility)
        ),
        TypeSpec::External(ExternalTypeSpec::Alias {
            type_name, target, ..
        }) => type_name
            .for_language(Language::Go)
            .map(|annotation| package.go_type_expr(annotation))
            .unwrap_or_else(|| go_authored_function_type_expr(target, package, visibility)),
        _ => go_authored_type_annotation(wit_type),
    };
    visibility.rewrite_go_expr(&expr)
}

fn primary_varargs_args_param(params: &[RenderedUnpackedParam]) -> Option<&RenderedUnpackedParam> {
    let primary_function = params.iter().find_map(|param| {
        let function = param.function.as_ref()?;
        if function.primary && matches!(function.args, FunctionArgsSpec::Varargs { .. }) {
            Some(function)
        } else {
            None
        }
    })?;
    params.iter().find(|param| {
        !param.required
            && param
                .function_args
                .as_ref()
                .is_some_and(|function| function == primary_function)
    })
}

fn unary_primary_varargs_function_param(
    params: &[RenderedUnpackedParam],
) -> Option<&RenderedUnpackedParam> {
    let function_param = params.iter().find(|param| {
        param.function.as_ref().is_some_and(|function| {
            function.primary && matches!(function.args, FunctionArgsSpec::Varargs { .. })
        })
    })?;
    let function = function_param.function.as_ref()?;
    let FunctionArgsSpec::Varargs { prefix, .. } = &function.args else {
        return None;
    };
    if prefix.is_empty() {
        return None;
    }
    let args = primary_varargs_args_param(params)?;
    (go_variadic_element_type(&args.go_type) == "any").then_some(function_param)
}

fn render_operation_wrapper_return_type(output: &mut String, package: &GoPackageContext) {
    render_operation_future_return_type(output, package);
}

fn render_function_name_inlining(output: &mut String, params: &[RenderedUnpackedParam]) {
    for param in params {
        if param
            .function
            .as_ref()
            .is_some_and(|function| !is_go_signal_function(function))
        {
            let name = function_name_local_var_for_params(param, params);
            render_function_name_inline_assignment_named(output, param, &name);
        }
    }
}

fn render_function_name_inline_assignment(output: &mut String, param: &RenderedUnpackedParam) {
    let name_var = function_name_local_var(param);
    render_function_name_inline_assignment_named(output, param, &name_var);
}

fn render_function_name_inline_assignment_named(
    output: &mut String,
    param: &RenderedUnpackedParam,
    name_var: &str,
) {
    let accepts_alternate = param
        .function
        .as_ref()
        .is_some_and(|function| function.alternate_type.is_some());
    output.push('\t');
    output.push_str(&name_var);
    output.push_str(" := \"\"\n");
    output.push_str("\t{\n");
    if accepts_alternate {
        output.push_str("\t\tswitch rv := reflect.ValueOf(");
    } else {
        output.push_str("\t\trv := reflect.ValueOf(");
    }
    output.push_str(&param.param_name);
    if accepts_alternate {
        output.push_str("); rv.Kind() {\n");
        output.push_str("\t\tcase reflect.String:\n\t\t\t");
        output.push_str(&name_var);
        output.push_str(" = rv.String()\n\t\tcase reflect.Func:\n\t");
    } else {
        output.push_str(")\n");
    }
    output.push_str("\t\tfullName := runtime.FuncForPC(rv.Pointer()).Name()\n");
    output.push_str("\t\telements := strings.Split(fullName, \".\")\n");
    output.push_str("\t\tshortName := elements[len(elements)-1]\n");
    output.push_str("\t\t");
    if accepts_alternate {
        output.push('\t');
    }
    output.push_str(&name_var);
    output.push_str(" = strings.TrimSuffix(shortName, \"-fm\")\n");
    if accepts_alternate {
        output.push_str("\t\tdefault:\n\t\t\tpanic(\"nexgen function name requires string or function\")\n\t\t}\n");
    }
    output.push_str("\t}\n");
}

fn function_name_local_var(param: &RenderedUnpackedParam) -> String {
    format!("{}Name", param.param_name)
}

fn function_name_local_var_for_params(
    target: &RenderedUnpackedParam,
    params: &[RenderedUnpackedParam],
) -> String {
    let base = function_name_local_var(target);
    let occupied = params
        .iter()
        .map(|param| param.param_name.as_str())
        .chain(["ctx", "opts", "arg", "args"])
        .collect::<BTreeSet<_>>();
    if !occupied.contains(base.as_str()) {
        return base;
    }
    let mut suffix = 2;
    loop {
        let candidate = format!("{base}{suffix}");
        if !occupied.contains(candidate.as_str()) {
            return candidate;
        }
        suffix += 1;
    }
}

fn render_exact_function_name_assignment(output: &mut String, param: &RenderedUnpackedParam) {
    let name_var = function_name_local_var(param);
    output.push('\t');
    output.push_str(&name_var);
    output.push_str(" := \"\"\n\t{\n");
    output.push_str("\t\trv := reflect.ValueOf(");
    output.push_str(&param.param_name);
    output.push_str(")\n");
    output.push_str("\t\tfullName := runtime.FuncForPC(rv.Pointer()).Name()\n");
    output.push_str("\t\telements := strings.Split(fullName, \".\")\n");
    output.push_str("\t\tshortName := elements[len(elements)-1]\n\t\t");
    output.push_str(&name_var);
    output.push_str(" = strings.TrimSuffix(shortName, \"-fm\")\n\t}\n");
}

fn wrapper_input_docs<'a>(
    params: impl IntoIterator<Item = &'a RenderedUnpackedParam>,
) -> Vec<(String, String)> {
    params
        .into_iter()
        .filter_map(|param| {
            let doc = param.doc.as_deref()?.trim();
            if doc.is_empty() {
                None
            } else {
                let name = if is_go_signal_args_param(param) {
                    signal_args_public_param_name(param)
                } else {
                    param.param_name.clone()
                };
                Some((name, doc.to_string()))
            }
        })
        .collect()
}

/// Renders an exported convenience wrapper that unpacks required fields as
/// positional arguments and optional fields into a required options struct.
///
/// The request struct is always constructed across multiple lines. The function
/// signature is also split across multiple lines when it has more than three
/// parameters (counting `ctx`).
///
/// ```go
/// func UpdateEmail(ctx workflow.Context, userId string, email string) (*User, error) {
///     return updateEmail(ctx, UpdateEmailRequest{
///         UserId: userId,
///         Email:  email,
///     })
/// }
/// ```
///
/// With more than three parameters:
/// ```go
/// func StartWorkflow(
///     ctx workflow.Context,
///     workflow string,
///     workflowId string,
///     taskQueue string,
///     opts StartWorkflowOptions,
/// ) (*StartedWorkflow, error) {
///     return startWorkflow(ctx, StartWorkflowRequest{
///         Workflow:           workflow,
///         Args:               opts.Args,
///         WorkflowId:         workflowId,
///         TaskQueue:          taskQueue,
///         WorkflowStartDelay: opts.WorkflowStartDelay,
///     })
/// }
/// ```
fn render_convenience_wrapper(
    output: &mut String,
    _service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) {
    let exported_name = go_field_name(operation.name);
    let mut type_params = operation
        .model_type_parameters
        .iter()
        .map(|usage| (usage.parameter.name.clone(), "any".to_string()))
        .collect::<Vec<_>>();
    type_params.extend(required_function_type_parameters(
        params, package, visibility,
    ));

    let positional_params = ordered_positional_params(params);
    let input_docs = wrapper_input_docs(positional_params.iter().copied());
    render_operation_doc_comment(output, operation, &input_docs);

    let mut signature_params: Vec<(String, String)> = vec![(
        "opts".to_string(),
        go_generic_reference(
            &format!("{exported_name}Options"),
            &operation.model_type_parameters,
            false,
        ),
    )];
    signature_params.extend(positional_params.iter().copied().map(|p| {
        let (name, ty) = if is_go_signal_param(p) {
            (p.param_name.clone(), "string".to_string())
        } else if is_go_signal_args_param(p) {
            (signal_args_public_param_name(p), "any".to_string())
        } else if let Some(function) = &p.function {
            let ty = if unary_primary_varargs_function_param(params)
                .is_some_and(|primary| primary.field_name == p.field_name)
            {
                "any".to_string()
            } else if function.alternate_type.is_some() {
                function_type_parameter_name(p)
            } else {
                go_function_type_expr(function, params, package, visibility)
            };
            (p.param_name.clone(), ty)
        } else if let Some(function) = &p.function_args {
            let ty = if matches!(function.args, FunctionArgsSpec::Varargs { .. }) {
                format!("...{}", go_variadic_element_type(&p.public_go_type))
            } else {
                p.public_go_type.clone()
            };
            (p.param_name.clone(), ty)
        } else {
            (p.param_name.clone(), p.public_go_type.clone())
        };
        (name, ty)
    }));

    // The signature is multi-line when it has more than 3 parameters total
    // (counting `ctx` plus the parameters above).
    let multiline_signature = signature_params.len() + 1 > 3;

    // Function signature
    output.push_str("func ");
    output.push_str(&exported_name);
    if !type_params.is_empty() {
        output.push('[');
        for (index, (name, constraint)) in type_params.iter().enumerate() {
            if index > 0 {
                output.push_str(", ");
            }
            output.push_str(name);
            output.push(' ');
            output.push_str(constraint);
        }
        output.push(']');
    }
    if multiline_signature {
        output.push_str("(\n\tctx ");
        output.push_str(&package.workflow_context_type());
        output.push_str(",\n");
        for (name, ty) in &signature_params {
            output.push('\t');
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
            output.push_str(",\n");
        }
        output.push(')');
    } else {
        output.push_str("(ctx ");
        output.push_str(&package.workflow_context_type());
        for (name, ty) in &signature_params {
            output.push_str(", ");
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
        }
        output.push(')');
    }
    output.push(' ');

    // Return type
    render_operation_wrapper_return_type(output, package);
    output.push_str(" {\n");

    // Function body -- build the request as a multi-line struct literal,
    // sourcing required fields from positional args and optional fields from
    // opts.
    render_public_default_punning_locals(output, params);
    render_function_name_inlining(output, params);
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, ");
    output.push_str(&operation.input_type);
    output.push_str("{\n");
    for param in params {
        output.push_str("\t\t");
        output.push_str(&param.field_name);
        output.push_str(": ");
        if is_go_signal_param(param) {
            output.push_str(&param.param_name);
        } else if is_go_signal_args_param(param) {
            output.push_str(&format!(
                "{}{{{}}}",
                param.go_type,
                signal_args_public_param_name(param)
            ));
        } else if param.function.is_some() {
            output.push_str(&function_name_local_var_for_params(param, params));
        } else if param.function_args.is_some() {
            output.push_str(&param.param_name);
        } else if param.default_punning_zero.is_some() {
            output.push_str(&param.param_name);
        } else if param.embed_in_options {
            output.push('&');
            output.push_str("opts.");
            output.push_str(&param.field_name);
        } else {
            output.push_str("opts.");
            output.push_str(&param.field_name);
        }
        output.push_str(",\n");
    }
    output.push_str("\t})\n");

    output.push_str("}\n");
}

fn signal_args_public_param_name(param: &RenderedUnpackedParam) -> String {
    param
        .param_name
        .strip_suffix("Args")
        .map(|prefix| format!("{prefix}Arg"))
        .unwrap_or_else(|| param.param_name.clone())
}

fn render_public_default_punning_locals(output: &mut String, params: &[RenderedUnpackedParam]) {
    for param in params
        .iter()
        .filter(|param| param_belongs_in_options(param))
    {
        if let Some(zero) = &param.default_punning_zero {
            output.push_str("\tvar ");
            output.push_str(&param.param_name);
            output.push(' ');
            output.push_str(&param.go_type);
            output.push('\n');
            output.push_str("\tif opts.");
            output.push_str(&param.field_name);
            output.push_str(" != ");
            output.push_str(zero);
            output.push_str(" {\n\t\t");
            output.push_str(&param.param_name);
            output.push_str(" = &opts.");
            output.push_str(&param.field_name);
            output.push_str("\n\t}\n");
        }
    }
}

fn render_operation_params(
    output: &mut String,
    signature_params: &[(String, String)],
    package: &GoPackageContext,
) {
    let multiline_signature = signature_params.len() + 1 > 3;
    if multiline_signature {
        output.push_str("(\n\tctx ");
        output.push_str(&package.workflow_context_type());
        output.push_str(",\n");
        for (name, ty) in signature_params {
            output.push('\t');
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
            output.push_str(",\n");
        }
        output.push(')');
    } else {
        output.push_str("(ctx ");
        output.push_str(&package.workflow_context_type());
        for (name, ty) in signature_params {
            output.push_str(", ");
            output.push_str(name);
            output.push(' ');
            output.push_str(ty);
        }
        output.push(')');
    }
}

fn render_typed_convenience_wrapper(
    output: &mut String,
    _service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    params: &[RenderedUnpackedParam],
    package: &GoPackageContext,
    visibility: &GoVisibility,
) {
    let primary = unary_primary_varargs_function_param(params)
        .expect("typed wrapper requires a unary-capable primary function");
    let function = primary.function.as_ref().unwrap();
    let exported_name = format!("{}Typed", go_field_name(operation.name));
    let options_name = format!("{}Options", go_field_name(operation.name));
    let arg_type = format!("{}Arg", primary.field_name);
    let result_type = function
        .result_type_parameter
        .clone()
        .unwrap_or_else(|| format!("{}Result", primary.field_name));
    let mut signature = vec![("opts".to_string(), options_name)];
    for param in ordered_positional_params(params) {
        if param.field_name == primary.field_name {
            let mut args = match &function.args {
                FunctionArgsSpec::Varargs { prefix, .. } => prefix
                    .iter()
                    .map(|arg| go_authored_function_type_expr(&arg.field_type, package, visibility))
                    .collect::<Vec<_>>(),
                FunctionArgsSpec::Fixed(_) => Vec::new(),
            };
            args.push(arg_type.clone());
            signature.push((
                param.param_name.clone(),
                format!("func({}) {result_type}", args.join(", ")),
            ));
            signature.push(("arg".to_string(), arg_type.clone()));
        } else if param.function_args.as_ref() == Some(function) {
            continue;
        } else if is_go_signal_param(param) {
            signature.push((param.param_name.clone(), "string".to_string()));
        } else if is_go_signal_args_param(param) {
            signature.push((signal_args_public_param_name(param), "any".to_string()));
        }
    }
    render_operation_doc_comment(
        output,
        operation,
        &wrapper_input_docs(ordered_positional_params(params)),
    );
    output.push_str("func ");
    output.push_str(&exported_name);
    output.push('[');
    output.push_str(&arg_type);
    output.push_str(" any, ");
    output.push_str(&result_type);
    output.push_str(" any]");
    render_operation_params(output, &signature, package);
    output.push(' ');
    render_operation_wrapper_return_type(output, package);
    output.push_str(" {\n");
    render_public_default_punning_locals(output, params);
    render_exact_function_name_assignment(output, primary);
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, ");
    output.push_str(&operation.input_type);
    output.push_str("{\n");
    for param in params {
        output.push_str("\t\t");
        output.push_str(&param.field_name);
        output.push_str(": ");
        if param.field_name == primary.field_name {
            output.push_str(&function_name_local_var(param));
        } else if param.function_args.as_ref() == Some(function) {
            output.push_str(&format!("{}{{arg}}", param.go_type));
        } else if is_go_signal_param(param) {
            output.push_str(&param.param_name);
        } else if is_go_signal_args_param(param) {
            output.push_str(&format!(
                "{}{{{}}}",
                param.go_type,
                signal_args_public_param_name(param)
            ));
        } else if param.default_punning_zero.is_some() {
            output.push_str(&param.param_name);
        } else if param.embed_in_options {
            output.push_str("&opts.");
            output.push_str(&param.field_name);
        } else {
            output.push_str("opts.");
            output.push_str(&param.field_name);
        }
        output.push_str(",\n");
    }
    output.push_str("\t})\n}\n");
}

/// Renders an exported forwarding wrapper for operations whose input type is
/// an external/replacement type (no model to unpack). The wrapper simply
/// forwards to the unexported operation function.
///
/// ```go
/// func ExampleOperation(ctx workflow.Context, request SomeExternalType) (*SomeExternalType, error) {
///     return exampleOperation(ctx, request)
/// }
/// ```
fn render_forwarding_wrapper(
    output: &mut String,
    _service: &RenderedService<'_>,
    operation: &RenderedOperation<'_>,
    package: &GoPackageContext,
) {
    let exported_name = go_field_name(operation.name);

    render_operation_doc_comment(output, operation, &[]);
    output.push_str("func ");
    output.push_str(&exported_name);
    output.push_str("(ctx ");
    output.push_str(&package.workflow_context_type());
    output.push_str(", _ ");
    output.push_str(&exported_name);
    output.push_str("Options, request ");
    output.push_str(&operation.input_type);
    output.push_str(") ");

    render_operation_wrapper_return_type(output, package);

    output.push_str(" {\n");
    output.push_str("\treturn ");
    output.push_str(&operation.func_name);
    output.push_str("(ctx, request)\n");
    output.push_str("}\n");
}

